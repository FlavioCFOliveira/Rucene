GENERATED_NOTE = "// Generated by `tools/translate/lang_families.py` from `{java}`; do not edit.\n"


class Deviation(Exception):
    """The Java class does not follow its family's template."""


# --------------------------------------------------------------------------
# Lexer
# --------------------------------------------------------------------------

TOKEN_RE = re.compile(
    r"""(?P<javadoc>/\*\*(?!/).*?\*/)
      |(?P<block>/\*.*?\*/)
      |(?P<line>//[^\n]*)
      |(?P<str>"(?:\\.|[^"\\])*")
      |(?P<chr>'(?:\\.|[^'\\])*')
      |(?P<cap>@\.\.\.[A-Za-z_]+|@[a-z_][A-Za-z_0-9]*)
      |(?P<id>[A-Za-z_$][A-Za-z_0-9$]*)
      |(?P<num>[0-9][0-9A-Za-z_.]*)
      |(?P<ws>\s+)
      |(?P<op>\+\+|--|&&|\|\||[=!<>]=|[{}()\[\];,.<>=+\-*/%!?:&|@])
    """, re.S | re.X)


class Tok:
    __slots__ = ("kind", "text", "line")

    def __init__(self, kind, text, line):
        self.kind, self.text, self.line = kind, text, line

    def __repr__(self):
        return f"{self.kind}:{self.text}"


def lex(src: str, allow_captures: bool = False) -> list[Tok]:
    toks, pos, line = [], 0, 1
    while pos < len(src):
        m = TOKEN_RE.match(src, pos)
        if not m:
            raise Deviation(f"cannot lex at line {line}: {src[pos:pos + 20]!r}")
        kind = m.lastgroup
        text = m.group()
        if kind == "cap" and not allow_captures:
            # an annotation: `@` then the name
            toks.append(Tok("op", "@", line))
            toks.append(Tok("id", text[1:], line))
        elif kind != "ws":
            toks.append(Tok(kind, text, line))
        line += text.count("\n")
        pos = m.end()
    return toks


def code(toks):
    return [t for t in toks if t.kind not in ("javadoc", "block", "line")]


# --------------------------------------------------------------------------
# Structure: class, members
# --------------------------------------------------------------------------

class Member:
    def __init__(self, javadoc, toks):
        self.javadoc = javadoc  # str or None
        self.toks = toks  # all tokens, comments included

    @property
    def code(self):
        return code(self.toks)

    def comments(self):
        return [t.text for t in self.toks if t.kind in ("line", "block", "javadoc")]


class JavaClass:
    def __init__(self, path: Path):
        self.path = path
        self.src = path.read_text(encoding="utf-8")
        toks = lex(self.src)
        # skip the license header, package and imports
        i = 0
        assert toks[0].kind == "block" and "Licensed to the Apache" in toks[0].text
        i = 1
        self.pre_comments = []
        while toks[i].kind in ("block", "line"):
            self.pre_comments.append(toks[i].text)
            i += 1
        if toks[i].text != "package":
            raise Deviation("no package declaration")
        while toks[i].text != ";":
            i += 1
        i += 1
        self.imports = []
        while toks[i].kind in ("line", "block"):
            self.pre_comments.append(toks[i].text)
            i += 1
        while i < len(toks) and toks[i].text == "import":
            j = i
            while toks[j].text != ";":
                j += 1
            self.imports.append("".join(t.text for t in toks[i + 1:j]))
            i = j + 1
            while toks[i].kind == "line" and toks[i].line == toks[i - 1].line:
                i += 1  # trailing comment on an import line
        self.class_javadoc = None
        while toks[i].kind in ("javadoc", "line", "block"):
            if toks[i].kind == "javadoc":
                self.class_javadoc = toks[i].text
            else:
                self.pre_comments.append(toks[i].text)
            i += 1
        self.annotations = []
        while toks[i].text == "@":
            self.annotations.append(toks[i + 1].text)
            i += 2
        j = i
        while toks[j].text != "{":
            j += 1
        self.header = [t.text for t in toks[i:j]]
        body, end = balanced(toks, j)
        if any(t.kind not in ("line", "block") for t in toks[end:]):
            raise Deviation("more than one top-level type")
        self.members = split_members(body)
        self.name = self.header[self.header.index("class") + 1]


def balanced(toks, open_index):
    """Tokens strictly inside the brace group opened at `open_index`, and the index after it."""
    depth = 0
    for k in range(open_index, len(toks)):
        if toks[k].text == "{":
            depth += 1
        elif toks[k].text == "}":
            depth -= 1
            if depth == 0:
                return toks[open_index + 1:k], k + 1
    raise Deviation("unbalanced braces")


def split_members(body):
    members, cur, javadoc, depth, paren = [], [], None, 0, 0
    for t in body:
        if t.kind == "javadoc" and depth == 0 and paren == 0 and not code(cur):
            javadoc = t.text
            continue
        cur.append(t)
        if t.text == "(":
            paren += 1
        elif t.text == ")":
            paren -= 1
        elif t.text == "{":
            depth += 1
        elif t.text == "}":
            depth -= 1
            if depth == 0 and paren == 0:
                members.append(Member(javadoc, cur))
                cur, javadoc = [], None
        elif t.text == ";" and depth == 0 and paren == 0:
            members.append(Member(javadoc, cur))
            cur, javadoc = [], None
    rest = code(cur)
    if rest:
        raise Deviation(f"trailing tokens in class body: {rest}")
    if any(t.kind in ("line", "block") for t in cur):
        raise Deviation("comment after the last member")
    return members


# --------------------------------------------------------------------------
# Pattern matching
# --------------------------------------------------------------------------

def match(pattern: str, toks) -> dict | None:
    """Matches the code tokens `toks` against `pattern`.

    `@name` captures one token; `@...name` captures the shortest balanced token
    run up to the next pattern token."""
    pat = lex(pattern, allow_captures=True)
    toks = code(toks)
    caps: dict = {}

    def go(pi, ti):
        if pi == len(pat):
            return ti == len(toks)
        p = pat[pi]
        if p.kind == "cap" and p.text.startswith("@..."):
            name = p.text[4:]
            depth = 0
            for end in range(ti, len(toks) + 1):
                if depth == 0:
                    caps[name] = toks[ti:end]
                    if go(pi + 1, end):
                        return True
                if end == len(toks):
                    break
                tx = toks[end].text
                if tx in "({[":
                    depth += 1
                elif tx in ")}]":
                    depth -= 1
                    if depth < 0:
                        break
            return False
        if ti == len(toks):
            return False
        if p.kind == "cap":
            caps[p.text[1:]] = toks[ti].text
            return go(pi + 1, ti + 1)
        if p.text != toks[ti].text:
            return False
        return go(pi + 1, ti + 1)

    return caps if go(0, 0) else None


def require(pattern, member, what):
    caps = match(pattern, member.toks)
    if caps is None:
        raise Deviation(f"{what} does not follow the template: "
                        + " ".join(t.text for t in member.code))
    return caps


