def pre_comments(jc: JavaClass) -> list[str]:
    out = []
    for c in jc.pre_comments:
        if not c.startswith("//"):
            raise Deviation(f"block comment before the class: {c[:40]!r}")
        out += ["", c]
    return out


def family_of(name: str):
    if name.endswith("Factory"):
        return "factory", factory
    if name.endswith("Analyzer"):
        return "analyzer", analyzer
    if name.endswith("StemFilter"):
        return "stem filter", stem_filter
    return None, None


def rustfmt(text: str) -> str:
    with tempfile.TemporaryDirectory() as d:
        p = Path(d) / "gen.rs"
        p.write_text(text, encoding="utf-8")
        subprocess.run(["rustfmt", "--edition", "2021", str(p)], check=True)
        return p.read_text(encoding="utf-8")


def main(argv):
    check = "--check" in argv
    listing = "--list" in argv
    args = [a for a in argv if not a.startswith("--")]
    root = Path(args[0]) if args else Path("/tmp/lucene1050")
    generated, deviating, stale = [], [], []
    for pkg in PACKAGES:
        for java in sorted((root / JAVA_REL / pkg).glob("*.java")):
            fam, fn = family_of(java.stem)
            if fam is None:
                continue
            try:
                jc = JavaClass(java)
                text = rustfmt(fn(jc, pkg))
            except Deviation as e:
                deviating.append((f"{pkg}.{java.stem}", fam, str(e)))
                continue
            target = CRATE_SRC / "analysis" / pkg / f"{snake(java.stem)}.rs"
            if not target.exists():
                raise SystemExit(f"no skeleton file {target}")
            generated.append((f"{pkg}.{java.stem}", fam))
            if check:
                if target.read_text(encoding="utf-8") != text:
                    stale.append(str(target))
            else:
                target.write_text(text, encoding="utf-8")
    if listing:
        for name, fam in generated:
            print(f"generated  {fam:12} {name}")
        for name, fam, why in deviating:
            print(f"by hand    {fam:12} {name}: {why}")
    else:
        print(f"{len(generated)} generated, {len(deviating)} deviating (translated by hand)")
    if stale:
        print("stale:", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
