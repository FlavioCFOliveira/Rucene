    if normalize:
        out += [""] + ["    " + c for c in normalize_comments]
        out += [f"    /// Equivalent to `{jc.name}.normalize(TokenStream)`, `create(input)`.",
                "    fn normalize(&self, input: Box<dyn TokenStream>) -> Result<Box<dyn TokenStream>> {",
                "        self.create(input)", "    }"]
    out += ["}"]
