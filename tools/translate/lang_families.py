def snake(name: str) -> str:
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    return s.lower()


def link_text(target: str, label: str | None) -> str:
    if label:
        return f"`{label}`"
    target = target.strip()
    if target.startswith("#"):
        target = target[1:]
    return "`" + target.replace("#", ".") + "`"


def inline(text: str) -> str:
    """Inline javadoc tags and HTML to Markdown."""
    def tag(m):
        kind, body = m.group(1), m.group(2).strip()
        if kind in ("link", "linkplain"):
            mm = re.match(r"(\S+(?:\([^)]*\))?)\s*(.*)$", body, re.S)
            return link_text(mm.group(1), mm.group(2).strip() or None)
        if kind == "code":
            return f"`{html.unescape(body)}`"
        if kind == "literal":
            return body
        if kind == "value":
            return f"`{body.lstrip('#')}`"
        raise Deviation(f"javadoc tag {{@{kind}}}")
    text = re.sub(r"\{@(\w+)\s+((?:[^{}]|\{[^{}]*\})*)\}", tag, text)
    text = re.sub(r"<a\s+href=\"([^\"]+)\"\s*>(.*?)</a>",
                  lambda m: f"[{m.group(2).strip()}]({m.group(1)})", text, flags=re.S)
    text = re.sub(r"</?(?:b|strong)>", "**", text)
    text = re.sub(r"</?(?:i|em)>", "*", text)
    text = re.sub(r"</?(?:code|tt)>", "`", text)
    text = re.sub(r"<br\s*/?>", " ", text)
    if re.search(r"<[A-Za-z/]", text):
        raise Deviation(f"unhandled HTML in javadoc: {text!r}")
    return html.unescape(text)


def javadoc_parts(jd: str | None):
    """Splits a javadoc into (blocks, tags): blocks are ('p', text) paragraphs,
    ('li', text) list items and ('pre', lines) code blocks; tags a list of
    (name, text)."""
    if jd is None:
        return [], []
    body = jd[3:-2]
    lines = []
    for raw in body.split("\n"):
        s = raw.strip()
        if s.startswith("*"):
            s = s[1:]
            if s.startswith(" "):
                s = s[1:]
        lines.append(s.rstrip())
    text = "\n".join(lines).strip()
    # tags
    tag_start = re.search(r"(?m)^@\w", text)
    tags = []
    if tag_start:
        tag_text = text[tag_start.start():]
        text = text[:tag_start.start()]
        for m in re.finditer(r"(?ms)^@([\w.]+)\s*(.*?)(?=^@[\w.]|\Z)", tag_text):
            tags.append((m.group(1), " ".join(m.group(2).split())))
    blocks = []
    # pre blocks
    parts = re.split(r"(<pre[^>]*>.*?</pre>)", text, flags=re.S)
    for part in parts:
        if part.startswith("<pre"):
            inner = re.sub(r"^<pre[^>]*>", "", part)[:-len("</pre>")]
            pre = [html.unescape(l) for l in inner.strip("\n").split("\n")]
            blocks.append(("pre", pre))
            continue
        # paragraphs and lists
        part = re.sub(r"</?ul>", "\n<p>\n", part)
        part = re.sub(r"</li>", "", part)
        for para in re.split(r"<p>|\n\s*\n", part):
            items = re.split(r"<li>", para)
            head = " ".join(items[0].split())
            if head:
                blocks.append(("p", inline(head)))
            for item in items[1:]:
                item = " ".join(item.split())
                if item:
                    blocks.append(("li", inline(item)))
    return blocks, tags


def wrap(text: str, width: int, first: str = "", rest: str = "") -> list[str]:
    words = [w for w in text.split(" ") if w]
    out, cur, filled = [], first, False
    for w in words:
        candidate = (cur + " " + w) if filled else (cur + w)
        if len(candidate) > width and filled:
            out.append(cur)
            cur = rest + w
        else:
            cur = candidate
        filled = True
    if filled:
        out.append(cur)
    return out


def render_doc(paragraphs: list, indent: int) -> list[str]:
    """Renders blocks into `///` lines for an item indented by `indent`."""
    width = 80 - indent - 4
    out = []
    prev = None
    for kind, val in paragraphs:
        if out and not (kind == "li" and prev == "li"):
            out.append("")
        if kind == "p":
            out.extend(wrap(val, width))
        elif kind == "li":
            out.extend(wrap(val, width, "* ", "  "))
        elif kind == "pre":
            out.append("```text")
            out.extend(val)
            out.append("```")
        else:
            raise AssertionError(kind)
        prev = kind
    pad = " " * indent
    return [pad + ("/// " + l if l else "///").rstrip() for l in out]


def doc_blocks(jd, extra_tags=()):
    """The javadoc's blocks plus its @param/@return/@see as list items."""
    blocks, tags = javadoc_parts(jd)
    items = []
    for name, val in tags:
        if name == "param":
            p, _, d = val.partition(" ")
            items.append(("li", f"`{snake(p)}`: {inline(d)}"))
        elif name == "return":
            items.append(("li", f"returns: {inline(val)}"))
        elif name == "see":
            items.append(("li", f"see: {inline(val)}"))
        elif name in ("since", "lucene.spi", "lucene.experimental", "lucene.internal",
                      "deprecated") or name in extra_tags:
            pass
        else:
            raise Deviation(f"javadoc tag @{name}")
    return blocks + items, dict(tags)


def claim(fqn: str, tags: dict, rest: str = ".") -> str:
    notes = []
    if "since" in tags:
        notes.append(f"since {tags['since']}")
    for t in ("lucene.experimental", "lucene.internal"):
        if t in tags:
            notes.append(f"`@{t}`")
    note = f" ({', '.join(notes)})" if notes else ""
    return f"Equivalent to `{fqn}`{note}{rest}"


def deprecated_attr(tags: dict, annotations, indent=0) -> list[str]:
    if ("deprecated" in tags) != ("Deprecated" in annotations):
        raise Deviation("@deprecated without @Deprecated, or the reverse")
    if "deprecated" not in tags:
        return []
    note = inline(tags["deprecated"]).replace('"', '\\"')
    return [" " * indent + f'#[deprecated(note = "{note}")]']


