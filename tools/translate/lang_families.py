#!/usr/bin/env python3
"""Translate the per-language class families of Lucene 10.5.0 `lucene/analysis/common`.

Three families of near-identical Java classes are generated into
`crates/rucene-analysis-common/src/analysis/<pkg>/<snake_name>.rs`:

* stem filters (`XStemFilter`, `XLightStemFilter`, `XMinimalStemFilter`): a
  keyword-aware `TokenFilter` holding a stemmer and calling
  `stemmer.stem(termAtt.buffer(), termAtt.length())` (or, in the variant,
  `stemmer.stem(termAtt.resizeBuffer(len + 1), len)`) on every non-keyword
  term;
* token filter factories (`XStemFilterFactory`, `XNormalizationFilterFactory`,
  ...): `NAME`, the `Map` constructor rejecting leftover arguments, the SPI
  default constructor, `create` building the filter from the input alone and,
  optionally, `normalize` returning `create(input)`;
* stop-word analyzers extending `StopwordAnalyzerBase`: `DEFAULT_STOPWORD_FILE`,
  optional constant `CharArraySet`s, a `DefaultSetHolder` loading the default
  stop set from a resource, the constructors `()`, `(stopwords)` and
  `(stopwords, stemExclusionSet)`, and a `createComponents` / `normalize` built
  from a `StandardTokenizer` and a chain of known filters.

Every Java class is matched token for token (comments aside) against its
family's template, with only the varying parts captured: class, stemmer and
filter names, `NAME`, resources, constants, the filter chain, the
error-message text, and the javadoc. A class that deviates from its template
in any other way is reported, with the reason, and not generated: those
classes are translated by hand. Comments inside method bodies are carried
over; one the template does not place fails the class.

The output is formatted by `rustfmt` and is the committed code: rerunning the
script leaves the files unchanged.

Usage: python3 tools/translate/lang_families.py [--check] [--list] [LUCENE_ROOT]
(default LUCENE_ROOT: /tmp/lucene1050). `--check` compares instead of
writing; `--list` prints, per class, `generated` or the deviation.
"""

