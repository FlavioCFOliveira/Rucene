#!/usr/bin/env python3
"""Translates the `switch` of Lucene's `ASCIIFoldingFilter.foldToASCII` into Rust.

Reads `ASCIIFoldingFilter.java` of Lucene 10.5.0 and rewrites the region of
`crates/rucene-analysis-common/src/analysis/miscellaneous/ascii_folding_filter.rs`
between the `BEGIN GENERATED` and `END GENERATED` markers with an equivalent
`match`, one arm per Java case group, keeping the Java comments, then formats the
file with `rustfmt`. Deterministic: the same Java source yields the same file.

Usage:
    python3 tools/translate/ascii_folding_filter.py [LUCENE_SRC_ROOT]

`LUCENE_SRC_ROOT` defaults to `/tmp/lucene1050`.
"""

import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
TARGET = (
    REPO
    / "crates/rucene-analysis-common/src/analysis/miscellaneous/ascii_folding_filter.rs"
)
JAVA_REL = (
    "lucene/analysis/common/src/java/org/apache/lucene/analysis/miscellaneous/"
    "ASCIIFoldingFilter.java"
)
BEGIN = "// BEGIN GENERATED by tools/translate/ascii_folding_filter.py"
END = "// END GENERATED by tools/translate/ascii_folding_filter.py"

CASE_RE = re.compile(r"^\s*case '\\u([0-9A-F]{4})':\s*//\s*(.*?)\s*$")
OUT_RE = re.compile(r"^\s*output\[outputPos\+\+\] = (.+);\s*$")


def rust_char(java_literal: str) -> str:
    """Returns the Rust expression for a Java `char` expression of the switch."""
    if java_literal == "c":
        return "c"
    m = re.fullmatch(r"'(.|\\\\|\\')'", java_literal)
    if not m:
        raise ValueError(f"unexpected output literal {java_literal!r}")
    return java_literal  # Java and Rust spell these literals the same way


def parse_switch(java: str):
    """Returns the case groups as (cases, outputs) with cases [(hex, comment)]."""
    lines = java.splitlines()
    start = next(i for i, line in enumerate(lines) if "switch (c) {" in line)
    groups = []
    cases, outputs = [], []
    default = None
    i = start + 1
    while i < len(lines):
        line = lines[i]
        m = CASE_RE.match(line)
        if m:
            if outputs:
                raise ValueError(f"case after outputs at line {i + 1}")
            cases.append((m.group(1), m.group(2)))
        elif line.strip() == "default:":
            default = []
            cases = None
        elif OUT_RE.match(line):
            target = default if cases is None else outputs
            target.append(rust_char(OUT_RE.match(line).group(1)))
        elif line.strip() == "break;":
            if cases is None:
                break
            groups.append((cases, outputs))
            cases, outputs = [], []
        elif line.strip():
            raise ValueError(f"unexpected line {i + 1}: {line!r}")
        i += 1
    return groups, default


def render(groups, default, indent: str) -> str:
    out = [indent + BEGIN, indent + "match c {"]
    for cases, outputs in groups:
        for n, (hexcode, comment) in enumerate(cases):
            sep = "" if n == 0 else "| "
            comment = comment.replace("\t", " ")
            out.append(f"{indent}    {sep}'\\u{{{hexcode}}}' // {comment}")
        out.append(f"{indent}    => {{")
        for value in outputs:
            out.append(f"{indent}        output[output_pos] = {value};")
            out.append(f"{indent}        output_pos += 1;")
        out.append(f"{indent}    }}")
    out.append(f"{indent}    _ => {{")
    for value in default:
        out.append(f"{indent}        output[output_pos] = {value};")
        out.append(f"{indent}        output_pos += 1;")
    out.append(f"{indent}    }}")
    out.append(indent + "}")
    out.append(indent + END)
    return "\n".join(out)


def main() -> None:
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("/tmp/lucene1050")
    java = (root / JAVA_REL).read_text(encoding="utf-8")
    groups, default = parse_switch(java)
    rust = TARGET.read_text(encoding="utf-8")
    begin = rust.index(BEGIN)
    end = rust.index(END) + len(END)
    line_start = rust.rindex("\n", 0, begin) + 1
    indent = rust[line_start:begin]
    rust = rust[:line_start] + render(groups, default, indent) + rust[end:]
    TARGET.write_text(rust, encoding="utf-8")
    subprocess.run(["rustfmt", "--edition", "2021", str(TARGET)], check=True)
    print(f"{TARGET}: {len(groups)} case groups, "
          f"{sum(len(c) for c, _ in groups)} case labels")


if __name__ == "__main__":
    main()
