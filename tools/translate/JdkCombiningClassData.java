// Generates crates/rucene-queryparser/src/jdk/combining_class_data.rs: the
// canonical combining class `sun.text.Normalizer.getCombiningClass(int)`
// gives every code point on the running JDK (run it with JDK 25; see
// tools/translate/README.md for the command line, which exports the JDK
// internal package read below). String.toLowerCase(Locale) reads it, through
// java.lang.ConditionalSpecialCasing, for the Lithuanian, Turkish and Azeri
// conditions (AFTER_SOFT_DOTTED, MORE_ABOVE, AFTER_I, NOT_BEFORE_DOT).
// Deterministic: the code points are walked in order, and only the runs of a
// non-zero class are written.
import java.lang.reflect.Method;

public class JdkCombiningClassData {
  public static void main(String[] args) throws Exception {
    if (Runtime.version().feature() != 25) throw new IllegalStateException("run with JDK 25");
    Method m = Class.forName("sun.text.Normalizer").getMethod("getCombiningClass", int.class);
    StringBuilder out = new StringBuilder();
    out.append("// @generated by tools/translate/JdkCombiningClassData.java on ")
        .append(System.getProperty("java.vm.name")).append(' ').append(Runtime.version().feature())
        .append(". Do not edit.\n\n");
    out.append("//! `sun.text.Normalizer.getCombiningClass(int)` of JDK 25: the runs of\n");
    out.append("//! code points with a non-zero canonical combining class, as\n");
    out.append("//! `(first, last, class)`, sorted.\n\n");
    out.append("/// The runs of a non-zero canonical combining class.\n");
    out.append("pub(super) static COMBINING_CLASSES: &[(u32, u32, u8)] = &[\n");
    int runStart = -1, runClass = 0, runs = 0;
    for (int cp = 0; cp <= 0x110000; cp++) {
      int cc = cp <= 0x10FFFF ? (Integer) m.invoke(null, cp) : 0;
      if (runStart >= 0 && cc != runClass) {
        out.append("    (0x").append(Integer.toHexString(runStart).toUpperCase()).append(", 0x")
            .append(Integer.toHexString(cp - 1).toUpperCase()).append(", ").append(runClass).append("),\n");
        runs++;
        runStart = -1;
      }
      if (runStart < 0 && cc != 0) {
        runStart = cp;
        runClass = cc;
      }
    }
    out.append("];\n");
    try (java.io.Writer w = new java.io.OutputStreamWriter(new java.io.FileOutputStream(args[0]), "UTF-8")) {
      w.write(out.toString());
    }
    System.err.println("runs=" + runs);
  }
}
