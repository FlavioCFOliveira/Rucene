// running JDK's public java.lang.Character API (run it with JDK 25):
//
//   java tools/translate/JdkCharacterTypeData.java \
//     > crates/rucene-analysis-common/src/jdk/character_type_data.rs
//
// Deterministic: the output depends only on the JDK's Unicode data.
public class JdkCharacterTypeData {
  public static void main(String[] args) {
    StringBuilder out = new StringBuilder();
    out.append(String.join("\n",
        "/*",
        " * Licensed to the Apache Software Foundation (ASF) under one or more",
        " * contributor license agreements.  See the NOTICE file distributed with",
        " * this work for additional information regarding copyright ownership.",
        " * The ASF licenses this file to You under the Apache License, Version 2.0",
        " * (the \"License\"); you may not use this file except in compliance with",
        " * the License.  You may obtain a copy of the License at",
        " *",
        " *     http://www.apache.org/licenses/LICENSE-2.0",
        " *",
        " * Unless required by applicable law or agreed to in writing, software",
        " * distributed under the License is distributed on an \"AS IS\" BASIS,",
        " * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.",
        " * See the License for the specific language governing permissions and",
        " * limitations under the License.",
        " */",
        "",
        "//! `java.lang.Character.getType(int)`, `isLowerCase(int)` and",
        "//! `isUpperCase(int)` data of the JDK that runs Lucene 10.5.0, as",
        "//! [`character`](super::character) reads it.",
        "//!",
        "//! Generated by `tools/translate/JdkCharacterTypeData.java` from OpenJDK "
            + Runtime.version() + " (Unicode data of the JDK's",
        "//! `java.lang.Character`), which calls the public API for every code point;",
        "//! no JDK code is reproduced. Do not edit by hand.",
        "",
        "/// `Character.getType(int)` for every code point, as runs `(first, last, type)`",
        "/// of consecutive code points sharing one general category, in order; the",
        "/// types are the values of Java's `Character` category constants.",
        "pub(super) const TYPES: &[(u32, u32, u8)] = &[",
        ""));
    int start = 0;
    int type = Character.getType(0);
    for (int c = 1; c <= 0x110000; c++) {
      int t = c == 0x110000 ? -1 : Character.getType(c);
      if (t != type) {
        out.append(String.format("    (0x%04X, 0x%04X, %d),%n", start, c - 1, type));
        start = c;
        type = t;
      }
    }
    out.append("];\n\n");
    out.append("/// The code points below U+0100 `Character.isLowerCase(int)` accepts.\n");
    out.append("pub(super) const LATIN1_LOWER_CASE: &[u8] = &[");
    appendLatin1(out, true);
    out.append("];\n\n");
    out.append("/// The code points below U+0100 `Character.isUpperCase(int)` accepts.\n");
    out.append("pub(super) const LATIN1_UPPER_CASE: &[u8] = &[");
    appendLatin1(out, false);
    out.append("];\n");
    System.out.print(out);
  }

  private static void appendLatin1(StringBuilder out, boolean lower) {
    boolean first = true;
    for (int c = 0; c < 256; c++) {
      if (lower ? Character.isLowerCase(c) : Character.isUpperCase(c)) {
        if (!first) out.append(", ");
        out.append(String.format("0x%02X", c));
        first = false;
      }
    }
  }
}
