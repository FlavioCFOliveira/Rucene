def rust_file(model: ClassModel, java_path: Path) -> str:
    name = model.name
    fname = java_path.name
    routine_rust = {}
    for rname, _, _ in model.methods:
        rs = snake(rname)
        if rs in routine_rust.values():
            raise TranslationError(f"{fname}: routine names collide on {rs}")
        routine_rust[rname] = rs
    field_rust = [snake(f) for f, _ in model.fields]
    if len(set(field_rust)) != len(field_rust):
        raise TranslationError(f"{fname}: field names collide in snake case")
    statics = [n.upper() for n, _ in model.ambs] + [n.upper() for n, _ in model.groupings]
    if len(set(statics)) != len(statics):
        raise TranslationError(f"{fname}: table names collide in upper case")

    used_methods = {e[3] for _, entries in model.ambs for e in entries if e[3]}
    if used_methods and not model.has_method_object:
        raise TranslationError(f"{fname}: Among routines without methodObject")
    if model.has_method_object and not used_methods:
        raise TranslationError(f"{fname}: methodObject without Among routines")
    for rname, public, _ in model.methods:
        if public != (rname in used_methods):
            raise TranslationError(f"{fname}: routine {rname} public={public} but Among use differs")

    o: list[str] = []
    o.append(GENERATOR_LINE)
    o.append("//")
    o.append(f"// Translated from Lucene 10.5.0 `{JAVA_REL}/{fname}` by")
    o.append("// `tools/translate/snowball_java_to_rust.py`: do not edit, rerun the translator.")
    o.append("")
    o.append(f"//! This class implements the stemming algorithm defined by a snowball script, ported from")
    o.append(f"//! `org.tartarus.snowball.ext.{name}`.")
    o.append("//!")
    o.append("//! Generated by Snowball 2.2.0 - <https://snowballstem.org/>")
    o.append("")
    o.append("// Java: `@SuppressWarnings(\"unused\")`; and the style lints of a statement-for-statement")
    o.append("// translation of generated code (see `tools/translate/snowball_java_to_rust.py`).")
    o.append("#![allow(")
    for lint in ALLOWED_LINTS:
        o.append(f"    {lint},")
    o.append(")]")
    o.append("")
    o.append("use std::hash::{Hash, Hasher};")
    o.append("")
    o.append("use rucene::util::java_collections::java_string_hash_code;")
    o.append("")
    o.append("use crate::tartarus::snowball::among::Among;")
    o.append("use crate::tartarus::snowball::snowball_program::{utf16, SnowballProgram};")
    o.append("use crate::tartarus::snowball::snowball_stemmer::SnowballStemmer;")
    o.append("")
    for aname, entries in model.ambs:
        where = f"{fname}:{aname}"
        o.append(f"static {aname.upper()}: [Among<{name}>; {len(entries)}] = [")
        for s, sub, res, meth in entries:
            lit = rust_string(s, where)
            if meth:
                if meth not in routine_rust:
                    raise TranslationError(f"{where}: Among names unknown routine {meth}")
                o.append(f"    Among::with_method(utf16!({lit}), {sub}, {res}, {name}::{routine_rust[meth]}),")
            else:
                o.append(f"    Among::new(utf16!({lit}), {sub}, {res}),")
        o.append("];")
        o.append("")
    for gname, values in model.groupings:
        o.append(f"static {gname.upper()}: [u16; {len(values)}] = [{', '.join(str(v) for v in values)}];")
        o.append("")

    o.append("/// This class implements the stemming algorithm defined by a snowball script.")
    o.append("///")
    o.append("/// Generated by Snowball 2.2.0 - <https://snowballstem.org/>")
    o.append("///")
    o.append(f"/// Equivalent to `org.tartarus.snowball.ext.{name}`, which extends")
    o.append("/// `org.tartarus.snowball.SnowballStemmer`: the superclass state is `base`.")
    o.append("#[derive(Debug)]")
    o.append(f"pub struct {name} {{")
    o.append("    base: SnowballProgram,")
    for (fname_java, kind), rs in zip(model.fields, field_rust):
        rtype = {"int": "i32", "boolean": "bool", "StringBuilder": "Vec<u16>"}[kind]
        jtype = {"int": "int", "boolean": "boolean", "StringBuilder": "java.lang.StringBuilder"}[kind]
        o.append(f"    /// Java: `private {jtype} {fname_java}`.")
        o.append(f"    {rs}: {rtype},")
    o.append("}")
    o.append("")
    o.append(f"impl Default for {name} {{")
    o.append("    fn default() -> Self {")
    o.append("        Self::new()")
    o.append("    }")
    o.append("}")
    o.append("")
    o.append(f"impl {name} {{")
    o.append(f"    /// Equivalent to the implicit public constructor `{name}()`.")
    o.append("    pub fn new() -> Self {")
    o.append("        Self {")
    o.append("            base: SnowballProgram::new(),")
    for (_, kind), rs in zip(model.fields, field_rust):
        init = {"int": "0", "boolean": "false", "StringBuilder": "Vec::new()"}[kind]
        o.append(f"            {rs}: {init},")
    o.append("        }")
    o.append("    }")
    for rname, public, body in model.methods:
        o.append("")
        if public:
            o.append(f"    /// Java: `public boolean {rname}()`, named by an `Among` entry.")
        vis = "pub " if public else ""
        o.append(f"    {vis}fn {routine_rust[rname]}(&mut self) -> bool {{")
        o.extend("        " + ln for ln in MethodTranslator(model, fname, body).translate())
        o.append("    }")
    o.append("")
    o.append(f"    /// Equivalent to `hashCode()`: `{name}.class.getName().hashCode()`.")
    o.append("    pub fn java_hash_code(&self) -> i32 {")
    o.append(f'        java_string_hash_code("org.tartarus.snowball.ext.{name}")')
    o.append("    }")
    o.append("}")
    o.append("")
    o.append(f"impl AsRef<SnowballProgram> for {name} {{")
    o.append("    fn as_ref(&self) -> &SnowballProgram {")
    o.append("        &self.base")
    o.append("    }")
    o.append("}")
    o.append("")
    o.append(f"impl AsMut<SnowballProgram> for {name} {{")
    o.append("    fn as_mut(&mut self) -> &mut SnowballProgram {")
    o.append("        &mut self.base")
    o.append("    }")
    o.append("}")
    o.append("")
    o.append(f"impl SnowballStemmer for {name} {{")
    o.append("    fn stem(&mut self) -> bool {")
    o.extend("        " + ln for ln in MethodTranslator(model, fname, model.stem_body).translate())
    o.append("    }")
    o.append("}")
    o.append("")
    o.append(f"/// Equivalent to `equals(Object o)`: `o instanceof {name}`, so any two")
    o.append("/// instances are equal.")
    o.append(f"impl PartialEq for {name} {{")
    o.append("    fn eq(&self, _other: &Self) -> bool {")
    o.append("        true")
    o.append("    }")
    o.append("}")
    o.append("")
    o.append(f"impl Eq for {name} {{}}")
    o.append("")
    o.append(f"/// Hashes [`{name}::java_hash_code`], Java's `hashCode()`.")
    o.append(f"impl Hash for {name} {{")
    o.append("    fn hash<H: Hasher>(&self, state: &mut H) {")
    o.append("        self.java_hash_code().hash(state);")
    o.append("    }")
    o.append("}")
    o.append("")
    return "\n".join(o)


def main(argv: list[str]) -> int:
    args = [a for a in argv[1:] if not a.startswith("--")]
    coverage = "--coverage" in argv
    lucene = Path(args[0]) if args else Path("/tmp/lucene1050")
    java_dir = lucene / JAVA_REL
    files = sorted(java_dir.glob("*Stemmer.java"))
    if len(files) != 30:
        raise TranslationError(f"expected 30 stemmers in {java_dir}, found {len(files)}")
    written = []
    for java_path in files:
        model = parse_class(java_path)
        text = rust_file(model, java_path)
        out = OUT_DIR / f"{snake_class(model.name)}.rs"
        out.write_text(text, encoding="utf-8")
        written.append(out)
    subprocess.run(["rustfmt", "--edition", "2021", *map(str, written)], check=True)
    if coverage:
        for construct, n in sorted(COVERAGE.items()):
            print(f"{n:7d}  {construct}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv))
    except TranslationError as e:
        print(f"snowball_java_to_rust: {e}", file=sys.stderr)
        sys.exit(1)
