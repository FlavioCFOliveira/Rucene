class ClassModel:
    def __init__(self, name: str):
        self.name = name
        self.ambs: list[tuple[str, list[tuple[str, int, int, str | None]]]] = []
        self.groupings: list[tuple[str, list[int]]] = []
        self.fields: list[tuple[str, str]] = []  # (java name, kind)
        self.methods: list[tuple[str, bool, list[tuple[int, str]]]] = []  # name, public, body
        self.stem_body: list[tuple[int, str]] | None = None
        self.has_method_object = False

    def field_kind(self, name: str) -> str | None:
        for fname, kind in self.fields:
            if fname == name:
                return kind
        return None

    def routine_names(self) -> set[str]:
        return {m[0] for m in self.methods}


AMONG_RE = re.compile(r'new Among\(("(?:[^"\\]|\\.)*"), (-?\d+), (-?\d+)(?:, "([A-Za-z0-9_]+)", methodObject)?\)')


def parse_among_entries(text: str, where: str) -> list[tuple[str, int, int, str | None]]:
    entries = []
    pos = 0
    text = text.strip()
    while pos < len(text):
        m = AMONG_RE.match(text, pos)
        if not m:
            raise TranslationError(f"{where}: unknown Among entry near {text[pos:pos + 60]!r}")
        entries.append((m.group(1), int(m.group(2)), int(m.group(3)), m.group(4)))
        pos = m.end()
        rest = text[pos:]
        stripped = rest.lstrip()
        if stripped.startswith(","):
            pos = len(text) - len(stripped) + 1
            while pos < len(text) and text[pos].isspace():
                pos += 1
        elif stripped == "":
            break
        else:
            raise TranslationError(f"{where}: unexpected text after Among entry: {rest[:40]!r}")
    return entries


def brace_delta(line: str) -> int:
    no_strings = re.sub(r'"(?:[^"\\]|\\.)*"', '""', line)
    return no_strings.count("{") - no_strings.count("}")


def parse_class(path: Path) -> ClassModel:
    lines = path.read_text(encoding="utf-8").split("\n")
    fname = path.name
    name = path.stem
    model = ClassModel(name)

    def where(i: int) -> str:
        return f"{fname}:{i + 1}"

    expected_head = [
        GENERATOR_LINE,
        "",
        "package org.tartarus.snowball.ext;",
        "",
        "import org.tartarus.snowball.Among;",
        "",
        "/**",
        " * This class implements the stemming algorithm defined by a snowball script.",
        " *",
        " * <p>Generated by Snowball 2.2.0 - https://snowballstem.org/",
        " */",
        '@SuppressWarnings("unused")',
        f"public class {name} extends org.tartarus.snowball.SnowballStemmer {{",
        "",
        "  private static final long serialVersionUID = 1L;",
    ]
    for k, exp in enumerate(expected_head):
        if lines[k] != exp:
            raise TranslationError(f"{where(k)}: expected {exp!r}, found {lines[k]!r}")
    count("header: generator comment, package, import, class javadoc")
    count('@SuppressWarnings("unused")')
    count("serialVersionUID field")

    i = len(expected_head)
    while i < len(lines):
        line = lines[i]
        s = line.strip()
        if s == "":
            i += 1
            continue
        if line == "}":
            rest = [ln for ln in lines[i + 1:] if ln.strip()]
            if rest:
                raise TranslationError(f"{where(i)}: text after the class body")
            break
        if s == "private static final java.lang.invoke.MethodHandles.Lookup methodObject =":
            if lines[i + 1].strip() != "java.lang.invoke.MethodHandles.lookup();":
                raise TranslationError(f"{where(i + 1)}: unknown methodObject initialiser")
            model.has_method_object = True
            count("methodObject (MethodHandles.lookup) field")
            i += 2
            continue
        m = re.match(r"private static final Among (a_\d+)\[\] = \{(.*)$", s)
        if m:
            text = m.group(2)
            j = i
            while not text.rstrip().endswith("};"):
                j += 1
                text += " " + lines[j].strip()
            text = text.rstrip()[:-2]
            entries = parse_among_entries(text, where(i))
            model.ambs.append((m.group(1), entries))
            count("Among table")
            for entry in entries:
                count("Among entry with routine" if entry[3] else "Among entry")
            i = j + 1
            continue
        m = re.match(r"private static final char (g_[A-Za-z0-9_]+)\[\] = \{(.*)$", s)
        if m:
            text = m.group(2)
            j = i
            while not text.rstrip().endswith("};"):
                j += 1
                text += " " + lines[j].strip()
            text = text.rstrip()[:-2]
            values = [int(v.strip()) for v in text.split(",") if v.strip()]
            for v in values:
                if not 0 <= v <= 0xFFFF:
                    raise TranslationError(f"{where(i)}: grouping value {v} is not a char")
            model.groupings.append((m.group(1), values))
            count("grouping (char[] bitmap)")
            i = j + 1
            continue
        m = re.match(r"private (int|boolean) ([IB]_[A-Za-z0-9_]+);$", s)
        if m:
            kind = m.group(1)
            if (kind == "int") != m.group(2).startswith("I_"):
                raise TranslationError(f"{where(i)}: field prefix does not match its type")
            model.fields.append((m.group(2), kind))
            count(f"{kind} field")
            i += 1
            continue
        m = re.match(r"private java\.lang\.StringBuilder (S_[A-Za-z0-9_]+) = new java\.lang\.StringBuilder\(\);$", s)
        if m:
            model.fields.append((m.group(1), "StringBuilder"))
            count("StringBuilder field")
            i += 1
            continue
        m = re.match(r"(private|public) boolean (r_[A-Za-z0-9_]+)\(\) \{$", s)
        if m and line.startswith("  ") and not line.startswith("   "):
            body, i = collect_body(lines, i, where)
            model.methods.append((m.group(2), m.group(1) == "public", body))
            count(f"{m.group(1)} routine")
            continue
        if s == "@Override":
            nxt = lines[i + 1].strip()
            if nxt == "public boolean stem() {":
                body, i = collect_body(lines, i + 1, where)
                model.stem_body = body
                count("stem() override")
                continue
            if nxt == "public boolean equals(Object o) {":
                exp = [f"return o instanceof {name};", "}"]
                if [lines[i + 2].strip(), lines[i + 3].strip()] != exp:
                    raise TranslationError(f"{where(i + 2)}: unknown equals body")
                count("equals(Object) (instanceof)")
                i += 4
                continue
            if nxt == "public int hashCode() {":
                exp = [f"return {name}.class.getName().hashCode();", "}"]
                if [lines[i + 2].strip(), lines[i + 3].strip()] != exp:
                    raise TranslationError(f"{where(i + 2)}: unknown hashCode body")
                count("hashCode() (class name hash)")
                i += 4
                continue
            raise TranslationError(f"{where(i + 1)}: unknown @Override member {nxt!r}")
        raise TranslationError(f"{where(i)}: unknown class member {s!r}")
    if model.stem_body is None:
        raise TranslationError(f"{fname}: no stem() method")
    return model


def collect_body(lines: list[str], i: int, where) -> tuple[list[tuple[int, str]], int]:
    """The statements of the method opening at line i: (line index, stripped text)."""
    depth = brace_delta(lines[i])
    body = []
    j = i + 1
    while True:
        line = lines[j]
        d = brace_delta(line)
        if depth + d == 0:
            if line.strip() != "}":
                raise TranslationError(f"{where(j)}: method does not end with a lone brace")
            return body, j + 1
        depth += d
        if line.strip():
            body.append((j, line.strip()))
        j += 1


