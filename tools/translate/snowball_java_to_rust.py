class Frame:
    def __init__(self, kind: str, label: str | None = None, ident: int = 0, var: str | None = None):
        self.kind = kind  # block | lab | loop | for | if | switch | case
        self.label = label
        self.ident = ident
        self.var = var
        self.needs_label = False
        self.terminated = False


class MethodTranslator:
    def __init__(self, model: ClassModel, fname: str, body: list[tuple[int, str]]):
        self.model = model
        self.fname = fname
        self.body = body
        self.out: list[str] = []
        self.stack: list[Frame] = []
        self.loop_counter = 0
        self.loops: dict[int, Frame] = {}
        self.locals: set[str] = set()
        self.pending_label: str | None = None

    def where(self, idx: int) -> str:
        return f"{self.fname}:{self.body[idx][0] + 1}"

    # -- expressions ------------------------------------------------------------------

    def field(self, name: str, where: str) -> str:
        if name in PROGRAM_FIELDS:
            return f"self.base.{name}"
        if re.match(r"[IBS]_", name):
            if self.model.field_kind(name) is None:
                raise TranslationError(f"{where}: undeclared field {name}")
            return f"self.{snake(name)}"
        if name in self.locals:
            return name
        raise TranslationError(f"{where}: unknown identifier {name}")

    def string_arg(self, tokens: list[str], where: str) -> str:
        if len(tokens) != 1:
            raise TranslationError(f"{where}: expected a string or StringBuilder argument")
        tok = tokens[0]
        if tok.startswith('"'):
            count("string literal argument (utf16!)")
            return f"utf16!({rust_string(tok, where)})"
        if re.match(r"S_[A-Za-z0-9_]+$", tok) and self.model.field_kind(tok) == "StringBuilder":
            count("StringBuilder argument")
            return f"&self.{snake(tok)}"
        raise TranslationError(f"{where}: unsupported string argument {tok}")

    def call(self, callee: str, args: list[list[str]], where: str) -> str:
        if callee in GROUPING_CALLS:
            if len(args) != 3 or len(args[0]) != 1 or not re.match(r"g_[A-Za-z0-9_]+$", args[0][0]):
                raise TranslationError(f"{where}: bad {callee} arguments")
            g = args[0][0]
            if g not in {n for n, _ in self.model.groupings}:
                raise TranslationError(f"{where}: unknown grouping {g}")
            lo, hi = (self.int_literal(a, where) for a in args[1:])
            count(f"call {callee}")
            return f"self.base.{callee}(&{g.upper()}, {lo}, {hi})"
        if callee in STRING_CALLS:
            if len(args) != 1:
                raise TranslationError(f"{where}: bad {callee} arguments")
            count(f"call {callee}")
            return f"self.base.{callee}({self.string_arg(args[0], where)})"
        if callee == "slice_del":
            if args:
                raise TranslationError(f"{where}: slice_del takes no argument")
            count("call slice_del")
            return "self.base.slice_del()"
        if callee == "slice_to":
            if len(args) != 1 or len(args[0]) != 1 or self.model.field_kind(args[0][0]) != "StringBuilder":
                raise TranslationError(f"{where}: bad slice_to argument")
            count("call slice_to")
            return f"self.base.slice_to(&mut self.{snake(args[0][0])})"
        if callee == "insert":
            if len(args) != 3:
                raise TranslationError(f"{where}: bad insert arguments")
            a = self.expr(args[0], where)
            b = self.expr(args[1], where)
            count("call insert")
            return f"self.base.insert({a}, {b}, {self.string_arg(args[2], where)})"
        if callee in AMONG_CALLS:
            if len(args) != 1 or len(args[0]) != 1 or not re.match(r"a_\d+$", args[0][0]):
                raise TranslationError(f"{where}: bad {callee} argument")
            a = args[0][0]
            if a not in {n for n, _ in self.model.ambs}:
                raise TranslationError(f"{where}: unknown among table {a}")
            count(f"call {callee}")
            return f"SnowballProgram::{callee}(self, &{a.upper()})"
        if callee.startswith("r_"):
            if args:
                raise TranslationError(f"{where}: routine call with arguments")
            if callee not in self.model.routine_names():
                raise TranslationError(f"{where}: unknown routine {callee}")
            count("call routine r_*")
            return f"self.{snake(callee)}()"
        raise TranslationError(f"{where}: unknown call {callee}")

    def int_literal(self, tokens: list[str], where: str) -> str:
        if len(tokens) == 1 and tokens[0].isdigit():
            return tokens[0]
        raise TranslationError(f"{where}: expected an int literal, found {' '.join(tokens)}")

    def expr(self, tokens: list[str], where: str) -> str:
        out = []
        i = 0
        while i < len(tokens):
            tok = tokens[i]
            if re.match(r"[A-Za-z_]", tok):
                if i + 1 < len(tokens) and tokens[i + 1] == "(":
                    depth = 0
                    j = i + 1
                    args: list[list[str]] = [[]]
                    while True:
                        t = tokens[j]
                        if t == "(":
                            depth += 1
                            if depth > 1:
                                args[-1].append(t)
                        elif t == ")":
                            depth -= 1
                            if depth == 0:
                                break
                            args[-1].append(t)
                        elif t == "," and depth == 1:
                            args.append([])
                        else:
                            args[-1].append(t)
                        j += 1
                    if args == [[]]:
                        args = []
                    out.append(self.call(tok, args, where))
                    i = j + 1
                    continue
                if tok in ("true", "false"):
                    out.append(tok)
                else:
                    out.append(self.field(tok, where))
                i += 1
                continue
            if tok.startswith('"'):
                raise TranslationError(f"{where}: string literal outside a call")
            out.append(tok)
            i += 1
        text = ""
        for k, piece in enumerate(out):
            if k == 0:
                text = piece
            elif piece in (")", ",") or out[k - 1] in ("(", "!"):
                text += piece if piece != "," else ", "
            else:
                text += " " + piece
        return text.replace(", ", ", ").replace("( ", "(")

    def cond(self, inner: str, where: str) -> str:
        return self.expr(tokenize(inner, where), where)

    # -- statements -------------------------------------------------------------------

    def emit(self, text: str) -> None:
        self.out.append(text)

    def mark_statement(self, where: str) -> None:
        top = self.stack[-1] if self.stack else None
        if top is not None and top.kind == "case" and top.terminated:
            raise TranslationError(f"{where}: statement after the end of a case")

    def scope_assignments(self, idx: int, name: str) -> tuple[int, bool]:
        """Assignments of local `name` after its declaration at idx, within its scope:
        (count, whether one happens inside a loop opened after the declaration)."""
        depth = 0
        loop_depths: list[int] = []
        n = 0
        in_loop = False
        assign = re.compile(rf"(^|[^A-Za-z0-9_]){re.escape(name)}\s*(=(?!=)|\+=|-=|\+\+|--)")
        for k in range(idx + 1, len(self.body)):
            s = self.body[k][1]
            d = brace_delta(s)
            if s.startswith("while (") or s.startswith("for ("):
                loop_depths.append(depth)
            if assign.search(s):
                n += 1
                if loop_depths:
                    in_loop = True
            depth += d
            while loop_depths and depth <= loop_depths[-1]:
                loop_depths.pop()
            if depth < 0:
                break
        return n, in_loop

    def break_target(self, kinds: set[str]) -> tuple[Frame, bool]:
        """The innermost frame of `kinds`, and whether a labelled block lies between."""
        crossed_lab = False
        for frame in reversed(self.stack):
            if frame.kind in kinds:
                return frame, crossed_lab
            if frame.kind == "lab":
                crossed_lab = True
        raise TranslationError("no enclosing construct")

    def loop_label(self, frame: Frame) -> str:
        if frame.label:
            return frame.label
        frame.needs_label = True
        return f"loop{frame.ident}"

    def translate(self) -> list[str]:
        for idx, (_, s) in enumerate(self.body):
            w = self.where(idx)
            self.statement(idx, s, w)
        if self.stack:
            raise TranslationError(f"{self.fname}: unbalanced method body")
        if self.pending_label:
            raise TranslationError(f"{self.fname}: dangling label")
        result = []
        for line in self.out:
            m = re.match(r"@@LOOP(\d+)@@(.*)$", line)
            if m:
                frame = self.loops[int(m.group(1))]
                prefix = f"'{frame.label}: " if frame.label else (
                    f"'loop{frame.ident}: " if frame.needs_label else "")
                line = prefix + m.group(2)
            result.append(line)
        return result

    def statement(self, idx: int, s: str, w: str) -> None:
        if self.pending_label is not None and s not in ("{", "while (true) {"):
            raise TranslationError(f"{w}: label not followed by a block or loop")

        m = re.match(r"((?:go)?lab\d+):$", s)
        if m:
            self.mark_statement(w)
            self.pending_label = m.group(1)
            return

        if s == "{":
            if self.pending_label is not None:
                self.stack.append(Frame("lab", self.pending_label))
                self.emit(f"'{self.pending_label}: {{")
                if not self.pending_label.startswith("lab"):
                    raise TranslationError(f"{w}: loop label on a block")
                count("labelled block (lab: { ... })")
                self.pending_label = None
            else:
                self.mark_statement(w)
                self.stack.append(Frame("block"))
                self.emit("{")
                count("anonymous block")
            return

        if s == "while (true) {":
            label = self.pending_label
            if label is not None:
                if not label.startswith("golab"):
                    raise TranslationError(f"{w}: block label on a loop")
                count("labelled loop (golab: while (true))")
            else:
                self.mark_statement(w)
                count("unlabelled loop (while (true))")
            self.pending_label = None
            self.loop_counter += 1
            frame = Frame("loop", label, self.loop_counter)
            self.loops[frame.ident] = frame
            self.stack.append(frame)
            self.emit(f"@@LOOP{frame.ident}@@loop {{")
            return

        m = re.match(r"for \(int (v_\d+) = (\d+); \1 > 0; \1--\) \{$", s)
        if m:
            self.mark_statement(w)
            var = m.group(1)
            self.locals.add(var)
            self.loop_counter += 1
            frame = Frame("for", None, self.loop_counter, var)
            self.loops[frame.ident] = frame
            self.stack.append(frame)
            self.emit("{")
            self.emit(f"let mut {var}: i32 = {m.group(2)};")
            self.emit(f"@@LOOP{frame.ident}@@while {var} > 0 {{")
            count("counted loop (for v = N; v > 0; v--)")
            return

        m = re.match(r"if \((.*)\) \{$", s)
        if m:
            self.mark_statement(w)
            self.stack.append(Frame("if"))
            self.emit(f"if {self.cond(m.group(1), w)} {{")
            count("if")
            return

        m = re.match(r"switch \(among_var\) \{$", s)
        if m:
            self.mark_statement(w)
            if "among_var" not in self.locals:
                raise TranslationError(f"{w}: switch on an undeclared among_var")
            self.stack.append(Frame("switch"))
            self.emit("match among_var {")
            count("switch (among_var)")
            return

        m = re.match(r"case (\d+):$", s)
        if m:
            top = self.stack[-1] if self.stack else None
            if top is not None and top.kind == "case":
                if not top.terminated:
                    raise TranslationError(f"{w}: case falls through")
                self.stack.pop()
                self.emit("}")
                top = self.stack[-1]
            if top is None or top.kind != "switch":
                raise TranslationError(f"{w}: case outside a switch")
            self.stack.append(Frame("case"))
            self.emit(f"{m.group(1)} => {{")
            count("case")
            return

        if s == "}":
            if not self.stack:
                raise TranslationError(f"{w}: unbalanced brace")
            frame = self.stack.pop()
            if frame.kind == "case":
                if not frame.terminated:
                    raise TranslationError(f"{w}: last case falls off the switch")
                self.emit("}")
                switch = self.stack.pop()
                if switch.kind != "switch":
                    raise TranslationError(f"{w}: case frame outside a switch")
                self.emit("_ => {}")
                self.emit("}")
                return
            if frame.kind == "switch":
                raise TranslationError(f"{w}: empty switch")
            if frame.kind == "for":
                self.emit(f"{frame.var} -= 1;")
                self.emit("}")
                self.emit("}")
                return
            self.emit("}")
            return

        if s == "break;":
            frame, crossed = self.break_target({"loop", "for", "switch", "case"})
            if frame.kind in ("case", "switch"):
                top = self.stack[-1]
                if top is not frame or frame.kind != "case":
                    raise TranslationError(f"{w}: break out of a switch from a nested construct")
                self.mark_statement(w)
                frame.terminated = True
                count("break ending a case (dropped)")
                return
            self.mark_statement(w)
            if crossed:
                self.emit(f"break '{self.loop_label(frame)};")
                count("break of a loop across a labelled block (labelled)")
            else:
                self.emit("break;")
                count("break of a loop")
            return

        if s == "continue;":
            self.mark_statement(w)
            frame, crossed = self.break_target({"loop", "for"})
            if frame.kind == "for":
                raise TranslationError(f"{w}: continue of a counted loop would skip its decrement")
            # a `switch` between does not matter: Java's continue skips it, as Rust's does a match
            if crossed:
                self.emit(f"continue '{self.loop_label(frame)};")
                count("continue across a labelled block (labelled)")
            else:
                self.emit("continue;")
                count("continue")
            return

        m = re.match(r"break ((?:go)?lab\d+);$", s)
        if m:
            self.mark_statement(w)
            label = m.group(1)
            if not any(f.label == label for f in self.stack):
                raise TranslationError(f"{w}: break to a label not in scope")
            self.emit(f"break '{label};")
            count("break label (labelled block)" if label.startswith("lab") else "break golab (labelled loop)")
            return

        m = re.match(r"return (.+);$", s)
        if m:
            self.mark_statement(w)
            self.emit(f"return {self.cond(m.group(1), w)};")
            top = self.stack[-1] if self.stack else None
            if top is not None and top.kind == "case":
                top.terminated = True
            count("return")
            return

        m = re.match(r"int ([A-Za-z_][A-Za-z0-9_]*);$", s)
        if m:
            self.mark_statement(w)
            name = m.group(1)
            n, in_loop = self.scope_assignments(idx, name)
            self.locals.add(name)
            mut = "mut " if (n > 1 or in_loop) else ""
            self.emit(f"let {mut}{name}: i32;")
            count("local declaration without initialiser")
            return

        m = re.match(r"int ([A-Za-z_][A-Za-z0-9_]*) = (.+);$", s)
        if m:
            self.mark_statement(w)
            name = m.group(1)
            value = self.cond(m.group(2), w)
            n, _ = self.scope_assignments(idx, name)
            self.locals.add(name)
            mut = "mut " if n > 0 else ""
            self.emit(f"let {mut}{name}: i32 = {value};")
            count("local declaration with initialiser")
            return

        m = re.match(r"([A-Za-z_][A-Za-z0-9_]*)(\+\+|--);$", s)
        if m:
            self.mark_statement(w)
            target = self.field(m.group(1), w)
            op = "+=" if m.group(2) == "++" else "-="
            self.emit(f"{target} {op} 1;")
            count(f"{m.group(2)} statement")
            return

        m = re.match(r"([A-Za-z_][A-Za-z0-9_]*) (=|\+=|-=) (.+);$", s)
        if m:
            self.mark_statement(w)
            target = self.field(m.group(1), w)
            value = m.group(3)
            if value in ("true", "false"):
                if self.model.field_kind(m.group(1)) != "boolean":
                    raise TranslationError(f"{w}: boolean assigned to a non-boolean")
            self.emit(f"{target} {m.group(2)} {self.cond(value, w)};")
            count("assignment" if m.group(2) == "=" else f"compound assignment {m.group(2)}")
            return

        m = re.match(r"([A-Za-z_][A-Za-z0-9_]*)\((.*)\);$", s)
        if m:
            self.mark_statement(w)
            self.emit(self.cond(s[:-1], w) + ";")
            count("call statement")
            return

        raise TranslationError(f"{w}: unknown statement {s!r}")


