#!/usr/bin/env python3
"""Translate Lucene 10.5.0's generated Snowball stemmers into Rust.

Input: the 30 `lucene/analysis/common/src/java/org/tartarus/snowball/ext/*Stemmer.java`
files, the output of the Snowball 2.2.0 Java generator as Lucene commits it (with
Lucene's edits: `@SuppressWarnings("unused")`, the `methodObject` lookup for `Among`
routines, `equals`/`hashCode`).

Output: `crates/rucene-analysis-common/src/tartarus/snowball/ext/<snake>_stemmer.rs`, one
file per class, matching the Java statement for statement, then formatted by `rustfmt`.

The translator accepts exactly the dialect those files use. Every line is matched
against a known construct; an unknown line, call, identifier, string escape or control
transfer stops the run with an error naming the file and line (it never guesses).

Usage: python3 tools/translate/snowball_java_to_rust.py [LUCENE_CHECKOUT]
       (default /tmp/lucene1050); add --coverage to print the construct counts.
"""

from __future__ import annotations

import collections
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT_DIR = REPO / "crates/rucene-analysis-common/src/tartarus/snowball/ext"
JAVA_REL = "lucene/analysis/common/src/java/org/tartarus/snowball/ext"

GENERATOR_LINE = "// Generated by Snowball 2.2.0 - https://snowballstem.org/"

PROGRAM_FIELDS = {"cursor", "limit", "limit_backward", "bra", "ket", "length"}
GROUPING_CALLS = {"in_grouping", "in_grouping_b", "out_grouping", "out_grouping_b"}
STRING_CALLS = {"eq_s", "eq_s_b", "slice_from"}
AMONG_CALLS = {"find_among", "find_among_b"}

# Lints the statement-for-statement translation trips, allowed in each generated
# module (measured: clippy reports exactly these on the unallowed output).
# `unused_labels` is Java's `@SuppressWarnings("unused")` (javac accepts a label no
# `break` names); the clippy lints are style lints on shapes the Java has: a `return`
# ending a routine, `int among_var;` assigned later, a `switch` of one case, an `if`
# alone in a `case`.
ALLOWED_LINTS = [
    "unused_labels",
    "clippy::collapsible_match",
    "clippy::needless_late_init",
    "clippy::needless_return",
    "clippy::single_match",
]


class TranslationError(Exception):
    pass


COVERAGE: collections.Counter[str] = collections.Counter()


def count(construct: str, n: int = 1) -> None:
    COVERAGE[construct] += n


# --------------------------------------------------------------------------------------
# Lexical helpers
# --------------------------------------------------------------------------------------

TOKEN_RE = re.compile(
    r'\s+|("(?:[^"\\]|\\.)*")|([A-Za-z_][A-Za-z0-9_]*)|(\d+)|(==|!=|<=|>=|&&|\|\||[-+*/<>!=(),])'
)

FORBIDDEN_ESCAPES = {"0022", "005C", "005c", "000A", "000a", "000D", "000d"}


def rust_string(java_literal: str, where: str) -> str:
    """The Rust literal for a Java string literal of the dialect (ASCII + \\uXXXX)."""
    body = java_literal[1:-1]
    out = []
    i = 0
    while i < len(body):
        ch = body[i]
        if ch == "\\":
            m = re.match(r"\\u([0-9A-Fa-f]{4})", body[i:])
            if not m:
                raise TranslationError(f"{where}: unsupported escape in {java_literal}")
            hexa = m.group(1)
            if hexa in FORBIDDEN_ESCAPES:
                raise TranslationError(f"{where}: escape \\u{hexa} is processed before lexing in Java")
            if 0xD800 <= int(hexa, 16) <= 0xDFFF:
                raise TranslationError(f"{where}: surrogate escape \\u{hexa} has no Rust str form")
            out.append("\\u{" + hexa.upper() + "}")
            count("string escape \\uXXXX")
            i += 6
        elif " " <= ch <= "~" and ch != '"':
            out.append(ch)
            i += 1
        else:
            raise TranslationError(f"{where}: unsupported character {ch!r} in {java_literal}")
    return '"' + "".join(out) + '"'


def tokenize(expr: str, where: str) -> list[str]:
    tokens = []
    pos = 0
    while pos < len(expr):
        m = TOKEN_RE.match(expr, pos)
        if not m or m.end() == pos:
            raise TranslationError(f"{where}: cannot tokenize {expr[pos:]!r}")
        text = m.group(0)
        if not text.isspace():
            tokens.append(text)
        pos = m.end()
    return tokens


def snake(name: str) -> str:
    return name.lower()


def snake_class(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


