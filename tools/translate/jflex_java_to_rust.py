#!/usr/bin/env python3
"""Translate Lucene 10.5.0's JFlex 1.8.2 scanners into Rust.

Input: the four JFlex-generated Java scanners of `lucene/analysis/common`
(`ClassicTokenizerImpl`, `WikipediaTokenizerImpl`, `UAX29URLEmailTokenizerImpl`,
`HTMLStripCharFilter`), as Lucene 10.5.0 commits them.

Output, per scanner:

* `<scanner>_tables.rs`, wholly generated: the DFA tables (`ZZ_CMAP_TOP`,
  `ZZ_CMAP_BLOCKS`, `ZZ_ACTION`, `ZZ_ROWMAP`, `ZZ_TRANS`, `ZZ_ATTRIBUTE`) in
  Java's own form: the packed `String` constants (`ZZ_TRANS_PACKED_0`, ...),
  one Rust line per Java literal, as Rust string literals whose chars are the
  UTF-16 units `javac` decodes from the Java literals (a constant holding a
  surrogate unit, which a Rust string cannot hold, as a `&[u16]` of the same
  units), and the ported `zzUnpack*` routines, run once at first use through a
  `LazyLock` (Java runs them in the class initializer). The script also
  unpacks every table itself and checks it against the `new int[N]` its
  routine allocates. Unlike the core's
  `src/analysis/standard/standard_tokenizer_impl_tables.rs`, the tables are
  not unpacked `static` arrays: a 1,095,920-entry array literal (the e-mail
  scanner's `ZZ_TRANS`) stops `rust-analyzer scip` from finishing.
* the regions between `// @generated begin <region>` and
  `// @generated end <region>` of the hand-written `<scanner>.rs`: `constants`
  (`YYEOF`, the lexical states, `ZZ_LEXSTATE`, the error messages, a constant
  `ZZ_BUFFERSIZE`), `fields` (the JFlex fields of the struct), `init` (their
  initial values in the constructor) and `skeleton` (an `impl` block with the
  JFlex skeleton, `zzRefill`, `yyreset`, `yypushback`, ..., and the scanning
  method with its action `switch`). The file is then formatted by `rustfmt`.

The JFlex user code (the `%{ ... %}` members, `%eof{ ... %}` and the action
bodies that are more than the simple statements below) is translated by hand,
outside the regions; the translator only calls it. Every skeleton member is
compared, token for token (comments and layout aside), with the JFlex 1.8.2
skeleton it was generated from; the user code and each hand-translated action
are pinned by the SHA-256 of their Java tokens. Any difference, any unknown
member and any action statement outside the mechanical subset (`return e;`,
`break;`, `yybegin(e);`, `yypushback(e);`, `field = e;`, `field++;`,
`if (e) ... else ...`, over fields, constants, integers, `yylength()`, `==`,
`!=`, `+`, `-`) stops the run with an error: it never guesses.

Usage: python3 tools/translate/jflex_java_to_rust.py [LUCENE_CHECKOUT]
       (default /tmp/lucene1050); `--check` compares the outputs with the
       committed files instead of writing them and exits 1 on a difference;
       `--only <JavaClass>` processes one scanner; `--hashes` prints the
       SHA-256 pins of the user code and of every action.
"""

