UNPACK_BODY = {"rle": UNPACK_RLE, "rowmap": UNPACK_ROWMAP, "trans": UNPACK_TRANS}

ERROR_MESSAGES = [
    "Unknown internal scanner error",
    "Error: could not match input",
    "Error: pushback value was too large",
]


# --------------------------------------------------------------------------
# Reading a scanner
# --------------------------------------------------------------------------


@dataclass
class Table:
    name: str  # ZZ_TRANS
    routine: str  # zzUnpackTrans
    kind: str  # "rle", "rowmap" or "trans"
    doc: str
    size: int  # the `new int[size]` of the unpacking driver
    packed: list  # (constant name, [UTF-16 units of each Java literal])
    values: list  # the unpacked values, as the Java routines produce them


@dataclass
class Parsed:
    sha256: str
    lexical_states: list  # (name, value, public)
    lexstate: list
    buffer_size: int
    buffer_size_is_field: bool
    refill: str  # "grow" or "fixed"
    public_api: bool
    public_class: bool  # the scanner class is `public` (else package-private)
    tables: list  # Table
    eof: list  # tokens after `zzAtEOF = true;` up to the closing brace
    actions: list  # (number, lookahead tokens, body tokens)
    break_labels: list
    has_do_eof: bool
    eof_code: list | None


def check_same(scanner: str, what: str, actual: list, expected: str):
    if norm(actual) != norm_java(expected):
        fail(scanner, f"{what} differs from the JFlex 1.8.2 skeleton:\n  {norm(actual)}\n"
                      f"  expected\n  {norm_java(expected)}")


def unpack(kind: str, packed: list, result: list, offset: int) -> int:
    """The `zzUnpack*(String packed, int offset, int [] result)` routines."""
    i = 0
    j = offset
    n = len(packed)
    while i < n:
        if kind == "rowmap":
            high = packed[i] << 16
            i += 1
            result[j] = high | packed[i]
            i += 1
            j += 1
        else:
            count = packed[i]
            i += 1
            value = packed[i]
            i += 1
            if kind == "trans":
                value -= 1
            while True:  # do result[j++] = value; while (--count > 0);
                result[j] = value
                j += 1
                count -= 1
                if count <= 0:
                    break
    return j


def to_i32(v: int) -> int:
    v &= 0xFFFFFFFF
    return v - (1 << 32) if v & 0x80000000 else v


def string_pieces(scanner: str, toks: list, name: str) -> list:
    """The UTF-16 units of each literal of `private static final String <name> = "..." + "...";`."""
    for i, t in enumerate(toks):
        if t.text == name and i + 1 < len(toks) and toks[i + 1].text == "=" and toks[i - 1].text == "String":
            pieces = []
            j = i + 2
            while True:
                if toks[j].kind != "str":
                    fail(scanner, f"{name}: expected a string literal, found {toks[j].text!r}")
                pieces.append(string_literal_body(toks[j].text[1:-1]))
                j += 1
                if toks[j].text == ";":
                    return pieces
                if toks[j].text != "+":
                    fail(scanner, f"{name}: unexpected {toks[j].text!r}")
                j += 1
    fail(scanner, f"string constant {name} not found")


def string_constant(scanner: str, toks: list, name: str) -> list:
    """The UTF-16 units of `private static final String <name> = "..." + "...";`."""
    return [u for piece in string_pieces(scanner, toks, name) for u in piece]


def read_tables(scanner: str, toks: list) -> list:
    tables = []
    for name, routine, kind, doc in TABLES:
        # private static final int [] NAME = routine();
        decl = f"private static final int [ ] {name} = {routine} ( ) ;"
        if decl not in norm(toks):
            fail(scanner, f"{name} is not initialised by {routine}()")
        method = None
        for i, t in enumerate(toks):
            if (t.text == routine and toks[i + 1].text == "(" and toks[i + 2].text == ")"
                    and toks[i - 1].text == "]"):
                method = find_method_at(scanner, toks, i)
        if method is None:
            fail(scanner, f"{routine}() not found")
        body = norm(method)
        m = re.fullmatch(
            r"int \[ \] result = new int \[ (\d+) \] ; int offset = 0 ; "
            r"((?:offset = " + re.escape(routine) + r" \( \w+ , offset , result \) ; )+)return result ;",
            body)
        if not m:
            fail(scanner, f"{routine}() is not the JFlex unpacking driver: {body}")
        size = int(m.group(1))
        consts = re.findall(r"offset = \w+ \( (\w+) , offset , result \) ;", m.group(2))
        # The three-argument routine.
        overload = None
        for i, t in enumerate(toks):
            if (t.text == routine and toks[i + 1].text == "(" and toks[i + 2].text == "String"
                    and toks[i - 1].text == "int"):
                overload = find_method_at(scanner, toks, i)
        if overload is None:
            fail(scanner, f"{routine}(String, int, int[]) not found")
        check_same(scanner, f"{routine}(String, int, int[])", overload, UNPACK_BODY[kind])
        result = [None] * size
        offset = 0
        packed = []
        for const in consts:
            pieces = string_pieces(scanner, toks, const)
            packed.append((const, pieces))
            offset = unpack(kind, [u for piece in pieces for u in piece], result, offset)
        if offset != size or any(v is None for v in result):
            fail(scanner, f"{name}: unpacked {offset} values into int[{size}]")
        tables.append(Table(name, routine, kind, doc, size, packed, [to_i32(v) for v in result]))
    return tables


def find_method_at(scanner: str, toks: list, i: int) -> list:
    """The body tokens of the method whose name is `toks[i]`."""
    close = match_close(toks, i + 1)
    if toks[close + 1].text != "{":
        fail(scanner, f"{toks[i].text} at {toks[i].pos} is not a declaration")
    return toks[close + 2:match_close(toks, close + 1)]


def parse(sc: Scanner, lucene: Path) -> Parsed:
    path = lucene / sc.java
    raw = path.read_text(encoding="utf-8")
    if raw.splitlines()[1] != GENERATOR_LINE:
        fail(sc.java_class, f"not generated by JFlex 1.8.2: {raw.splitlines()[1]!r}")
    src = unicode_preprocess(raw)
    toks = lex(src)
    text = norm(toks)

    # Lexical states: the run of `[public|private] static final int NAME = 2k;`
    # declarations that starts with `YYINITIAL = 0`.
    states = []
    m = re.search(r"(public|private) static final int YYINITIAL = 0 ;", text)
    if not m:
        fail(sc.java_class, "no YYINITIAL lexical state")
    pos = m.start()
    state_re = re.compile(r"(public|private) static final int ([A-Z_]+) = (\d+) ; ")
    while True:
        m = state_re.match(text, pos)
        if not m:
            break
        if int(m.group(3)) != 2 * len(states):
            fail(sc.java_class, f"lexical state {m.group(2)} is not {2 * len(states)}")
        states.append((m.group(2), int(m.group(3)), m.group(1) == "public"))
        pos = m.end()
    m = re.search(r"(public|private) static final int YYEOF = - 1 ;", text)
    if not m:
        fail(sc.java_class, "YYEOF not found")
    public_api = m.group(1) == "public"
    m = re.search(r"(?:^| )(public )?(?:final )?class " + re.escape(sc.java_class) + " ", text)
    if not m:
        fail(sc.java_class, "class declaration not found")
    public_class = m.group(1) is not None
    m = re.search(r"private static final int ZZ_LEXSTATE \[ \] = \{ ([\d ,]+) \} ;", text)
    if not m:
        fail(sc.java_class, "ZZ_LEXSTATE not found")
    lexstate = [int(v) for v in m.group(1).replace(",", " ").split()]
    if len(lexstate) != 2 * len(states):
        fail(sc.java_class, f"ZZ_LEXSTATE has {len(lexstate)} entries for {len(states)} states")

    m = re.search(r"private (static final )?int ZZ_BUFFERSIZE = (\d+) ;", text)
    if not m:
        fail(sc.java_class, "ZZ_BUFFERSIZE not found")
    buffer_size = int(m.group(2))
    buffer_size_is_field = m.group(1) is None

    for codes in ("private static final int ZZ_UNKNOWN_ERROR = 0 ;",
                  "private static final int ZZ_NO_MATCH = 1 ;",
                  "private static final int ZZ_PUSHBACK_2BIG = 2 ;"):
        if codes not in text:
            fail(sc.java_class, f"missing `{codes}`")
    m = re.search(r"private static final String ZZ_ERROR_MSG \[ \] = \{ (.*?) \} ;", text)
    if not m or [s.strip()[1:-1] for s in re.findall(r'"[^"]*"', m.group(1))] != ERROR_MESSAGES:
        fail(sc.java_class, "ZZ_ERROR_MSG differs")

    fields = [
        "private java.io.Reader zzReader ;", "private int zzState ;",
        "private int zzLexicalState = YYINITIAL ;",
        "private char zzBuffer [ ] = new char [ ZZ_BUFFERSIZE ] ;",
        "private int zzMarkedPos ;", "private int zzCurrentPos ;", "private int zzStartRead ;",
        "private int zzEndRead ;", "private boolean zzAtEOF ;",
        "private int zzFinalHighSurrogate = 0 ;", "private int yyline ;",
        "private int yycolumn ;", "private long yychar ;", "private boolean zzAtBOL = true ;",
        "private boolean zzEOFDone ;",
    ]
    stripped = text.replace('@ SuppressWarnings ( "unused" ) ', "")
    for decl in fields:
        if norm_java(decl) not in stripped:
            fail(sc.java_class, f"missing field `{decl}`")

    tables = read_tables(sc.java_class, toks)

    # The constructor: `[public] Name(java.io.Reader in) { [super(in);] this.zzReader = in; }`.
    ctor = re.search(r"(?:public )?" + sc.java_class +
                     r" \( java \. io \. Reader in \) \{ (super \( in \) ; )?this \. zzReader = in ; \}", text)
    if not ctor:
        fail(sc.java_class, "the JFlex constructor differs")

    # The user code: from `/* user code: */` to the constructor's javadoc.
    start = next((i for i, t in enumerate(toks) if t.kind == "comment" and t.text == "/* user code: */"),
                 None)
    if start is None:
        fail(sc.java_class, "no `/* user code: */` section")
    end = next(i for i, t in enumerate(toks)
               if i > start and t.kind == "comment" and "Creates a new scanner" in t.text)
    user_sha = sha(toks[start + 1:end])
    HASHES.append((sc.java_class, "user code", user_sha))
    if user_sha != sc.user_code_sha and not PRINT_HASHES:
        fail(sc.java_class, f"the user code changed (sha256 {user_sha}, pinned {sc.user_code_sha!r}): "
                            "re-translate it by hand, then pin the new hash")

    user = range(start, end)
    for name, expected in SKELETON.items():
        method = find_method(sc.java_class, toks, name, skip=user)
        check_same(sc.java_class, name, method.body, expected)
    refill = find_method(sc.java_class, toks, "zzRefill", skip=user).body
    if norm(refill) == norm_java(REFILL_GROW):
        refill_kind = "grow"
    elif norm(refill) == norm_java(REFILL_FIXED):
        refill_kind = "fixed"
    else:
        fail(sc.java_class, f"zzRefill matches no known skeleton: {norm(refill)}")
    if (refill_kind == "fixed") != buffer_size_is_field:
        fail(sc.java_class, "a fixed buffer comes with a settable ZZ_BUFFERSIZE, and only then")

    do_eof = find_method(sc.java_class, toks, "zzDoEOF", required=False, skip=user)
    eof_code = None
    if do_eof is not None:
        b = code(do_eof.body)
        head = lex("if (!zzEOFDone) { zzEOFDone = true;")
        if norm(b[:len(head)]) != norm(head) or b[-1].text != "}":
            fail(sc.java_class, f"zzDoEOF differs from the skeleton: {norm(b)}")
        eof_code = b[len(head):-1]
        eof_sha = sha(eof_code)
        HASHES.append((sc.java_class, "%eof code", eof_sha))
        if eof_sha != sc.eof_code_sha and not PRINT_HASHES:
            fail(sc.java_class, f"the %eof code changed (sha256 {eof_sha}, pinned {sc.eof_code_sha!r})")
    elif sc.eof_code_sha is not None:
        fail(sc.java_class, "zzDoEOF expected")

    nxt = find_method(sc.java_class, toks, sc.next_method, skip=user)
    if (sc.next_method != "getNextToken") == public_api:
        fail(sc.java_class, "a private API names its scanning method, a public one does not")
    body = nxt.body
    cbody = code(body)
    head = norm_java(NEXT_HEAD)
    nh = len(lex(NEXT_HEAD))
    if norm(cbody[:nh]) != head:
        fail(sc.java_class, f"{sc.next_method} differs from the skeleton:\n{norm(cbody[:nh])}")
    # The EOF section runs to the `}` matching the `if`'s `{`.
    if_open = nh - 5  # `{ zzAtEOF = true ;` are the last 5 tokens
    if cbody[if_open].text != "{":
        fail(sc.java_class, "the EOF test is not where the skeleton puts it")
    if_close = match_close(cbody, if_open)
    eof = cbody[nh:if_close]
    # Comments are kept for the actions: re-slice `body` by token identity.
    rest = body[body.index(cbody[if_close]):]
    nrest = norm(rest)
    if not nrest.startswith(ACTION_SWITCH) or not nrest.endswith(NEXT_TAIL):
        fail(sc.java_class, f"the action switch differs from the skeleton: {nrest[:120]}")
    switch_open = next(i for i, t in enumerate(rest) if t.text == "{" and i > 2 and rest[i - 1].text == ")")
    switch_close = match_close(rest, switch_open)
    actions, labels = parse_cases(sc.java_class, rest[switch_open + 1:switch_close])

    return Parsed(
        sha256=hashlib.sha256(raw.encode("utf-8")).hexdigest(),
        lexical_states=states,
        lexstate=lexstate,
        buffer_size=buffer_size,
        buffer_size_is_field=buffer_size_is_field,
        refill=refill_kind,
        public_api=public_api,
        public_class=public_class,
        tables=tables,
        eof=eof,
        actions=actions,
        break_labels=labels,
        has_do_eof=do_eof is not None,
        eof_code=eof_code,
    )


LOOKAHEAD_RE = re.compile(
    r"zzMarkedPos = Character \. offsetByCodePoints \( zzBufferL , zzStartRead , "
    r"zzEndRead - zzStartRead , (zzMarkedPos|zzStartRead) , (- )?(\d+) \) ;")


def parse_cases(scanner: str, toks: list):
    """The actions of the action `switch`: `case N: [lookahead] { body } // fall through
    case M: break;`, then `default: zzScanError(ZZ_NO_MATCH);`."""
    actions = []
    labels = []
    i = 0
    while i < len(toks):
        t = toks[i]
        if t.kind == "comment":
            i += 1
            continue
        if t.text == "default":
            break
        if t.text != "case" or toks[i + 1].kind != "num" or toks[i + 2].text != ":":
            fail(scanner, f"unexpected {t.text!r} in the action switch")
        number = int(toks[i + 1].text)
        i += 3
        while toks[i].kind == "comment":
            i += 1
        if toks[i].text == "break":  # `case M: break;`, the label ending an action
            labels.append(number)
            i += 2
            continue
        look = []
        while toks[i].text != "{":
            look.append(toks[i])
            i += 1
        close = match_close(toks, i)
        actions.append((number, look, toks[i + 1:close]))
        i = close + 1
    numbers = [a[0] for a in actions]
    if numbers != list(range(1, len(actions) + 1)):
        fail(scanner, f"actions are not numbered 1..{len(actions)}: {numbers}")
    return actions, labels


