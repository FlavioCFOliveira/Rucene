CONSTANT_RE = re.compile(r"[A-Z][A-Z0-9_]*$")


class ActionTranslator:
    """Translates the statement subset documented in the module docstring."""

    def __init__(self, scanner: Scanner, toks: list):
        self.sc = scanner
        self.toks = toks
        self.i = 0

    def error(self, message: str):
        at = self.toks[self.i].text if self.i < len(self.toks) else "end of action"
        fail(self.sc.java_class, f"{message} at {at!r}; translate this action by hand")

    def peek(self, k: int = 0):
        j = self.i
        while j < len(self.toks):
            if self.toks[j].kind != "comment":
                if k == 0:
                    return self.toks[j]
                k -= 1
            j += 1
        return None

    def take_comments(self, out: list, indent: str):
        while self.i < len(self.toks) and self.toks[self.i].kind == "comment":
            out.append(indent + rust_comment(self.toks[self.i].text))
            self.i += 1

    def expect(self, text: str):
        while self.i < len(self.toks) and self.toks[self.i].kind == "comment":
            self.i += 1
        if self.i >= len(self.toks) or self.toks[self.i].text != text:
            self.error(f"expected {text!r}")
        self.i += 1

    def statements(self, indent: str) -> list:
        out = []
        while True:
            self.take_comments(out, indent)
            if self.i >= len(self.toks) or self.peek().text == "}":
                return out
            out.extend(self.statement(indent))

    def statement(self, indent: str) -> list:
        t = self.peek()
        if t.text == "{":
            self.expect("{")
            body = self.statements(indent + "    ")
            self.expect("}")
            return [indent + "{"] + body + [indent + "}"]
        if t.text == "if":
            self.expect("if")
            self.expect("(")
            cond = self.expr()
            self.expect(")")
            then = self.branch(indent)
            lines = [indent + f"if {cond} {{"] + then
            if self.peek() is not None and self.peek().text == "else":
                self.expect("else")
                lines += [indent + "} else {"] + self.branch(indent)
            return lines + [indent + "}"]
        if t.text == "return":
            self.expect("return")
            value = self.expr()
            self.expect(";")
            return [indent + f"return Ok({value});"]
        if t.text == "break":
            self.expect("break")
            self.expect(";")
            # Java leaves the `switch`, which ends the loop body: the scan
            # goes on with the next match.
            return [indent + "continue;"]
        if t.kind == "id" and t.text in ("yybegin", "yypushback"):
            self.i_skip()
            self.expect("(")
            arg = self.expr()
            self.expect(")")
            self.expect(";")
            return [indent + f"self.{t.text}({arg});"]
        if t.kind == "id" and t.text in self.sc.action_fields:
            target = "self." + self.sc.action_fields[t.text]
            self.i_skip()
            op = self.peek().text
            if op == "=":
                self.expect("=")
                value = self.expr()
                self.expect(";")
                return [indent + f"{target} = {value};"]
            if op == "++":
                self.expect("++")
                self.expect(";")
                return [indent + f"{target} += 1;"]
            self.error("unsupported assignment")
        if t.text == ";":
            self.expect(";")
            return []
        self.error("unsupported statement")

    def branch(self, indent: str) -> list:
        if self.peek().text == "{":
            self.expect("{")
            body = self.statements(indent + "    ")
            self.expect("}")
            return body
        return self.statement(indent + "    ")

    def i_skip(self):
        while self.toks[self.i].kind == "comment":
            self.i += 1
        self.i += 1

    def expr(self) -> str:
        left = self.additive()
        t = self.peek()
        if t is not None and t.text in ("==", "!="):
            self.i_skip()
            return f"{left} {t.text} {self.additive()}"
        return left

    def additive(self) -> str:
        left = self.primary()
        while self.peek() is not None and self.peek().text in ("+", "-"):
            op = self.peek().text
            self.i_skip()
            left = f"{left} {op} {self.primary()}"
        return left

    def primary(self) -> str:
        t = self.peek()
        if t is None:
            self.error("expression expected")
        if t.kind == "num":
            self.i_skip()
            return t.text
        if t.text == "(":
            self.expect("(")
            inner = self.expr()
            self.expect(")")
            return f"({inner})"
        if t.kind == "id" and t.text == "yylength":
            self.i_skip()
            self.expect("(")
            self.expect(")")
            return "self.yylength()"
        if t.kind == "id" and t.text in self.sc.action_fields:
            self.i_skip()
            return "self." + self.sc.action_fields[t.text]
        if t.kind == "id" and CONSTANT_RE.match(t.text):
            self.i_skip()
            return t.text
        self.error("unsupported expression")


def rust_comment(text: str) -> str:
    if text.startswith("//"):
        body = text[2:].strip()
    else:
        body = " ".join(line.strip().lstrip("*").strip() for line in text[2:-2].splitlines()).strip()
    return f"// {body}" if body else "//"


def translate_action(sc: Scanner, number: int, body: list, indent: str) -> list:
    if number in sc.hand_actions or (PRINT_HASHES and number):
        actual = sha(body)
        HASHES.append((sc.java_class, f"action {number}", actual))
        if PRINT_HASHES:
            return []
        if actual != sc.hand_actions[number]:
            fail(sc.java_class, f"action {number} changed (sha256 {actual}): re-translate it by hand")
        return [indent + f"if let Some(value) = self.action_{number}() {{",
                indent + "    return Ok(value);",
                indent + "}"]
    tr = ActionTranslator(sc, body)
    lines = tr.statements(indent)
    if tr.i != len(body):
        tr.error("trailing tokens")
    # A trailing `continue;` is the end of the arm anyway.
    code_lines = [k for k, line in enumerate(lines) if not line.strip().startswith("//")]
    if code_lines and lines[code_lines[-1]].strip() == "continue;":
        del lines[code_lines[-1]]
    return lines


def translate_lookahead(sc: Scanner, look: list, indent: str) -> list:
    if not code(look):
        return []
    m = LOOKAHEAD_RE.fullmatch(norm(look))
    if not m:
        fail(sc.java_class, f"unknown lookahead code: {norm(look)}")
    base = "self.zz_marked_pos" if m.group(1) == "zzMarkedPos" else "self.zz_start_read"
    offset = ("-" if m.group(2) else "") + m.group(3)
    kind = "fixed lookahead length" if m.group(1) == "zzMarkedPos" else "fixed base length"
    return [
        indent + f"// lookahead expression with {kind}",
        indent + "self.zz_marked_pos = crate::jdk::character::offset_by_code_points(",
        indent + "    &self.zz_buffer,",
        indent + "    self.zz_start_read,",
        indent + "    self.zz_end_read - self.zz_start_read,",
        indent + f"    {base},",
        indent + f"    {offset},",
        indent + ")?;",
    ]


def translate_eof(sc: Scanner, parsed: Parsed, indent: str) -> list:
    toks = parsed.eof
    text = norm(toks)
    if text == "return YYEOF ;":
        return [indent + "return Ok(YYEOF);"]
    if parsed.has_do_eof and text.startswith("zzDoEOF ( ) ; {") and toks[-1].text == "}":
        return ([indent + "self.zz_do_eof();", indent + "{"]
                + translate_action(sc, 0, toks[5:-1], indent + "    ") + [indent + "}"])
    if text.startswith("switch ( zzLexicalState ) {") and toks[-1].text == "}":
        names = {s[0] for s in parsed.lexical_states}
        lines = [indent + "match self.zz_lexical_state {"]
        i = 5
        labels = []
        while i < len(toks) - 1:
            if toks[i].text == "case" and toks[i + 2].text == ":":
                label = toks[i + 1].text
                if toks[i + 3].text == "{":
                    close = match_close(toks, i + 3)
                    if label not in names:
                        fail(sc.java_class, f"EOF case {label} is not a lexical state")
                    lines.append(indent + f"    {label} => {{")
                    lines += translate_action(sc, 0, toks[i + 4:close], indent + "        ")
                    lines.append(indent + "    }")
                    i = close + 1
                    continue
                if toks[i + 3].text == "break" and toks[i + 4].text == ";":
                    labels.append(label)
                    i += 5
                    continue
            if toks[i].text == "default" and toks[i + 1].text == ":":
                body = toks[i + 2:len(toks) - 1]
                if labels:
                    lines.append(indent + f"    {' | '.join(labels)} => {{}}")
                lines.append(indent + "    _ => {")
                lines += translate_action(sc, 0, body, indent + "        ")
                lines.append(indent + "    }")
                lines.append(indent + "}")
                return lines
            fail(sc.java_class, f"unknown EOF switch construct {toks[i].text!r}")
    fail(sc.java_class, f"unknown EOF code: {text}")


