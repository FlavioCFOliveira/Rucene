REGIONS = ["constants", "fields", "init", "skeleton"]


def fill_regions(sc: Scanner, text: str, parsed: Parsed, lucene_java: str) -> str:
    bodies = {
        "constants": [
            f"// From Lucene 10.5.0's {lucene_java}",
            f"// (sha256 {parsed.sha256}).",
            "",
        ] + emit_constants(sc, parsed),
        "fields": emit_fields(parsed),
        "init": emit_init(parsed),
        "skeleton": emit_skeleton(sc, parsed),
    }
    for region in REGIONS:
        begin = re.compile(r"^([ \t]*)// @generated begin " + region + r"\b.*$", re.M)
        m = begin.search(text)
        if not m:
            fail(sc.java_class, f"{sc.rust} has no `// @generated begin {region}` marker")
        end = re.compile(r"^[ \t]*// @generated end " + region + r"\s*$", re.M)
        e = end.search(text, m.end())
        if not e:
            fail(sc.java_class, f"{sc.rust} has no `// @generated end {region}` marker")
        indent = m.group(1)
        marker = f"{indent}// @generated begin {region} by {SCRIPT}; DO NOT EDIT"
        block = [marker] + [(indent + line) if line else "" for line in bodies[region]] + [
            f"{indent}// @generated end {region}"]
        text = text[:m.start()] + "\n".join(block) + text[e.end():]
    # Every hand-translated action must exist outside the regions.
    for number in sc.hand_actions:
        if not re.search(r"fn action_" + str(number) + r"\(&mut self\) -> Option<i32>", text):
            fail(sc.java_class, f"{sc.rust} lacks the hand translation `fn action_{number}`")
    if parsed.has_do_eof and "fn eof_code(&mut self)" not in text:
        fail(sc.java_class, f"{sc.rust} lacks the hand translation `fn eof_code`")
    return text


def rustfmt(text: str) -> str:
    with tempfile.NamedTemporaryFile("w", suffix=".rs", delete=False, encoding="utf-8") as f:
        f.write(text)
        name = f.name
    try:
        subprocess.run(["rustfmt", "--edition", "2021", name], check=True)
        return Path(name).read_text(encoding="utf-8")
    finally:
        Path(name).unlink()


def main(argv: list) -> int:
    global PRINT_HASHES
    check = "--check" in argv
    PRINT_HASHES = "--hashes" in argv
    only = None
    if "--only" in argv:
        k = argv.index("--only")
        only = argv[k + 1]
        argv = argv[:k] + argv[k + 2:]
    args = [a for a in argv if a not in ("--check", "--hashes")]
    lucene = Path(args[0] if args else "/tmp/lucene1050")
    differ = False
    try:
        for sc in SCANNERS:
            if only is not None and sc.java_class != only:
                continue
            parsed = parse(sc, lucene)
            if PRINT_HASHES:
                emit_skeleton(sc, parsed)
                continue
            tables = rustfmt(emit_tables(sc, parsed, sc.java))
            rust_path = REPO / sc.rust
            scanner_text = rustfmt(fill_regions(sc, rust_path.read_text(encoding="utf-8"), parsed, sc.java))
            for path, text in ((REPO / sc.tables, tables), (rust_path, scanner_text)):
                if check:
                    if not path.exists() or path.read_text(encoding="utf-8") != text:
                        print(f"{path.relative_to(REPO)} differs from what {sc.java} generates",
                              file=sys.stderr)
                        differ = True
                elif not path.exists() or path.read_text(encoding="utf-8") != text:
                    path.write_text(text, encoding="utf-8")
                    print(f"wrote {path.relative_to(REPO)}")
    except TranslationError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    if PRINT_HASHES:
        for scanner, what, digest in HASHES:
            print(f"{scanner} {what}: {digest}")
        return 0
    if check:
        if differ:
            return 1
        print("all JFlex ports are current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
