TOKEN_RE = re.compile(
    r"""
     (?P<ws>\s+)
    |(?P<comment>//[^\n]*|/\*.*?\*/)
    |(?P<str>"(?:[^"\\\n]|\\.)*")
    |(?P<chr>'(?:[^'\\\n]|\\.)+')
    |(?P<num>0[xX][0-9a-fA-F]+[lL]?|\d+[lL]?)
    |(?P<id>[A-Za-z_$][A-Za-z0-9_$]*)
    |(?P<op>>>>=|<<=|>>=|>>>|\+\+|--|&&|\|\||==|!=|<=|>=|\+=|-=|\*=|/=|&=|\|=|\^=|%=|<<|>>
           |[{}()\[\];,.=<>!~?:+\-*/&|^%@])
    """,
    re.S | re.X,
)


@dataclass
class Tok:
    kind: str
    text: str
    pos: int


def lex(src: str) -> list:
    """The tokens of `src`, whitespace dropped, comments kept."""
    toks = []
    pos = 0
    while pos < len(src):
        m = TOKEN_RE.match(src, pos)
        if not m:
            raise TranslationError(f"unlexable Java at {pos}: {src[pos:pos + 40]!r}")
        if m.lastgroup != "ws":
            toks.append(Tok(m.lastgroup, m.group(), pos))
        pos = m.end()
    return toks


def code(toks: list) -> list:
    """`toks` without comments."""
    return [t for t in toks if t.kind != "comment"]


def norm(toks: list) -> str:
    """The canonical text of `toks`: code tokens joined by one space."""
    return " ".join(t.text for t in code(toks))


def norm_java(text: str) -> str:
    return norm(lex(text))


def sha(toks: list) -> str:
    return hashlib.sha256(norm(toks).encode("utf-8")).hexdigest()


def match_close(toks: list, i: int) -> int:
    """The index of the bracket closing the one at `toks[i]`."""
    pairs = {"{": "}", "(": ")", "[": "]"}
    opening = toks[i].text
    closing = pairs[opening]
    depth = 0
    for j in range(i, len(toks)):
        if toks[j].kind != "op":
            continue
        if toks[j].text == opening:
            depth += 1
        elif toks[j].text == closing:
            depth -= 1
            if depth == 0:
                return j
    raise TranslationError(f"unbalanced {opening!r} at {toks[i].pos}")


@dataclass
class Method:
    modifiers: list
    params: list
    body: list  # tokens strictly inside the braces


def find_method(scanner: str, toks: list, name: str, required: bool = True, skip=range(0)):
    """The method `name` declared at class level, outside the token range
    `skip` (the user code): its modifiers and body."""
    found = None
    for i, t in enumerate(toks):
        if t.kind != "id" or t.text != name or i + 1 >= len(toks) or toks[i + 1].text != "(":
            continue
        if i in skip:
            continue
        close = match_close(toks, i + 1)
        j = close + 1
        while j < len(toks) and toks[j].kind == "comment":
            j += 1
        if toks[j].text == "throws":
            while toks[j].text != "{":
                j += 1
        if toks[j].text != "{":
            continue  # a call, not a declaration
        k = i - 1
        mods = []
        while k >= 0 and toks[k].kind == "id":
            mods.append(toks[k].text)
            k -= 1
        while k >= 0 and toks[k].text in ("[", "]"):
            k -= 1
            while k >= 0 and toks[k].kind == "id":
                mods.append(toks[k].text)
                k -= 1
        if found is not None:
            fail(scanner, f"{name} is declared twice")
        end = match_close(toks, j)
        found = Method(list(reversed(mods)), toks[i + 2:close], toks[j + 1:end])
    if found is None and required:
        fail(scanner, f"method {name} not found")
    return found


