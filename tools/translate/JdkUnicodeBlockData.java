// running JDK's public java.lang.Character.UnicodeBlock API (run it with JDK 25):
//
//   java tools/translate/JdkUnicodeBlockData.java \
//     > crates/rucene-analysis-common/src/jdk/unicode_block_data.rs
//
// Deterministic: the output depends only on the JDK's Unicode data.
