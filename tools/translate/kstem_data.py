#!/usr/bin/env python3
"""Translates the word tables of Lucene's KStem stemmer into Rust.

Reads, from Lucene 10.5.0's `org.apache.lucene.analysis.en` package:

* `KStemData1.java` ... `KStemData8.java`, and writes each as
  `crates/rucene-analysis-common/src/analysis/en/kstem_dataN.rs`: the CIIR
  licence header of the Java file, kept verbatim, then `KStemDataN::DATA`
  holding the strings of `KStemDataN.data` in the Java order and in the
  Java layout (the files are declared `#[rustfmt::skip]` in `en.rs`);
* the string tables of `KStemmer.java` (`exceptionWords`,
  `directConflations`, `countryNationality`, `supplementDict`,
  `properNouns`), and rewrites the region of
  `crates/rucene-analysis-common/src/analysis/en/kstemmer.rs` between the
  `BEGIN GENERATED` and `END GENERATED` markers with the equivalent Rust
  constants, keeping the Java comments inside the tables, then formats that
  file with `rustfmt`.

Deterministic: the same Java sources yield the same files.

Usage:
    python3 tools/translate/kstem_data.py [LUCENE_SRC_ROOT]

`LUCENE_SRC_ROOT` defaults to `/tmp/lucene1050`.
"""

import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
EN_DIR = REPO / "crates/rucene-analysis-common/src/analysis/en"
JAVA_DIR_REL = "lucene/analysis/common/src/java/org/apache/lucene/analysis/en"
BEGIN = "// BEGIN GENERATED by tools/translate/kstem_data.py"
END = "// END GENERATED by tools/translate/kstem_data.py"

# A Java string literal of these tables: no escapes occur in them, which
# `check_literal` enforces, so the Java spelling is the Rust spelling.
STRING_RE = re.compile(r'"([^"\\]*)"')


def check_literal(value: str, where: str) -> None:
    if not value.isascii() or not value.isprintable():
        raise ValueError(f"unexpected literal {value!r} in {where}")


def translate_data(java: str, n: int) -> str:
    """Returns the Rust file for `KStemData<n>.java`."""
    header_end = java.index("*/") + 2
    header = java[:header_end]
    body = java[header_end:]
    start = body.index("static final String[] data = {")
    end = body.index("};", start)
    table = body[start:end].splitlines()[1:]
    lines = []
    count = 0
    for line in table:
        stripped = line.strip()
        if not stripped:
            continue
        values = STRING_RE.findall(stripped)
        rebuilt = ", ".join(f'"{v}"' for v in values) + ","
        if rebuilt != stripped:
            raise ValueError(f"KStemData{n}: unexpected table line {line!r}")
        for value in values:
            check_literal(value, f"KStemData{n}")
        count += len(values)
        lines.append("        " + rebuilt)
    out = [
        header,
        "",
        f"//! A list of words used by Kstem, ported from",
        f"//! `org.apache.lucene.analysis.en.KStemData{n}`.",
        "//!",
        "//! Generated by `tools/translate/kstem_data.py` from Lucene 10.5.0's",
        f"//! `KStemData{n}.java`; do not edit.",
        "",
        "/// A list of words used by Kstem.",
        "///",
        f"/// Equivalent to `org.apache.lucene.analysis.en.KStemData{n}`, a class",
        "/// with a private constructor and one static field: the type has no",
        "/// value.",
        f"pub(crate) enum KStemData{n} {{}}",
        "",
        f"impl KStemData{n} {{",
        '    // KStemData1 ... KStemData8 are created from "head_word_list.txt"',
        f"    /// Equivalent to `KStemData{n}.data` ({count} words).",
        "    pub(crate) const DATA: &'static [&'static str] = &[",
        *lines,
        "    ];",
        "}",
        "",
    ]
    return "\n".join(out)


def table_body(java: str, declaration: str) -> list:
    """Returns the lines between `<declaration> = {` and its closing `};`."""
    start = java.index(declaration + " = {")
    end = java.index("};", start)
    return java[start:end].splitlines()[1:]


def translate_list(java: str, name: str, rust_name: str, doc: str) -> list:
    """Translates `private static final String[] <name> = {...};`."""
    out = [f"/// {doc}", "///", f"/// Equivalent to `KStemmer.{name}`.",
           f"const {rust_name}: &[&str] = &["]
    for line in table_body(java, f"private static final String[] {name}"):
        stripped = line.strip()
        if not stripped:
            continue
        if stripped.startswith("//"):
            out.append("    " + stripped)
            continue
        m = re.fullmatch(r'"([^"\\]*)",?', stripped)
        if not m:
            raise ValueError(f"{name}: unexpected line {line!r}")
        check_literal(m.group(1), name)
        out.append(f'    "{m.group(1)}",')
    out.append("];")
    return out


def translate_pairs(java: str, name: str, rust_name: str, doc: str) -> list:
    """Translates `private static final String[][] <name> = {...};`."""
    out = [f"/// {doc}", "///", f"/// Equivalent to `KStemmer.{name}`.",
           f"const {rust_name}: &[[&str; 2]] = &["]
    for line in table_body(java, f"private static final String[][] {name}"):
        stripped = line.strip()
        if not stripped:
            continue
        if stripped.startswith("//"):
            out.append("    " + stripped)
            continue
        m = re.fullmatch(r'\{"([^"\\]*)", "([^"\\]*)"\},?', stripped)
        if not m:
            raise ValueError(f"{name}: unexpected line {line!r}")
        check_literal(m.group(1), name)
        check_literal(m.group(2), name)
        out.append(f'    ["{m.group(1)}", "{m.group(2)}"],')
    out.append("];")
    return out


def render_kstemmer_tables(java: str) -> str:
    out = [BEGIN]
    out += translate_list(java, "exceptionWords", "EXCEPTION_WORDS",
                          "Words that are their own root, not stemmed further.")
    out.append("")
    out += translate_pairs(java, "directConflations", "DIRECT_CONFLATIONS",
                           "Words mapped directly to their root.")
    out.append("")
    out += translate_pairs(java, "countryNationality", "COUNTRY_NATIONALITY",
                           "Nationalities mapped to their country.")
    out.append("")
    out += translate_list(java, "supplementDict", "SUPPLEMENT_DICT",
                          "Words added to the head word list.")
    out.append("")
    out += translate_list(java, "properNouns", "PROPER_NOUNS",
                          "Proper nouns, kept as they are.")
    out.append(END)
    return "\n".join(out)


def main() -> None:
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("/tmp/lucene1050")
    java_dir = root / JAVA_DIR_REL
    for n in range(1, 9):
        java = (java_dir / f"KStemData{n}.java").read_text(encoding="utf-8")
        target = EN_DIR / f"kstem_data{n}.rs"
        target.write_text(translate_data(java, n), encoding="utf-8")
        print(f"{target}: written")
    kstemmer = EN_DIR / "kstemmer.rs"
    java = (java_dir / "KStemmer.java").read_text(encoding="utf-8")
    rust = kstemmer.read_text(encoding="utf-8")
    begin = rust.index(BEGIN)
    end = rust.index(END) + len(END)
    rust = rust[:begin] + render_kstemmer_tables(java) + rust[end:]
    kstemmer.write_text(rust, encoding="utf-8")
    subprocess.run(["rustfmt", "--edition", "2021", str(kstemmer)], check=True)
    print(f"{kstemmer}: tables written")


if __name__ == "__main__":
    main()
