#!/usr/bin/env python3
"""Generate the DFA tables of `StandardTokenizerImpl` from Lucene's Java source.

Lucene 10.5.0's `StandardTokenizerImpl.java` is generated by JFlex 1.8.2 and
holds its tables as packed `String` constants that static initializers unpack
at class-load time (`zzUnpackcmap_top`, `zzUnpackcmap_blocks`,
`zzUnpackAction`, `zzUnpackRowMap`, `zzUnpackTrans`, `zzUnpackAttribute`).
This script reads the Java file, decodes the string literals exactly as
`javac` does (Unicode escapes first, then the octal escapes), runs the same
unpacking routines, checks each result against the array size the Java
routine allocates, and writes the unpacked tables as Rust `static` arrays.

    python3 tools/gen/standard_tokenizer_tables.py \
        [/tmp/lucene1050/lucene/core/src/java/org/apache/lucene/analysis/standard/StandardTokenizerImpl.java] \
        [src/analysis/standard/standard_tokenizer_impl_tables.rs]

`--check` compares the output with the existing file instead of writing it,
and exits 1 when they differ.
"""
import hashlib
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from java_source import string_literal_body, unicode_preprocess  # noqa: E402

DEFAULT_JAVA = (
    "/tmp/lucene1050/lucene/core/src/java/org/apache/lucene/analysis/standard/"
    "StandardTokenizerImpl.java"
)
DEFAULT_OUT = "src/analysis/standard/standard_tokenizer_impl_tables.rs"

# (Java table, packed constants, unpacking routine, Rust element type, doc)
TABLES = [
    ("ZZ_CMAP_TOP", "zzUnpackcmap_top", "rle", "i32",
     "Top-level table for translating characters to character classes."),
    ("ZZ_CMAP_BLOCKS", "zzUnpackcmap_blocks", "rle", "i32",
     "Second-level tables for translating characters to character classes."),
    ("ZZ_ACTION", "zzUnpackAction", "rle", "i32",
     "Translates DFA states to action switch labels."),
    ("ZZ_ROWMAP", "zzUnpackRowMap", "rowmap", "i32",
     "Translates a state to a row index in the transition table."),
    ("ZZ_TRANS", "zzUnpackTrans", "trans", "i32",
     "The transition table of the DFA."),
    ("ZZ_ATTRIBUTE", "zzUnpackAttribute", "rle", "i32",
     "`ZZ_ATTRIBUTE[aState]` contains the attributes of state `aState`."),
]


def packed_constant(src: str, name: str) -> list:
    """The UTF-16 units of `private static final String <name> = "..."+"...";`."""
    m = re.search(r"private static final String " + re.escape(name) + r"\s*=\s*(.*?);\n", src, re.S)
    if not m:
        raise SystemExit(f"{name} not found")
    expr = m.group(1)
    units = []
    pos = 0
    lit = re.compile(r'\s*"((?:[^"\\\n]|\\.)*)"\s*(\+)?', re.S)
    while pos < len(expr):
        lm = lit.match(expr, pos)
        if not lm:
            raise SystemExit(f"{name}: unexpected text at {pos}: {expr[pos:pos + 40]!r}")
        units.extend(string_literal_body(lm.group(1)))
        pos = lm.end()
        if lm.group(2) is None:
            if expr[pos:].strip():
                raise SystemExit(f"{name}: trailing text {expr[pos:]!r}")
            break
    return units


def allocated_size(src: str, routine: str) -> int:
    """The `new int[N]` of the no-argument unpacking routine."""
    m = re.search(r"private static int \[\] " + re.escape(routine) +
                  r"\(\) \{\s*int \[\] result = new int\[(\d+)\];(.*?)return result;", src, re.S)
    if not m:
        raise SystemExit(f"{routine}() not found")
    calls = re.findall(r"offset = " + re.escape(routine) + r"\((\w+), offset, result\);", m.group(2))
    return int(m.group(1)), calls


def unpack(kind: str, packed: list, size: int, result: list, offset: int) -> int:
    """The `zzUnpack*(String packed, int offset, int [] result)` routines."""
    i = 0
    j = offset
    n = len(packed)
    while i < n:
        if kind == "rowmap":
            high = packed[i] << 16
            i += 1
            result[j] = high | packed[i]
            i += 1
            j += 1
        else:
            count = packed[i]
            i += 1
            value = packed[i]
            i += 1
            if kind == "trans":
                value -= 1
            # do result[j++] = value; while (--count > 0);
            while True:
                result[j] = value
                j += 1
                count -= 1
                if count <= 0:
                    break
    return j


def to_i32(v: int) -> int:
    v &= 0xFFFFFFFF
    return v - (1 << 32) if v & 0x80000000 else v


def generate(java_path: str) -> str:
    raw = Path(java_path).read_text(encoding="utf-8")
    sha = hashlib.sha256(raw.encode("utf-8")).hexdigest()
    src = unicode_preprocess(raw)
    lines = [
        "// @generated by tools/gen/standard_tokenizer_tables.py from Lucene 10.5.0's",
        "// lucene/core/src/java/org/apache/lucene/analysis/standard/StandardTokenizerImpl.java",
        f"// (sha256 {sha}). DO NOT EDIT: rerun the script.",
        "",
        "//! The DFA tables of `StandardTokenizerImpl`, unpacked exactly as the",
        "//! static initializers of the JFlex-generated Java class unpack them.",
        "",
    ]
    for table, routine, kind, rty, doc in TABLES:
        size, consts = allocated_size(src, routine)
        if not consts:
            raise SystemExit(f"{routine}() unpacks nothing")
        result = [None] * size
        offset = 0
        for const in consts:
            offset = unpack(kind, packed_constant(src, const), size, result, offset)
        if offset != size or any(v is None for v in result):
            raise SystemExit(f"{table}: unpacked {offset} values into int[{size}]")
        values = [to_i32(v) for v in result]
        lines.append(f"/// {doc}")
        lines.append("///")
        lines.append(f"/// Equivalent to `StandardTokenizerImpl.{table}` (`{routine}()`).")
        lines.append("#[rustfmt::skip]")
        lines.append(f"pub(super) static {table}: [{rty}; {size}] = [")
        per_line = 16
        for k in range(0, size, per_line):
            lines.append("    " + ", ".join(str(v) for v in values[k:k + per_line]) + ",")
        lines.append("];")
        lines.append("")
    return "\n".join(lines)


def main(argv: list) -> int:
    check = "--check" in argv
    args = [a for a in argv if a != "--check"]
    java = args[0] if len(args) > 0 else DEFAULT_JAVA
    out = Path(args[1] if len(args) > 1 else DEFAULT_OUT)
    text = generate(java)
    if check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print(f"{out} differs from what {java} generates", file=sys.stderr)
            return 1
        print(f"{out} is current")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
