//! `java.lang` behaviour: `String.hashCode`, `String.trim`,
//! `Character.digit`, `Integer.parseInt`, `Long.parseLong`,
//! `Double.parseDouble`, `Float.parseFloat`, `Double.toString` and
//! `Float.toString`.
//!
//! Each function reproduces the JDK 25 contract from its javadoc; the
//! parsers' accepted grammars and values are pinned against JDK 25 by the
//! oracle grid in `tests/fixtures/java_lang.tsv`.

use std::sync::LazyLock;

/// `String.hashCode()`: `s[0]*31^(n-1) + ... + s[n-1]` over the UTF-16 code
/// units, in `int` arithmetic.
pub fn string_hash_code(s: &str) -> i32 {
    s.encode_utf16().fold(0i32, |h, unit| {
        h.wrapping_mul(31).wrapping_add(i32::from(unit))
    })
}

/// `String.trim()`: removes every leading and trailing char whose code is
/// `<= U+0020`. Unlike `str::trim`, it removes control characters and keeps
/// non-ASCII white space such as U+00A0.
pub fn trim(s: &str) -> &str {
    s.trim_matches(|c: char| c <= '\u{20}')
}

/// The zero of every run of `DECIMAL_DIGIT_NUMBER` code units in the Basic
/// Multilingual Plane, as JDK 25 reports them (`jdk/data/bmp_decimal_zeros.txt`,
/// generated by the oracle). Each run holds ten consecutive digits.
static BMP_DECIMAL_ZEROS: LazyLock<Vec<u16>> = LazyLock::new(|| {
    include_str!("data/bmp_decimal_zeros.txt")
        .lines()
        .filter(|l| !l.is_empty())
        .map(|l| u16::from_str_radix(l, 16).expect("hex code unit"))
        .collect()
});

/// `Character.digit(char ch, 10)`: the decimal value of the UTF-16 code unit
/// `ch`, or `-1`.
pub fn character_digit_10(ch: u16) -> i32 {
    let zeros = &*BMP_DECIMAL_ZEROS;
    let idx = zeros.partition_point(|&z| z <= ch);
    if idx == 0 {
        return -1;
    }
    let delta = ch - zeros[idx - 1];
    if delta < 10 {
        i32::from(delta)
    } else {
        -1
    }
}

/// The digits of `Integer.parseInt` / `Long.parseLong` in radix 10: an
/// optional `+` or `-` and at least one `Character.digit` digit, over the
/// UTF-16 code units of `s`, with overflow detection against `[min, max]`.
fn parse_decimal(s: &str, min: i64, max: i64) -> Option<i64> {
    let units: Vec<u16> = s.encode_utf16().collect();
    let (negative, digits) = match units.first() {
        None => return None,
        Some(&u) if u == u16::from(b'-') => (true, &units[1..]),
        Some(&u) if u == u16::from(b'+') => (false, &units[1..]),
        Some(_) => (false, &units[..]),
    };
    if digits.is_empty() {
        return None;
    }
    let mut value: i128 = 0;
    for &u in digits {
        let d = character_digit_10(u);
        if d < 0 {
            return None;
        }
        value = value * 10 + i128::from(d);
        if value > i128::from(max) + 1 {
            return None;
        }
    }
    let value = if negative { -value } else { value };
    if value < i128::from(min) || value > i128::from(max) {
        return None;
    }
    Some(value as i64)
}

/// `Integer.parseInt(s)`; `None` where Java throws `NumberFormatException`.
pub fn parse_int(s: &str) -> Option<i32> {
    parse_decimal(s, i64::from(i32::MIN), i64::from(i32::MAX)).map(|v| v as i32)
}

/// `Long.parseLong(s)`; `None` where Java throws `NumberFormatException`.
pub fn parse_long(s: &str) -> Option<i64> {
    parse_decimal(s, i64::MIN, i64::MAX)
}

/// The binary format a floating-point string is rounded to.
#[derive(Clone, Copy)]
struct BinaryFormat {
    /// Explicit significand bits (52 or 23).
    mant_bits: u32,
    /// Exponent bias (1023 or 127).
    bias: i64,
}

const F64_FORMAT: BinaryFormat = BinaryFormat {
    mant_bits: 52,
    bias: 1023,
};
const F32_FORMAT: BinaryFormat = BinaryFormat {
    mant_bits: 23,
    bias: 127,
};

/// Rounds `m * 2^e` (plus a nonzero remainder below `m`'s last bit when
/// `sticky`) to the nearest value of `format`, ties to even, and returns its
/// unsigned bit pattern (`+inf` on overflow).
fn round_binary(m: u64, e: i64, sticky: bool, format: BinaryFormat) -> u64 {
    if m == 0 {
        return 0;
    }
    let mb = i64::from(format.mant_bits);
    let emin = 1 - format.bias;
    let emax = format.bias;
    let inf_bits = ((2 * format.bias + 1) as u64) << format.mant_bits;
    let n = 64 - i64::from(m.leading_zeros());
    let top = e + n - 1;
    if top > emax + 1 {
        return inf_bits;
    }
    // The weight of the last bit kept.
    let unit = top.max(emin) - mb;
    let shift = unit - e;
    let q: u64 = if shift <= 0 {
        // Exact: fewer significant bits than the format keeps.
        m << (-shift)
    } else if shift > 64 {
        // The value is below half the smallest subnormal: it rounds to zero.
        0
    } else {
        let shift = shift as u32;
        let wide = u128::from(m);
        let kept = (wide >> shift) as u64;
        let rem = wide & ((1u128 << shift) - 1);
        let half = 1u128 << (shift - 1);
        let round_up = rem > half || (rem == half && (sticky || kept & 1 == 1));
        kept + u64::from(round_up)
    };
    let base = ((top.max(emin) + format.bias - 1) as u64) << format.mant_bits;
    let bits = base + q;
    if bits >= inf_bits {
        inf_bits
    } else {
        bits
    }
}

/// Parses the hexadecimal significand and binary exponent of a Java hex
/// floating-point literal (after the sign and `0x`), rounding to `format`.
/// `None` when the text does not match
/// `(HexDigits\.?|HexDigits?\.HexDigits)[pP][+-]?Digits[fFdD]?`.
fn parse_hex(body: &[u8], format: BinaryFormat) -> Option<u64> {
    let mut i = 0;
    let mut m: u64 = 0;
    let mut e: i64 = 0;
    let mut sticky = false;
    let mut digits = 0;
    let accumulate = |d: u64, fraction: bool, m: &mut u64, e: &mut i64, sticky: &mut bool| {
        if *m >> 60 == 0 {
            *m = (*m << 4) | d;
            if fraction {
                *e -= 4;
            }
        } else {
            if d != 0 {
                *sticky = true;
            }
            if !fraction {
                *e += 4;
            }
        }
    };
    while i < body.len() && body[i].is_ascii_hexdigit() {
        let d = u64::from((body[i] as char).to_digit(16)?);
        accumulate(d, false, &mut m, &mut e, &mut sticky);
        i += 1;
        digits += 1;
    }
    if i < body.len() && body[i] == b'.' {
        i += 1;
        while i < body.len() && body[i].is_ascii_hexdigit() {
            let d = u64::from((body[i] as char).to_digit(16)?);
            accumulate(d, true, &mut m, &mut e, &mut sticky);
            i += 1;
            digits += 1;
        }
    }
    if digits == 0 {
        return None;
    }
    if i >= body.len() || (body[i] != b'p' && body[i] != b'P') {
        return None;
    }
    i += 1;
    let mut exp_negative = false;
    if i < body.len() && (body[i] == b'+' || body[i] == b'-') {
        exp_negative = body[i] == b'-';
        i += 1;
    }
    let exp_start = i;
    let mut exp: i64 = 0;
    while i < body.len() && body[i].is_ascii_digit() {
        // Saturate: any exponent this large over- or underflows.
        exp = (exp * 10 + i64::from(body[i] - b'0')).min(1 << 40);
        i += 1;
    }
    if i == exp_start {
        return None;
    }
    if i < body.len() && matches!(body[i], b'f' | b'F' | b'd' | b'D') {
        i += 1;
    }
    if i != body.len() {
        return None;
    }
    let exp = if exp_negative { -exp } else { exp };
    Some(round_binary(m, e + exp, sticky, format))
}

/// Whether `body` (after the sign) is a Java decimal floating-point literal:
/// `Digits.Digits?Exponent?|.Digits Exponent?|Digits Exponent?`, where
/// `Exponent` is `[eE][+-]?Digits`. Returns the length without a trailing
/// `[fFdD]` suffix.
fn decimal_literal_len(body: &[u8]) -> Option<usize> {
    let mut i = 0;
    let mut digits = 0;
    while i < body.len() && body[i].is_ascii_digit() {
        i += 1;
        digits += 1;
    }
    if i < body.len() && body[i] == b'.' {
        i += 1;
        while i < body.len() && body[i].is_ascii_digit() {
            i += 1;
            digits += 1;
        }
    }
    if digits == 0 {
        return None;
    }
    if i < body.len() && (body[i] == b'e' || body[i] == b'E') {
        i += 1;
        if i < body.len() && (body[i] == b'+' || body[i] == b'-') {
            i += 1;
        }
        let start = i;
        while i < body.len() && body[i].is_ascii_digit() {
            i += 1;
        }
        if i == start {
            return None;
        }
    }
    let len = i;
    if i < body.len() && matches!(body[i], b'f' | b'F' | b'd' | b'D') {
        i += 1;
    }
    (i == body.len()).then_some(len)
}

/// What a Java floating-point string denotes, before rounding.
enum JavaFloat<'a> {
    NaN,
    Infinity(bool),
    /// A decimal literal (sign, then the literal without its suffix).
    Decimal(bool, &'a str),
    /// A hexadecimal literal (sign, then the text after `0x`).
    Hex(bool, &'a [u8]),
}

/// `FloatingDecimal.readJavaFormatString`'s grammar: `String.trim()`, an
/// optional sign, then `NaN`, `Infinity`, a hexadecimal literal or a decimal
/// literal with an optional `[fFdD]` suffix.
fn classify(s: &str) -> Option<JavaFloat<'_>> {
    let s = trim(s);
    let bytes = s.as_bytes();
    if bytes.is_empty() || !s.is_ascii() {
        return None;
    }
    let (negative, rest) = match bytes[0] {
        b'-' => (true, &s[1..]),
        b'+' => (false, &s[1..]),
        _ => (false, s),
    };
    if rest == "NaN" {
        return Some(JavaFloat::NaN);
    }
    if rest == "Infinity" {
        return Some(JavaFloat::Infinity(negative));
    }
    let rb = rest.as_bytes();
    if rb.len() >= 2 && rb[0] == b'0' && (rb[1] == b'x' || rb[1] == b'X') {
        return Some(JavaFloat::Hex(negative, &rb[2..]));
    }
    let len = decimal_literal_len(rb)?;
    Some(JavaFloat::Decimal(negative, &rest[..len]))
}

/// `Double.parseDouble(s)`; `None` where Java throws
/// `NumberFormatException`.
pub fn parse_double(s: &str) -> Option<f64> {
    match classify(s)? {
        JavaFloat::NaN => Some(f64::NAN),
        JavaFloat::Infinity(neg) => Some(if neg {
            f64::NEG_INFINITY
        } else {
            f64::INFINITY
        }),
        JavaFloat::Decimal(neg, lit) => {
            // The literal matches Java's grammar, which `f64::from_str`
            // accepts and rounds correctly, as Java does.
            let v: f64 = lit.parse().ok()?;
            Some(if neg { -v } else { v })
        }
        JavaFloat::Hex(neg, body) => {
            let v = f64::from_bits(parse_hex(body, F64_FORMAT)?);
            Some(if neg { -v } else { v })
        }
    }
}

/// `Float.parseFloat(s)`; `None` where Java throws `NumberFormatException`.
/// The string is rounded to `float` directly, not through `double`.
pub fn parse_float(s: &str) -> Option<f32> {
    match classify(s)? {
        JavaFloat::NaN => Some(f32::NAN),
        JavaFloat::Infinity(neg) => Some(if neg {
            f32::NEG_INFINITY
        } else {
            f32::INFINITY
        }),
        JavaFloat::Decimal(neg, lit) => {
            let v: f32 = lit.parse().ok()?;
            Some(if neg { -v } else { v })
        }
        JavaFloat::Hex(neg, body) => {
            let v = f32::from_bits(parse_hex(body, F32_FORMAT)? as u32);
            Some(if neg { -v } else { v })
        }
    }
}

/// Formats shortest decimal digits as `Double.toString` / `Float.toString`
/// do: plain notation with at least one fraction digit for magnitudes in
/// `[10^-3, 10^7)`, otherwise `d.dddE[-]n`.
fn java_float_format(sci: &str, negative: bool) -> String {
    // `sci` is Rust's shortest round-trip form, `d[.ddd]e[-]n`.
    let (mantissa, exp) = sci.split_once('e').expect("scientific notation");
    let exp: i32 = exp.parse().expect("exponent");
    let digits: String = mantissa.chars().filter(|c| *c != '.').collect();
    let mut out = String::new();
    if negative {
        out.push('-');
    }
    if (-3..7).contains(&exp) {
        if exp < 0 {
            out.push_str("0.");
            for _ in 0..(-exp - 1) {
                out.push('0');
            }
            out.push_str(&digits);
        } else {
            let int_len = (exp + 1) as usize;
            if digits.len() <= int_len {
                out.push_str(&digits);
                for _ in digits.len()..int_len {
                    out.push('0');
                }
                out.push_str(".0");
            } else {
                out.push_str(&digits[..int_len]);
                out.push('.');
                out.push_str(&digits[int_len..]);
            }
        }
    } else {
        out.push_str(&digits[..1]);
        out.push('.');
        if digits.len() > 1 {
            out.push_str(&digits[1..]);
        } else {
            out.push('0');
        }
        out.push('E');
        out.push_str(&exp.to_string());
    }
    out
}

/// `Double.toString(d)`.
pub fn double_to_string(d: f64) -> String {
    if d.is_nan() {
        return "NaN".to_string();
    }
    if d.is_infinite() {
        return if d > 0.0 { "Infinity" } else { "-Infinity" }.to_string();
    }
    if d == 0.0 {
        return if d.is_sign_negative() { "-0.0" } else { "0.0" }.to_string();
    }
    java_float_format(&format!("{:e}", d.abs()), d < 0.0)
}

/// `Float.toString(f)`.
pub fn float_to_string(f: f32) -> String {
    if f.is_nan() {
        return "NaN".to_string();
    }
    if f.is_infinite() {
        return if f > 0.0 { "Infinity" } else { "-Infinity" }.to_string();
    }
    if f == 0.0 {
        return if f.is_sign_negative() { "-0.0" } else { "0.0" }.to_string();
    }
    java_float_format(&format!("{:e}", f.abs()), f < 0.0)
}

/// `Integer.toHexString(i)`: lower-case hex of the unsigned value.
pub fn integer_to_hex_string(i: i32) -> String {
    format!("{:x}", i as u32)
}
