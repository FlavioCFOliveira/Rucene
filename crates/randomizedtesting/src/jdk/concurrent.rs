    #[test]
    fn convert_matches_jdk25_on_every_unit_pair() {
        for (src, (name, row)) in UNITS.iter().zip(JDK25) {
            let expected: Vec<i64> = row.split(',').map(|v| v.parse().unwrap()).collect();
            let actual: Vec<i64> = UNITS
                .iter()
                .flat_map(|dst| DURATIONS.iter().map(move |d| dst.convert(*d, *src)))
                .collect();
            assert_eq!(actual, expected, "source unit {name}");
        }
    }

    /// The `toX` methods, against the same JDK 25 probe.
    #[test]
    fn to_x_matches_jdk25() {
        assert_eq!(TimeUnit::Milliseconds.to_nanos(9_223_372_036_855), i64::MAX);
        assert_eq!(TimeUnit::Days.to_nanos(106_752), i64::MAX);
        assert_eq!(TimeUnit::Nanoseconds.to_millis(-1_999_999), -1);
        assert_eq!(TimeUnit::Minutes.to_seconds(i64::MIN / 30), i64::MIN);
        assert_eq!(TimeUnit::Seconds.to_minutes(-119), -1);
        assert_eq!(TimeUnit::Hours.to_days(49), 2);
        assert_eq!(
            TimeUnit::Microseconds.convert(-9_223_372_036_854_775, TimeUnit::Milliseconds),
            -9_223_372_036_854_775_000
        );
        assert_eq!(
            TimeUnit::Microseconds.convert(-9_223_372_036_854_776, TimeUnit::Milliseconds),
            i64::MIN
        );
        assert_eq!(TimeUnit::Seconds.to_micros(3), 3_000_000);
        assert_eq!(TimeUnit::Days.to_hours(2), 48);
    }
