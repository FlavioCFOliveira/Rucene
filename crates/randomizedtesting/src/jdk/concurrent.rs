//! `java.util.concurrent` behaviour the runner depends on: `TimeUnit`.

/// `java.util.concurrent.TimeUnit`: a time duration at a given unit of
/// granularity, and the conversions between units.
///
/// Emulates the JDK 25 enum (javadoc of `TimeUnit`), verified against
/// OpenJDK 25.0.5: every conversion to a finer unit multiplies and
/// **saturates** at `Long.MAX_VALUE` or `Long.MIN_VALUE` on overflow; every
/// conversion to a coarser unit divides, truncating toward zero.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum TimeUnit {
    /// `NANOSECONDS`: a thousandth of a microsecond.
    Nanoseconds,
    /// `MICROSECONDS`: a thousandth of a millisecond.
    Microseconds,
    /// `MILLISECONDS`: a thousandth of a second.
    Milliseconds,
    /// `SECONDS`.
    Seconds,
    /// `MINUTES`: sixty seconds.
    Minutes,
    /// `HOURS`: sixty minutes.
    Hours,
    /// `DAYS`: twenty-four hours.
    Days,
}

impl TimeUnit {
    /// The length of one unit, in nanoseconds.
    const fn nanos_per_unit(self) -> i64 {
        match self {
            TimeUnit::Nanoseconds => 1,
            TimeUnit::Microseconds => 1_000,
            TimeUnit::Milliseconds => 1_000_000,
            TimeUnit::Seconds => 1_000_000_000,
            TimeUnit::Minutes => 60_000_000_000,
            TimeUnit::Hours => 3_600_000_000_000,
            TimeUnit::Days => 86_400_000_000_000,
        }
    }

    /// `duration` of `from` expressed in `to`: an exact multiple of the
    /// ratio, saturated, toward a finer unit; a quotient truncated toward
    /// zero toward a coarser one.
    fn convert_between(duration: i64, from: TimeUnit, to: TimeUnit) -> i64 {
        let (src, dst) = (from.nanos_per_unit(), to.nanos_per_unit());
        if src >= dst {
            // Every ratio is exact: each scale divides the coarser ones.
            let ratio = src / dst;
            duration
                .checked_mul(ratio)
                .unwrap_or(if duration > 0 { i64::MAX } else { i64::MIN })
        } else {
            duration / (dst / src)
        }
    }

    /// `convert(long sourceDuration, TimeUnit sourceUnit)`: the duration
    /// `source_duration` of `source_unit` in this unit, saturated on
    /// overflow; `convert(999, MILLISECONDS)` in `SECONDS` is `0`.
    pub fn convert(self, source_duration: i64, source_unit: TimeUnit) -> i64 {
        Self::convert_between(source_duration, source_unit, self)
    }

    /// `toNanos(long duration)`: `NANOSECONDS.convert(duration, this)`.
    pub fn to_nanos(self, duration: i64) -> i64 {
        TimeUnit::Nanoseconds.convert(duration, self)
    }

    /// `toMicros(long duration)`: `MICROSECONDS.convert(duration, this)`.
    pub fn to_micros(self, duration: i64) -> i64 {
        TimeUnit::Microseconds.convert(duration, self)
    }

    /// `toMillis(long duration)`: `MILLISECONDS.convert(duration, this)`.
    pub fn to_millis(self, duration: i64) -> i64 {
        TimeUnit::Milliseconds.convert(duration, self)
    }

    /// `toSeconds(long duration)`: `SECONDS.convert(duration, this)`.
    pub fn to_seconds(self, duration: i64) -> i64 {
        TimeUnit::Seconds.convert(duration, self)
    }

    /// `toMinutes(long duration)`: `MINUTES.convert(duration, this)`.
    pub fn to_minutes(self, duration: i64) -> i64 {
        TimeUnit::Minutes.convert(duration, self)
    }

    /// `toHours(long duration)`: `HOURS.convert(duration, this)`.
    pub fn to_hours(self, duration: i64) -> i64 {
        TimeUnit::Hours.convert(duration, self)
    }

    /// `toDays(long duration)`: `DAYS.convert(duration, this)`.
    pub fn to_days(self, duration: i64) -> i64 {
        TimeUnit::Days.convert(duration, self)
    }
}

