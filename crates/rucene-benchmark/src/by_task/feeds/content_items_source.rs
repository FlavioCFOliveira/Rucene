//! The types declared in `ContentItemsSource.java`, of the Java package
//! `org.apache.lucene.benchmark.byTask.feeds`.

use std::any::Any;
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex, MutexGuard};

use rucene::error::Result;

use crate::by_task::utils::config::Config;
use crate::by_task::utils::format::Format;
use crate::jdk::NEW_LINE;

/// The fields of `ContentItemsSource`.
#[derive(Debug, Default)]
struct ItemsState {
    bytes_count: i64,
    total_bytes_count: i64,
    item_count: i32,
    total_item_count: i32,
    config: Option<Arc<Config>>,
    last_printed_num_unique_texts: i32,
    last_printed_num_unique_bytes: i64,
    print_num: i32,
    forever: bool,
    log_step: i32,
    verbose: bool,
    encoding: Option<String>,
}

/// The state and the `final`/`protected` members of
/// `org.apache.lucene.benchmark.byTask.feeds.ContentItemsSource`, which every
/// source embeds.
///
/// Keeps track of various statistics, such as how many data items were
/// generated, size in bytes etc.
///
/// Supports the following configuration parameters:
///
/// * **content.source.forever** - specifies whether to generate items
///   forever (**default=true**).
/// * **content.source.verbose** - specifies whether messages should be
///   output by the content source (**default=false**).
/// * **content.source.encoding** - specifies which encoding to use when
///   reading the files of that content source. Certain implementations may
///   define a default value if this parameter is not specified.
///   (**default=null**).
/// * **content.source.log.step** - specifies for how many items a message
///   should be logged. If set to 0 it means no logging should occur.
///   **NOTE:** if verbose is set to false, logging should not occur even if
///   logStep is not 0 (**default=0**).
#[derive(Debug, Default)]
pub struct ContentItemsSourceBase {
    state: Mutex<ItemsState>,
}

impl ContentItemsSourceBase {
    /// A fresh base: every count 0, no config.
    pub fn new() -> Self {
        Self::default()
    }

    fn lock(&self) -> MutexGuard<'_, ItemsState> {
        self.state.lock().unwrap_or_else(|e| e.into_inner())
    }

    /// `addBytes(long numBytes)`: update count of bytes generated by this
    /// source.
    pub fn add_bytes(&self, num_bytes: i64) {
        let mut s = self.lock();
        s.bytes_count += num_bytes;
        s.total_bytes_count += num_bytes;
    }

    /// `addItem()`: update count of items generated by this source.
    pub fn add_item(&self) {
        let mut s = self.lock();
        s.item_count += 1;
        s.total_item_count += 1;
    }

    /// `collectFiles(Path dir, ArrayList<Path> files)`: a convenience method
    /// for collecting all the files of a content source from a given
    /// directory (`Files.walkFileTree`, which does not follow links), each
    /// readable file stored as its real path.
    ///
    /// # Errors
    ///
    /// The `IOException` of walking the tree or of `toRealPath`.
    pub fn collect_files(dir: &Path, files: &mut Vec<PathBuf>) -> Result<()> {
        let meta = std::fs::symlink_metadata(dir)?;
        if meta.is_dir() {
            for entry in std::fs::read_dir(dir)? {
                let entry = entry?;
                Self::collect_files(&entry.path(), files)?;
            }
        } else if std::fs::File::open(dir).is_ok() {
            files.push(std::fs::canonicalize(dir)?);
        }
        Ok(())
    }

    /// `shouldLog()`: whether it's time to log a message (depending on
    /// verbose and the number of items generated).
    pub fn should_log(&self) -> bool {
        let s = self.lock();
        s.verbose && s.log_step > 0 && s.item_count % s.log_step == 0
    }

    /// `getBytesCount()`: the number of bytes generated since last reset.
    pub fn get_bytes_count(&self) -> i64 {
        self.lock().bytes_count
    }

    /// `getItemsCount()`: the number of generated items since last reset.
    pub fn get_items_count(&self) -> i32 {
        self.lock().item_count
    }

    /// `getConfig()`.
    pub fn get_config(&self) -> Option<Arc<Config>> {
        self.lock().config.clone()
    }

    /// `getTotalBytesCount()`: the total number of bytes that were generated
    /// by this source.
    pub fn get_total_bytes_count(&self) -> i64 {
        self.lock().total_bytes_count
    }

    /// `getTotalItemsCount()`: the total number of generated items.
    pub fn get_total_items_count(&self) -> i32 {
        self.lock().total_item_count
    }

    /// `ContentItemsSource.resetInputs()`: resets the number of bytes and
    /// items generated since the last reset.
    pub fn reset_inputs(&self) {
        let mut s = self.lock();
        s.bytes_count = 0;
        s.item_count = 0;
    }

    /// `ContentItemsSource.setConfig(Config)`.
    ///
    /// # Errors
    ///
    /// The `NumberFormatException`/`ClassCastException` of reading the
    /// properties.
    pub fn set_config(&self, config: Arc<Config>) -> Result<()> {
        let forever = config.get_bool("content.source.forever", true)?;
        let log_step = config.get_int("content.source.log.step", 0)?;
        let verbose = config.get_bool("content.source.verbose", false)?;
        let encoding = config.get_str("content.source.encoding", None)?;
        let mut s = self.lock();
        s.config = Some(config);
        s.forever = forever;
        s.log_step = log_step;
        s.verbose = verbose;
        s.encoding = encoding;
        Ok(())
    }

    /// `forever`.
    pub fn forever(&self) -> bool {
        self.lock().forever
    }

    /// `logStep`.
    pub fn log_step(&self) -> i32 {
        self.lock().log_step
    }

    /// `verbose`.
    pub fn verbose(&self) -> bool {
        self.lock().verbose
    }

    /// `encoding`.
    pub fn encoding(&self) -> Option<String> {
        self.lock().encoding.clone()
    }

    /// `encoding = value`.
    pub fn set_encoding(&self, encoding: Option<String>) {
        self.lock().encoding = encoding;
    }

    /// `printStatistics(String itemsName)` of a source whose
    /// `getClass().getSimpleName()` is `simple_name`.
    pub fn print_statistics(&self, simple_name: &str, items_name: &str) {
        let mut s = self.lock();
        if !s.verbose {
            return;
        }
        let mut print = false;
        let col = "                  ";
        let mut sb = String::new();
        let newline = NEW_LINE;
        sb.push_str(&format!("------------> {simple_name} statistics ({}): {newline}", s.print_num));
        let nut = s.total_item_count;
        if nut > s.last_printed_num_unique_texts {
            print = true;
            sb.push_str(&format!(
                "total count of {items_name}: {}{newline}",
                Format::format_double(0, f64::from(nut), col)
            ));
            s.last_printed_num_unique_texts = nut;
        }
        let nub = s.total_bytes_count;
        if nub > s.last_printed_num_unique_bytes {
            print = true;
            sb.push_str(&format!(
                "total bytes of {items_name}: {}{newline}",
                Format::format_double(0, nub as f64, col)
            ));
            s.last_printed_num_unique_bytes = nub;
        }
        if s.item_count > 0 {
            print = true;
            sb.push_str(&format!(
                "num {items_name} added since last inputs reset:   {}{newline}",
                Format::format_double(0, f64::from(s.item_count), col)
            ));
            sb.push_str(&format!(
                "total bytes added for {items_name} since last inputs reset: {}{newline}",
                Format::format_double(0, s.bytes_count as f64, col)
            ));
        }
        if print {
            sb.push_str(newline);
            println!("{sb}");
            s.print_num += 1;
        }
    }
}

/// Equivalent to `org.apache.lucene.benchmark.byTask.feeds.ContentItemsSource`
/// (`public abstract class ContentItemsSource implements Closeable`): base
/// class for source of data for benchmarking.
///
/// A source is shared by every task and thread of a run, so its methods
/// take `&self`; the base's state is [`ContentItemsSourceBase`].
pub trait ContentItemsSource: Send + Sync + Any {
    /// The embedded base state.
    fn items_base(&self) -> &ContentItemsSourceBase;

    /// `getClass().getSimpleName()`.
    fn java_simple_name(&self) -> &'static str;

    /// `close()`: called when reading from this content source is no longer
    /// required.
    ///
    /// # Errors
    ///
    /// The `IOException` of closing.
    fn close(&self) -> Result<()>;

    /// `resetInputs()`: resets the input for this content source, so that
    /// the test would behave as if it was just started, input-wise.
    ///
    /// **NOTE:** the default implementation resets the number of bytes and
    /// items generated since the last reset, so it's important to call
    /// [`ContentItemsSourceBase::reset_inputs`] in case you override this
    /// method.
    ///
    /// # Errors
    ///
    /// The `IOException` of reopening the input.
    fn reset_inputs(&self) -> Result<()> {
        self.items_base().reset_inputs();
        Ok(())
    }

    /// `setConfig(Config)`: sets the [`Config`] for this content source. If
    /// you override this method, you must call
    /// [`ContentItemsSourceBase::set_config`].
    ///
    /// # Errors
    ///
    /// The exception of reading the configuration.
    fn set_config(&self, config: Arc<Config>) -> Result<()> {
        self.items_base().set_config(config)
    }

    /// `printStatistics(String itemsName)`.
    fn print_statistics(&self, items_name: &str) {
        self.items_base().print_statistics(self.java_simple_name(), items_name);
    }

    /// `getBytesCount()`.
    fn get_bytes_count(&self) -> i64 {
        self.items_base().get_bytes_count()
    }

    /// `getItemsCount()`.
    fn get_items_count(&self) -> i32 {
        self.items_base().get_items_count()
    }

    /// `getTotalBytesCount()`.
    fn get_total_bytes_count(&self) -> i64 {
        self.items_base().get_total_bytes_count()
    }

    /// `getTotalItemsCount()`.
    fn get_total_items_count(&self) -> i32 {
        self.items_base().get_total_items_count()
    }

    /// `getConfig()`.
    fn get_config(&self) -> Option<Arc<Config>> {
        self.items_base().get_config()
    }

    /// This source as `Any`, for `instanceof`.
    fn as_any(&self) -> &dyn Any;
}
