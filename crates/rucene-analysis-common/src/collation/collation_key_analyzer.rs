//! Configures `KeywordTokenizer` with `CollationAttributeFactory`, ported
//! from `org.apache.lucene.collation.CollationKeyAnalyzer`.

use std::sync::Arc;

use rucene::analysis::{Analyzer, AnalyzerState, GlobalReuseStrategy, TokenStreamComponents};
use rucene::error::Result;
use rucene::util::atomic_ref_cell::AtomicRefCell;
use rucene::util::attribute::AttributeFactory;

use super::collation_attribute_factory::CollationAttributeFactory;
use crate::analysis::core::keyword_tokenizer::{
    new_keyword_tokenizer_with_factory, DEFAULT_BUFFER_SIZE,
};
use crate::jdk::collator::RuleBasedCollator;

/// Configures `KeywordTokenizer` with `CollationAttributeFactory`.
///
/// Converts the token into its `java.text.CollationKey`, and then encodes
/// the CollationKey directly to allow it to be stored as an index term.
///
/// **WARNING:** Make sure you use exactly the same Collator at index and
/// query time -- CollationKeys are only comparable when produced by the same
/// Collator. Since `java.text.RuleBasedCollator`s are not independently
/// versioned, it is unsafe to search against stored CollationKeys unless the
/// following are exactly the same (best practice is to store this
/// information with the index and check that they remain the same at query
/// time):
///
/// 1. JVM vendor
/// 2. JVM version, including patch version
/// 3. The language (and country and variant, if specified) of the Locale used
///    when constructing the collator via `Collator.getInstance(Locale)`.
/// 4. The collation strength used - see `Collator.setStrength(int)`
///
/// The `ICUCollationKeyAnalyzer` in the analysis-icu package uses ICU4J's
/// Collator, which makes its version available, thus allowing collation to
/// be versioned independently from the JVM. ICUCollationKeyAnalyzer is also
/// significantly faster and generates significantly shorter keys than
/// CollationKeyAnalyzer. See
/// [http://site.icu-project.org/charts/collation-icu4j-sun](http://site.icu-project.org/charts/collation-icu4j-sun)
/// for key generation timing and key length comparisons between ICU4J and
/// java.text.Collator over several languages.
///
/// CollationKeys generated by java.text.Collators are not compatible with
/// those those generated by ICU Collators. Specifically, if you use
/// CollationKeyAnalyzer to generate index terms, do not use
/// ICUCollationKeyAnalyzer on the query side, or vice versa.
///
/// Equivalent to `org.apache.lucene.collation.CollationKeyAnalyzer` (since
/// 3.1).
#[derive(Debug)]
pub struct CollationKeyAnalyzer {
    state: AnalyzerState,
    factory: Arc<CollationAttributeFactory>,
}

impl CollationKeyAnalyzer {
    /// Create a new CollationKeyAnalyzer, using the specified collator.
    ///
    /// * `collator`: CollationKey generator
    ///
    /// Equivalent to `CollationKeyAnalyzer(Collator)`, whose `Analyzer()`
    /// uses `GLOBAL_REUSE_STRATEGY`.
    pub fn new(collator: &RuleBasedCollator) -> Self {
        Self {
            state: AnalyzerState::new(Box::new(GlobalReuseStrategy)),
            factory: Arc::new(CollationAttributeFactory::new(collator)),
        }
    }
}

impl Analyzer for CollationKeyAnalyzer {
    fn analyzer_state(&self) -> &AnalyzerState {
        &self.state
    }

    fn java_class_name(&self) -> &'static str {
        "org.apache.lucene.collation.CollationKeyAnalyzer"
    }

    /// Equivalent to `CollationKeyAnalyzer.attributeFactory(String)`: the
    /// analyzer's `CollationAttributeFactory`.
    fn attribute_factory(&self, _field_name: &str) -> Arc<dyn AttributeFactory> {
        self.factory.clone()
    }

    /// Equivalent to `CollationKeyAnalyzer.createComponents(String)`: a
    /// `KeywordTokenizer(factory, KeywordTokenizer.DEFAULT_BUFFER_SIZE)`.
    fn create_components(&self, _field_name: &str) -> Result<TokenStreamComponents> {
        let tokenizer =
            new_keyword_tokenizer_with_factory(self.factory.clone(), DEFAULT_BUFFER_SIZE)?;
        Ok(TokenStreamComponents::from_tokenizer(Arc::new(
            AtomicRefCell::new(tokenizer),
        )))
    }
}
