//! Converts each token into its `CollationKey`, and then encodes the bytes
//! as an index term, ported from
//! `org.apache.lucene.collation.CollationAttributeFactory`.

use std::any::TypeId;
use std::fmt;
use std::sync::Arc;

use rucene::analysis::default_token_attribute_factory;
use rucene::error::LuceneError;
use rucene::util::attribute::{
    AttributeFactory, AttributeImpl, StaticImplementationAttributeFactory,
};

use super::tokenattributes::collated_term_attribute_impl::CollatedTermAttributeImpl;
use crate::jdk::collator::RuleBasedCollator;

/// Converts each token into its `java.text.CollationKey`, and then encodes
/// the bytes as an index term.
///
/// **WARNING:** Make sure you use exactly the same Collator at index and
/// query time -- CollationKeys are only comparable when produced by the same
/// Collator. Since `java.text.RuleBasedCollator`s are not independently
/// versioned, it is unsafe to search against stored CollationKeys unless the
/// following are exactly the same (best practice is to store this
/// information with the index and check that they remain the same at query
/// time):
///
/// 1. JVM vendor
/// 2. JVM version, including patch version
/// 3. The language (and country and variant, if specified) of the Locale used
///    when constructing the collator via `Collator.getInstance(Locale)`.
/// 4. The collation strength used - see `Collator.setStrength(int)`
///
/// The `ICUCollationAttributeFactory` in the analysis-icu package uses
/// ICU4J's Collator, which makes its version available, thus allowing
/// collation to be versioned independently from the JVM.
/// ICUCollationAttributeFactory is also significantly faster and generates
/// significantly shorter keys than CollationAttributeFactory. See
/// [http://site.icu-project.org/charts/collation-icu4j-sun](http://site.icu-project.org/charts/collation-icu4j-sun)
/// for key generation timing and key length comparisons between ICU4J and
/// java.text.Collator over several languages.
///
/// CollationKeys generated by java.text.Collators are not compatible with
/// those those generated by ICU Collators. Specifically, if you use
/// CollationAttributeFactory to generate index terms, do not use
/// ICUCollationAttributeFactory on the query side, or vice versa.
///
/// The collator is the emulation of JDK 25's [`RuleBasedCollator`]; the keys
/// are JDK 25's.
///
/// Equivalent to `org.apache.lucene.collation.CollationAttributeFactory`,
/// which extends
/// `AttributeFactory.StaticImplementationAttributeFactory<CollatedTermAttributeImpl>`:
/// the base is the [`StaticImplementationAttributeFactory`] this factory
/// holds, whose `createInstance()` is [`create_instance`](Self::create_instance).
pub struct CollationAttributeFactory {
    base: StaticImplementationAttributeFactory,
    collator: RuleBasedCollator,
}

impl CollationAttributeFactory {
    /// Create a CollationAttributeFactory, using
    /// `TokenStream.DEFAULT_TOKEN_ATTRIBUTE_FACTORY` as the factory for all
    /// other attributes.
    ///
    /// * `collator`: CollationKey generator
    ///
    /// Equivalent to `CollationAttributeFactory(Collator)`.
    pub fn new(collator: &RuleBasedCollator) -> Self {
        Self::with_delegate(default_token_attribute_factory(), collator)
    }

    /// Create a CollationAttributeFactory, using the supplied Attribute
    /// Factory as the factory for all other attributes.
    ///
    /// * `delegate`: Attribute Factory
    /// * `collator`: CollationKey generator
    ///
    /// Equivalent to `CollationAttributeFactory(AttributeFactory, Collator)`,
    /// which keeps the collator itself (each attribute clones it).
    pub fn with_delegate(
        delegate: Arc<dyn AttributeFactory>,
        collator: &RuleBasedCollator,
    ) -> Self {
        let instance_collator = collator.clone();
        Self {
            base: StaticImplementationAttributeFactory::new(
                delegate,
                CollatedTermAttributeImpl::interfaces(),
                move || CollatedTermAttributeImpl::new(&instance_collator),
            ),
            collator: collator.clone(),
        }
    }

    /// Equivalent to `CollationAttributeFactory.createInstance()`, `new
    /// CollatedTermAttributeImpl(collator)`.
    pub fn create_instance(&self) -> CollatedTermAttributeImpl {
        CollatedTermAttributeImpl::new(&self.collator)
    }
}

impl fmt::Debug for CollationAttributeFactory {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("CollationAttributeFactory")
            .field("base", &self.base)
            .finish_non_exhaustive()
    }
}

impl AttributeFactory for CollationAttributeFactory {
    /// The inherited final
    /// `StaticImplementationAttributeFactory.createAttributeInstance(Class)`:
    /// a [`CollatedTermAttributeImpl`] for the interfaces it implements, the
    /// delegate's attribute for any other.
    fn create_attribute_instance(
        &self,
        attribute_type: TypeId,
    ) -> Result<Box<dyn AttributeImpl>, LuceneError> {
        self.base.create_attribute_instance(attribute_type)
    }
}
