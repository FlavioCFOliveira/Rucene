//! The JDK behaviour `lucene/analysis/common` calls that the `rucene` crate
//! does not emulate.
//!
//! **Divergence.** These modules are emulations, not ports of a Lucene file:
//! the JDK is GPL with the Classpath Exception, so each one reproduces, from
//! the JDK's specification, the part of JDK 25 the module calls, verified
//! against a JDK 25 oracle. Each states at its point what the JDK does and
//! where the emulation differs.

pub mod base64;
pub mod break_dictionary;
pub mod break_iterator;
pub mod break_iterator_rules;
pub mod byte_buffer;
pub mod character;
pub mod charset;
pub mod charset_multibyte;
// Generated by `tools/translate/JdkCharsetData.java`; its layout is not rustfmt's.
#[rustfmt::skip]
mod charset_data;
// Generated from a JDK 25 oracle; its layout is not rustfmt's.
#[rustfmt::skip]
mod character_data;
// Generated by `tools/translate/JdkCharacterTypeData.java`; its layout is not rustfmt's.
#[rustfmt::skip]
mod character_type_data;
pub mod character_iterator;
pub mod io;
pub mod locale;
pub mod locale_data;
pub mod sax;
pub mod simple_date_format;
pub mod string;
pub mod system;
pub mod time_zone;
pub mod zip_input_stream;
