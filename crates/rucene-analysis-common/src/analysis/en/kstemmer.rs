/// An entry of the stemmer's dictionary.
///
/// Equivalent to `org.apache.lucene.analysis.en.KStemmer$DictEntry`; its
/// `root` is one of the static tables' strings, `None` for Java's `null`.
#[derive(Debug, Clone, Copy)]
pub(crate) struct DictEntry {
    pub(crate) exception: bool,
    pub(crate) root: Option<&'static str>,
}

impl DictEntry {
    /// Equivalent to `DictEntry(String, boolean)`.
    pub(crate) fn new(root: Option<&'static str>, is_exception: bool) -> Self {
        Self {
            root,
            exception: is_exception,
        }
    }
}

/// Equivalent to `KStemmer.dict_ht`, built by `initializeDictHash()`.
static DICT_HT: LazyLock<CharArrayMap<DictEntry>> = LazyLock::new(initialize_dict_hash);

/// The UTF-16 units of an ASCII string, the `char[]` Java's string literals
/// give.
fn units(s: &str) -> Vec<u16> {
    s.encode_utf16().collect()
}

/// `throw new RuntimeException(message)` of `initializeDictHash()`, which
/// Java raises from the class's static initializer (as an
/// `ExceptionInInitializerError`); the tables hold no duplicate, so it is
/// never raised.
fn duplicate_entry(message: String) -> ! {
    rucene::store::java_nio_file::throw_unchecked("java.lang.RuntimeException", Some(&message))
}

/// Equivalent to `KStemmer.initializeDictHash()`.
fn initialize_dict_hash() -> CharArrayMap<DictEntry> {
    let mut d: CharArrayMap<DictEntry> = CharArrayMap::new(1000, false);
    for &exception_word in EXCEPTION_WORDS {
        if !d.contains_key(exception_word) {
            let entry = DictEntry::new(Some(exception_word), true);
            d.put(exception_word, entry);
        } else {
            duplicate_entry(format!(
                "Warning: Entry [{exception_word}] already in dictionary 1"
            ));
        }
    }

    for direct_conflation in DIRECT_CONFLATIONS {
        if !d.contains_key(direct_conflation[0]) {
            let entry = DictEntry::new(Some(direct_conflation[1]), false);
            d.put(direct_conflation[0], entry);
        } else {
            duplicate_entry(format!(
                "Warning: Entry [{}] already in dictionary 2",
                direct_conflation[0]
            ));
        }
    }

    for strings in COUNTRY_NATIONALITY {
        if !d.contains_key(strings[0]) {
            let entry = DictEntry::new(Some(strings[1]), false);
            d.put(strings[0], entry);
        } else {
            duplicate_entry(format!(
                "Warning: Entry [{}] already in dictionary 3",
                strings[0]
            ));
        }
    }

    let default_entry = DictEntry::new(None, false);

    for array in [
        KStemData1::DATA,
        KStemData2::DATA,
        KStemData3::DATA,
        KStemData4::DATA,
        KStemData5::DATA,
        KStemData6::DATA,
        KStemData7::DATA,
        KStemData8::DATA,
    ] {
        for &s in array {
            if !d.contains_key(s) {
                d.put(s, default_entry);
            } else {
                duplicate_entry(format!("Warning: Entry [{s}] already in dictionary 4"));
            }
        }
    }

    for &s in SUPPLEMENT_DICT {
        if !d.contains_key(s) {
            d.put(s, default_entry);
        } else {
            duplicate_entry(format!("Warning: Entry [{s}] already in dictionary 5"));
        }
    }

    for &proper_noun in PROPER_NOUNS {
        if !d.contains_key(proper_noun) {
            d.put(proper_noun, default_entry);
        } else {
            duplicate_entry(format!(
                "Warning: Entry [{proper_noun}] already in dictionary 6"
            ));
        }
    }

    d
}

/// The result of the last stem, as [`KStemmer::as_char_sequence`] returns
/// it: Java's `CharSequence`, either the `result` string or the `word`
/// builder.
#[derive(Debug, Clone, Copy)]
pub(crate) enum StemResult<'a> {
    /// The root of a dictionary entry, Java's `result`.
    Root(&'static str),
    /// The UTF-16 units of the stemmed word, Java's `word`.
    Word(&'a [u16]),
}

/// This class implements the Kstem algorithm.
///
/// Equivalent to `org.apache.lucene.analysis.en.KStemmer`. The term it
/// stems is the `char[]` of Java, UTF-16 units.
#[derive(Debug)]
pub(crate) struct KStemmer {
    word: OpenStringBuilder,
    /// index of final letter in stem (within word)
    j: i32,
    /// INDEX of final letter in word. You must add 1 to k to get the current
    /// length of word. When you want the length of word, use the method
    /// wordLength, which returns (k+1).
    k: i32,
    /// Returns true if the word is found in the dictionary: almost all uses
    /// of lookup() return immediately and are followed by another lookup in
    /// the dict. Store the match to avoid this double lookup.
    matched_entry: Option<&'static DictEntry>,
    result: Option<&'static str>,
}

impl Default for KStemmer {
    fn default() -> Self {
        Self::new()
    }
}

impl KStemmer {
    /// Equivalent to `KStemmer()`.
    pub(crate) fn new() -> Self {
        Self {
            word: OpenStringBuilder::new(),
            j: 0,
            k: 0,
            matched_entry: None,
            result: None,
        }
    }

    /// `word.charAt(index)`; a negative index fails as Java's
    /// `ArrayIndexOutOfBoundsException` does.
    fn char_at(&self, index: i32) -> u16 {
        self.word.char_at(index as usize)
    }

    /// `word.setCharAt(index, ch)`.
    fn set_char_at(&mut self, index: i32, ch: char) {
        self.word.set_char_at(index as usize, ch as u16);
    }

    /// `word.setLength(len)`.
    fn set_length(&mut self, len: i32) {
        self.word.set_length(len as usize);
    }

    /// `word.unsafeWrite(ch)`.
    fn unsafe_write(&mut self, ch: u16) {
        self.word.unsafe_write(ch);
    }

    /// `word.append(s)`.
    fn append(&mut self, s: &str) {
        self.word.append(&units(s));
    }

    /// `word.length()`.
    fn word_length(&self) -> i32 {
        self.word.length() as i32
    }

    /// Equivalent to `penultChar()`.
    fn penult_char(&self) -> u16 {
        self.char_at(self.k - 1)
    }

    /// Equivalent to `isVowel(int)`.
    fn is_vowel(&self, index: i32) -> bool {
        !self.is_cons(index)
    }

    /// Equivalent to `isCons(int)`.
    fn is_cons(&self, index: i32) -> bool {
        let ch = self.char_at(index);

        if ch == 'a' as u16
            || ch == 'e' as u16
            || ch == 'i' as u16
            || ch == 'o' as u16
            || ch == 'u' as u16
        {
            return false;
        }
        if ch != 'y' as u16 || index == 0 {
            true
        } else {
            !self.is_cons(index - 1)
        }
    }

    /// Equivalent to `isAlpha(char)`: terms must be lowercased already.
    fn is_alpha(ch: u16) -> bool {
        ch >= 'a' as u16 && ch <= 'z' as u16
    }

    /// length of stem within word
    ///
    /// Equivalent to `stemLength()`.
    fn stem_length(&self) -> i32 {
        self.j + 1
    }

    /// Equivalent to `endsIn(char[])`.
    fn ends_in(&mut self, s: &[u16]) -> bool {
        if s.len() as i32 > self.k {
            return false;
        }

        let r = self.word_length() - s.len() as i32; // length of word before this suffix
        self.j = self.k;
        for (r1, &c) in (r..).zip(s) {
            if c != self.char_at(r1) {
                return false;
            }
        }
        self.j = r - 1; // index of the character BEFORE the posfix
        true
    }

    /// Equivalent to `endsIn(char, char)`.
    fn ends_in2(&mut self, a: char, b: char) -> bool {
        if 2 > self.k {
            return false;
        }
        // check left to right since the endings have often already matched
        if self.char_at(self.k - 1) == a as u16 && self.char_at(self.k) == b as u16 {
            self.j = self.k - 2;
            return true;
        }
        false
    }

    /// Equivalent to `endsIn(char, char, char)`.
    fn ends_in3(&mut self, a: char, b: char, c: char) -> bool {
        if 3 > self.k {
            return false;
        }
        if self.char_at(self.k - 2) == a as u16
            && self.char_at(self.k - 1) == b as u16
            && self.char_at(self.k) == c as u16
        {
            self.j = self.k - 3;
            return true;
        }
        false
    }

    /// Equivalent to `endsIn(char, char, char, char)`.
    fn ends_in4(&mut self, a: char, b: char, c: char, d: char) -> bool {
        if 4 > self.k {
            return false;
        }
        if self.char_at(self.k - 3) == a as u16
            && self.char_at(self.k - 2) == b as u16
            && self.char_at(self.k - 1) == c as u16
            && self.char_at(self.k) == d as u16
        {
            self.j = self.k - 4;
            return true;
        }
        false
    }

    /// Equivalent to `wordInDict()`.
    fn word_in_dict(&mut self) -> Option<&'static DictEntry> {
        if self.matched_entry.is_some() {
            return self.matched_entry;
        }
        let e = DICT_HT.get_chars(self.word.get_array(), 0, self.word.length());
        if let Some(entry) = e {
            if !entry.exception {
                self.matched_entry = e; // only cache if it's not an exception.
            }
        }
        e
    }

    /// Convert plurals to singular form, and '-ies' to 'y'.
    ///
    /// Equivalent to `plural()`.
    fn plural(&mut self) {
        if self.char_at(self.k) == 's' as u16 {
            if self.ends_in3('i', 'e', 's') {
                self.set_length(self.j + 3);
                self.k -= 1;
                if self.lookup() {
                    // ensure calories -> calorie
                    return;
                }
                self.k += 1;
                self.unsafe_write('s' as u16);
                self.set_suffix("y");
                self.lookup();
            } else if self.ends_in2('e', 's') {
                // try just removing the "s"
                self.set_length(self.j + 2);
                self.k -= 1;

                // note: don't check for exceptions here. So, `aides' -> `aide', but
                // `aided' -> `aid'. The exception for double s is used to prevent
                // crosses -> crosse. This is actually correct if crosses is a plural
                // noun (a type of racket used in lacrosse), but the verb is much more
                // common

                // YCS: this was the one place where lookup was not followed by return.
                // So restructure it. if ((j>0)&&(lookup(word.toString())) &&
                // !((word.charAt(j) == 's') && (word.charAt(j-1) == 's'))) return;
                let try_e = self.j > 0
                    && !(self.char_at(self.j) == 's' as u16
                        && self.char_at(self.j - 1) == 's' as u16);
                if try_e && self.lookup() {
                    return;
                }

                // try removing the "es"

                self.set_length(self.j + 1);
                self.k -= 1;
                if self.lookup() {
                    return;
                }

                // the default is to retain the "e"
                self.unsafe_write('e' as u16);
                self.k += 1;

                if !try_e {
                    self.lookup(); // if we didn't try the "e" ending before
                }
            } else if self.word_length() > 3
                && self.penult_char() != 's' as u16
                && !self.ends_in3('o', 'u', 's')
            {
                // unless the word ends in "ous" or a double "s", remove the final "s"

                self.set_length(self.k);
                self.k -= 1;
                self.lookup();
            }
        }
    }

    /// Equivalent to `setSuffix(String)`.
    fn set_suffix(&mut self, s: &str) {
        self.set_suff(s, s.len() as i32);
    }

    /// replace old suffix with s
    ///
    /// Equivalent to `setSuff(String, int)`.
    fn set_suff(&mut self, s: &str, len: i32) {
        self.set_length(self.j + 1);
        let s = units(s);
        for l in 0..len {
            self.unsafe_write(s[l as usize]);
        }
        self.k = self.j + len;
    }

    /// Returns true if the word is found in the dictionary.
    ///
    /// Equivalent to `lookup()`.
    fn lookup(&mut self) -> bool {
        self.matched_entry = DICT_HT.get_chars(self.word.get_array(), 0, self.word.size());
        self.matched_entry.is_some()
    }

    /// convert past tense (-ed) to present, and `-ied' to `y'
    ///
    /// Equivalent to `pastTense()`.
    fn past_tense(&mut self) {
        // Handle words less than 5 letters with a direct mapping This prevents
        // (fled -> fl).
        if self.word_length() <= 4 {
            return;
        }

        if self.ends_in3('i', 'e', 'd') {
            self.set_length(self.j + 3);
            self.k -= 1;
            if self.lookup() {
                // we almost always want to convert -ied to -y, but
                return; // this isn't true for short words (died->die)
            }
            self.k += 1; // I don't know any long words that this applies to,
            self.unsafe_write('d' as u16); // but just in case...
            self.set_suffix("y");
            self.lookup();
            return;
        }

        // the vowelInStem() is necessary so we don't stem acronyms
        if self.ends_in2('e', 'd') && self.vowel_in_stem() {
            // see if the root ends in `e'
            self.set_length(self.j + 2);
            self.k = self.j + 1;

            let entry = self.word_in_dict();
            if let Some(entry) = entry {
                if !entry.exception {
                    // if it's in the dictionary and not an exception
                    return;
                }
            }

            // try removing the "ed"
            self.set_length(self.j + 1);
            self.k = self.j;
            if self.lookup() {
                return;
            }

            // try removing a doubled consonant. if the root isn't found in the
            // dictionary, the default is to leave it doubled. This will correctly
            // capture `backfilled' -> `backfill' instead of `backfill' ->
            // `backfille', and seems correct most of the time

            if self.double_c(self.k) {
                self.set_length(self.k);
                self.k -= 1;
                if self.lookup() {
                    return;
                }
                let ch = self.char_at(self.k);
                self.unsafe_write(ch);
                self.k += 1;
                self.lookup();
                return;
            }

            // if we have a `un-' prefix, then leave the word alone
            // (this will sometimes screw up with `under-', but we
            // will take care of that later)

            if self.char_at(0) == 'u' as u16 && self.char_at(1) == 'n' as u16 {
                self.unsafe_write('e' as u16);
                self.unsafe_write('d' as u16);
                self.k += 2;
                // nolookup()
                return;
            }

            // it wasn't found by just removing the `d' or the `ed', so prefer to end
            // with an `e' (e.g., `microcoded' -> `microcode').

            self.set_length(self.j + 1);
            self.unsafe_write('e' as u16);
            self.k = self.j + 1;
            // nolookup() - we already tried the "e" ending
        }
    }

    /// return TRUE if word ends with a double consonant
    ///
    /// Equivalent to `doubleC(int)`.
    fn double_c(&self, i: i32) -> bool {
        if i < 1 {
            return false;
        }

        if self.char_at(i) != self.char_at(i - 1) {
            return false;
        }
        self.is_cons(i)
    }

    /// Equivalent to `vowelInStem()`.
    fn vowel_in_stem(&self) -> bool {
        for i in 0..self.stem_length() {
            if self.is_vowel(i) {
                return true;
            }
        }
        false
    }

    /// handle `-ing' endings
    ///
    /// Equivalent to `aspect()`.
    fn aspect(&mut self) {
        // handle short words (aging -> age) via a direct mapping. This prevents
        // (thing -> the) in the version of this routine that ignores inflectional
        // variants that are mentioned in the dictionary (when the root is also
        // present)

        if self.word_length() <= 5 {
            return;
        }

        // the vowelinstem() is necessary so we don't stem acronyms
        if self.ends_in3('i', 'n', 'g') && self.vowel_in_stem() {
            // try adding an `e' to the stem and check against the dictionary
            self.set_char_at(self.j + 1, 'e');
            self.set_length(self.j + 2);
            self.k = self.j + 1;

            let entry = self.word_in_dict();
            if let Some(entry) = entry {
                if !entry.exception {
                    // if it's in the dictionary and not an exception
                    return;
                }
            }

            // adding on the `e' didn't work, so remove it
            self.set_length(self.k);
            self.k -= 1; // note that `ing' has also been removed

            if self.lookup() {
                return;
            }

            // if I can remove a doubled consonant and get a word, then do so
            if self.double_c(self.k) {
                self.k -= 1;
                self.set_length(self.k + 1);
                if self.lookup() {
                    return;
                }
                let ch = self.char_at(self.k);
                self.unsafe_write(ch); // restore the doubled consonant

                // the default is to leave the consonant doubled
                // (e.g.,`fingerspelling' -> `fingerspell'). Unfortunately
                // `bookselling' -> `booksell' and `mislabelling' -> `mislabell').
                // Without making the algorithm significantly more complicated, this
                // is the best I can do
                self.k += 1;
                self.lookup();
                return;
            }

            // the word wasn't in the dictionary after removing the stem, and then
            // checking with and without a final `e'. The default is to add an `e'
            // unless the word ends in two consonants, so `microcoding' ->
            // `microcode'. The two consonants restriction wouldn't normally be
            // necessary, but is needed because we don't try to deal with prefixes and
            // compounds, and most of the time it is correct (e.g., footstamping ->
            // footstamp, not footstampe; however, decoupled -> decoupl). We can
            // prevent almost all of the incorrect stems if we try to do some prefix
            // analysis first

            if self.j > 0 && self.is_cons(self.j) && self.is_cons(self.j - 1) {
                self.k = self.j;
                self.set_length(self.k + 1);
                // nolookup() because we already did according to the comment
                return;
            }

            self.set_length(self.j + 1);
            self.unsafe_write('e' as u16);
            self.k = self.j + 1;
            // nolookup(); we already tried an 'e' ending
        }
    }

    /// this routine deals with -ity endings. It accepts -ability, -ibility, and
    /// -ality, even without checking the dictionary because they are so
    /// productive. The first two are mapped to -ble, and the -ity is remove for
    /// the latter
    ///
    /// Equivalent to `ityEndings()`.
    fn ity_endings(&mut self) {
        let old_k = self.k;

        if self.ends_in3('i', 't', 'y') {
            self.set_length(self.j + 1); // try just removing -ity
            self.k = self.j;
            if self.lookup() {
                return;
            }
            self.unsafe_write('e' as u16); // try removing -ity and adding -e
            self.k = self.j + 1;
            if self.lookup() {
                return;
            }
            self.set_char_at(self.j + 1, 'i');
            self.append("ty");
            self.k = old_k;
            // the -ability and -ibility endings are highly productive, so just accept
            // them
            if self.j > 0
                && self.char_at(self.j - 1) == 'i' as u16
                && self.char_at(self.j) == 'l' as u16
            {
                self.set_length(self.j - 1);
                self.append("le"); // convert to -ble
                self.k = self.j;
                self.lookup();
                return;
            }

            // ditto for -ivity
            if self.j > 0
                && self.char_at(self.j - 1) == 'i' as u16
                && self.char_at(self.j) == 'v' as u16
            {
                self.set_length(self.j + 1);
                self.unsafe_write('e' as u16); // convert to -ive
                self.k = self.j + 1;
                self.lookup();
                return;
            }
            // ditto for -ality
            if self.j > 0
                && self.char_at(self.j - 1) == 'a' as u16
                && self.char_at(self.j) == 'l' as u16
            {
                self.set_length(self.j + 1);
                self.k = self.j;
                self.lookup();
                return;
            }

            // if the root isn't in the dictionary, and the variant *is* there, then
            // use the variant. This allows `immunity'->`immune', but prevents
            // `capacity'->`capac'. If neither the variant nor the root form are in
            // the dictionary, then remove the ending as a default

            if self.lookup() {
                return;
            }

            // the default is to remove -ity altogether
            self.set_length(self.j + 1);
            self.k = self.j;
            // nolookup(), we already did it.
        }
    }

    /// handle -ence and -ance
    ///
    /// Equivalent to `nceEndings()`.
    fn nce_endings(&mut self) {
        let old_k = self.k;

        if self.ends_in3('n', 'c', 'e') {
            let word_char = self.char_at(self.j);
            if !(word_char == 'e' as u16 || word_char == 'a' as u16) {
                return;
            }
            self.set_length(self.j);
            self.unsafe_write('e' as u16); // try converting -e/ance to -e (adherance/adhere)
            self.k = self.j;
            if self.lookup() {
                return;
            }
            self.set_length(self.j); // try removing -e/ance altogether (disappearance/disappear)
            self.k = self.j - 1;
            if self.lookup() {
                return;
            }
            self.unsafe_write(word_char); // restore the original ending
            self.append("nce");
            self.k = old_k;
            // nolookup() because we restored the original ending
        }
    }

    /// handle -ness
    ///
    /// Equivalent to `nessEndings()`.
    fn ness_endings(&mut self) {
        if self.ends_in4('n', 'e', 's', 's') {
            // this is a very productive endings, so
            // just accept it
            self.set_length(self.j + 1);
            self.k = self.j;
            if self.char_at(self.j) == 'i' as u16 {
                self.set_char_at(self.j, 'y');
            }
            self.lookup();
        }
    }

    /// handle -ism
    ///
    /// Equivalent to `ismEndings()`.
    fn ism_endings(&mut self) {
        if self.ends_in3('i', 's', 'm') {
            // this is a very productive ending, so just
            // accept it
            self.set_length(self.j + 1);
            self.k = self.j;
            self.lookup();
        }
    }

    /// this routine deals with -ment endings.
    ///
    /// Equivalent to `mentEndings()`.
    fn ment_endings(&mut self) {
        let old_k = self.k;

        if self.ends_in4('m', 'e', 'n', 't') {
            self.set_length(self.j + 1);
            self.k = self.j;
            if self.lookup() {
                return;
            }
            self.append("ment");
            self.k = old_k;
            // nolookup
        }
    }

    /// this routine deals with -ize endings.
    ///
    /// Equivalent to `izeEndings()`.
    fn ize_endings(&mut self) {
        let old_k = self.k;

        if self.ends_in3('i', 'z', 'e') {
            self.set_length(self.j + 1); // try removing -ize entirely
            self.k = self.j;
            if self.lookup() {
                return;
            }
            self.unsafe_write('i' as u16);

            if self.double_c(self.j) {
                // allow for a doubled consonant
                self.set_length(self.j);
                self.k = self.j - 1;
                if self.lookup() {
                    return;
                }
                let ch = self.char_at(self.j - 1);
                self.unsafe_write(ch);
            }

            self.set_length(self.j + 1);
            self.unsafe_write('e' as u16); // try removing -ize and adding -e
            self.k = self.j + 1;
            if self.lookup() {
                return;
            }
            self.set_length(self.j + 1);
            self.append("ize");
            self.k = old_k;
            // nolookup()
        }
    }

    /// handle -ency and -ancy
    ///
    /// Equivalent to `ncyEndings()`.
    fn ncy_endings(&mut self) {
        if self.ends_in3('n', 'c', 'y') {
            if !(self.char_at(self.j) == 'e' as u16 || self.char_at(self.j) == 'a' as u16) {
                return;
            }
            self.set_char_at(self.j + 2, 't'); // try converting -ncy to -nt
            self.set_length(self.j + 3);
            self.k = self.j + 2;

            if self.lookup() {
                return;
            }

            self.set_char_at(self.j + 2, 'c'); // the default is to convert it to -nce
            self.unsafe_write('e' as u16);
            self.k = self.j + 3;
            self.lookup();
        }
    }

    /// handle -able and -ible
    ///
    /// Equivalent to `bleEndings()`.
    fn ble_endings(&mut self) {
        let old_k = self.k;

        if self.ends_in3('b', 'l', 'e') {
            if !(self.char_at(self.j) == 'a' as u16 || self.char_at(self.j) == 'i' as u16) {
                return;
            }
            let word_char = self.char_at(self.j);
            self.set_length(self.j); // try just removing the ending
            self.k = self.j - 1;
            if self.lookup() {
                return;
            }
            if self.double_c(self.k) {
                // allow for a doubled consonant
                self.set_length(self.k);
                self.k -= 1;
                if self.lookup() {
                    return;
                }
                self.k += 1;
                let ch = self.char_at(self.k - 1);
                self.unsafe_write(ch);
            }
            self.set_length(self.j);
            self.unsafe_write('e' as u16); // try removing -a/ible and adding -e
            self.k = self.j;
            if self.lookup() {
                return;
            }
            self.set_length(self.j);
            self.append("ate"); // try removing -able and adding -ate
                                // (e.g., compensable/compensate)
            self.k = self.j + 2;
            if self.lookup() {
                return;
            }
            self.set_length(self.j);
            self.unsafe_write(word_char); // restore the original values
            self.append("ble");
            self.k = old_k;
            // nolookup()
        }
    }

    /// handle -ic endings. This is fairly straightforward, but this is also the
    /// only place we try *expanding* an ending, -ic -> -ical. This is to handle
    /// cases like `canonic' -> `canonical'
    ///
    /// Equivalent to `icEndings()`.
    fn ic_endings(&mut self) {
        if self.ends_in2('i', 'c') {
            self.set_length(self.j + 3);
            self.append("al"); // try converting -ic to -ical
            self.k = self.j + 4;
            if self.lookup() {
                return;
            }

            self.set_char_at(self.j + 1, 'y'); // try converting -ic to -y
            self.set_length(self.j + 2);
            self.k = self.j + 1;
            if self.lookup() {
                return;
            }

            self.set_char_at(self.j + 1, 'e'); // try converting -ic to -e
            if self.lookup() {
                return;
            }

            self.set_length(self.j + 1); // try removing -ic altogether
            self.k = self.j;
            if self.lookup() {
                return;
            }
            self.append("ic"); // restore the original ending
            self.k = self.j + 2;
            // nolookup()
        }
    }

    /// handle some derivational endings
    ///
    /// this routine deals with -ion, -ition, -ation, -ization, and -ication. The
    /// -ization ending is always converted to -ize
    ///
    /// Equivalent to `ionEndings()`; `ization`, `ition`, `ation` and
    /// `ication` are the static `char[]` suffixes of `KStemmer`.
    fn ion_endings(&mut self) {
        let old_k = self.k;
        if !self.ends_in3('i', 'o', 'n') {
            return;
        }

        if self.ends_in(&units("ization")) {
            // the -ize ending is very productive, so simply
            // accept it as the root
            self.set_length(self.j + 3);
            self.unsafe_write('e' as u16);
            self.k = self.j + 3;
            self.lookup();
            return;
        }

        if self.ends_in(&units("ition")) {
            self.set_length(self.j + 1);
            self.unsafe_write('e' as u16);
            self.k = self.j + 1;
            if self.lookup() {
                // remove -ition and add `e', and check against the
                // dictionary
                return; // (e.g., definition->define, opposition->oppose)
            }

            // restore original values
            self.set_length(self.j + 1);
            self.append("ition");
            self.k = old_k;
            // nolookup()
        } else if self.ends_in(&units("ation")) {
            self.set_length(self.j + 3);
            self.unsafe_write('e' as u16);
            self.k = self.j + 3;
            if self.lookup() {
                // remove -ion and add `e', and check against the dictionary
                return; // (elmination -> eliminate)
            }

            self.set_length(self.j + 1);
            self.unsafe_write('e' as u16); // remove -ation and add `e', and check against the dictionary
            self.k = self.j + 1;
            if self.lookup() {
                return;
            }

            self.set_length(self.j + 1); // just remove -ation (resignation->resign) and check dictionary
            self.k = self.j;
            if self.lookup() {
                return;
            }

            // restore original values
            self.set_length(self.j + 1);
            self.append("ation");
            self.k = old_k;
            // nolookup()
        }

        // test -ication after -ation is attempted (e.g., `complication->complicate'
        // rather than `complication->comply')

        if self.ends_in(&units("ication")) {
            self.set_length(self.j + 1);
            self.unsafe_write('y' as u16);
            self.k = self.j + 1;
            if self.lookup() {
                // remove -ication and add `y', and check against the
                // dictionary
                return; // (e.g., amplification -> amplify)
            }

            // restore original values
            self.set_length(self.j + 1);
            self.append("ication");
            self.k = old_k;
            // nolookup()
        }

        // if (endsIn(ion)) {
        // `if (true)`: we checked for this earlier... just need to set "j"
        {
            self.j = self.k - 3; // YCS

            self.set_length(self.j + 1);
            self.unsafe_write('e' as u16);
            self.k = self.j + 1;
            if self.lookup() {
                // remove -ion and add `e', and check against the dictionary
                return;
            }

            self.set_length(self.j + 1);
            self.k = self.j;
            if self.lookup() {
                // remove -ion, and if it's found, treat that as the root
                return;
            }

            // restore original values
            self.set_length(self.j + 1);
            self.append("ion");
            self.k = old_k;
            // nolookup()
        }

        // nolookup(); all of the other paths restored original values
    }

    /// this routine deals with -er, -or, -ier, and -eer. The -izer ending is
    /// always converted to -ize
    ///
    /// Equivalent to `erAndOrEndings()`.
    fn er_and_or_endings(&mut self) {
        let old_k = self.k;

        if self.char_at(self.k) != 'r' as u16 {
            return; // YCS
        }

        if self.ends_in4('i', 'z', 'e', 'r') {
            // -ize is very productive, so accept it
            // as the root
            self.set_length(self.j + 4);
            self.k = self.j + 3;
            self.lookup();
            return;
        }

        if self.ends_in2('e', 'r') || self.ends_in2('o', 'r') {
            let word_char = self.char_at(self.j + 1); // so we can remember if it was -er or -or
            if self.double_c(self.j) {
                self.set_length(self.j);
                self.k = self.j - 1;
                if self.lookup() {
                    return;
                }
                let ch = self.char_at(self.j - 1);
                self.unsafe_write(ch); // restore the doubled consonant
            }

            if self.char_at(self.j) == 'i' as u16 {
                // do we have a -ier ending?
                self.set_char_at(self.j, 'y');
                self.set_length(self.j + 1);
                self.k = self.j;
                if self.lookup() {
                    // yes, so check against the dictionary
                    return;
                }
                self.set_char_at(self.j, 'i'); // restore the endings
                self.unsafe_write('e' as u16);
            }

            if self.char_at(self.j) == 'e' as u16 {
                // handle -eer
                self.set_length(self.j);
                self.k = self.j - 1;
                if self.lookup() {
                    return;
                }
                self.unsafe_write('e' as u16);
            }

            self.set_length(self.j + 2); // remove the -r ending
            self.k = self.j + 1;
            if self.lookup() {
                return;
            }
            self.set_length(self.j + 1); // try removing -er/-or
            self.k = self.j;
            if self.lookup() {
                return;
            }
            self.unsafe_write('e' as u16); // try removing -or and adding -e
            self.k = self.j + 1;
            if self.lookup() {
                return;
            }
            self.set_length(self.j + 1);
            self.unsafe_write(word_char);
            self.unsafe_write('r' as u16); // restore the word to the way it was
            self.k = old_k;
            // nolookup()
        }
    }

    /// this routine deals with -ly endings. The -ally ending is always converted
    /// to -al Sometimes this will temporarily leave us with a non-word (e.g.,
    /// heuristically maps to heuristical), but then the -al is removed in the next
    /// step.
    ///
    /// Equivalent to `lyEndings()`.
    fn ly_endings(&mut self) {
        let old_k = self.k;

        if self.ends_in2('l', 'y') {
            self.set_char_at(self.j + 2, 'e'); // try converting -ly to -le

            if self.lookup() {
                return;
            }
            self.set_char_at(self.j + 2, 'y');

            self.set_length(self.j + 1); // try just removing the -ly
            self.k = self.j;

            if self.lookup() {
                return;
            }

            if self.j > 0
                && self.char_at(self.j - 1) == 'a' as u16
                && self.char_at(self.j) == 'l' as u16
            {
                // always convert -ally to -al
                return;
            }
            self.append("ly");
            self.k = old_k;

            if self.j > 0
                && self.char_at(self.j - 1) == 'a' as u16
                && self.char_at(self.j) == 'b' as u16
            {
                // always convert -ably to -able
                self.set_char_at(self.j + 2, 'e');
                self.k = self.j + 2;
                return;
            }

            if self.char_at(self.j) == 'i' as u16 {
                // e.g., militarily -> military
                self.set_length(self.j);
                self.unsafe_write('y' as u16);
                self.k = self.j;
                if self.lookup() {
                    return;
                }
                self.set_length(self.j);
                self.append("ily");
                self.k = old_k;
            }

            self.set_length(self.j + 1); // the default is to remove -ly

            self.k = self.j;
            // nolookup()... we already tried removing the "ly" variant
        }
    }

    /// this routine deals with -al endings. Some of the endings from the previous
    /// routine are finished up here.
    ///
    /// Equivalent to `alEndings()`.
    fn al_endings(&mut self) {
        let old_k = self.k;

        if self.word_length() < 4 {
            return;
        }
        if self.ends_in2('a', 'l') {
            self.set_length(self.j + 1);
            self.k = self.j;
            if self.lookup() {
                // try just removing the -al
                return;
            }

            if self.double_c(self.j) {
                // allow for a doubled consonant
                self.set_length(self.j);
                self.k = self.j - 1;
                if self.lookup() {
                    return;
                }
                let ch = self.char_at(self.j - 1);
                self.unsafe_write(ch);
            }

            self.set_length(self.j + 1);
            self.unsafe_write('e' as u16); // try removing the -al and adding -e
            self.k = self.j + 1;
            if self.lookup() {
                return;
            }

            self.set_length(self.j + 1);
            self.append("um"); // try converting -al to -um
                               // (e.g., optimal - > optimum )
            self.k = self.j + 2;
            if self.lookup() {
                return;
            }

            self.set_length(self.j + 1);
            self.append("al"); // restore the ending to the way it was
            self.k = old_k;

            if self.j > 0
                && self.char_at(self.j - 1) == 'i' as u16
                && self.char_at(self.j) == 'c' as u16
            {
                self.set_length(self.j - 1); // try removing -ical
                self.k = self.j - 2;
                if self.lookup() {
                    return;
                }

                self.set_length(self.j - 1);
                self.unsafe_write('y' as u16); // try turning -ical to -y (e.g., bibliographical)
                self.k = self.j - 1;
                if self.lookup() {
                    return;
                }

                self.set_length(self.j - 1);
                self.append("ic"); // the default is to convert -ical to -ic
                self.k = self.j;
                // nolookup() ... converting ical to ic means removing "al" which we
                // already tried
                // ERROR
                self.lookup();
                return;
            }

            if self.char_at(self.j) == 'i' as u16 {
                // sometimes -ial endings should be removed
                self.set_length(self.j); // (sometimes it gets turned into -y, but we
                self.k = self.j - 1; // aren't dealing with that case for now)
                if self.lookup() {
                    return;
                }
                self.append("ial");
                self.k = old_k;
                self.lookup();
            }
        }
    }

    /// this routine deals with -ive endings. It normalizes some of the -ative
    /// endings directly, and also maps some -ive endings to -ion.
    ///
    /// Equivalent to `iveEndings()`.
    fn ive_endings(&mut self) {
        let old_k = self.k;

        if self.ends_in3('i', 'v', 'e') {
            self.set_length(self.j + 1); // try removing -ive entirely
            self.k = self.j;
            if self.lookup() {
                return;
            }

            self.unsafe_write('e' as u16); // try removing -ive and adding -e
            self.k = self.j + 1;
            if self.lookup() {
                return;
            }
            self.set_length(self.j + 1);
            self.append("ive");
            if self.j > 0
                && self.char_at(self.j - 1) == 'a' as u16
                && self.char_at(self.j) == 't' as u16
            {
                self.set_char_at(self.j - 1, 'e'); // try removing -ative and adding -e
                self.set_length(self.j); // (e.g., determinative -> determine)
                self.k = self.j - 1;
                if self.lookup() {
                    return;
                }
                self.set_length(self.j - 1); // try just removing -ative
                if self.lookup() {
                    return;
                }

                self.append("ative");
                self.k = old_k;
            }

            // try mapping -ive to -ion (e.g., injunctive/injunction)
            self.set_char_at(self.j + 2, 'o');
            self.set_char_at(self.j + 3, 'n');
            if self.lookup() {
                return;
            }

            self.set_char_at(self.j + 2, 'v'); // restore the original values
            self.set_char_at(self.j + 3, 'e');
            self.k = old_k;
            // nolookup()
        }
    }

    /// Stems `term`, returning the stem, or `term` itself when the stemmer
    /// did not change it.
    ///
    /// Equivalent to `stem(String)`; `term` holds the UTF-16 units of Java's
    /// string.
    pub(crate) fn stem_string(&mut self, term: &[u16]) -> Vec<u16> {
        let changed = self.stem(term, term.len());
        if !changed {
            return term.to_vec();
        }
        self.as_string()
    }

    /// Returns the result of the stem (assuming the word was changed) as a
    /// String.
    ///
    /// Equivalent to `asString()`, as UTF-16 units.
    pub(crate) fn as_string(&self) -> Vec<u16> {
        match self.get_string() {
            Some(s) => units(s),
            None => self.word.to_char_array(),
        }
    }

    /// Equivalent to `asCharSequence()`: `result`, or else `word`.
    pub(crate) fn as_char_sequence(&self) -> StemResult<'_> {
        match self.result {
            Some(result) => StemResult::Root(result),
            None => StemResult::Word(&self.word.get_array()[..self.word.length()]),
        }
    }

    /// Equivalent to `getString()`: `result`, `None` for Java's `null`.
    pub(crate) fn get_string(&self) -> Option<&'static str> {
        self.result
    }

    /// Equivalent to `getChars()`.
    pub(crate) fn get_chars(&self) -> &[u16] {
        self.word.get_array()
    }

    /// Equivalent to `getLength()`.
    pub(crate) fn get_length(&self) -> usize {
        self.word.length()
    }

    /// Equivalent to `matched()`.
    fn matched(&self) -> bool {
        self.matched_entry.is_some()
    }

    /// Stems the text in the token. Returns true if changed.
    ///
    /// Equivalent to `stem(char[], int)`: `term` holds UTF-16 units, Java's
    /// `char[]`.
    #[allow(clippy::never_loop)]
    pub(crate) fn stem(&mut self, term: &[u16], len: usize) -> bool {
        self.result = None;

        self.k = len as i32 - 1;
        if self.k <= 1 || self.k >= MAX_WORD_LEN - 1 {
            return false; // don't stem
        }

        // first check the stemmer dictionaries, and avoid using the
        // cache if it's in there.
        let entry = DICT_HT.get_chars(term, 0, len);
        if let Some(entry) = entry {
            if let Some(root) = entry.root {
                self.result = Some(root);
                return true;
            }
            return false;
        }

        self.word.reset();
        // allocate enough space so that an expansion is never needed
        self.word.reserve(len + 10);
        for &ch in &term[..len] {
            if !Self::is_alpha(ch) {
                return false; // don't stem
            }
            // don't lowercase... it's a requirement that lowercase filter be
            // used before this stemmer.
            self.word.unsafe_write(ch);
        }

        self.matched_entry = None;

        // This while loop will never be executed more than one time; it is here
        // only to allow the break statement to be used to escape as soon as a word
        // is recognized
        loop {
            // YCS: extra lookup()s were inserted so we don't need to
            // do an extra wordInDict() here.
            self.plural();
            if self.matched() {
                break;
            }
            self.past_tense();
            if self.matched() {
                break;
            }
            self.aspect();
            if self.matched() {
                break;
            }
            self.ity_endings();
            if self.matched() {
                break;
            }
            self.ness_endings();
            if self.matched() {
                break;
            }
            self.ion_endings();
            if self.matched() {
                break;
            }
            self.er_and_or_endings();
            if self.matched() {
                break;
            }
            self.ly_endings();
            if self.matched() {
                break;
            }
            self.al_endings();
            if self.matched() {
                break;
            }
            // `entry = wordInDict();`: the value is overwritten below.
            let _ = self.word_in_dict();
            self.ive_endings();
            if self.matched() {
                break;
            }
            self.ize_endings();
            if self.matched() {
                break;
            }
            self.ment_endings();
            if self.matched() {
                break;
            }
            self.ble_endings();
            if self.matched() {
                break;
            }
            self.ism_endings();
            if self.matched() {
                break;
            }
            self.ic_endings();
            if self.matched() {
                break;
            }
            self.ncy_endings();
            if self.matched() {
                break;
            }
            self.nce_endings();
            self.matched();
            break;
        }

        // try for a direct mapping (allows for cases like `Italian'->`Italy' and
        // `Italians'->`Italy')
        let entry = self.matched_entry;
        if let Some(entry) = entry {
            self.result = entry.root; // may be null, which means that "word" is the stem
        }

        // no entry matched means result is "word"
        true
    }
}
