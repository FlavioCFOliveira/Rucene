//! A `TokenFilter` that applies `PersianNormalizer` to normalize the
//! orthography, ported from
//! `org.apache.lucene.analysis.fa.PersianNormalizationFilter`.

use rucene::analysis::{CharTermAttribute, TokenFilter, TokenFilterLogic, TokenStream};
use rucene::error::Result;
use rucene::util::attribute::AttributeSource;

use super::persian_normalizer::PersianNormalizer;
use crate::jdk::character::{chars_to_utf16, utf16_to_term_chars};

/// The body of [`PersianNormalizationFilter`]: what Lucene's
/// `PersianNormalizationFilter` adds to `TokenFilter`.
#[derive(Debug)]
pub struct PersianNormalizationFilterLogic {
    normalizer: PersianNormalizer,
}

impl TokenFilterLogic for PersianNormalizationFilterLogic {
    /// Equivalent to `PersianNormalizationFilter.incrementToken()`. The normalizer
    /// reads the term's UTF-16 units, Java's `termAtt.buffer()`, and may
    /// change them in place; the first `newlen` units become the term, as
    /// Java's `termAtt.setLength(newlen)` keeps them.
    fn increment_token(
        &mut self,
        source: &mut AttributeSource,
        input: &mut dyn TokenStream,
    ) -> Result<bool> {
        if input.increment_token()? {
            let mut term_att = source
                .get_attribute_interface_mut::<dyn CharTermAttribute>()
                .expect("INVARIANT: the constructor added the CharTermAttribute");
            let mut buffer = chars_to_utf16(&term_att.buffer()[..term_att.length()]);
            let length = buffer.len();
            let newlen = self.normalizer.normalize(&mut buffer, length);
            let chars = utf16_to_term_chars(&buffer[..newlen]);
            term_att.copy_buffer(&chars, 0, chars.len());
            Ok(true)
        } else {
            Ok(false)
        }
    }
}

/// A `TokenFilter` that applies `PersianNormalizer` to normalize the
/// orthography.
///
/// Equivalent to `org.apache.lucene.analysis.fa.PersianNormalizationFilter`.
pub type PersianNormalizationFilter = TokenFilter<PersianNormalizationFilterLogic>;

/// Equivalent to `PersianNormalizationFilter(TokenStream)`, whose attribute field adds
/// the `CharTermAttribute`.
///
/// # Errors
///
/// What the stream's attribute factory raises for an interface it cannot
/// implement, as Java's `addAttribute` throws.
pub fn new_persian_normalization_filter(
    input: Box<dyn TokenStream>,
) -> Result<PersianNormalizationFilter> {
    let mut filter = TokenFilter::new(
        input,
        PersianNormalizationFilterLogic {
            normalizer: PersianNormalizer::new(),
        },
    );
    let source = filter.attribute_source_mut();
    source.add_attribute_interface::<dyn CharTermAttribute>()?;
    Ok(filter)
}
