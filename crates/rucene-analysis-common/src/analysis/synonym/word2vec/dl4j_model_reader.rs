//! Reads a word2vec model generated by Deeplearning4j, ported from
//! `org.apache.lucene.analysis.synonym.word2vec.Dl4jModelReader`.

use std::io::Read;

use rucene::error::{LuceneError, Result};
use rucene::util::misc::TermAndVector;
use rucene::util::BytesRef;

use super::word2vec_model::{array_index_out_of_bounds, Word2VecModel};
use crate::jdk::base64;
use crate::jdk::io::{BufferedReader, InputStreamReader};
use crate::jdk::zip_input_stream::ZipInputStream;

/// `MODEL_FILE_NAME_PREFIX`.
const MODEL_FILE_NAME_PREFIX: &str = "syn0";

/// `String.split(" ")`: the parts between spaces, trailing empty parts
/// dropped, and the string itself when it holds no space.
fn split_space(s: &[u16]) -> Vec<Vec<u16>> {
    let space = u16::from(b' ');
    if !s.contains(&space) {
        return vec![s.to_vec()];
    }
    let mut list: Vec<Vec<u16>> = s
        .split(|&unit| unit == space)
        .map(<[u16]>::to_vec)
        .collect();
    while list.last().is_some_and(Vec::is_empty) {
        list.pop();
    }
    list
}

/// `tokens[index]`, failing as Java's array access does.
fn token(tokens: &[Vec<u16>], index: usize) -> Result<&[u16]> {
    tokens
        .get(index)
        .map(Vec::as_slice)
        .ok_or_else(|| array_index_out_of_bounds(index, tokens.len()))
}

/// `String.substring(begin, end)` of `s`, failing as Java's
/// `StringIndexOutOfBoundsException` does.
fn substring(s: &[u16], begin: usize, end: usize) -> Result<&[u16]> {
    if begin > end || end > s.len() {
        return Err(LuceneError::unchecked(
            "java.lang.StringIndexOutOfBoundsException",
            format!("begin {begin}, end {end}, length {}", s.len()),
        ));
    }
    Ok(&s[begin..end])
}

/// The Java string of `units` as a Rust one; the lines the reader decodes
/// are well-formed UTF-16.
fn to_string(units: &[u16]) -> String {
    String::from_utf16_lossy(units)
}

/// `Integer.parseInt(String)`.
fn parse_int(s: &str) -> Result<i32> {
    rucene::util::extra::java_parse_int(s)
        .ok_or_else(|| LuceneError::number_format_for_input_string(s, 10))
}

/// `Float.parseFloat(String)`, whose `NumberFormatException` says `empty
/// String` for a string that trims to nothing and `For input string:
/// "<s>"` otherwise.
pub(crate) fn parse_float(s: &str) -> Result<f32> {
    rucene::util::java_fmt::parse_float(s).ok_or_else(|| {
        if s.trim_matches(|c: char| c <= '\u{20}').is_empty() {
            LuceneError::number_format("empty String")
        } else {
            LuceneError::number_format(format!("For input string: \"{s}\""))
        }
    })
}

/// Dl4jModelReader reads the file generated by the library Deeplearning4j
/// and provide a Word2VecModel with normalized vectors
///
/// Dl4j Word2Vec documentation:
/// <https://deeplearning4j.konduit.ai/v/en-1.0.0-beta7/language-processing/word2vec>
/// Example to generate a model using dl4j:
/// <https://github.com/eclipse/deeplearning4j-examples/blob/master/dl4j-examples/src/main/java/org/deeplearning4j/examples/advanced/modelling/embeddingsfromcorpus/word2vec/Word2VecRawTextExample.java>
///
/// Equivalent to `org.apache.lucene.analysis.synonym.word2vec.Dl4jModelReader`
/// (`@lucene.experimental`), which implements `Closeable`.
#[derive(Debug)]
pub struct Dl4jModelReader {
    word2_vec_model_zip_file: ZipInputStream<Box<dyn Read + Send>>,
}

impl Dl4jModelReader {
    /// Equivalent to `Dl4jModelReader(InputStream)`, which reads the stream
    /// as a `ZipInputStream` over a `BufferedInputStream`.
    pub fn new(stream: Box<dyn Read + Send>) -> Self {
        Self {
            word2_vec_model_zip_file: ZipInputStream::new(stream),
        }
    }

    /// Reads the model from the first entry whose name starts with `syn0`.
    ///
    /// Equivalent to `read()`: a header line `<dictionarySize>
    /// <vectorDimension>`, then a line per term, the term (base64 after a
    /// `B64:` prefix when the first term's prefix says so) and its vector,
    /// separated by spaces, read through a UTF-8 `InputStreamReader` (which
    /// replaces malformed input).
    ///
    /// # Errors
    ///
    /// `IllegalArgumentException` when no `syn0` entry exists, for a
    /// malformed number or base64 term, `RuntimeException` for a vector of
    /// the wrong size, `NullPointerException` for an empty entry, the array
    /// and string index exceptions Java throws for short lines, and what
    /// reading the ZIP stream raises.
    pub fn read(&mut self) -> Result<Word2VecModel> {
        while let Some(entry) = self.word2_vec_model_zip_file.get_next_entry()? {
            let file_name = entry.get_name();
            if file_name.starts_with(MODEL_FILE_NAME_PREFIX) {
                let mut reader = BufferedReader::new(InputStreamReader::new_utf8(
                    &mut self.word2_vec_model_zip_file,
                ));

                let Some(header) = reader.read_line()? else {
                    // `header.split(" ")` on a `null` header.
                    return Err(LuceneError::null_pointer());
                };
                let header_values = split_space(&header);
                let dictionary_size = parse_int(&to_string(token(&header_values, 0)?))?;
                let vector_dimension = parse_int(&to_string(token(&header_values, 1)?))?;

                let mut model = Word2VecModel::new(dictionary_size, vector_dimension)?;
                let line = reader.read_line()?;
                let mut is_term_b64_encoded = false;
                if let Some(line) = line {
                    let tokens = split_space(&line);
                    // `substring(0, 3).toLowerCase(Locale.ROOT).compareTo("b64") == 0`;
                    // `str::to_lowercase` is the same locale-independent mapping.
                    is_term_b64_encoded =
                        to_string(substring(token(&tokens, 0)?, 0, 3)?).to_lowercase() == "b64";
                    model.add_term_and_vector(Self::extract_term_and_vector(
                        &tokens,
                        vector_dimension,
                        is_term_b64_encoded,
                    )?)?;
                }
                while let Some(line) = reader.read_line()? {
                    let tokens = split_space(&line);
                    model.add_term_and_vector(Self::extract_term_and_vector(
                        &tokens,
                        vector_dimension,
                        is_term_b64_encoded,
                    )?)?;
                }
                return Ok(model);
            }
        }
        Err(LuceneError::illegal_argument(format!(
            "Cannot read Dl4j word2vec model - '{MODEL_FILE_NAME_PREFIX}' file is missing in the zip. '{MODEL_FILE_NAME_PREFIX}' is a mandatory file containing the mapping between terms and vectors generated by the DL4j library."
        )))
    }

    /// Equivalent to `extractTermAndVector(String[], int, boolean)`.
    fn extract_term_and_vector(
        tokens: &[Vec<u16>],
        vector_dimension: i32,
        is_term_b64_encoded: bool,
    ) -> Result<TermAndVector> {
        let term_token = token(tokens, 0)?;
        let term = if is_term_b64_encoded {
            Self::decode_b64_term(term_token)?
        } else {
            BytesRef::new(to_string(term_token).into_bytes())
        };

        let vector_length = tokens.len() - 1;

        if vector_dimension as i64 != vector_length as i64 {
            return Err(LuceneError::from(rucene::error::LuceneErrorKind::Unchecked {
                class: "java.lang.RuntimeException",
                message: Some(format!(
                    "Word2Vec model file corrupted. Declared vectors of size {} but found vector of size {} for word {} ({})",
                    vector_dimension,
                    vector_length,
                    to_string(term_token),
                    term.utf8_to_string()?
                )),
                cause: None,
            }));
        }

        let mut vector = vec![0f32; vector_length];
        for i in 1..tokens.len() {
            vector[i - 1] = parse_float(&to_string(&tokens[i]))?;
        }
        Ok(TermAndVector::new(term, vector))
    }

    /// Equivalent to `decodeB64Term(String)`: the base64 decoding of the
    /// term after its 4-unit prefix (`B64:`).
    ///
    /// # Errors
    ///
    /// `StringIndexOutOfBoundsException` for a term shorter than 4 units,
    /// and the `IllegalArgumentException` of `Base64.Decoder.decode`.
    ///
    /// Java's method is package-private (`static`), reached by the same
    /// package's `TestDl4jModelReader`; Rust's integration tests are another
    /// crate, so the port makes it public (hidden from the documentation).
    #[doc(hidden)]
    pub fn decode_b64_term(term: &[u16]) -> Result<BytesRef> {
        let buffer = base64::decode_string(substring(term, 4, term.len())?)?;
        Ok(BytesRef::new(buffer))
    }

    /// Equivalent to `close()`: closes the ZIP stream.
    ///
    /// # Errors
    ///
    /// Never; Java's `ZipInputStream.close()` declares `IOException`.
    pub fn close(&mut self) -> Result<()> {
        self.word2_vec_model_zip_file.close();
        Ok(())
    }
}
