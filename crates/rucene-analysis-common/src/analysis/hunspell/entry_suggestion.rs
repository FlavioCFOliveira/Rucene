//! The dictionary changes `WordFormGenerator.compress` suggests, ported from
//! `org.apache.lucene.analysis.hunspell.EntrySuggestion`.

use std::fmt;

use super::dict_entry::DictEntry;

/// Suggestion to add/edit dictionary entries to generate a given list of
/// words created by
/// [`WordFormGenerator::compress`](super::word_form_generator::WordFormGenerator::compress).
///
/// Equivalent to `org.apache.lucene.analysis.hunspell.EntrySuggestion`.
#[derive(Debug, Clone)]
pub struct EntrySuggestion {
    to_edit: Vec<DictEntry>,
    to_add: Vec<DictEntry>,
    extra_generated: Vec<String>,
}

impl EntrySuggestion {
    /// Equivalent to `EntrySuggestion(List<DictEntry>, List<DictEntry>,
    /// List<String>)`.
    pub(crate) fn new(
        to_edit: Vec<DictEntry>,
        to_add: Vec<DictEntry>,
        extra_generated: Vec<String>,
    ) -> Self {
        Self {
            to_edit,
            to_add,
            extra_generated,
        }
    }

    /// The existing dictionary entries whose flags would need changing to
    /// accommodate the given word list.
    ///
    /// Equivalent to `getEntriesToEdit()`.
    pub fn get_entries_to_edit(&self) -> &[DictEntry] {
        &self.to_edit
    }

    /// New dictionary entries to be added to accommodate the given word list.
    ///
    /// Equivalent to `getEntriesToAdd()`.
    pub fn get_entries_to_add(&self) -> &[DictEntry] {
        &self.to_add
    }

    /// Additional words generated by union of
    /// [`get_entries_to_add`](Self::get_entries_to_add) and
    /// [`get_entries_to_edit`](Self::get_entries_to_edit) which weren't in
    /// the given list of words.
    ///
    /// Equivalent to `getExtraGeneratedWords()`.
    pub fn get_extra_generated_words(&self) -> &[String] {
        &self.extra_generated
    }

    /// Equivalent to `internalsToString()`.
    pub(crate) fn internals_to_string(&self) -> String {
        let list = |items: Vec<String>| format!("[{}]", items.join(", "));
        format!(
            "toEdit={}, toAdd={}, extra={}",
            list(self.to_edit.iter().map(ToString::to_string).collect()),
            list(self.to_add.iter().map(ToString::to_string).collect()),
            list(self.extra_generated.clone())
        )
    }
}

impl fmt::Display for EntrySuggestion {
    /// Equivalent to `toString()`.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "EntrySuggestion{{{}}}", self.internals_to_string())
    }
}
