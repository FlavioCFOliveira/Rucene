//! A `TokenFilter` that applies `PortugueseStemmer` to stem Portuguese
//! words, ported from `org.apache.lucene.analysis.pt.PortugueseStemFilter`.

use rucene::analysis::{
    CharTermAttribute, KeywordAttribute, TokenFilter, TokenFilterLogic, TokenStream,
};
use rucene::error::Result;
use rucene::util::attribute::AttributeSource;

use super::portuguese_stemmer::PortugueseStemmer;
use crate::jdk::character::{chars_to_utf16, utf16_to_term_chars};

/// The body of [`PortugueseStemFilter`]: what Lucene's
/// `PortugueseStemFilter` adds to `TokenFilter`.
#[derive(Debug)]
pub struct PortugueseStemFilterLogic {
    stemmer: PortugueseStemmer,
}

impl TokenFilterLogic for PortugueseStemFilterLogic {
    /// Equivalent to `PortugueseStemFilter.incrementToken()`. The stemmer
    /// reads the term's UTF-16 units, Java's `termAtt.buffer()`, and may
    /// change them in place; the first `newlen` units become the term, as
    /// Java's `termAtt.setLength(newlen)` keeps them.
    ///
    /// Java's `termAtt.resizeBuffer(len + 1)` gives the stemmer one unit
    /// beyond the term to write into; the units grow by one here.
    fn increment_token(
        &mut self,
        source: &mut AttributeSource,
        input: &mut dyn TokenStream,
    ) -> Result<bool> {
        if input.increment_token()? {
            let is_keyword = source
                .get_attribute_interface::<dyn KeywordAttribute>()
                .expect("INVARIANT: the constructor added the KeywordAttribute")
                .is_keyword();
            if !is_keyword {
                let mut term_att = source
                    .get_attribute_interface_mut::<dyn CharTermAttribute>()
                    .expect("INVARIANT: the constructor added the CharTermAttribute");
                let mut buffer = chars_to_utf16(&term_att.buffer()[..term_att.length()]);
                // this stemmer increases word length by 1: worst case '*ã' -> '*ão'
                let len = buffer.len();
                buffer.resize(len + 1, 0);
                let newlen = self.stemmer.stem(&mut buffer, len);
                let chars = utf16_to_term_chars(&buffer[..newlen]);
                term_att.copy_buffer(&chars, 0, chars.len());
            }
            Ok(true)
        } else {
            Ok(false)
        }
    }
}

/// A `TokenFilter` that applies `PortugueseStemmer` to stem Portuguese words.
///
/// To prevent terms from being stemmed use an instance of
/// `SetKeywordMarkerFilter` or a custom `TokenFilter` that sets the
/// `KeywordAttribute` before this `TokenStream`.
///
/// Equivalent to `org.apache.lucene.analysis.pt.PortugueseStemFilter`.
pub type PortugueseStemFilter = TokenFilter<PortugueseStemFilterLogic>;

/// Equivalent to `PortugueseStemFilter(TokenStream)`, whose fields add the
/// `CharTermAttribute` and the `KeywordAttribute`, in that order.
///
/// # Errors
///
/// What the stream's attribute factory raises for an interface it cannot
/// implement, as Java's `addAttribute` throws.
pub fn new_portuguese_stem_filter(input: Box<dyn TokenStream>) -> Result<PortugueseStemFilter> {
    let mut filter = TokenFilter::new(
        input,
        PortugueseStemFilterLogic {
            stemmer: PortugueseStemmer::new(),
        },
    );
    let source = filter.attribute_source_mut();
    source.add_attribute_interface::<dyn CharTermAttribute>()?;
    source.add_attribute_interface::<dyn KeywordAttribute>()?;
    Ok(filter)
}
