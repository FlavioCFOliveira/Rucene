//! Generated from OpenJDK 25.0.5 (Unicode 16.0) by an oracle that calls the
//! public `java.lang.Character` API for every code point `0..=0x10FFFF`:
//! `isLetter(int)`, `isDigit(int)` and `isWhitespace(int)`, kept as the
//! inclusive ranges of the code points each accepts, and
//! `getNumericValue(int)`, kept as runs `(first, last, value, step)` where the
//! code point `c` of a run has the value `value + step * (c - first)` (`-2`
//! for every code point of a run whose `value` is `-2`); a code point in no
//! run has the value `-1`. The oracle read the runs back and found no code
//! point whose value differs from the JDK's. The data is Unicode's (Unicode
//! License v3); no JDK code is reproduced.

