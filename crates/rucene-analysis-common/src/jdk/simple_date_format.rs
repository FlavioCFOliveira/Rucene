/// One element of a compiled pattern.
#[derive(Clone, Debug, PartialEq, Eq)]
enum Element {
    /// `TAG_QUOTE_ASCII_CHAR`: one literal ASCII character.
    QuoteAsciiChar(u16),
    /// `TAG_QUOTE_CHARS`: literal characters.
    QuoteChars(Vec<u16>),
    /// A pattern field: its index in [`PATTERN_CHARS`] and its count.
    Field(usize, usize),
}

/// `java.text.ParsePosition`: the index parsing is at, and the index of an
/// error (`-1` for none).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct ParsePosition {
    /// `getIndex()`, in UTF-16 units.
    pub index: usize,
    /// `getErrorIndex()`, `-1` when no error was recorded.
    pub error_index: i64,
}

impl ParsePosition {
    /// `new ParsePosition(index)`.
    pub fn new(index: usize) -> Self {
        Self {
            index,
            error_index: -1,
        }
    }
}

/// `java.text.ParseException`: the message and the error offset.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ParseException {
    /// `getMessage()`.
    pub message: String,
    /// `getErrorOffset()`.
    pub error_offset: i64,
}

impl fmt::Display for ParseException {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "java.text.ParseException: {}", self.message)
    }
}

impl std::error::Error for ParseException {}

/// The string the generated table holds at `id`, as UTF-16 units.
fn string(id: u16) -> Vec<u16> {
    STRINGS[usize::from(id)].encode_utf16().collect()
}

fn strings(ids: &[u16]) -> Vec<Vec<u16>> {
    ids.iter().map(|&id| string(id)).collect()
}

/// The data of `locale`: the record of the first candidate of
/// `ResourceBundle.Control.getCandidateLocales`'s default list the JDK
/// lists, the root locale last (see the module documentation).
fn locale_data(locale: &Locale) -> &'static LocaleDateData {
    let language = locale.get_language();
    let script = locale.get_script();
    let country = locale.get_country();
    let variant = locale.get_variant();
    let mut variants: Vec<String> = Vec::new();
    if !variant.is_empty() {
        let parts: Vec<&str> = variant.split('_').collect();
        for n in (1..=parts.len()).rev() {
            variants.push(parts[..n].join("_"));
        }
    }
    let mut candidates: Vec<(String, String, String, String)> = Vec::new();
    let mut add = |l: &str, s: &str, c: &str, v: &str| {
        candidates.push((l.to_string(), s.to_string(), c.to_string(), v.to_string()));
    };
    for v in &variants {
        add(language, script, country, v);
    }
    if !country.is_empty() {
        add(language, script, country, "");
    }
    if !script.is_empty() {
        add(language, script, "", "");
        for v in &variants {
            add(language, "", country, v);
        }
        if !country.is_empty() {
            add(language, "", country, "");
        }
    }
    if !language.is_empty() {
        add(language, "", "", "");
    }
    add("", "", "", "");
    for (l, s, c, v) in candidates {
        let key = format!("{l}_{s}_{c}_{v}");
        if let Ok(i) = LOCALES.binary_search_by(|(k, _)| (*k).cmp(key.as_str())) {
            return &RECORDS[usize::from(LOCALES[i].1)];
        }
    }
    unreachable!("INVARIANT: the root locale is listed")
}

/// `Character.toUpperCase(int)`, the simple mapping.
fn upper(c: i32) -> i32 {
    rucene::util::automaton::case_folding::to_upper_case(c)
}

/// `Character.toLowerCase(int)`, the simple mapping.
fn lower(c: i32) -> i32 {
    rucene::util::automaton::case_folding::to_lower_case(c)
}

/// `String.regionMatches(ignoreCase, toffset, other, 0, other.length())`:
/// `false` when the region runs past the text; with `ignore_case`, two
/// characters match when equal, equal after `Character.toUpperCase`, or
/// equal after `Character.toLowerCase` of that.
fn region_matches(ignore_case: bool, text: &[u16], toffset: usize, other: &[u16]) -> bool {
    if toffset + other.len() > text.len() {
        return false;
    }
    let mut i = 0;
    while i < other.len() {
        let c1 = text[toffset + i];
        let c2 = other[i];
        if c1 == c2 {
            i += 1;
            continue;
        }
        if !ignore_case {
            return false;
        }
        let u1 = upper(i32::from(c1));
        let u2 = upper(i32::from(c2));
        if u1 == u2 || lower(u1) == lower(u2) {
            i += 1;
            continue;
        }
        return false;
    }
    true
}

/// `Character.digit(char, 10)`.
fn digit(c: u16) -> Option<u32> {
    char::from_u32(u32::from(c)).and_then(|c| rucene::util::java_character_digit(c, 10))
}

/// `DigitList.fitsIntoLong(isPositive, true)` followed by `getLong()` (as
/// a magnitude): the value of `digits` (significant digits, `decimal_at`
/// the position of the decimal point) when it is an integer that fits a
/// `long`.
fn fits_into_long(positive: bool, digits: &[u8], decimal_at: i64) -> Option<i64> {
    let mut count = digits.len();
    while count > 0 && digits[count - 1] == 0 {
        count -= 1;
    }
    if count == 0 {
        return Some(0);
    }
    if decimal_at < count as i64 || decimal_at > 19 {
        return None;
    }
    let mut value: i128 = 0;
    for &d in &digits[..count] {
        value = value * 10 + i128::from(d);
    }
    for _ in count as i64..decimal_at {
        value *= 10;
    }
    let limit = if positive {
        i128::from(i64::MAX)
    } else {
        -i128::from(i64::MIN)
    };
    if value > limit {
        return None;
    }
    Some(value as i64)
}

/// The number `DecimalFormat.parse` returns, reduced to what
/// `Number.intValue()` gives.
fn int_value(negative: bool, digits: &[u8], decimal_at: i64) -> i32 {
    if let Some(magnitude) = fits_into_long(!negative, digits, decimal_at) {
        // `Long.intValue()`: the low 32 bits.
        let value = if negative {
            magnitude.wrapping_neg()
        } else {
            magnitude
        };
        return value as i32;
    }
    // `Double.intValue()`: rounding toward zero, saturating.
    let mut count = digits.len();
    while count > 0 && digits[count - 1] == 0 {
        count -= 1;
    }
    let mantissa: String = digits[..count]
        .iter()
        .map(|d| char::from(b'0' + d))
        .collect();
    let value: f64 = format!("0.{mantissa}e{decimal_at}")
        .parse()
        .unwrap_or(f64::INFINITY);
    let value = if negative { -value } else { value };
    value as i32
}

/// A compiled `java.text.SimpleDateFormat`, for parsing.
///
/// Equivalent to `java.text.SimpleDateFormat` built with `new
/// SimpleDateFormat(pattern, locale)` or `DateFormat.getDateInstance(DEFAULT,
/// locale)`, lenient (its default); see the module documentation for what
/// is emulated.
#[derive(Debug)]
pub struct SimpleDateFormat {
    pattern: String,
    compiled: Vec<Element>,
    data: &'static LocaleDateData,
}

impl SimpleDateFormat {
    /// `new SimpleDateFormat(pattern, locale)`.
    ///
    /// # Errors
    ///
    /// `IllegalArgumentException` where `SimpleDateFormat.compile` throws it:
    /// `Illegal pattern character 'c'`, `Unterminated quote`, and `invalid
    /// ISO 8601 format: length=n`.
    pub fn new(pattern: &str, locale: &Locale) -> Result<Self> {
        Ok(Self {
            pattern: pattern.to_string(),
            compiled: compile(pattern)?,
            data: locale_data(locale),
        })
    }

    /// `DateFormat.getDateInstance(DateFormat.DEFAULT, locale)`: the
    /// locale's medium date pattern.
    pub fn get_date_instance_default(locale: &Locale) -> Self {
        let data = locale_data(locale);
        let pattern = STRINGS[usize::from(data.default_pattern)].to_string();
        let compiled = compile(&pattern).expect("INVARIANT: the JDK's own patterns compile");
        Self {
            pattern,
            compiled,
            data,
        }
    }

    /// `toPattern()`.
    pub fn to_pattern(&self) -> &str {
        &self.pattern
    }

    /// `DateFormat.parse(String)`: whether `source` starts with a date.
    ///
    /// # Errors
    ///
    /// The `ParseException` "Unparseable date: \"source\"" when no date is
    /// parsed from the start of `source` (Java's `pos.index == 0`).
    pub fn parse(&self, source: &str) -> std::result::Result<(), ParseException> {
        let mut pos = ParsePosition::new(0);
        let parsed = self.parse_position(source, &mut pos);
        if pos.index == 0 || !parsed {
            return Err(ParseException {
                message: format!("Unparseable date: \"{source}\""),
                error_offset: pos.error_index,
            });
        }
        Ok(())
    }

    /// `SimpleDateFormat.parse(String, ParsePosition)`: `true` where Java
    /// returns a `Date`, `false` where it returns `null`; `pos` is updated as
    /// Java updates it.
    pub fn parse_position(&self, text: &str, pos: &mut ParsePosition) -> bool {
        let text: Vec<u16> = text.encode_utf16().collect();
        let mut start = pos.index;
        let old_start = start;
        let text_length = text.len();
        let mut i = 0;
        while i < self.compiled.len() {
            match &self.compiled[i] {
                Element::QuoteAsciiChar(c) => {
                    if start >= text_length || text[start] != *c {
                        pos.index = old_start;
                        pos.error_index = start as i64;
                        return false;
                    }
                    start += 1;
                }
                Element::QuoteChars(chars) => {
                    for c in chars {
                        if start >= text_length || text[start] != *c {
                            pos.index = old_start;
                            pos.error_index = start as i64;
                            return false;
                        }
                        start += 1;
                    }
                }
                Element::Field(tag, count) => {
                    let mut obey_count = false;
                    let mut use_following_minus_sign_as_delimiter = false;
                    if let Some(next) = self.compiled.get(i + 1) {
                        if let Element::Field(next_tag, next_count) = next {
                            obey_count = should_obey_count(*next_tag, *next_count);
                        }
                        if self.data.has_following_minus_sign {
                            let next_char = match next {
                                Element::QuoteAsciiChar(c) => Some(*c),
                                Element::QuoteChars(chars) => chars.first().copied(),
                                Element::Field(..) => None,
                            };
                            if next_char == Some(self.data.minus_sign as u16) {
                                use_following_minus_sign_as_delimiter = true;
                            }
                        }
                    }
                    match self.sub_parse(
                        &text,
                        start,
                        *tag,
                        *count,
                        obey_count,
                        pos,
                        use_following_minus_sign_as_delimiter,
                    ) {
                        Some(next) => start = next,
                        None => {
                            pos.index = old_start;
                            return false;
                        }
                    }
                }
            }
            i += 1;
        }
        // A lenient calendar establishes every field value.
        pos.index = start;
        true
    }

    /// The integer `DecimalFormat.parse(text, pos)` over `text`, as
    /// `Number.intValue()`; `None` where it returns `null`.
    fn parse_number(&self, text: &[u16], pos: &mut ParsePosition) -> Option<i32> {
        let nan = string(self.data.nan);
        if region_matches(false, text, pos.index, &nan) {
            pos.index += nan.len();
            return Some(0); // `Double.NaN.intValue()`
        }
        let positive_prefix = string(self.data.positive_prefix);
        let negative_prefix = string(self.data.negative_prefix);
        let mut status_infinite = false;
        let mut digits: Vec<u8> = Vec::new();
        let mut decimal_at = 0i64;
        let positive = self.subparse(
            text,
            pos,
            &positive_prefix,
            &negative_prefix,
            &mut digits,
            &mut decimal_at,
            false,
            &mut status_infinite,
        )?;
        if status_infinite {
            return Some(if positive { i32::MAX } else { i32::MIN });
        }
        Some(int_value(!positive, &digits, decimal_at))
    }

    /// `DecimalFormat.subparse`: whether the number is positive, `None` on
    /// failure.
    #[allow(clippy::too_many_arguments)]
    fn subparse(
        &self,
        text: &[u16],
        pos: &mut ParsePosition,
        positive_prefix: &[u16],
        negative_prefix: &[u16],
        digits: &mut Vec<u8>,
        decimal_at: &mut i64,
        is_exponent: bool,
        status_infinite: &mut bool,
    ) -> Option<bool> {
        let mut position = pos.index;
        let old_start = position;
        let mut got_positive = region_matches(false, text, position, positive_prefix);
        let mut got_negative = region_matches(false, text, position, negative_prefix);
        if got_positive && got_negative {
            if positive_prefix.len() > negative_prefix.len() {
                got_negative = false;
            } else if positive_prefix.len() < negative_prefix.len() {
                got_positive = false;
            }
        }
        if got_positive {
            position += positive_prefix.len();
        } else if got_negative {
            position += negative_prefix.len();
        } else {
            pos.error_index = position as i64;
            return None;
        }
        let Some(after) = self.subparse_number(
            text,
            position,
            digits,
            decimal_at,
            is_exponent,
            status_infinite,
        ) else {
            pos.index = old_start;
            pos.error_index = old_start as i64;
            return None;
        };
        position = after;
        if !is_exponent {
            let positive_suffix = string(self.data.positive_suffix);
            let negative_suffix = string(self.data.negative_suffix);
            if got_positive {
                got_positive = region_matches(false, text, position, &positive_suffix);
            }
            if got_negative {
                got_negative = region_matches(false, text, position, &negative_suffix);
            }
            if got_positive && got_negative {
                if positive_suffix.len() > negative_suffix.len() {
                    got_negative = false;
                } else if positive_suffix.len() < negative_suffix.len() {
                    got_positive = false;
                }
            }
            if got_positive == got_negative {
                pos.error_index = position as i64;
                return None;
            }
            pos.index = position
                + if got_positive {
                    positive_suffix.len()
                } else {
                    negative_suffix.len()
                };
        } else {
            pos.index = position;
        }
        if pos.index == old_start {
            pos.error_index = position as i64;
            return None;
        }
        Some(got_positive)
    }

    /// `DecimalFormat.subparseNumber` of an integer-only format without
    /// grouping: the position after the number, `None` (Java's `-1`) when no
    /// digit was read. `digits` receives the significant digits (Java's
    /// `DigitList`, leading zeros of the integer part skipped) and
    /// `decimal_at` the position of the decimal point among them.
    fn subparse_number(
        &self,
        text: &[u16],
        position: usize,
        digits: &mut Vec<u8>,
        decimal_at: &mut i64,
        is_exponent: bool,
        status_infinite: &mut bool,
    ) -> Option<usize> {
        let mut position = position;
        *status_infinite = false;
        let infinity = string(self.data.infinity);
        if !is_exponent && region_matches(false, text, position, &infinity) {
            *status_infinite = true;
            return Some(position + infinity.len());
        }
        digits.clear();
        let zero = self.data.zero_digit as u32;
        let decimal = self.data.decimal_separator as u16;
        let exponent_string = string(self.data.exponent_separator);
        let mut saw_digit = false;
        let mut digit_count: i32 = 0;
        let mut exponent: i32 = 0;
        while position < text.len() {
            let ch = text[position];
            let d = u32::from(ch).wrapping_sub(zero);
            let d = if d <= 9 { Some(d) } else { digit(ch) };
            match d {
                Some(0) => {
                    saw_digit = true;
                    // Ignore leading zeros in integer part of number (the
                    // decimal point is never seen: the format is integer
                    // only).
                    if !digits.is_empty() {
                        digit_count += 1;
                        digits.push(0);
                    }
                }
                Some(d) => {
                    saw_digit = true;
                    digit_count += 1;
                    digits.push(d as u8);
                }
                None => {
                    if !is_exponent && ch == decimal {
                        // integer only: stop at the decimal separator
                        break;
                    }
                    if !is_exponent && region_matches(false, text, position, &exponent_string) {
                        // Process the exponent by recursively calling this method.
                        let mut exponent_pos = ParsePosition::new(position + exponent_string.len());
                        let mut exponent_digits = Vec::new();
                        let mut exponent_decimal_at = 0;
                        let mut exponent_infinite = false;
                        let minus_sign_text = string(self.data.minus_sign_text);
                        if let Some(positive) = self.subparse(
                            text,
                            &mut exponent_pos,
                            &[],
                            &minus_sign_text,
                            &mut exponent_digits,
                            &mut exponent_decimal_at,
                            true,
                            &mut exponent_infinite,
                        ) {
                            if let Some(value) =
                                fits_into_long(positive, &exponent_digits, exponent_decimal_at)
                            {
                                position = exponent_pos.index; // Advance past the exponent
                                exponent = value as i32;
                                if !positive {
                                    exponent = exponent.wrapping_neg();
                                }
                            }
                        }
                    }
                    // Whether we fail or succeed, we exit this loop
                    break;
                }
            }
            position += 1;
        }
        // If there was no decimal point we have an integer
        *decimal_at = i64::from(digit_count.wrapping_add(exponent));
        // If none of the text string was recognized.
        if !saw_digit && digit_count == 0 {
            return None;
        }
        Some(position)
    }

    /// `SimpleDateFormat.subParse`: the index after the field, `None`
    /// (Java's negative result) on failure, with `orig_pos.error_index` set.
    #[allow(clippy::too_many_arguments)]
    fn sub_parse(
        &self,
        text: &[u16],
        start: usize,
        pattern_char_index: usize,
        count: usize,
        obey_count: bool,
        orig_pos: &mut ParsePosition,
        use_following_minus_sign_as_delimiter: bool,
    ) -> Option<usize> {
        let mut pos = ParsePosition::new(start);

        // If there are any spaces here, skip over them.  If we hit the end
        // of the string, then fail.
        loop {
            if pos.index >= text.len() {
                orig_pos.error_index = start as i64;
                return None;
            }
            let c = text[pos.index];
            if c != u16::from(b' ') && c != u16::from(b'\t') {
                break;
            }
            pos.index += 1;
        }

        let parsed = 'parsing: {
            // We handle a few special cases here where we need to parse a
            // number value.
            if pattern_char_index == PATTERN_HOUR_OF_DAY1
                || pattern_char_index == PATTERN_HOUR1
                || (pattern_char_index == PATTERN_MONTH && count <= 2)
                || (pattern_char_index == PATTERN_MONTH_STANDALONE && count <= 2)
                || pattern_char_index == PATTERN_YEAR
                || pattern_char_index == PATTERN_WEEK_YEAR
            {
                let number = if obey_count {
                    if start + count > text.len() {
                        break 'parsing None;
                    }
                    self.parse_number(&text[..start + count], &mut pos)
                } else {
                    self.parse_number(text, &mut pos)
                };
                match number {
                    // A Gregorian calendar has no text years.
                    None => break 'parsing None,
                    Some(value) => {
                        if use_following_minus_sign_as_delimiter
                            && value < 0
                            && ((pos.index < text.len()
                                && text[pos.index] != self.data.minus_sign as u16)
                                || (pos.index == text.len()
                                    && text[pos.index - 1] == self.data.minus_sign as u16))
                        {
                            pos.index -= 1;
                        }
                    }
                }
            }

            match pattern_char_index {
                PATTERN_ERA => {
                    let index = match_string(text, start, false, &strings(self.data.eras));
                    if index > 0 {
                        return Some(index as usize);
                    }
                    break 'parsing None;
                }
                PATTERN_WEEK_YEAR | PATTERN_YEAR => {
                    // Gregorian: the value is kept (the two-digit year
                    // adjustment does not change whether the text parses).
                    Some(pos.index)
                }
                PATTERN_MONTH => {
                    if count <= 2 {
                        // [We computed 'value' above.]
                        return Some(pos.index);
                    }
                    // count >= 3 // i.e., MMM or MMMM
                    // Want to be able to parse both short and long forms.
                    let new_start = match_string(text, start, false, &strings(self.data.months));
                    if new_start > 0 {
                        return Some(new_start as usize);
                    }
                    let index = match_string(text, start, false, &strings(self.data.short_months));
                    if index > 0 {
                        return Some(index as usize);
                    }
                    break 'parsing None;
                }
                PATTERN_MONTH_STANDALONE => {
                    if count <= 2 {
                        return Some(pos.index);
                    }
                    let index = match_name_set(text, start, &strings(self.data.month_names));
                    if index > 0 {
                        return Some(index as usize);
                    }
                    break 'parsing None;
                }
                PATTERN_HOUR_OF_DAY1 | PATTERN_HOUR1 => {
                    // lenient: no validation of the hour value
                    Some(pos.index)
                }
                PATTERN_DAY_OF_WEEK => {
                    let new_start = match_string(text, start, true, &strings(self.data.weekdays));
                    if new_start > 0 {
                        return Some(new_start as usize);
                    }
                    let index = match_string(text, start, true, &strings(self.data.short_weekdays));
                    if index > 0 {
                        return Some(index as usize);
                    }
                    break 'parsing None;
                }
                PATTERN_AM_PM => {
                    let index = match_string(text, start, false, &strings(self.data.am_pm));
                    if index > 0 {
                        return Some(index as usize);
                    }
                    break 'parsing None;
                }
                PATTERN_ZONE_NAME | PATTERN_ZONE_VALUE => {
                    break 'parsing self.sub_parse_zone(text, start, &mut pos);
                }
                PATTERN_ISO_ZONE => {
                    if text.len() <= pos.index {
                        break 'parsing None;
                    }
                    let c = text[pos.index];
                    if c == u16::from(b'Z') {
                        return Some(pos.index + 1);
                    }
                    // parse text as "+/-hh[[:]mm]" based on count
                    let sign = if c == u16::from(b'+') {
                        1
                    } else if c == u16::from(b'-') {
                        -1
                    } else {
                        pos.index += 1;
                        break 'parsing None;
                    };
                    pos.index += 1;
                    match sub_parse_numeric_zone(text, pos.index, sign, count, count == 3) {
                        Ok(i) => return Some(i),
                        Err(i) => {
                            pos.index = i;
                            break 'parsing None;
                        }
                    }
                }
                PATTERN_DAY_OF_MONTH
                | PATTERN_HOUR_OF_DAY0
                | PATTERN_MINUTE
                | PATTERN_SECOND
                | PATTERN_MILLISECOND
                | PATTERN_DAY_OF_YEAR
                | PATTERN_DAY_OF_WEEK_IN_MONTH
                | PATTERN_WEEK_OF_YEAR
                | PATTERN_WEEK_OF_MONTH
                | PATTERN_HOUR0
                | PATTERN_ISO_DAY_OF_WEEK => {
                    // Handle "generic" fields
                    let number = if obey_count {
                        if start + count > text.len() {
                            break 'parsing None;
                        }
                        self.parse_number(&text[..start + count], &mut pos)
                    } else {
                        self.parse_number(text, &mut pos)
                    };
                    match number {
                        Some(value) => {
                            if use_following_minus_sign_as_delimiter
                                && value < 0
                                && ((pos.index < text.len()
                                    && text[pos.index] != self.data.minus_sign as u16)
                                    || (pos.index == text.len()
                                        && text[pos.index - 1] == self.data.minus_sign as u16))
                            {
                                pos.index -= 1;
                            }
                            Some(pos.index)
                        }
                        None => None,
                    }
                }
                _ => unreachable!("INVARIANT: compile accepts only the pattern letters"),
            }
        };
        if parsed.is_none() {
            // Parsing failed.
            orig_pos.error_index = pos.index as i64;
        }
        parsed
    }

    /// The `z` and `Z` fields: a `GMT` form or an RFC 822 offset.
    ///
    /// **Divergence.** A zone name (`subParseZoneString`) is not matched;
    /// see the module documentation.
    fn sub_parse_zone(&self, text: &[u16], start: usize, pos: &mut ParsePosition) -> Option<usize> {
        const GMT: [u16; 3] = [b'G' as u16, b'M' as u16, b'T' as u16];
        // Java catches the IndexOutOfBoundsException of `charAt`.
        let mut c = *text.get(pos.index)?;
        let mut sign = 0;
        if c == u16::from(b'+') {
            sign = 1;
        } else if c == u16::from(b'-') {
            sign = -1;
        }
        if sign == 0 {
            // Try parsing a custom time zone "GMT+hh:mm" or "GMT".
            if (c == u16::from(b'G') || c == u16::from(b'g'))
                && text.len() >= start + GMT.len()
                && region_matches(true, text, start, &GMT)
            {
                pos.index = start + GMT.len();

                if text.len() > pos.index {
                    c = text[pos.index];
                    if c == u16::from(b'+') {
                        sign = 1;
                    } else if c == u16::from(b'-') {
                        sign = -1;
                    }
                }

                if sign == 0 {
                    /* "GMT" without offset */
                    return Some(pos.index);
                }

                // Parse the rest as "hh:mm"
                pos.index += 1;
                match sub_parse_numeric_zone(text, pos.index, sign, 0, true) {
                    Ok(i) => Some(i),
                    Err(i) => {
                        pos.index = i;
                        None
                    }
                }
            } else {
                // A time zone name or abbreviation: not emulated.
                None
            }
        } else {
            // Parse the rest as "hhmm" (RFC 822)
            pos.index += 1;
            match sub_parse_numeric_zone(text, pos.index, sign, 0, false) {
                Ok(i) => Some(i),
                Err(i) => {
                    pos.index = i;
                    None
                }
            }
        }
    }
}

/// `SimpleDateFormat.shouldObeyCount(int, int)`: whether the following
/// field is a number field, so that this field reads only `count`
/// characters.
fn should_obey_count(tag: usize, count: usize) -> bool {
    match tag {
        PATTERN_MONTH | PATTERN_MONTH_STANDALONE => count <= 2,
        PATTERN_YEAR
        | PATTERN_DAY_OF_MONTH
        | PATTERN_HOUR_OF_DAY1
        | PATTERN_HOUR_OF_DAY0
        | PATTERN_MINUTE
        | PATTERN_SECOND
        | PATTERN_MILLISECOND
        | PATTERN_DAY_OF_YEAR
        | PATTERN_DAY_OF_WEEK_IN_MONTH
        | PATTERN_WEEK_OF_YEAR
        | PATTERN_WEEK_OF_MONTH
        | PATTERN_HOUR1
        | PATTERN_HOUR0
        | PATTERN_WEEK_YEAR
        | PATTERN_ISO_DAY_OF_WEEK => true,
        _ => false,
    }
}

/// `SimpleDateFormat.matchString(String, int, int, String[], CalendarBuilder)`:
/// the longest of `data` matching `text` at `start`, case-insensitively,
/// where a datum ending with `.` also matches without it; the index after
/// it, or `-start` when none matches. `day_of_week` skips `data[0]`.
fn match_string(text: &[u16], start: usize, day_of_week: bool, data: &[Vec<u16>]) -> i64 {
    let mut i = usize::from(day_of_week);
    let mut best_match_length = 0;
    let mut best_match: Option<usize> = None;
    while i < data.len() {
        let length = data[i].len();
        // Always compare if we have no match yet; otherwise only compare
        // against potentially better matches (longer strings).
        if length > best_match_length && region_matches(true, text, start, &data[i]) {
            best_match = Some(i);
            best_match_length = length;
        }

        // When the input option ends with a period (usually an abbreviated
        // form), attempt to match all chars up to that period.
        if length > 0
            && data[i][length - 1] == u16::from(b'.')
            && (length - 1) > best_match_length
            && region_matches(true, text, start, &data[i][..length - 1])
        {
            best_match = Some(i);
            best_match_length = length - 1;
        }
        i += 1;
    }
    match best_match {
        Some(_) => (start + best_match_length) as i64,
        None => -(start as i64),
    }
}

/// `SimpleDateFormat.matchString(String, int, int, Map, CalendarBuilder)`
/// over a `HashMap` of names: the longest name matching `text` at `start`,
/// case-insensitively; the index after it, or `-start` when none matches.
fn match_name_set(text: &[u16], start: usize, names: &[Vec<u16>]) -> i64 {
    let mut best_match: Option<usize> = None;
    for name in names {
        if best_match.is_none_or(|best| name.len() > best)
            && region_matches(true, text, start, name)
        {
            best_match = Some(name.len());
        }
    }
    match best_match {
        Some(length) => (start + length) as i64,
        None => -(start as i64),
    }
}

/// `SimpleDateFormat.subParseNumericZone`: `Ok(index after the offset)`, or
/// `Err(index)` where Java returns `1 - index`.
fn sub_parse_numeric_zone(
    text: &[u16],
    start: usize,
    _sign: i32,
    count: usize,
    colon: bool,
) -> std::result::Result<usize, usize> {
    let is_digit = |c: u16| (u16::from(b'0')..=u16::from(b'9')).contains(&c);
    let mut index = start;
    let result: Option<usize> = (|| {
        // Java catches the IndexOutOfBoundsException of `charAt`.
        let next = |index: &mut usize| -> Option<u16> {
            let c = text.get(*index).copied();
            *index += 1;
            c
        };
        let mut c = next(&mut index)?;
        // Parse hh
        if !is_digit(c) {
            return None;
        }
        let mut hours = i32::from(c - u16::from(b'0'));
        c = next(&mut index)?;
        if is_digit(c) {
            hours = hours * 10 + i32::from(c - u16::from(b'0'));
        } else {
            // If no colon in RFC 822 or 'X' (ISO), two digits are
            // required.
            if count > 0 || !colon {
                return None;
            }
            index -= 1;
        }
        if hours > 23 {
            return None;
        }
        if count != 1 {
            // Proceed with parsing mm
            c = next(&mut index)?;
            if colon {
                if c != u16::from(b':') {
                    return None;
                }
                c = next(&mut index)?;
            }
            if !is_digit(c) {
                return None;
            }
            let mut minutes = i32::from(c - u16::from(b'0'));
            c = next(&mut index)?;
            if !is_digit(c) {
                return None;
            }
            minutes = minutes * 10 + i32::from(c - u16::from(b'0'));
            if minutes > 59 {
                return None;
            }
        }
        Some(index)
    })();
    match result {
        Some(index) => Ok(index),
        None => Err(index.saturating_sub(1)),
    }
}

/// `SimpleDateFormat.compile(String)`, for parsing.
fn compile(pattern: &str) -> Result<Vec<Element>> {
    let pattern: Vec<u16> = pattern.encode_utf16().collect();
    let length = pattern.len();
    let mut in_quote = false;
    let mut compiled: Vec<Element> = Vec::new();
    let mut tmp_buffer: Vec<u16> = Vec::new();
    let mut count = 0;
    let mut last_tag: Option<usize> = None;
    let is_letter = |c: u16| {
        (u16::from(b'a')..=u16::from(b'z')).contains(&c)
            || (u16::from(b'A')..=u16::from(b'Z')).contains(&c)
    };
    let encode = |tag: usize, length: usize, compiled: &mut Vec<Element>| -> Result<()> {
        if tag == PATTERN_ISO_ZONE && length >= 4 {
            return Err(LuceneError::illegal_argument(format!(
                "invalid ISO 8601 format: length={length}"
            )));
        }
        compiled.push(Element::Field(tag, length));
        Ok(())
    };
    let mut i = 0;
    while i < length {
        let mut c = pattern[i];
        if c == u16::from(b'\'') {
            // '' is treated as a single quote regardless of being in a
            // quoted section.
            if i + 1 < length {
                c = pattern[i + 1];
                if c == u16::from(b'\'') {
                    i += 1;
                    if count != 0 {
                        encode(last_tag.expect("INVARIANT: count"), count, &mut compiled)?;
                        last_tag = None;
                        count = 0;
                    }
                    if in_quote {
                        tmp_buffer.push(c);
                    } else {
                        compiled.push(Element::QuoteAsciiChar(c));
                    }
                    i += 1;
                    continue;
                }
            }
            if !in_quote {
                if count != 0 {
                    encode(last_tag.expect("INVARIANT: count"), count, &mut compiled)?;
                    last_tag = None;
                    count = 0;
                }
                tmp_buffer.clear();
                in_quote = true;
            } else {
                if tmp_buffer.len() == 1 && tmp_buffer[0] < 128 {
                    compiled.push(Element::QuoteAsciiChar(tmp_buffer[0]));
                } else {
                    compiled.push(Element::QuoteChars(tmp_buffer.clone()));
                }
                in_quote = false;
            }
            i += 1;
            continue;
        }
        if in_quote {
            tmp_buffer.push(c);
            i += 1;
            continue;
        }
        if !is_letter(c) {
            if count != 0 {
                encode(last_tag.expect("INVARIANT: count"), count, &mut compiled)?;
                last_tag = None;
                count = 0;
            }
            if c < 128 {
                // In most cases, c would be a delimiter, such as ':'.
                compiled.push(Element::QuoteAsciiChar(c));
            } else {
                // Take any contiguous non-ASCII alphabet characters and put
                // them in a single TAG_QUOTE_CHARS.
                let mut j = i + 1;
                while j < length {
                    let d = pattern[j];
                    if d == u16::from(b'\'') || is_letter(d) {
                        break;
                    }
                    j += 1;
                }
                compiled.push(Element::QuoteChars(pattern[i..j].to_vec()));
                i = j;
                continue;
            }
            i += 1;
            continue;
        }

        let Some(tag) = PATTERN_CHARS.encode_utf16().position(|p| p == c) else {
            return Err(LuceneError::illegal_argument(format!(
                "Illegal pattern character '{}'",
                char::from_u32(u32::from(c)).unwrap_or(char::REPLACEMENT_CHARACTER)
            )));
        };
        if last_tag.is_none() || last_tag == Some(tag) {
            last_tag = Some(tag);
            count += 1;
            i += 1;
            continue;
        }
        encode(last_tag.expect("INVARIANT: checked"), count, &mut compiled)?;
        last_tag = Some(tag);
        count = 1;
        i += 1;
    }

    if in_quote {
        return Err(LuceneError::illegal_argument("Unterminated quote"));
    }

    if count != 0 {
        encode(last_tag.expect("INVARIANT: count"), count, &mut compiled)?;
    }

    Ok(compiled)
}
