/// The locale data `SimpleDateFormat.parse` reads, as indices into the
/// generated string table.
#[derive(Debug)]
pub struct LocaleDateData {
    pub(super) default_pattern: u16,
    pub(super) eras: &'static [u16],
    pub(super) months: &'static [u16],
    pub(super) short_months: &'static [u16],
    pub(super) weekdays: &'static [u16],
    pub(super) short_weekdays: &'static [u16],
    pub(super) am_pm: &'static [u16],
    /// The `MONTH` display names of the `SHORT_FORMAT`, `SHORT_STANDALONE`,
    /// `LONG_FORMAT` and `LONG_STANDALONE` styles (`getDisplayNamesMap`).
    pub(super) month_names: &'static [u16],
    pub(super) zero_digit: char,
    pub(super) decimal_separator: char,
    pub(super) minus_sign: char,
    pub(super) minus_sign_text: u16,
    pub(super) exponent_separator: u16,
    pub(super) nan: u16,
    pub(super) infinity: u16,
    pub(super) positive_prefix: u16,
    pub(super) positive_suffix: u16,
    pub(super) negative_prefix: u16,
    pub(super) negative_suffix: u16,
    pub(super) has_following_minus_sign: bool,
}

