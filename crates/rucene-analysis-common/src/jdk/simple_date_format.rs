//! The parsing of `java.text.SimpleDateFormat` and
//! `DateFormat.getDateInstance(DateFormat.DEFAULT, Locale)`, which
//! `DateRecognizerFilter` and its factory call.
//!
//! **Divergence.** This is an emulation of JDK 25, written from the
//! `SimpleDateFormat`, `DateFormat`, `DecimalFormat` and `ParsePosition`
//! javadoc and from the JDK's observed behaviour, over the locale data the
//! JDK holds for every locale of `DateFormat.getAvailableLocales()`
//! (`date_format_data`, generated by `tools/translate/JdkDateFormatData.java`).
//! No JDK code is reproduced. Its scope is what a lenient `SimpleDateFormat`
//! needs to tell whether a text parses as a date: the pattern is compiled as
//! `SimpleDateFormat` compiles it (same errors), and each field is parsed as
//! `SimpleDateFormat.subParse` parses it (numbers through the locale's
//! integer `DecimalFormat`, names through the locale's `DateFormatSymbols`,
//! case-insensitively, longest match first); the calendar fields are not
//! computed, because a lenient calendar accepts every value. It differs from
//! the JDK in these points, each to be verified against JDK 25:
//!
//! * the locale's data is found by the base locale (language, script,
//!   country, variant), falling back as `ResourceBundle.Control`'s default
//!   candidate list does to a locale the JDK lists, then to the root locale;
//!   the Unicode extensions of a locale (`-u-ca-`, `-u-nu-`, `-u-rg-`, ...)
//!   are not applied, so a calendar other than the Gregorian (and the
//!   Buddhist one of `th_TH`, which parses the same way), or another
//!   numbering system, is not emulated;
//! * a general time zone given by name (pattern letter `z` or `Z` followed
//!   by a zone name such as `PST`) is not matched: only the `GMT` forms and
//!   the RFC 822 and ISO 8601 offsets are, so such a text does not parse
//!   where the JDK may parse it.

