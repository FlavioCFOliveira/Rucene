//! Port of `org.apache.lucene.codecs.bitvectors.HnswBitVectorsFormat`.

use std::fmt;
use std::sync::Arc;

use rucene::codecs::hnsw::flat_vectors::FlatVectorsFormat;
use rucene::codecs::knn_vectors::{FieldVectorWriter, IORunnable};
use rucene::codecs::lucene99::hnsw_vectors_format::{
    DEFAULT_BEAM_WIDTH, DEFAULT_MAX_CONN, DEFAULT_NUM_MERGE_WORKER, HNSW_GRAPH_THRESHOLD,
    MAXIMUM_BEAM_WIDTH, MAXIMUM_MAX_CONN, VERSION_CURRENT,
};
use rucene::codecs::lucene99::{
    Lucene99FlatVectorsFormat, Lucene99HnswVectorsReader, Lucene99HnswVectorsWriter,
};
use rucene::codecs::postings::MergeState;
use rucene::codecs::state::OwnedSegmentWriteState;
use rucene::codecs::{
    KnnVectorsFormat, KnnVectorsReader, KnnVectorsWriter, SegmentReadState, SorterDocMap,
};
use rucene::error::{LuceneError, Result};
use rucene::index::{FieldInfo, VectorEncoding};
use rucene::search::{Executor, TaskExecutor};

use super::flat_bit_vectors_scorer::FlatBitVectorsScorer;

/// The format's name.
pub const NAME: &str = "HnswBitVectorsFormat";

/// Encodes bit vector values into an associated graph connecting the
/// documents having values. The graph is used to power HNSW search. The
/// format consists of two files, and uses `Lucene99FlatVectorsFormat` to
/// store the actual vectors, but with a custom scorer implementation: for
/// details on graph storage and file extensions, see
/// `Lucene99HnswVectorsFormat`.
///
/// Port of `org.apache.lucene.codecs.bitvectors.HnswBitVectorsFormat`.
#[derive(Debug, Clone)]
pub struct HnswBitVectorsFormat {
    /// Controls how many of the nearest neighbor candidates are connected to
    /// the new node. Defaults to `Lucene99HnswVectorsFormat.DEFAULT_MAX_CONN`.
    max_conn: i32,
    /// The number of candidate neighbors to track while searching the graph
    /// for each newly inserted node. Defaults to
    /// `Lucene99HnswVectorsFormat.DEFAULT_BEAM_WIDTH`.
    beam_width: i32,
    /// The format for storing, reading, merging vectors on disk.
    flat_vectors_format: Lucene99FlatVectorsFormat,
    num_merge_workers: i32,
    merge_exec: Option<Arc<TaskExecutor>>,
}

impl Default for HnswBitVectorsFormat {
    fn default() -> Self {
        Self::new()
    }
}

impl HnswBitVectorsFormat {
    /// Constructs a format using default graph construction parameters.
    ///
    /// Port of `HnswBitVectorsFormat()`.
    pub fn new() -> Self {
        Self::with_merge_exec(
            DEFAULT_MAX_CONN,
            DEFAULT_BEAM_WIDTH,
            DEFAULT_NUM_MERGE_WORKER,
            None,
        )
        .expect("INVARIANT: the default parameters are valid")
    }

    /// Constructs a format using the given graph construction parameters:
    /// `max_conn`, the maximum number of connections to a node in the HNSW
    /// graph, and `beam_width`, the size of the queue maintained during
    /// graph construction.
    ///
    /// Port of `HnswBitVectorsFormat(int, int)`.
    ///
    /// # Errors
    ///
    /// `IllegalArgumentException` as for [`with_merge_exec`](Self::with_merge_exec).
    pub fn with_params(max_conn: i32, beam_width: i32) -> Result<Self> {
        Self::with_merge_exec(max_conn, beam_width, DEFAULT_NUM_MERGE_WORKER, None)
    }

    /// Constructs a format using the given graph construction parameters
    /// and scalar quantization: `num_merge_workers` is the number of workers
    /// (threads) that will be used when doing merge (if larger than 1, a
    /// non-`None` `merge_exec` must be passed), and `merge_exec` the executor
    /// that will be used by ALL vector writers that are generated by this
    /// format to do the merge.
    ///
    /// Port of `HnswBitVectorsFormat(int, int, int, ExecutorService)`.
    ///
    /// # Errors
    ///
    /// `IllegalArgumentException` when `max_conn` is not in `1..=512`,
    /// `beam_width` not in `1..=3200`, or one merge worker comes with an
    /// executor.
    pub fn with_merge_exec(
        max_conn: i32,
        beam_width: i32,
        num_merge_workers: i32,
        merge_exec: Option<Arc<dyn Executor>>,
    ) -> Result<Self> {
        if max_conn <= 0 || max_conn > MAXIMUM_MAX_CONN {
            return Err(LuceneError::IllegalArgument(format!(
                "maxConn must be positive and less than or equal to {MAXIMUM_MAX_CONN}; \
                 maxConn={max_conn}"
            )));
        }
        if beam_width <= 0 || beam_width > MAXIMUM_BEAM_WIDTH {
            return Err(LuceneError::IllegalArgument(format!(
                "beamWidth must be positive and less than or equal to {MAXIMUM_BEAM_WIDTH}; \
                 beamWidth={beam_width}"
            )));
        }
        if num_merge_workers == 1 && merge_exec.is_some() {
            return Err(LuceneError::IllegalArgument(
                "No executor service is needed as we'll use single thread to merge".to_string(),
            ));
        }
        Ok(Self {
            max_conn,
            beam_width,
            flat_vectors_format: Lucene99FlatVectorsFormat::new(FlatBitVectorsScorer::new()),
            num_merge_workers,
            merge_exec: merge_exec.map(|exec| Arc::new(TaskExecutor::new(exec))),
        })
    }
}

impl KnnVectorsFormat for HnswBitVectorsFormat {
    fn name(&self) -> &str {
        NAME
    }

    fn fields_writer(&self, state: &OwnedSegmentWriteState) -> Result<Box<dyn KnnVectorsWriter>> {
        let flat_vector_writer = self.flat_vectors_format.fields_writer_flat(state)?;
        Ok(Box::new(FlatBitVectorsWriter {
            delegate: Box::new(Lucene99HnswVectorsWriter::with_flat_format(
                state,
                self.max_conn,
                self.beam_width,
                self.num_merge_workers,
                self.merge_exec.clone(),
                HNSW_GRAPH_THRESHOLD,
                VERSION_CURRENT,
                Box::new(self.flat_vectors_format.clone()),
                flat_vector_writer,
            )?),
        }))
    }

    fn fields_reader<'a>(&self, state: &SegmentReadState<'a>) -> Result<Box<dyn KnnVectorsReader>> {
        let flat_reader = self.flat_vectors_format.fields_reader_flat(state)?;
        Ok(Box::new(Lucene99HnswVectorsReader::new(
            state,
            flat_reader,
        )?))
    }

    fn get_max_dimensions(&self, _field_name: &str) -> i32 {
        1024
    }

    /// The format itself, so that a caller holding the trait object can
    /// reach its Java `toString()` ([`fmt::Display`]) or test
    /// `instanceof HnswBitVectorsFormat`.
    fn as_any(&self) -> Option<&dyn std::any::Any> {
        Some(self)
    }
}

impl fmt::Display for HnswBitVectorsFormat {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "HnswBitVectorsFormat(name=HnswBitVectorsFormat, maxConn={}, beamWidth={}, \
             flatVectorFormat={})",
            self.max_conn, self.beam_width, self.flat_vectors_format
        )
    }
}

/// Port of the private class `HnswBitVectorsFormat.FlatBitVectorsWriter`:
/// the HNSW writer, refusing fields that do not encode bytes.
#[derive(Debug)]
struct FlatBitVectorsWriter {
    delegate: Box<dyn KnnVectorsWriter>,
}

impl KnnVectorsWriter for FlatBitVectorsWriter {
    fn merge_one_field<'m>(
        &mut self,
        field_info: &FieldInfo,
        merge_state: &'m MergeState,
    ) -> Result<Option<Box<dyn IORunnable + 'm>>> {
        self.delegate.merge_one_field(field_info, merge_state)
    }

    fn finish(&mut self) -> Result<()> {
        self.delegate.finish()
    }

    fn add_field(&mut self, field_info: &FieldInfo) -> Result<FieldVectorWriter> {
        if field_info.vector_encoding != VectorEncoding::BYTE {
            return Err(LuceneError::IllegalArgument(
                "HnswBitVectorsFormat only supports BYTE encoding".to_string(),
            ));
        }
        self.delegate.add_field(field_info)
    }

    fn flush(&mut self, max_doc: i32, sort_map: Option<&SorterDocMap>) -> Result<()> {
        self.delegate.flush(max_doc, sort_map)
    }

    fn close(&mut self) -> Result<()> {
        self.delegate.close()
    }

    fn ram_bytes_used(&self) -> i64 {
        self.delegate.ram_bytes_used()
    }
}
