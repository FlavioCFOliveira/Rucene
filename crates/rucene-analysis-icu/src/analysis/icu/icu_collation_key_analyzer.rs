//! Configures `KeywordTokenizer` with `ICUCollationAttributeFactory`,
//! ported from `org.apache.lucene.analysis.icu.ICUCollationKeyAnalyzer`.

use std::sync::Arc;

use icu4j::text::collator::Collator;
use rucene::analysis::{Analyzer, AnalyzerState, GlobalReuseStrategy, TokenStreamComponents};
use rucene::error::Result;
use rucene::util::atomic_ref_cell::AtomicRefCell;
use rucene_analysis_common::analysis::core::keyword_tokenizer::{
    new_keyword_tokenizer_with_factory, DEFAULT_BUFFER_SIZE,
};

use super::icu_collation_attribute_factory::ICUCollationAttributeFactory;

/// Configures `KeywordTokenizer` with `ICUCollationAttributeFactory`.
///
/// Converts the token into its `com.ibm.icu.text.CollationKey`, and then
/// encodes the CollationKey directly to allow it to be stored as an index
/// term.
///
/// **WARNING:** Make sure you use exactly the same Collator at index and
/// query time -- CollationKeys are only comparable when produced by the same
/// Collator. `com.ibm.icu.text.RuleBasedCollator`s are independently
/// versioned, so it is safe to search against stored CollationKeys if the
/// following are exactly the same (best practice is to store this
/// information with the index and check that they remain the same at query
/// time):
///
/// 1. Collator version - see `Collator.getVersion()`
/// 2. The collation strength used - see `Collator.setStrength(int)`
///
/// CollationKeys generated by ICU Collators are not compatible with those
/// generated by java.text.Collators. Specifically, if you use
/// ICUCollationKeyAnalyzer to generate index terms, do not use
/// `CollationKeyAnalyzer` on the query side, or vice versa.
///
/// ICUCollationKeyAnalyzer is significantly faster and generates
/// significantly shorter keys than CollationKeyAnalyzer. See
/// <http://site.icu-project.org/charts/collation-icu4j-sun> for key
/// generation timing and key length comparisons between ICU4J and
/// java.text.Collator over several languages.
///
/// Equivalent to `org.apache.lucene.analysis.icu.ICUCollationKeyAnalyzer`
/// (since 3.1).
#[derive(Debug)]
pub struct ICUCollationKeyAnalyzer {
    state: AnalyzerState,
    factory: Arc<ICUCollationAttributeFactory>,
}

impl ICUCollationKeyAnalyzer {
    /// Create a new ICUCollationKeyAnalyzer, using the specified collator.
    ///
    /// * `collator`: CollationKey generator
    ///
    /// Equivalent to `ICUCollationKeyAnalyzer(Collator)`, whose implicit
    /// `Analyzer()` uses `GLOBAL_REUSE_STRATEGY`.
    pub fn new(collator: Arc<dyn Collator>) -> Self {
        Self {
            state: AnalyzerState::new(Box::new(GlobalReuseStrategy)),
            factory: Arc::new(ICUCollationAttributeFactory::new(collator)),
        }
    }
}

impl Analyzer for ICUCollationKeyAnalyzer {
    fn analyzer_state(&self) -> &AnalyzerState {
        &self.state
    }

    fn java_class_name(&self) -> &'static str {
        "org.apache.lucene.analysis.icu.ICUCollationKeyAnalyzer"
    }

    /// Equivalent to `ICUCollationKeyAnalyzer.createComponents(String)`: a
    /// `KeywordTokenizer(factory, KeywordTokenizer.DEFAULT_BUFFER_SIZE)`.
    fn create_components(&self, _field_name: Option<&str>) -> Result<TokenStreamComponents> {
        let tokenizer = new_keyword_tokenizer_with_factory(self.factory.clone(), DEFAULT_BUFFER_SIZE)?;
        Ok(TokenStreamComponents::from_tokenizer(Arc::new(
            AtomicRefCell::new(tokenizer),
        )))
    }
}
