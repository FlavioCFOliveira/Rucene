//! Converts each token into its `com.ibm.icu.text.CollationKey`, and then
//! encodes bytes as an index term, ported from
//! `org.apache.lucene.analysis.icu.ICUCollationAttributeFactory`.

use std::any::TypeId;
use std::fmt;
use std::sync::Arc;

use icu4j::text::collator::Collator;
use rucene::analysis::default_token_attribute_factory;
use rucene::error::LuceneError;
use rucene::util::attribute::{
    AttributeFactory, AttributeImpl, StaticImplementationAttributeFactory,
};

use super::tokenattributes::icu_collated_term_attribute_impl::ICUCollatedTermAttributeImpl;

/// Converts each token into its `com.ibm.icu.text.CollationKey`, and then
/// encodes bytes as an index term.
///
/// **WARNING:** Make sure you use exactly the same Collator at index and
/// query time -- CollationKeys are only comparable when produced by the same
/// Collator. `com.ibm.icu.text.RuleBasedCollator`s are independently
/// versioned, so it is safe to search against stored CollationKeys if the
/// following are exactly the same (best practice is to store this
/// information with the index and check that they remain the same at query
/// time):
///
/// 1. Collator version - see `Collator.getVersion()`
/// 2. The collation strength used - see `Collator.setStrength(int)`
///
/// CollationKeys generated by ICU Collators are not compatible with those
/// generated by java.text.Collators. Specifically, if you use
/// ICUCollationAttributeFactory to generate index terms, do not use
/// `CollationAttributeFactory` on the query side, or vice versa.
///
/// ICUCollationAttributeFactory is significantly faster and generates
/// significantly shorter keys than CollationAttributeFactory. See
/// <http://site.icu-project.org/charts/collation-icu4j-sun> for key
/// generation timing and key length comparisons between ICU4J and
/// java.text.Collator over several languages.
///
/// Equivalent to `org.apache.lucene.analysis.icu.ICUCollationAttributeFactory`,
/// which extends
/// `AttributeFactory.StaticImplementationAttributeFactory<ICUCollatedTermAttributeImpl>`:
/// the base is the [`StaticImplementationAttributeFactory`] this factory
/// holds, whose `createInstance()` is [`create_instance`](Self::create_instance).
/// The collator is shared (`Arc`), as Java keeps the caller's object; each
/// attribute clones it.
pub struct ICUCollationAttributeFactory {
    base: StaticImplementationAttributeFactory,
    collator: Arc<dyn Collator>,
}

impl ICUCollationAttributeFactory {
    /// Create an ICUCollationAttributeFactory, using
    /// TokenStream.DEFAULT_TOKEN_ATTRIBUTE_FACTORY as the factory for all
    /// other attributes.
    ///
    /// * `collator`: CollationKey generator
    ///
    /// Equivalent to `ICUCollationAttributeFactory(Collator)`.
    pub fn new(collator: Arc<dyn Collator>) -> Self {
        Self::with_delegate(default_token_attribute_factory(), collator)
    }

    /// Create an ICUCollationAttributeFactory, using the supplied Attribute
    /// Factory as the factory for all other attributes.
    ///
    /// * `delegate`: Attribute Factory
    /// * `collator`: CollationKey generator
    ///
    /// Equivalent to `ICUCollationAttributeFactory(AttributeFactory, Collator)`.
    pub fn with_delegate(delegate: Arc<dyn AttributeFactory>, collator: Arc<dyn Collator>) -> Self {
        let instance_collator = Arc::clone(&collator);
        Self {
            base: StaticImplementationAttributeFactory::new(
                delegate,
                ICUCollatedTermAttributeImpl::interfaces(),
                move || ICUCollatedTermAttributeImpl::new(instance_collator.as_ref()),
            ),
            collator,
        }
    }

    /// Equivalent to `ICUCollationAttributeFactory.createInstance()`, `new
    /// ICUCollatedTermAttributeImpl(collator)`.
    ///
    /// # Panics
    ///
    /// As [`ICUCollatedTermAttributeImpl::new`].
    pub fn create_instance(&self) -> ICUCollatedTermAttributeImpl {
        ICUCollatedTermAttributeImpl::new(self.collator.as_ref())
    }
}

impl fmt::Debug for ICUCollationAttributeFactory {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("ICUCollationAttributeFactory")
            .field("base", &self.base)
            .finish_non_exhaustive()
    }
}

impl AttributeFactory for ICUCollationAttributeFactory {
    /// The inherited final
    /// `StaticImplementationAttributeFactory.createAttributeInstance(Class)`:
    /// an [`ICUCollatedTermAttributeImpl`] for the interfaces it implements,
    /// the delegate's attribute for any other.
    fn create_attribute_instance(
        &self,
        attribute_type: TypeId,
    ) -> Result<Box<dyn AttributeImpl>, LuceneError> {
        self.base.create_attribute_instance(attribute_type)
    }
}
