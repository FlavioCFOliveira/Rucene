//! `com.ibm.icu.text.RBNFPostProcessor`.

use rucene::error::Result;

use crate::text::nf_rule_set::NFRuleSet;
use crate::text::rule_based_number_format::RuleBasedNumberFormat;

/// Post processor for RBNF output.
///
/// Equivalent to the package-private interface
/// `com.ibm.icu.text.RBNFPostProcessor`. The rule set Java passes may be
/// `null` (the formatting of `Long.MIN_VALUE`), so it is an `Option`; the
/// unchecked exceptions an implementation throws are `Err` values.
pub(crate) trait RBNFPostProcessor: std::fmt::Debug + Send + Sync {
    /// Initialization routine for this instance, called once immediately
    /// after first construction and never again. `formatter` is the
    /// formatter that will be using this post-processor, `rules` the special
    /// rules for this post-processor. Equivalent to
    /// `init(RuleBasedNumberFormat formatter, String rules)`.
    ///
    /// # Errors
    ///
    /// The implementation's.
    fn init(&mut self, formatter: &RuleBasedNumberFormat, rules: &[u16]) -> Result<()>;

    /// Work routine. Post process the output, which was generated by the
    /// rule set with the given name. Equivalent to `process(StringBuilder
    /// output, NFRuleSet ruleSet)`.
    ///
    /// # Errors
    ///
    /// The implementation's.
    fn process(&mut self, output: &mut Vec<u16>, rule_set: Option<&NFRuleSet>) -> Result<()>;
}
