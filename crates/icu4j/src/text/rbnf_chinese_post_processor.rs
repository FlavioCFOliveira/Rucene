//! `com.ibm.icu.text.RBNFChinesePostProcessor`.

use rucene::error::Result;

use crate::jdk::{index_of, last_index_of, units};
use crate::text::nf_rule_set::NFRuleSet;
use crate::text::rbnf_post_processor::RBNFPostProcessor;
use crate::text::rule_based_number_format::{char_at, npe, sb_delete, sb_insert, RuleBasedNumberFormat};

/// `rulesetNames` (private static).
const RULESET_NAMES: [&str; 4] = ["%traditional", "%simplified", "%accounting", "%time"];

/// A post-processor for Chinese text.
///
/// Equivalent to the package-private final class
/// `com.ibm.icu.text.RBNFChinesePostProcessor`.
#[derive(Debug, Default)]
pub(crate) struct RBNFChinesePostProcessor {
    //private NFRuleSet lastRuleSet;
    /// `longForm`.
    long_form: bool,
    /// `format`.
    format: usize,
}

impl RBNFChinesePostProcessor {
    /// The implicit no-argument constructor `Class.newInstance()` calls.
    pub(crate) fn new() -> Self {
        Self::default()
    }
}

impl RBNFPostProcessor for RBNFChinesePostProcessor {
    /// Initialization routine for this instance, called once immediately
    /// after first construction and never again. Equivalent to
    /// `init(RuleBasedNumberFormat formatter, String rules)` (it does
    /// nothing).
    fn init(&mut self, _formatter: &RuleBasedNumberFormat, _rules: &[u16]) -> Result<()> {
        Ok(())
    }

    /// Work routine. Post process the output, which was generated by the
    /// rule set with the given name: removes the `*` markers of the long
    /// forms, or the optional lings of adjacent 10,000 chunks. Equivalent to
    /// `process(StringBuilder buf, NFRuleSet ruleSet)`.
    ///
    /// # Errors
    ///
    /// `NullPointerException` for a `null` rule set; `IllegalStateException`
    /// for an impossible state.
    ///
    /// # Panics
    ///
    /// `StringIndexOutOfBoundsException` where Java's deletions fall
    /// outside the buffer.
    fn process(&mut self, buf: &mut Vec<u16>, rule_set: Option<&NFRuleSet>) -> Result<()> {
        // markers depend on what rule set we are using

        // Commented by johnvu on the if statement since lastRuleSet is never initialized
        //if (ruleSet != lastRuleSet) {
        let name = rule_set.ok_or_else(npe)?.get_name();
        for (i, ruleset_name) in RULESET_NAMES.iter().enumerate() {
            if units(ruleset_name).as_slice() == name {
                self.format = i;
                self.long_form = i == 1 || i == 3;
                break;
            }
        }
        //}

        let star = units("*");
        if self.long_form {
            let mut i = index_of(buf, &star, 0);
            while i != -1 {
                sb_delete(buf, i, i + 1);
                i = index_of(buf, &star, i);
            }
            return Ok(());
        }

        let dian = units("\u{9ede}"); // decimal point

        let markers: [[&str; 4]; 3] = [
            ["\u{842c}", "\u{5104}", "\u{5146}", "\u{3007}"], // marker chars, last char is the 'zero'
            ["\u{4e07}", "\u{4ebf}", "\u{5146}", "\u{3007}"],
            ["\u{842c}", "\u{5104}", "\u{5146}", "\u{96f6}"],
            // need markers for time?
        ];

        // remove unwanted lings
        // a '0' (ling) with * might be removed
        // mark off 10,000 'chunks', markers are Z, Y, W (zhao, yii, and wan)
        // already, we avoid two lings in the same chunk -- ling without * wins
        // now, just need  to avoid optional lings in adjacent chunks
        // process right to left

        // decision matrix:
        // state, situation
        //     state         none       opt.          req.
        //     -----         ----       ----          ----
        // none to right     none       opt.          req.
        // opt. to right     none   clear, none  clear right, req.
        // req. to right     none   clear, none       req.

        // mark chunks with '|' for convenience
        {
            let m = &markers[crate::text::rule_based_number_format::array_index(self.format as i64, markers.len())];
            for marker in &m[..m.len() - 1] {
                let marker = units(marker);
                let n = index_of(buf, &marker, 0);
                if n != -1 {
                    sb_insert(buf, n + marker.len() as i32, &[u16::from(b'|')]);
                }
            }
        }

        let mut x = index_of(buf, &dian, 0);
        if x == -1 {
            x = buf.len() as i32;
        }
        let mut s = 0; // 0 = none to right, 1 = opt. to right, 2 = req. to right
        let mut n = -1; // previous optional ling
        let ling = units(markers[self.format][3]);
        let bar = units("|");
        while x >= 0 {
            let m = last_index_of(buf, &bar, x);
            let nn = last_index_of(buf, &ling, x);
            let mut ns = 0;
            if nn > m {
                ns = if nn > 0 && char_at(buf, nn - 1) != u16::from(b'*') { 2 } else { 1 };
            }
            x = m - 1;

            // actually much simpler, but leave this verbose for now so it's easier to follow
            match s * 3 + ns {
                0 => {
                    /* none, none */
                    s = ns; // redundant
                    n = -1;
                }
                1 => {
                    /* none, opt. */
                    s = ns;
                    n = nn; // remember optional ling to right
                }
                2 => {
                    /* none, req. */
                    s = ns;
                    n = -1;
                }
                3 => {
                    /* opt., none */
                    s = ns;
                    n = -1;
                }
                4 => {
                    /* opt., opt. */
                    sb_delete(buf, nn - 1, nn + ling.len() as i32); // delete current optional ling
                    s = 0;
                    n = -1;
                }
                5 => {
                    /* opt., req. */
                    sb_delete(buf, n - 1, n + ling.len() as i32); // delete previous optional ling
                    s = ns;
                    n = -1;
                }
                6 => {
                    /* req., none */
                    s = ns;
                    n = -1;
                }
                7 => {
                    /* req., opt. */
                    sb_delete(buf, nn - 1, nn + ling.len() as i32); // delete current optional ling
                    s = 0;
                    n = -1;
                }
                8 => {
                    /* req., req. */
                    s = ns;
                    n = -1;
                }
                _ => {
                    return Err(rucene::error::LuceneError::unchecked_with_message(
                        "java.lang.IllegalStateException",
                        None,
                    ));
                }
            }
        }

        let mut i = buf.len() as i32;
        while i > 0 {
            i -= 1;
            let c = char_at(buf, i);
            if c == u16::from(b'*') || c == u16::from(b'|') {
                sb_delete(buf, i, i + 1);
            }
        }
        Ok(())
    }
}
