use crate::text::utf16::UTF16;

/// Data and functions for the FCD check fast path.
///
/// Equivalent to `com.ibm.icu.impl.coll.CollationFCD`: the lccc and tccc
/// tables are the generated data of the Java file, value for value.
#[derive(Debug)]
pub struct CollationFCD;

/// A Java `int` hexadecimal literal with the high bit set.
const fn h(v: u32) -> i32 {
    v as i32
}

impl CollationFCD {
    /// `hasLccc(int)`: c is a BMP code point (or negative).
    pub fn has_lccc(c: i32) -> bool {
        debug_assert!(c <= 0xffff);
        // c can be negative, e.g., Collation.SENTINEL_CP from UCharIterator;
        // that is handled in the first test.
        // U+0300 is the first character with lccc!=0.
        if c < 0x300 {
            return false;
        }
        let i = LCCC_INDEX[(c >> 5) as usize] as i32;
        i != 0 && (LCCC_BITS[i as usize] & (1 << (c & 0x1f))) != 0
    }

    /// `hasTccc(int)`: c is a BMP code point (or negative).
    pub fn has_tccc(c: i32) -> bool {
        debug_assert!(c <= 0xffff);
        // U+00C0 is the first character with tccc!=0.
        if c < 0xc0 {
            return false;
        }
        let i = TCCC_INDEX[(c >> 5) as usize] as i32;
        i != 0 && (TCCC_BITS[i as usize] & (1 << (c & 0x1f))) != 0
    }

    /// `mayHaveLccc(int)`: handles all of Unicode 0..10FFFF.
    pub fn may_have_lccc(mut c: i32) -> bool {
        // c can be negative, e.g., Collation.SENTINEL_CP.
        // U+0300 is the first character with lccc!=0.
        if c < 0x300 {
            return false;
        }
        if c > 0xffff {
            c = UTF16::get_lead_surrogate(c) as i32;
        }
        let i = LCCC_INDEX[(c >> 5) as usize] as i32;
        i != 0 && (LCCC_BITS[i as usize] & (1 << (c & 0x1f))) != 0
    }

    /// Tibetan composite vowel signs (U+0F73, U+0F75, U+0F81) need special
    /// handling; true if c is one of them or maybe another such character.
    pub fn maybe_tibetan_composite_vowel(c: i32) -> bool {
        (c & 0x1fff01) == 0xf01
    }

    /// Tibetan composite vowel signs: true if fcd16 belongs to one of them.
    pub fn is_fcd16_of_tibetan_composite_vowel(fcd16: i32) -> bool {
        fcd16 == 0x8182 || fcd16 == 0x8184
    }
}

