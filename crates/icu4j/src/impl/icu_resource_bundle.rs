/// The state a top-level bundle and all its items share.
///
/// Equivalent to `ICUResourceBundle.WholeBundle` (protected).
#[derive(Debug)]
pub struct WholeBundle {
    pub(crate) base_name: String,
    pub(crate) locale_id: String,
    pub(crate) ulocale: ULocale,
    pub(crate) loader: ClassLoader,
    pub(crate) reader: Arc<ICUResourceBundleReader>,
    // TODO: Remove topLevelKeys when we upgrade to Java 6 where ResourceBundle caches the keySet().
    pub(crate) top_level_keys: Mutex<Option<Arc<Vec<String>>>>,
}

impl WholeBundle {
    fn new(
        base_name: &str,
        locale_id: &str,
        loader: ClassLoader,
        reader: Arc<ICUResourceBundleReader>,
    ) -> Result<Self> {
        Ok(Self {
            base_name: base_name.to_string(),
            locale_id: locale_id.to_string(),
            ulocale: ULocale::new(locale_id)?,
            loader,
            reader,
            top_level_keys: Mutex::new(None),
        })
    }
}

/// `OpenType`: how a bundle falls back (C++ `uresbund.cpp`: `enum
/// UResOpenType`).
///
/// Equivalent to the enum `ICUResourceBundle.OpenType`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum OpenType {
    /// `LOCALE_DEFAULT_ROOT`: open a resource bundle for the locale; if
    /// there is not even a base language bundle, then fall back to the
    /// default locale; if there is no bundle for that either, then load the
    /// root bundle. This is the default bundle loading behavior.
    LocaleDefaultRoot,
    // TODO: ICU ticket #11271 "consistent default locale across locale trees"
    // Add an option to look at the main locale tree for whether to
    // fall back to root directly (if the locale has main data) or
    // fall back to the default locale first (if the locale does not even have main data).
    /// `LOCALE_ROOT`: open a resource bundle for the locale; if there is not
    /// even a base language bundle, then load the root bundle; never fall
    /// back to the default locale.
    LocaleRoot,
    /// `LOCALE_ONLY`: open a resource bundle for the locale; if there is not
    /// even a base language bundle, then fail; never fall back to the
    /// default locale nor to the root locale.
    LocaleOnly,
    /// `DIRECT`: open a resource bundle for the exact bundle name as
    /// requested; no item fallback.
    Direct,
}

impl OpenType {
    fn ordinal(self) -> u8 {
        match self {
            OpenType::LocaleDefaultRoot => 0,
            OpenType::LocaleRoot => 1,
            OpenType::LocaleOnly => 2,
            OpenType::Direct => 3,
        }
    }
}

