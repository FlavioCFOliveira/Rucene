    /// `getFunctionalEquivalent(String baseName, ClassLoader loader, String
    /// resName, String keyword, ULocale locID, boolean[] isAvailable,
    /// boolean omitDefault)`: the functionally equivalent locale for a
    /// resource keyword; `is_available` receives whether `locID` is an
    /// available locale.
    ///
    /// # Errors
    ///
    /// `MissingResourceException("Could not find locale containing
    /// requested or default keyword.")`; the errors of bundle loading.
    #[allow(clippy::too_many_arguments)]
    pub fn get_functional_equivalent(
        base_name: &str,
        loader: ClassLoader,
        res_name: &str,
        keyword: &str,
        loc_id: &ULocale,
        is_available: Option<&mut bool>,
        omit_default: bool,
    ) -> Result<ULocale> {
        let mut kw_val = loc_id.get_keyword_value(keyword);
        let base_loc = loc_id.get_base_name();
        let mut def_str: Option<String> = None;
        let mut parent = ULocale::new(&base_loc)?;
        let mut def_loc: Option<ULocale> = None; // locale where default (found) resource is
        let mut look_for_default = false; // true if kwVal needs to be set
        let mut full_base: Option<ULocale> = None; // base locale of found (target) resource
        let mut def_depth = 0; // depth of 'default' marker
        let mut res_depth = 0; // depth of found resource;

        if kw_val
            .as_deref()
            .is_none_or(|k| k.is_empty() || k == DEFAULT_TAG)
        {
            kw_val = Some(String::new()); // default tag is treated as no keyword
            look_for_default = true;
        }
        let mut kw_val = kw_val.expect("set above");

        // Check top level locale first
        let mut r: Option<Arc<ICUResourceBundle>> = Some(
            UResourceBundle::get_bundle_instance_for(Some(base_name), Some(&parent))?
                .as_icu()?
                .clone(),
        );
        if let Some(is_available) = is_available {
            *is_available = false;
            let available_u_locales = get_avail_entry(base_name, loader)?
                .get_u_locale_list(AvailableType::Default)?
                .ok_or_else(LuceneError::null_pointer)?;
            for a in &available_u_locales {
                if parent == *a {
                    *is_available = true;
                    break;
                }
            }
        }
        // determine in which locale (if any) the currently relevant 'default' is
        loop {
            let rr = r.clone().expect("loop condition");
            let attempt = (|| -> Result<()> {
                let irb = rr.get_key_fallback(res_name)?;
                let d = irb.get_string_by_key(DEFAULT_TAG)?;
                def_str = Some(String::from_utf16_lossy(&d));
                if look_for_default {
                    kw_val = def_str.clone().expect("set above");
                    look_for_default = false;
                }
                def_loc = Some(rr.get_u_locale());
                Ok(())
            })();
            match attempt {
                Ok(()) => {}
                // Ignore error and continue search.
                Err(t) if is_missing_resource(&t) => {}
                Err(t) => return Err(t),
            }
            if def_loc.is_none() {
                r = rr.get_parent();
                def_depth += 1;
            }
            if r.is_none() || def_loc.is_some() {
                break;
            }
        }

        // Now, search for the named resource
        parent = ULocale::new(&base_loc)?;
        r = Some(
            UResourceBundle::get_bundle_instance_for(Some(base_name), Some(&parent))?
                .as_icu()?
                .clone(),
        );
        // determine in which locale (if any) the named resource is located
        loop {
            let rr = r.clone().expect("loop condition");
            let attempt = (|| -> Result<()> {
                let irb = rr.get_key_fallback(res_name)?;
                /* UResourceBundle urb = */
                UResourceBundle::Icu(irb.clone()).get(&kw_val)?;
                full_base = Some(irb.get_u_locale());
                // If the get() completed, we have the full base locale
                // If we fell back to an ancestor of the old 'default',
                // we need to re calculate the "default" keyword.
                if full_base.is_some() && res_depth > def_depth {
                    let d = irb.get_string_by_key(DEFAULT_TAG)?;
                    def_str = Some(String::from_utf16_lossy(&d));
                    def_loc = Some(rr.get_u_locale());
                    def_depth = res_depth;
                }
                Ok(())
            })();
            match attempt {
                Ok(()) => {}
                // Ignore error,
                Err(t) if is_missing_resource(&t) => {}
                Err(t) => return Err(t),
            }
            if full_base.is_none() {
                r = rr.get_parent();
                res_depth += 1;
            }
            if r.is_none() || full_base.is_some() {
                break;
            }
        }

        if full_base.is_none() // Could not find resource 'kwVal'
            && def_str.as_deref().is_some_and(|d| d != kw_val)
        // default was defined, kwVal is not default
        {
            // couldn't find requested resource. Fall back to default.
            kw_val = def_str.clone().expect("checked above"); // Fall back to default.
            parent = ULocale::new(&base_loc)?;
            r = Some(
                UResourceBundle::get_bundle_instance_for(Some(base_name), Some(&parent))?
                    .as_icu()?
                    .clone(),
            );
            res_depth = 0;
            // determine in which locale (if any) the named resource is located
            loop {
                let rr = r.clone().expect("loop condition");
                let attempt = (|| -> Result<()> {
                    let irb = rr.get_key_fallback(res_name)?;
                    let urb = UResourceBundle::Icu(irb.clone()).get(&kw_val)?;
                    let urb = urb.as_icu()?.clone();

                    // if we didn't fail before this..
                    full_base = Some(rr.get_u_locale());

                    // If the fetched item (urb) is in a different locale than our outer locale (r/fullBase)
                    // then we are in a 'fallback' situation. treat as a missing resource situation.
                    if full_base.as_ref().expect("set above").get_base_name()
                        != urb.get_u_locale().get_base_name()
                    {
                        full_base = None; // fallback condition. Loop and try again.
                    }

                    // If we fell back to an ancestor of the old 'default',
                    // we need to re calculate the "default" keyword.
                    if full_base.is_some() && res_depth > def_depth {
                        let d = irb.get_string_by_key(DEFAULT_TAG)?;
                        def_str = Some(String::from_utf16_lossy(&d));
                        def_loc = Some(rr.get_u_locale());
                        def_depth = res_depth;
                    }
                    Ok(())
                })();
                match attempt {
                    Ok(()) => {}
                    // Ignore error, continue search.
                    Err(t) if is_missing_resource(&t) => {}
                    Err(t) => return Err(t),
                }
                if full_base.is_none() {
                    r = rr.get_parent();
                    res_depth += 1;
                }
                if r.is_none() || full_base.is_some() {
                    break;
                }
            }
        }
        let _ = def_loc;

        let full_base = match full_base {
            Some(f) => f,
            None => {
                return Err(missing_resource(
                    "Could not find locale containing requested or default keyword.",
                    base_name,
                    format!("{keyword}={kw_val}"),
                ))
            }
        };

        if omit_default
            && def_str.as_deref().ok_or_else(LuceneError::null_pointer)? == kw_val // if default was requested and
            && res_depth <= def_depth
        {
            // default was set in same locale or child
            Ok(full_base) // Keyword value is default - no keyword needed in locale
        } else {
            ULocale::new(&format!(
                "{}@{}={}",
                full_base.get_base_name(),
                keyword,
                kw_val
            ))
        }
    }

    /// `getKeywordValues(String baseName, String keyword)`: the values of
    /// the keyword that some available locale defines.
    ///
    /// # Errors
    ///
    /// The errors of reading the available locales.
    pub fn get_keyword_values(base_name: &str, keyword: &str) -> Result<Vec<String>> {
        let mut keywords: HashSet<String> = HashSet::new();
        let locales = get_avail_entry(base_name, icu_data_class_loader())?
            .get_u_locale_list(AvailableType::Default)?
            .ok_or_else(LuceneError::null_pointer)?;
        for locale in &locales {
            // catch (Throwable t): ignore the err - just skip that resource
            let r = catch_unwind(AssertUnwindSafe(|| -> Result<Vec<String>> {
                let b = UResourceBundle::get_bundle_instance_for(Some(base_name), Some(locale))?;
                // downcast to ICUResourceBundle?
                let irb = match b.get_object(keyword)? {
                    ResourceObject::Bundle(UResourceBundle::Icu(irb)) => irb,
                    _ => {
                        return Err(LuceneError::unchecked(
                            "java.lang.ClassCastException",
                            "the object is not an ICUResourceBundle",
                        ))
                    }
                };
                UResourceBundle::Icu(irb).get_keys()
            }));
            if let Ok(Ok(e)) = r {
                for s in e {
                    if DEFAULT_TAG != s && !s.starts_with("private-") {
                        // don't add 'default' items, nor unlisted types
                        keywords.insert(s);
                    }
                }
            }
        }
        Ok(keywords.into_iter().collect())
    }

    /// `getWithFallback(String path)`: the resource at the slash-separated
    /// `path`, with fallback through the parent bundles.
    ///
    /// # Errors
    ///
    /// `MissingResourceException` when not found, or when the value is the
    /// no-inheritance marker.
    pub fn get_with_fallback(self: &Arc<Self>, path: &str) -> Result<Arc<ICUResourceBundle>> {
        let actual_bundle = UResourceBundle::Icu(self.clone());
        // now recurse to pick up sub levels of the items
        let result = Self::find_resource_with_fallback_path(path, &actual_bundle, None)?;

        let result = match result {
            Some(r) => r,
            None => {
                return Err(missing_resource(
                    format!(
                        "Can't find resource for bundle {}, key {}",
                        self.java_class_name(),
                        self.get_type()
                    ),
                    path,
                    null_str(self.get_key()),
                ))
            }
        };

        if result.get_type() == UResourceBundle::STRING
            && String::from_utf16_lossy(&result.get_string()?) == NO_INHERITANCE_MARKER
        {
            return Err(missing_resource(
                "Encountered NO_INHERITANCE_MARKER",
                path,
                null_str(self.get_key()),
            ));
        }

        Ok(result)
    }

    /// `at(int index)`: the item at `index`, without fallback.
    ///
    /// # Errors
    ///
    /// The errors of `handleGet`.
    pub fn at(self: &Arc<Self>, index: i32) -> Result<Option<Arc<ICUResourceBundle>>> {
        let this = UResourceBundle::Icu(self.clone());
        Ok(self.handle_get_at(index, None, &this)?.map(|b| match b {
            UResourceBundle::Icu(b) => b,
            UResourceBundle::Wrapper(_) => unreachable!("an ICU item is an ICU bundle"),
        }))
    }

    /// `at(String key)`: the item of `key` of a table, without fallback;
    /// `None` for any other resource (the key is never read as an index).
    ///
    /// # Errors
    ///
    /// The errors of `handleGet`.
    pub fn at_key(self: &Arc<Self>, key: &str) -> Result<Option<Arc<ICUResourceBundle>>> {
        // don't ever presume the key is an int in disguise, like ResourceArray does.
        if self.is_table() {
            let this = UResourceBundle::Icu(self.clone());
            return Ok(self.handle_get(key, None, &this)?.map(|b| match b {
                UResourceBundle::Icu(b) => b,
                UResourceBundle::Wrapper(_) => unreachable!("an ICU item is an ICU bundle"),
            }));
        }
        Ok(None)
    }

    /// `findWithFallback(String path)`: as
    /// [`get_with_fallback`](Self::get_with_fallback), `None` when not
    /// found.
    ///
    /// # Errors
    ///
    /// The errors of alias resolution.
    pub fn find_with_fallback(
        self: &Arc<Self>,
        path: &str,
    ) -> Result<Option<Arc<ICUResourceBundle>>> {
        Self::find_resource_with_fallback_path(path, &UResourceBundle::Icu(self.clone()), None)
    }

