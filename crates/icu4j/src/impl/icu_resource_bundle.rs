/// `AvailEntry` (private): the lazily computed available-locale lists of a
/// bundle prefix.
#[derive(Debug)]
#[allow(clippy::type_complexity)] // type mirrors the Java signature
struct AvailEntry {
    prefix: String,
    loader: ClassLoader,
    ulocales: Mutex<Option<Arc<HashMap<AvailableType, Vec<ULocale>>>>>,
    locales: Mutex<Option<Arc<Vec<Locale>>>>,
    name_set: Mutex<Option<Arc<HashSet<String>>>>,
    full_name_set: Mutex<Option<Arc<HashSet<String>>>>,
}

impl AvailEntry {
    fn new(prefix: &str, loader: ClassLoader) -> Self {
        Self {
            prefix: prefix.to_string(),
            loader,
            ulocales: Mutex::new(None),
            locales: Mutex::new(None),
            name_set: Mutex::new(None),
            full_name_set: Mutex::new(None),
        }
    }

    fn ulocales(&self) -> Result<Arc<HashMap<AvailableType, Vec<ULocale>>>> {
        let mut u = self.ulocales.lock().unwrap_or_else(|e| e.into_inner());
        if u.is_none() {
            *u = Some(Arc::new(ICUResourceBundle::create_u_locale_list(
                &self.prefix,
                self.loader,
            )?));
        }
        Ok(u.clone().expect("set above"))
    }

    fn get_u_locale_list(&self, ty: AvailableType) -> Result<Option<Vec<ULocale>>> {
        // Direct data is available for DEFAULT and ONLY_LEGACY_ALIASES
        debug_assert!(ty != AvailableType::WithLegacyAliases);
        Ok(self.ulocales()?.get(&ty).cloned())
    }

    fn get_locale_list(&self, ty: AvailableType) -> Result<Arc<Vec<Locale>>> {
        let mut l = self.locales.lock().unwrap_or_else(|e| e.into_inner());
        if l.is_none() {
            let list = self.ulocales()?.get(&ty).cloned();
            let list = list.ok_or_else(LuceneError::null_pointer)?;
            *l = Some(Arc::new(ICUResourceBundle::get_locale_list(&list)));
        }
        Ok(l.clone().expect("set above"))
    }

    fn get_locale_name_set(&self) -> Result<Arc<HashSet<String>>> {
        let mut n = self.name_set.lock().unwrap_or_else(|e| e.into_inner());
        if n.is_none() {
            *n = Some(Arc::new(ICUResourceBundle::create_locale_name_set(
                &self.prefix,
                self.loader,
            )?));
        }
        Ok(n.clone().expect("set above"))
    }

    fn get_full_locale_name_set(&self) -> Result<Arc<HashSet<String>>> {
        // When there's no prebuilt index, we iterate through the jar files
        // and read the contents to build it.  If many threads try to read the
        // same jar at the same time, java thrashes.  Synchronize here
        // so that we can avoid this problem. We don't synchronize on the
        // other methods since they don't do this.
        //
        // This is the common entry point for access into the code that walks
        // through the resources, and is cached.  So it's a good place to lock
        // access.  Locking in the URLHandler doesn't give us a common object
        // to lock.
        let mut f = self.full_name_set.lock().unwrap_or_else(|e| e.into_inner());
        if f.is_none() {
            *f = Some(Arc::new(ICUResourceBundle::create_full_locale_name_set(
                &self.prefix,
                self.loader,
            )?));
        }
        Ok(f.clone().expect("set above"))
    }
}

/// `GET_AVAILABLE_CACHE`: cache used for `AvailEntry`.
static GET_AVAILABLE_CACHE: LazyLock<SoftCache<String, Arc<AvailEntry>, ClassLoader>> =
    LazyLock::new(|| {
        SoftCache::new(|key: &String, loader: ClassLoader| {
            Ok(Some(Arc::new(AvailEntry::new(key, loader))))
        })
    });

fn get_avail_entry(key: &str, loader: ClassLoader) -> Result<Arc<AvailEntry>> {
    Ok(GET_AVAILABLE_CACHE
        .get_instance(key.to_string(), loader)?
        .expect("the cache creates an entry for every key"))
}

/// `AvailableLocalesSink` (private).
struct AvailableLocalesSink<'a> {
    output: &'a mut HashMap<AvailableType, Vec<ULocale>>,
}

impl Sink for AvailableLocalesSink<'_> {
    fn put(
        &mut self,
        key: &mut Key,
        value: &mut dyn u_resource::Value,
        _no_fallback: bool,
    ) -> Result<()> {
        let res_index_table = value.get_table()?;
        let mut i = 0;
        while res_index_table.get_key_and_value(i, key, value) {
            let ty = if key.content_equals("InstalledLocales") {
                AvailableType::Default
            } else if key.content_equals("AliasLocales") {
                AvailableType::OnlyLegacyAliases
            } else {
                // CLDRVersion, etc.
                i += 1;
                continue;
            };
            let available_locales_table = value.get_table()?;
            let mut locales = Vec::with_capacity(available_locales_table.get_size() as usize);
            let mut j = 0;
            while available_locales_table.get_key_and_value(j, key, value) {
                locales.push(ULocale::new(&key.to_java_string())?);
                j += 1;
            }
            self.output.insert(ty, locales);
            i += 1;
        }
        Ok(())
    }
}

/// The visitor of `addBundleBaseNamesFromClassLoader`.
struct ResNameVisitor<'a> {
    names: &'a mut HashSet<String>,
}

impl URLVisitor for ResNameVisitor<'_> {
    fn visit(&mut self, s: &str) {
        if let Some(locstr) = s.strip_suffix(".res") {
            self.names.insert(locstr.to_string());
        }
    }
}

