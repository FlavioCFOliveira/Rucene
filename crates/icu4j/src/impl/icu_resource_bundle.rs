    /// when not found.
    ///
    /// # Errors
    ///
    /// `UResourceTypeMismatchException` when the resource is not a string.
    pub fn find_string_with_fallback(self: &Arc<Self>, path: &str) -> Result<Option<Vec<u16>>> {
        Self::find_string_with_fallback_impl(path, self, None)
    }

    /// `getStringWithFallback(String path)`: the string at `path`.
    ///
    /// # Errors
    ///
    /// `MissingResourceException` when not found or the no-inheritance
    /// marker; `UResourceTypeMismatchException` when not a string.
    pub fn get_string_with_fallback(self: &Arc<Self>, path: &str) -> Result<Vec<u16>> {
        // Optimized form of getWithFallback(path).getString();
        let result = Self::find_string_with_fallback_impl(path, self, None)?;

        let result = match result {
            Some(r) => r,
            None => {
                return Err(missing_resource(
                    format!(
                        "Can't find resource for bundle {}, key {}",
                        self.java_class_name(),
                        self.get_type()
                    ),
                    path,
                    null_str(self.get_key()),
                ))
            }
        };

        if String::from_utf16_lossy(&result) == NO_INHERITANCE_MARKER {
            return Err(missing_resource(
                "Encountered NO_INHERITANCE_MARKER",
                path,
                null_str(self.get_key()),
            ));
        }
        Ok(result)
    }

    /// `getValueWithFallback(String path)`: the value at `path` (this
    /// resource for an empty path).
    ///
    /// # Errors
    ///
    /// `MissingResourceException` when not found.
    pub fn get_value_with_fallback(self: &Arc<Self>, path: &str) -> Result<ReaderValue> {
        let rb = if path.is_empty() {
            self.clone()
        } else {
            match Self::find_resource_with_fallback_path(
                path,
                &UResourceBundle::Icu(self.clone()),
                None,
            )? {
                Some(rb) => rb,
                None => {
                    return Err(missing_resource(
                        format!(
                            "Can't find resource for bundle {}, key {}",
                            self.java_class_name(),
                            self.get_type()
                        ),
                        path,
                        null_str(self.get_key()),
                    ))
                }
            }
        };
        let mut reader_value = ReaderValue::new();
        reader_value.reader = Some(rb.whole_bundle.reader.clone());
        reader_value.res = rb.get_resource();
        Ok(reader_value)
    }

    /// `getAllItemsWithFallbackNoFail(String path, UResource.Sink sink)`:
    /// as [`get_all_items_with_fallback`](Self::get_all_items_with_fallback),
    /// quietly ignoring a missing resource.
    ///
    /// # Errors
    ///
    /// The errors of the sink.
    pub fn get_all_items_with_fallback_no_fail(
        self: &Arc<Self>,
        path: &str,
        sink: &mut dyn Sink,
    ) -> Result<()> {
        match self.get_all_items_with_fallback(path, sink) {
            // Quietly ignore the exception.
            Err(e) if is_missing_resource(&e) => Ok(()),
            other => other,
        }
    }

    /// `getAllItemsWithFallback(String path, UResource.Sink sink)`: calls
    /// the sink with the resource at `path` of this bundle and of each
    /// parent bundle, child first.
    ///
    /// # Errors
    ///
    /// `MissingResourceException` when the path is found nowhere; the
    /// errors of the sink.
    pub fn get_all_items_with_fallback(
        self: &Arc<Self>,
        path: &str,
        sink: &mut dyn Sink,
    ) -> Result<()> {
        // Collect existing and parsed key objects into an array of keys,
        // rather than assembling and parsing paths.
        let num_path_keys = Self::count_path_keys(path); // How much deeper does the path go?
        let rb = if num_path_keys == 0 {
            self.clone()
        } else {
            // Get the keys for finding the target.
            let depth = self.get_res_depth(); // How deep are we in this bundle?
            let mut path_keys = vec![String::new(); (depth + num_path_keys) as usize];
            Self::get_res_path_keys_from_path(path, num_path_keys, &mut path_keys, depth);
            match Self::find_resource_with_fallback(path_keys, depth, self.clone(), None)? {
                Some(rb) => rb,
                None => {
                    return Err(missing_resource(
                        format!(
                            "Can't find resource for bundle {}, key {}",
                            self.java_class_name(),
                            self.get_type()
                        ),
                        path,
                        null_str(self.get_key()),
                    ))
                }
            }
        };
        let mut key = Key::new();
        let mut reader_value = ReaderValue::new();
        rb.get_all_items_with_fallback_impl(
            &mut key,
            &mut reader_value,
            sink,
            &UResourceBundle::Icu(self.clone()),
        )
    }

    /// `getAllChildrenWithFallback(String path, UResource.Sink sink)`: as
    /// [`get_all_items_with_fallback`](Self::get_all_items_with_fallback)
    /// over the children of a table, following each child alias and
    /// calling the sink for each table the alias target inherits from.
    ///
    /// # Errors
    ///
    /// `MissingResourceException` when the path is found nowhere; the
    /// errors of the sink.
    pub fn get_all_children_with_fallback(
        self: &Arc<Self>,
        path: &str,
        sink: &mut dyn Sink,
    ) -> Result<()> {
        let mut all = AllChildrenSink {
            outer: self.clone(),
            sink,
        };
        self.get_all_items_with_fallback(path, &mut all)
    }

    fn get_all_items_with_fallback_impl(
        self: &Arc<Self>,
        key: &mut Key,
        reader_value: &mut ReaderValue,
        sink: &mut dyn Sink,
        requested: &UResourceBundle,
    ) -> Result<()> {
        // We recursively enumerate child-first,
        // only storing parent items in the absence of child items.
        // The sink needs to store a placeholder value for the no-fallback/no-inheritance marker
        // to prevent a parent item from being stored.
        //
        // It would be possible to recursively enumerate parent-first,
        // overriding parent items with child items.
        // When the sink sees the no-fallback/no-inheritance marker,
        // then it would remove the parent's item.
        // We would deserialize parent values even though they are overridden in a child bundle.
        reader_value.reader = Some(self.whole_bundle.reader.clone());
        reader_value.res = self.get_resource();
        key.set_string(self.key.as_deref().unwrap_or(""))?;
        let parent = self.get_parent();
        sink.put(key, reader_value, parent.is_none())?;
        if let Some(parent_bundle) = parent {
            // We might try to query the sink whether
            // any fallback from the parent bundle is still possible.
            let depth = self.get_res_depth();
            let rb = if depth == 0 {
                Some(parent_bundle)
            } else {
                // Re-fetch the path keys: They may differ from the original ones
                // if we had followed an alias.
                let mut path_keys = vec![String::new(); depth as usize];
                self.get_res_path_keys(&mut path_keys, depth);
                Self::find_resource_with_fallback(path_keys, 0, parent_bundle, Some(requested))?
            };
            if let Some(rb) = rb {
                rb.get_all_items_with_fallback_impl(key, reader_value, sink, requested)?;
            }
        }
        Ok(())
    }

