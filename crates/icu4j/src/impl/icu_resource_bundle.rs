    /// `addLocaleIDsFromIndexBundle(String baseName, ClassLoader root,
    /// Set<String> locales)` (private): as `createULocaleList`, but
    /// catching the `MissingResourceException`.
    fn add_locale_ids_from_index_bundle(
        base_name: &str,
        root: ClassLoader,
        locales: &mut HashSet<String>,
    ) -> Result<()> {
        let bundle = (|| -> Result<UResourceBundle> {
            let b = UResourceBundle::instantiate_bundle(
                Some(base_name),
                ICU_RESOURCE_INDEX,
                root,
                true,
            )?;
            let b = b.as_icu()?.clone();
            UResourceBundle::Icu(b).get(INSTALLED_LOCALES)
        })();
        let bundle = match bundle {
            Ok(b) => b,
            Err(e) if is_missing_resource(&e) => {
                if *DEBUG {
                    println!("couldn't find {base_name}/{ICU_RESOURCE_INDEX}.res");
                }
                return Ok(());
            }
            Err(e) => return Err(e),
        };
        let mut iter = bundle.get_iterator();
        iter.reset();
        while iter.has_next() {
            let locstr = iter.next()?.get_key();
            locales.insert(locstr.unwrap_or_else(|| "null".to_string()));
        }
        Ok(())
    }

    fn add_bundle_base_names_from_class_loader(
        bn: &str,
        root: ClassLoader,
        names: &mut HashSet<String>,
    ) {
        // bn has a trailing slash: The WebSphere class loader would return null
        // for a raw directory name without it.
        let urls = root.get_resources(bn);
        let mut v = ResNameVisitor { names };
        for url in &urls {
            match URLHandler::get(Some(url)) {
                Some(handler) => handler.guide(&mut v, false),
                None => {
                    if *DEBUG {
                        println!("handler for {url} is null");
                    }
                }
            }
        }
    }

    fn add_locale_ids_from_list_file(bn: &str, root: ClassLoader, locales: &mut HashSet<String>) {
        if let Some(mut s) = root.get_resource_as_stream(&format!("{bn}{FULL_LOCALE_NAMES_LIST}")) {
            use crate::jdk::InputStream;
            let mut bytes = Vec::new();
            let mut buf = [0u8; 4096];
            while let Ok(n) = s.read(&mut buf, 0, 4096) {
                if n < 0 {
                    break;
                }
                bytes.extend_from_slice(&buf[..n as usize]);
            }
            let _ = s.close();
            // new InputStreamReader(s, "ASCII"): bytes above 0x7F decode as U+FFFD.
            let text: String = bytes
                .iter()
                .map(|&b| if b < 0x80 { b as char } else { '\u{FFFD}' })
                .collect();
            for line in java_lines(&text) {
                if !line.is_empty() && !line.starts_with('#') {
                    locales.insert(line.to_string());
                }
            }
        }
    }

    fn create_full_locale_name_set(
        base_name: &str,
        loader: ClassLoader,
    ) -> Result<HashSet<String>> {
        let bn = if base_name.ends_with('/') {
            base_name.to_string()
        } else {
            format!("{base_name}/")
        };
        let mut set: HashSet<String> = HashSet::new();
        let skip_scan = ICUConfig::get_or(
            "com.ibm.icu.impl.ICUResourceBundle.skipRuntimeLocaleResourceScan",
            Some("false"),
        )
        .unwrap_or_default();
        if !skip_scan.eq_ignore_ascii_case("true") {
            // scan available locale resources under the base url first
            Self::add_bundle_base_names_from_class_loader(&bn, loader, &mut set);
            if base_name.starts_with(ICUData::ICU_BASE_NAME) {
                let folder = if base_name.len() == ICUData::ICU_BASE_NAME.len() {
                    Some(String::new())
                } else if base_name.as_bytes()[ICUData::ICU_BASE_NAME.len()] == b'/' {
                    Some(base_name[ICUData::ICU_BASE_NAME.len() + 1..].to_string())
                } else {
                    None
                };
                if let Some(folder) = folder {
                    ICUBinary::add_base_names_in_file_folder(&folder, ".res", &mut set);
                }
            }
            set.remove(ICU_RESOURCE_INDEX); // "res_index"
                                            // HACK: TODO: Figure out how we can distinguish locale data from other data items.
            set.retain(|name| {
                let n = name.encode_utf16().count();
                // Does not look like a locale ID.
                !((n == 1 || n > 3) && !name.contains('_'))
            });
        }
        // look for prebuilt full locale names list next
        if set.is_empty() {
            if *DEBUG {
                println!("unable to enumerate data files in {base_name}");
            }
            Self::add_locale_ids_from_list_file(&bn, loader, &mut set);
        }
        if set.is_empty() {
            // Use locale name set as the last resort fallback
            Self::add_locale_ids_from_index_bundle(base_name, loader, &mut set)?;
        }
        // We need to have the root locale in the set, but not as "root".
        set.remove("root");
        set.insert(ULocale::root().to_string()); // ""
        Ok(set)
    }

    fn create_locale_name_set(base_name: &str, loader: ClassLoader) -> Result<HashSet<String>> {
        let mut set = HashSet::new();
        Self::add_locale_ids_from_index_bundle(base_name, loader, &mut set)?;
        Ok(set)
    }

    fn find_resource_with_fallback_path(
        path: &str,
        actual_bundle: &UResourceBundle,
        requested: Option<&UResourceBundle>,
    ) -> Result<Option<Arc<ICUResourceBundle>>> {
        if path.is_empty() {
            return Ok(None);
        }
        let base = actual_bundle.as_icu()?.clone();
        // Collect existing and parsed key objects into an array of keys,
        // rather than assembling and parsing paths.
        let depth = base.get_res_depth();
        let num_path_keys = Self::count_path_keys(path);
        debug_assert!(num_path_keys > 0);
        let mut keys = vec![String::new(); (depth + num_path_keys) as usize];
        Self::get_res_path_keys_from_path(path, num_path_keys, &mut keys, depth);
        Self::find_resource_with_fallback(keys, depth, base, requested)
    }

    fn find_resource_with_fallback(
        mut keys: Vec<String>,
        mut depth: i32,
        mut base: Arc<ICUResourceBundle>,
        requested: Option<&UResourceBundle>,
    ) -> Result<Option<Arc<ICUResourceBundle>>> {
        let requested = match requested {
            Some(r) => r.clone(),
            None => UResourceBundle::Icu(base.clone()),
        };

        loop {
            // Iterate over the parent bundles.
            loop {
                // Iterate over the keys on the requested path, within a bundle.
                let sub_key = keys[depth as usize].clone();
                depth += 1;
                let sub = base.handle_get(&sub_key, None, &requested)?;
                let sub = match sub {
                    None => {
                        depth -= 1;
                        break;
                    }
                    Some(s) => s.as_icu()?.clone(),
                };
                if depth as usize == keys.len() {
                    // We found it.
                    return Ok(Some(sub));
                }
                base = sub;
            }
            // Try the parent bundle of the last-found resource.
            let next_base = match base.get_parent() {
                None => return Ok(None),
                Some(n) => n,
            };
            // If we followed an alias, then we may have switched bundle (locale) and key path.
            // Set the lower parts of the path according to the last-found resource.
            // This relies on a resource found via alias to have its original location information,
            // rather than the location of the alias.
            let base_depth = base.get_res_depth();
            if depth != base_depth {
                let mut new_keys =
                    vec![String::new(); (base_depth as usize) + (keys.len() - depth as usize)];
                new_keys[base_depth as usize..].clone_from_slice(&keys[depth as usize..]);
                keys = new_keys;
            }
            base.get_res_path_keys(&mut keys, base_depth);
            base = next_base;
            depth = 0; // getParent() returned a top level table resource.
        }
    }

    // Java decrements `depth` before leaving the key loop even where the
    // next read resets it.
    #[allow(unused_assignments)]
    fn find_string_with_fallback_impl(
        path: &str,
        actual_bundle: &Arc<ICUResourceBundle>,
        requested: Option<&UResourceBundle>,
    ) -> Result<Option<Vec<u16>>> {
        if path.is_empty() {
            return Ok(None);
        }
        if !actual_bundle.is_container() {
            return Ok(None);
        }
        let requested = match requested {
            Some(r) => r.clone(),
            None => UResourceBundle::Icu(actual_bundle.clone()),
        };

        let mut base = actual_bundle.clone();
        let mut reader = base.whole_bundle.reader.clone();
        let mut res = Self::RES_BOGUS;

        // Collect existing and parsed key objects into an array of keys,
        // rather than assembling and parsing paths.
        let mut base_depth = base.get_res_depth();
        let mut depth = base_depth;
        let num_path_keys = Self::count_path_keys(path);
        debug_assert!(num_path_keys > 0);
        let mut keys = vec![String::new(); (depth + num_path_keys) as usize];
        Self::get_res_path_keys_from_path(path, num_path_keys, &mut keys, depth);

        loop {
            // Iterate over the parent bundles.
            loop {
                // Iterate over the keys on the requested path, within a bundle.
                let reader_container: Arc<Container>;
                if res == Self::RES_BOGUS {
                    let ty = base.get_type();
                    if ty == UResourceBundle::TABLE || ty == UResourceBundle::ARRAY {
                        reader_container = base
                            .container_value()
                            .expect("a container has a value")
                            .clone();
                    } else {
                        break;
                    }
                } else {
                    let ty = ICUResourceBundleReader::res_get_type(res);
                    if ICUResourceBundleReader::ures_is_table(ty) {
                        reader_container =
                            reader.get_table(res).expect("a table resource has a table");
                    } else if ICUResourceBundleReader::ures_is_array(ty) {
                        reader_container = reader
                            .get_array(res)
                            .expect("an array resource has an array");
                    } else {
                        res = Self::RES_BOGUS;
                        break;
                    }
                }
                let sub_key = keys[depth as usize].clone();
                depth += 1;
                res = reader_container.get_resource(&reader, &sub_key)?;
                if res == Self::RES_BOGUS {
                    depth -= 1;
                    break;
                }
                let sub: Option<Arc<ICUResourceBundle>> =
                    if ICUResourceBundleReader::res_get_type(res) == Self::ALIAS {
                        base.get_res_path_keys(&mut keys, base_depth);
                        Some(Self::get_aliased_resource_of(
                            &base,
                            Some(&keys),
                            depth,
                            &sub_key,
                            res,
                            None,
                            &requested,
                        )?)
                    } else {
                        None
                    };
                if depth as usize == keys.len() {
                    // We found it.
                    if let Some(sub) = sub {
                        return Ok(Some(sub.get_string()?)); // string from alias handling
                    } else {
                        return match reader.get_string(res) {
                            Some(s) => Ok(Some(s)),
                            None => Err(type_mismatch("")),
                        };
                    }
                }
                if let Some(sub) = sub {
                    base = sub;
                    reader = base.whole_bundle.reader.clone();
                    res = Self::RES_BOGUS;
                    // If we followed an alias, then we may have switched bundle (locale) and key path.
                    // Reserve space for the lower parts of the path according to the last-found resource.
                    // This relies on a resource found via alias to have its original location information,
                    // rather than the location of the alias.
                    base_depth = base.get_res_depth();
                    if depth != base_depth {
                        let mut new_keys = vec![
                            String::new();
                            (base_depth as usize)
                                + (keys.len() - depth as usize)
                        ];
                        new_keys[base_depth as usize..].clone_from_slice(&keys[depth as usize..]);
                        keys = new_keys;
                        depth = base_depth;
                    }
                }
            }
            // Try the parent bundle of the last-found resource.
            let next_base = match base.get_parent() {
                None => return Ok(None),
                Some(n) => n,
            };
            // We probably have not yet set the lower parts of the key path.
            base.get_res_path_keys(&mut keys, base_depth);
            base = next_base;
            reader = base.whole_bundle.reader.clone();
            depth = 0;
            base_depth = 0; // getParent() returned a top level table resource.
        }
    }

    fn get_res_depth(&self) -> i32 {
        match &self.container {
            None => 0,
            Some(c) => c.get_res_depth() + 1,
        }
    }

    /// `getResPathKeys(String[] keys, int depth)` (private): fills the
    /// first `depth` keys with this resource's path.
    fn get_res_path_keys(&self, keys: &mut [String], mut depth: i32) {
        let mut b: &ICUResourceBundle = self;
        while depth > 0 {
            depth -= 1;
            keys[depth as usize] = b.key.clone().unwrap_or_default();
            b = b.container.as_deref().expect("an item has a container");
            debug_assert!((depth == 0) == b.container.is_none());
        }
    }

    fn count_path_keys(path: &str) -> i32 {
        if path.is_empty() {
            return 0;
        }
        let mut num = 1;
        for c in path.chars() {
            if c == RES_PATH_SEP_CHAR {
                num += 1;
            }
        }
        num
    }

    /// `getResPathKeys(String path, int num, String[] keys, int start)`
    /// (private): fills `keys` with the parts of the path.
    fn get_res_path_keys_from_path(path: &str, mut num: i32, keys: &mut [String], mut start: i32) {
        if num == 0 {
            return;
        }
        if num == 1 {
            keys[start as usize] = path.to_string();
            return;
        }
        let mut i = 0usize;
        loop {
            let j = path[i..]
                .find(RES_PATH_SEP_CHAR)
                .map(|x| x + i)
                .expect("num counts the separators");
            keys[start as usize] = path[i..j].to_string();
            start += 1;
            if num == 2 {
                debug_assert!(!path[j + 1..].contains(RES_PATH_SEP_CHAR));
                keys[start as usize] = path[j + 1..].to_string();
                break;
            } else {
                i = j + 1;
                num -= 1;
            }
        }
    }

