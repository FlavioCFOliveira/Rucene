    /// `getBundleInstance(String baseName, String localeID, ClassLoader
    /// root, OpenType openType)`.
    ///
    /// # Errors
    ///
    /// `MissingResourceException("Could not find the bundle
    /// <baseName>/<localeID>.res")`.
    pub fn get_bundle_instance_open(
        base_name: Option<&str>,
        locale_id: &str,
        root: ClassLoader,
        open_type: OpenType,
    ) -> Result<Arc<ICUResourceBundle>> {
        let base_name = base_name.unwrap_or(ICUData::ICU_BASE_NAME);
        let locale_id = ULocale::get_base_name_of(locale_id)?;
        let b = if open_type == OpenType::LocaleDefaultRoot {
            Self::instantiate_bundle(
                base_name,
                &locale_id,
                None,
                Some(&ULocale::get_default().get_base_name()),
                root,
                open_type,
            )?
        } else {
            Self::instantiate_bundle(base_name, &locale_id, None, None, root, open_type)?
        };
        match b {
            Some(b) => Ok(b),
            None => Err(missing_resource(
                format!("Could not find the bundle {base_name}/{locale_id}.res"),
                "",
                "",
            )),
        }
    }

    fn locale_id_starts_with_lang_subtag(locale_id: &str, lang: &str) -> bool {
        locale_id.starts_with(lang)
            && (locale_id.len() == lang.len() || locale_id.as_bytes()[lang.len()] == b'_')
    }

    fn get_explicit_parent(locale_id: &str) -> Option<&'static str> {
        PARENT_LOCALE_TABLE.get(locale_id).copied()
    }

    fn get_default_script(language: &str, region: Option<&str>) -> String {
        let locale_id = format!("{}_{}", language, null_str(region));
        let mut result = DEFAULT_SCRIPT_TABLE.get(locale_id.as_str()).copied();
        if result.is_none() {
            result = DEFAULT_SCRIPT_TABLE.get(language).copied();
        }
        result.unwrap_or("Latn").to_string()
    }

    /// `getParentLocaleID(String name, String origName, OpenType
    /// openType)`: the parent of a locale ID along the fallback chain,
    /// `None` when the next step is root.
    ///
    /// # Errors
    ///
    /// `IllegalArgumentException("variants is too long")` from the parser.
    pub fn get_parent_locale_id(
        name: &str,
        orig_name: &str,
        open_type: OpenType,
    ) -> Result<Option<String>> {
        Self::get_parent_locale_id_impl(name, orig_name, open_type)
    }

    fn get_parent_locale_id_impl(
        name: &str,
        orig_name: &str,
        open_type: OpenType,
    ) -> Result<Option<String>> {
        // early out if the locale ID has a variant code or ends with _
        if name.ends_with('_') || !ULocale::get_variant_of(name)?.is_empty() {
            let last_underbar_pos = name.rfind('_');
            return Ok(last_underbar_pos.map(|p| name[..p].to_string()));
        }

        // TODO: Is there a better way to break the locale ID up into its consituent parts?
        let name_locale = ULocale::new(name)?;
        let language = name_locale.get_language();
        let script = name_locale.get_script();
        let region = name_locale.get_country();

        // if our open type is LOCALE_DEFAULT_ROOT, first look the locale ID up in the parent locale table; if that
        // table specifies a parent for it, return that (we don't do this for the other open types-- if we're not
        // falling back through the system default locale, we also want to do straight truncation fallback instead
        // of looking things up in the parent locale table-- see https://www.unicode.org/reports/tr35/tr35.html#Parent_Locales:
        // "Collation data, however, is an exception...")
        if open_type == OpenType::LocaleDefaultRoot {
            if let Some(parent_id) = Self::get_explicit_parent(name) {
                return Ok(if parent_id == "root" {
                    None
                } else {
                    Some(parent_id.to_string())
                });
            }
        }

        // if it's not in the parent locale table, figure out the fallback script algorithmically
        // (see CLDR-15265 for an explanation of the algorithm)
        Ok(if !script.is_empty() && !region.is_empty() {
            // if "name" has both script and region, is the script the default script?
            // - if so, remove it and keep the region
            // - if not, remove the region and keep the script
            if Self::get_default_script(&language, Some(&region)) == script {
                Some(format!("{language}_{region}"))
            } else {
                Some(format!("{language}_{script}"))
            }
        } else if !region.is_empty() {
            // if "name" has region but not script, did the original locale ID specify a script?
            // - if yes, replace the region with the script from the original locale ID
            // - if no, replace the region with the default script for that language and region
            let orig_name_script = ULocale::get_script_of(orig_name);
            if !orig_name_script.is_empty() {
                Some(format!("{language}_{orig_name_script}"))
            } else {
                Some(format!(
                    "{}_{}",
                    language,
                    Self::get_default_script(&language, Some(&region))
                ))
            }
        } else if !script.is_empty() {
            // if "name" has script but not region (and our open type is LOCALE_DEFAULT_ROOT), is the script the
            // default script for the language?
            // - if so, remove it from the locale ID
            // - if not, return "root" (bypassing the system default locale ID)
            // (we don't do this for other open types for the same reason we don't look things up in the parent
            // locale table for other open types-- see the reference to UTS #35 above)
            if open_type != OpenType::LocaleDefaultRoot
                || Self::get_default_script(&language, None) == script
            {
                Some(language)
            } else {
                /*"root"*/
                None
            }
        } else {
            // if "name" just contains a language code, return null so the calling code falls back to "root"
            None
        })
    }

    fn instantiate_bundle(
        base_name: &str,
        locale_id: &str,
        orig_locale_id: Option<&str>,
        default_id: Option<&str>,
        root: ClassLoader,
        open_type: OpenType,
    ) -> Result<Option<Arc<ICUResourceBundle>>> {
        debug_assert!(!locale_id.contains('@'));
        debug_assert!(default_id.is_none_or(|d| !d.contains('@')));
        let full_name = ICUResourceBundleReader::get_full_name(Some(base_name), locale_id);
        let open_type_char = (b'0' + open_type.ordinal()) as char;
        let cache_key = if open_type != OpenType::LocaleDefaultRoot {
            format!("{full_name}#{open_type_char}")
        } else {
            format!("{}#{}#{}", full_name, open_type_char, null_str(default_id))
        };
        let base_name = base_name.to_string();
        let locale_id = locale_id.to_string();
        let orig_locale_id = orig_locale_id.map(str::to_string);
        let default_id = default_id.map(str::to_string);
        let loader: Loader = Box::new(move || -> Result<Option<Arc<ICUResourceBundle>>> {
            if *DEBUG {
                println!("Creating {full_name}");
            }
            // here we assume that java type resource bundle organization
            // is required then the base name contains '.' else
            // the resource organization is of ICU type
            // so clients can instantiate resources of the type
            // com.mycompany.data.MyLocaleElements_en.res and
            // com.mycompany.data.MyLocaleElements.res
            //
            let root_locale = if !base_name.contains('.') { "root" } else { "" };
            let mut locale_name = if locale_id.is_empty() {
                root_locale.to_string()
            } else {
                locale_id.clone()
            };
            let mut b = ICUResourceBundle::create_bundle(&base_name, &locale_name, root)?;

            if *DEBUG {
                println!(
                    "The bundle created is: {} and openType={:?} and bundle.getNoFallback={}",
                    b.as_ref()
                        .map(|b| b.get_locale_id().to_string())
                        .unwrap_or_else(|| "null".into()),
                    open_type,
                    b.as_ref().is_some_and(|b| b.get_no_fallback())
                );
            }
            if open_type == OpenType::Direct || b.as_ref().is_some_and(|b| b.get_no_fallback()) {
                // no fallback because the caller said so or because the bundle says so
                //
                // TODO for b!=null: In C++, ures_openDirect() builds the parent chain
                // for its bundle unless its nofallback flag is set.
                // Otherwise we get test failures.
                // For example, item aliases are followed via ures_openDirect(),
                // and fail if the target bundle needs fallbacks but the chain is not set.
                // Figure out why Java does not build the parent chain
                // for a bundle that does not have nofallback.
                // Are the relevant test cases just disabled?
                // Do item aliases not get followed via "direct" loading?
                return Ok(b);
            }

            // fallback to locale ID parent
            match &b {
                None => {
                    let mut local_open_type = open_type;
                    if open_type == OpenType::LocaleDefaultRoot
                        && Some(locale_name.as_str()) == default_id.as_deref()
                    {
                        local_open_type = OpenType::LocaleRoot;
                    }
                    let orig_locale_name = orig_locale_id
                        .clone()
                        .unwrap_or_else(|| locale_name.clone());
                    let fallback_locale_id =
                        Self::get_parent_locale_id(&locale_name, &orig_locale_name, open_type)?;
                    if let Some(fallback_locale_id) = fallback_locale_id {
                        b = Self::instantiate_bundle(
                            &base_name,
                            &fallback_locale_id,
                            Some(&orig_locale_name),
                            default_id.as_deref(),
                            root,
                            local_open_type,
                        )?;
                    } else if local_open_type == OpenType::LocaleDefaultRoot
                        && !Self::locale_id_starts_with_lang_subtag(
                            default_id
                                .as_deref()
                                .expect("LOCALE_DEFAULT_ROOT has a default ID"),
                            &locale_name,
                        )
                    {
                        // Go to the default locale before root.
                        b = Self::instantiate_bundle(
                            &base_name,
                            default_id
                                .as_deref()
                                .expect("LOCALE_DEFAULT_ROOT has a default ID"),
                            None,
                            default_id.as_deref(),
                            root,
                            local_open_type,
                        )?;
                    } else if local_open_type != OpenType::LocaleOnly && !root_locale.is_empty() {
                        // Ultimately go to root.
                        b = ICUResourceBundle::create_bundle(&base_name, root_locale, root)?;
                    }
                }
                Some(bb) => {
                    let mut parent: Option<Arc<ICUResourceBundle>> = None;
                    locale_name = bb.get_locale_id().to_string();
                    let i = locale_name.rfind('_');

                    // TODO: C++ uresbund.cpp also checks for %%ParentIsRoot. Why not Java?
                    let parent_locale_name = bb.find_string("%%Parent");
                    if let Some(parent_locale_name) = parent_locale_name {
                        parent = Self::instantiate_bundle(
                            &base_name,
                            &String::from_utf16_lossy(&parent_locale_name),
                            None,
                            default_id.as_deref(),
                            root,
                            open_type,
                        )?;
                    } else if let Some(i) = i {
                        parent = Self::instantiate_bundle(
                            &base_name,
                            &locale_name[..i],
                            None,
                            default_id.as_deref(),
                            root,
                            open_type,
                        )?;
                    } else if locale_name != root_locale {
                        parent = Self::instantiate_bundle(
                            &base_name,
                            root_locale,
                            None,
                            default_id.as_deref(),
                            root,
                            open_type,
                        )?;
                    }

                    let same = parent.as_ref().is_some_and(|p| bb.java_equals(p));
                    if !same {
                        bb.set_parent(parent);
                    }
                }
            }
            Ok(b)
        });
        BUNDLE_CACHE.get_instance(cache_key, loader)
    }

    /// `get(String aKey, HashMap<String, String> aliasesVisited,
    /// UResourceBundle requested)` (package-private): the item of `aKey`
    /// here or in a parent bundle.
    ///
    /// # Errors
    ///
    /// `MissingResourceException` when found nowhere.
    pub(crate) fn get_with_aliases(
        self: &Arc<Self>,
        a_key: &str,
        mut aliases_visited: Option<&mut HashMap<String, String>>,
        requested: &UResourceBundle,
    ) -> Result<Arc<ICUResourceBundle>> {
        let obj = self.handle_get(a_key, aliases_visited.as_deref_mut(), requested)?;
        match obj {
            Some(o) => Ok(o.as_icu()?.clone()),
            None => {
                if let Some(p) = self.get_parent() {
                    //call the get method to recursively fetch the resource
                    return p.get_with_aliases(a_key, aliases_visited, requested);
                }
                let full_name = ICUResourceBundleReader::get_full_name(
                    Some(self.get_base_name()),
                    self.get_locale_id(),
                );
                Err(missing_resource(
                    format!("Can't find resource for bundle {full_name}, key {a_key}"),
                    self.java_class_name(),
                    a_key,
                ))
            }
        }
    }

