    /// `getLocaleList(ULocale[] ulocales)`: the distinct `toLocale()` of
    /// each, in order.
    pub fn get_locale_list(ulocales: &[ULocale]) -> Vec<Locale> {
        let mut list = Vec::with_capacity(ulocales.len());
        let mut unique_set: HashSet<Locale> = HashSet::new();
        for u in ulocales {
            let loc = u.to_locale();
            if !unique_set.contains(&loc) {
                list.push(loc.clone());
                unique_set.insert(loc);
            }
        }
        list
    }

