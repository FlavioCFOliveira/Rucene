    /// Equivalent to the protected `getDistanceQuery(List<SrndQuery>,
    /// boolean, Token, boolean)`.
    ///
    /// # Errors
    ///
    /// The `ParseException` of a sub-query a distance operator does not
    /// allow.
    fn get_distance_query(
        &mut self,
        queries: Vec<Arc<dyn SrndQuery>>,
        infix: bool,
        d_token: &TokenRef,
        ordered: bool,
    ) -> Result<Arc<dyn SrndQuery>> {
        let image = image_of(d_token)?;
        let dq = DistanceQuery::new(queries, infix, get_op_distance(&image)?, &image, ordered)?;
        check_distance_sub_queries(&dq, &image)?;
        Ok(Arc::new(dq))
    }

    /// Equivalent to the protected `getTermQuery(String, boolean)`.
    fn get_term_query(&mut self, term: &str, quoted: bool) -> Arc<dyn SrndQuery> {
        Arc::new(SrndTermQuery::new(term, quoted))
    }

    /// Equivalent to the protected `allowedSuffix(String)`.
    fn allowed_suffix(&mut self, suffixed: &str) -> bool {
        (crate::javacc::length(suffixed) - 1) >= MINIMUM_PREFIX_LENGTH
    }

    /// Equivalent to the protected `getPrefixQuery(String, boolean)`.
    ///
    /// # Errors
    ///
    /// The errors of the automaton compilation.
    fn get_prefix_query(&mut self, prefix: &str, quoted: bool) -> Result<Arc<dyn SrndQuery>> {
        Ok(Arc::new(SrndPrefixQuery::new(prefix, quoted, TRUNCATOR)?))
    }

    /// At least 3 normal characters needed.
    ///
    /// Equivalent to the protected `allowedTruncation(String)`.
    fn allowed_truncation(&mut self, truncated: &str) -> bool {
        let mut nr_normal_chars = 0;
        for c in truncated.encode_utf16() {
            if c != TRUNCATOR as u16 && c != ANY_CHAR as u16 {
                nr_normal_chars += 1;
            }
        }
        nr_normal_chars >= MINIMUM_CHARS_IN_TRUNC
    }

