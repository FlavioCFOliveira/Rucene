    /// Equivalent to `parse2(String)`.
    ///
    /// # Errors
    ///
    /// The `ParseException` of a syntax error, and the one a lexical error
    /// is rethrown as.
    fn parse2(&mut self, query: &str) -> Result<Arc<dyn SrndQuery>> {
        self.re_init(Box::new(FastCharStream::new(Box::new(
            StringCharReader::new(query),
        ))));
        match self.top_srnd_query() {
            Err(tme) => match TokenMgrError::of(&tme) {
                Some(t) => Err(match t.get_message() {
                    Some(message) => ParseException::with_message(message),
                    None => ParseException::new(),
                }
                .error()),
                None => Err(tme),
            },
            ok => ok,
        }
    }

