//! The port of `ParserExtension.java`, of the Java package
//! `org.apache.lucene.queryparser.ext`.

use std::fmt::Debug;
use std::sync::Arc;

use rucene::error::Result;
use rucene::search::Query;

use super::extension_query::ExtensionQuery;

/// This class represents an extension base class to the Lucene standard
/// `QueryParser`. The `QueryParser` is generated by the JavaCC parser
/// generator. Changing or adding functionality or syntax in the standard
/// query parser requires changes to the JavaCC source file. To enable
/// extending the standard query parser without changing the JavaCC sources
/// and re-generating the parser the `ParserExtension` can be customized
/// and plugged into an instance of `ExtendableQueryParser`, a direct
/// subclass of `QueryParser`.
///
/// Equivalent to the abstract class `org.apache.lucene.queryparser.ext.ParserExtension`.
pub trait ParserExtension: Debug + Send + Sync {
    /// Processes the given `ExtensionQuery` and returns a corresponding
    /// `Query` instance. Subclasses must either return a `Query` instance or
    /// raise a `ParseException`. This method must not return `None`.
    ///
    /// Equivalent to `parse(ExtensionQuery)`.
    ///
    /// # Errors
    ///
    /// The `ParseException` of a query the extension cannot parse.
    fn parse(&self, query: ExtensionQuery<'_>) -> Result<Option<Arc<dyn Query>>>;
}
