//! `java.util.TimeZone` as JDK 25 builds it: `TimeZone.getTimeZone(String)`,
//! `getDefault()`/`setDefault`, the offsets of a zone at an instant, and the
//! offsets of a wall time that `GregorianCalendar.computeTime` asks for.
//!
//! **Divergence.** An emulation of JDK 25 on Linux, not a port of a Lucene
//! file, merged from the two emulations other crates of the workspace hold
//! (`crates/rucene-analysis-common/src/jdk/time_zone.rs`, the IDs and the
//! platform default, and `crates/rucene-test-framework/src/jdk/time_zone.rs`,
//! the rules), which this crate cannot depend on. It is written from
//! `java.util.TimeZone`, `java.util.SimpleTimeZone`,
//! `sun.util.calendar.ZoneInfo` and the native `TimeZone_md.c` (OpenJDK 25,
//! read as specification; no JDK code is reproduced).
//!
//! `TimeZone.getTimeZone(id)` returns a `sun.util.calendar.ZoneInfo`:
//! `ZoneInfoFile` derives it from the tzdb rules as a transition table bounded
//! to 1900..2037 and, for a zone that still observes daylight saving time, a
//! `SimpleTimeZone` "last rule" for the instants beyond it. The rule data
//! (the private module `time_zone_data`, generated by
//! `tools/gen/TimeZoneRules.java` on the JDK 25 oracle) is each zone's
//! `ZoneInfo` fields and the fields of its last rule; this module reproduces
//! the computations that read them: `ZoneInfo.getOffsets(long, int[], type)`
//! for UTC and wall times and `SimpleTimeZone.getOffsets`.
//!
//! What differs from the JDK, each stated where it applies:
//!
//! * the JVM system property `user.timezone` has no counterpart: the default
//!   zone is the one a JVM started without `-Duser.timezone` computes, until
//!   [`TimeZone::set_default`] sets another;
//! * when the platform names a zone the JDK does not know, the JDK falls back
//!   to a `GMT±hh:mm` ID computed from the C library's local time
//!   (`getSystemGMTOffsetID`); the emulation falls back to `GMT`;
//! * `SimpleTimeZone`'s one-year cache, which changes no answer except for an
//!   instant within `rawOffset` of `Long.MAX_VALUE`, is not kept: every
//!   offset is computed afresh, as a new `TimeZone.getTimeZone(id)` does;
//! * the Julian calendar `SimpleTimeZone` uses before the Gregorian cutover
//!   is not reproduced: a last rule is only reached beyond a transition table,
//!   which ends in 2037 or later.

use std::path::Path;
use std::sync::{Arc, LazyLock, RwLock};

use super::locale_data::data;
use super::time_zone_data::{IDS, RULES};
/// `ZoneInfo.OFFSET_MASK`: the bits of a transition holding the index of
/// its total offset in `offsets`.
const OFFSET_MASK: i64 = 0x0f;
/// `ZoneInfo.TRANSITION_NSHIFT`: the shift of a transition's UTC instant, in
/// milliseconds.
const TRANSITION_NSHIFT: u32 = 12;

/// `AbstractCalendar.DAY_IN_MILLIS`.
const DAY_IN_MILLIS: i64 = 86_400_000;
/// `AbstractCalendar.EPOCH_OFFSET`: the fixed date of 1970-01-01.
const EPOCH_OFFSET: i64 = 719_163;

/// `SimpleTimeZone.DOM_MODE`: "Mar 1".
const DOM_MODE: i32 = 1;
/// `SimpleTimeZone.DOW_IN_MONTH_MODE`: "lastSun".
const DOW_IN_MONTH_MODE: i32 = 2;
/// `SimpleTimeZone.DOW_GE_DOM_MODE`: "Sun>=15".
const DOW_GE_DOM_MODE: i32 = 3;
/// `SimpleTimeZone.DOW_LE_DOM_MODE`: "Sun<=21".
const DOW_LE_DOM_MODE: i32 = 4;
/// `SimpleTimeZone.WALL_TIME`.
const WALL_TIME: i32 = 0;
/// `SimpleTimeZone.UTC_TIME`.
const UTC_TIME: i32 = 2;

/// The fields of a `sun.util.calendar.ZoneInfo` that its offsets depend on.
///
/// `rawOffsetDiff`, which only `setRawOffset` changes, is 0 for every zone
/// `TimeZone.getTimeZone` returns (the generator checks it), so
/// `getLastRawOffset()` is `raw_offset`.
#[derive(Debug)]
pub struct ZoneInfo {
    /// `rawOffset`: the GMT offset of the last standard time, in
    /// milliseconds.
    pub(super) raw_offset: i32,
    /// `transitions`: each a UTC instant in milliseconds shifted left by
    /// [`TRANSITION_NSHIFT`], with the index of its total offset in the low
    /// four bits and of its saving in the next four. `None` for a zone that
    /// never changed its offset.
    pub(super) transitions: Option<&'static [i64]>,
    /// `offsets`: the offsets the transitions index.
    pub(super) offsets: &'static [i32],
    /// `getLastRuleInstance()`: the rule beyond the table, `None` for a zone
    /// that no longer observes daylight saving time.
    pub(super) last_rule: Option<SimpleTimeZone>,
}

/// The fields of a `java.util.SimpleTimeZone` its offsets depend on, as its
/// constructor decoded them (`decodeRules`).
#[derive(Debug)]
pub struct SimpleTimeZone {
    /// `useDaylight`.
    pub(super) use_daylight: bool,
    /// `rawOffset`.
    pub(super) raw_offset: i32,
    /// `dstSavings`.
    pub(super) dst_savings: i32,
    /// `startYear`.
    pub(super) start_year: i32,
    /// `startMode`.
    pub(super) start_mode: i32,
    /// `startMonth`, 0-based.
    pub(super) start_month: i32,
    /// `startDay`.
    pub(super) start_day: i32,
    /// `startDayOfWeek`, `Calendar.SUNDAY` (1) to `Calendar.SATURDAY` (7).
    pub(super) start_day_of_week: i32,
    /// `startTime`, in milliseconds.
    pub(super) start_time: i32,
    /// `startTimeMode`.
    pub(super) start_time_mode: i32,
    /// `endMode`.
    pub(super) end_mode: i32,
    /// `endMonth`, 0-based.
    pub(super) end_month: i32,
    /// `endDay`.
    pub(super) end_day: i32,
    /// `endDayOfWeek`.
    pub(super) end_day_of_week: i32,
    /// `endTime`, in milliseconds.
    pub(super) end_time: i32,
    /// `endTimeMode`.
    pub(super) end_time_mode: i32,
}

/// Returns the `ZoneInfo` `TimeZone.getTimeZone(id)` returns for an ID of
/// `TimeZone.getAvailableIDs()`, or `None` for any other ID.
pub fn zone_info(id: &str) -> Option<&'static ZoneInfo> {
    IDS.binary_search_by(|(key, _)| key.encode_utf16().cmp(id.encode_utf16()))
        .ok()
        .map(|i| &RULES[IDS[i].1])
}

/// The `ZoneInfo` of a custom time zone of offset `raw_offset`, as
/// `ZoneInfoFile.getCustomTimeZone(id, gmtOffset)` builds it: `new
/// ZoneInfo(toCustomID(gmtOffset), gmtOffset)`, a zone with no transitions
/// and no rule, whose offset is always `raw_offset`. One value per offset is
/// kept for the life of the process.
pub fn custom_zone_info(raw_offset: i32) -> &'static ZoneInfo {
    static CUSTOM: std::sync::Mutex<Vec<&'static ZoneInfo>> = std::sync::Mutex::new(Vec::new());
    let mut custom = CUSTOM
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner);
    if let Some(zone) = custom.iter().find(|z| z.raw_offset == raw_offset) {
        return zone;
    }
    let zone: &'static ZoneInfo = Box::leak(Box::new(ZoneInfo {
        raw_offset,
        transitions: None,
        offsets: &[],
        last_rule: None,
    }));
    custom.push(zone);
    zone
}

impl ZoneInfo {
    /// `getRawOffset()`: the GMT offset of the last standard time, in
    /// milliseconds.
    pub fn raw_offset(&self) -> i32 {
        self.raw_offset
    }

    /// Returns the total offset from UTC, in milliseconds, at the UTC instant
    /// `date`.
    ///
    /// Equivalent to `ZoneInfo.getOffset(long)`, `getOffsets(date, null,
    /// UTC_TIME)`: the raw offset before the table (Java's "FIXME: should
    /// support LMT"), the offset of the transition at or before `date` inside
    /// it, and beyond its last instant the last rule — or, without one, the
    /// last transition's offset. An instant equal to the last transition is
    /// inside the table; any later one is beyond it.
    pub fn get_offset(&self, date: i64) -> i32 {
        let Some(transitions) = self.transitions else {
            return self.raw_offset;
        };
        let index = Self::transition_index(transitions, date);
        if index < 0 {
            return self.raw_offset;
        }
        let index = index as usize;
        if index < transitions.len() {
            return self.offsets[(transitions[index] & OFFSET_MASK) as usize];
        }
        match &self.last_rule {
            Some(tz) => {
                let rawoffset = tz.raw_offset;
                // `tz.getOffset(msec) - rawOffset`: `ZoneInfo.rawOffset`, which
                // the last rule was built with.
                let dstoffset = tz.get_offset(date).wrapping_sub(self.raw_offset);
                rawoffset.wrapping_add(dstoffset)
            }
            None => {
                let val = transitions[transitions.len() - 1];
                self.offsets[(val & OFFSET_MASK) as usize]
            }
        }
    }

    /// `ZoneInfo.getTransitionIndex(date, UTC_TIME)`: the index of the
    /// transition equal to `date`, else of the last one before it (-1 when
    /// none), else `transitions.length` when `date` is beyond them all.
    fn transition_index(transitions: &[i64], date: i64) -> i32 {
        let mut low: i32 = 0;
        let mut high: i32 = transitions.len() as i32 - 1;
        while low <= high {
            let mid = (low + high) / 2;
            let mid_val = transitions[mid as usize] >> TRANSITION_NSHIFT; // sign extended
            match mid_val.cmp(&date) {
                std::cmp::Ordering::Less => low = mid + 1,
                std::cmp::Ordering::Greater => high = mid - 1,
                std::cmp::Ordering::Equal => return mid,
            }
        }
        // if beyond the transitions, returns that index.
        if low as usize >= transitions.len() {
            return low;
        }
        low - 1
    }

    /// The UTC instants of the transition table, in milliseconds
    /// (`transitions[i] >> TRANSITION_NSHIFT`); empty for a zone without one.
    pub fn transition_instants(&self) -> impl Iterator<Item = i64> + '_ {
        self.transitions
            .unwrap_or(&[])
            .iter()
            .map(|val| val >> TRANSITION_NSHIFT)
    }

    /// Returns whether the zone has a last rule, the `SimpleTimeZone` that
    /// applies beyond its transition table.
    pub fn has_last_rule(&self) -> bool {
        self.last_rule.is_some()
    }
}

impl SimpleTimeZone {
    /// `SimpleTimeZone.getOffset(long date)`, `getOffsets(date, null)`,
    /// computed without the instance's cache (see the module documentation).
    fn get_offset(&self, date: i64) -> i32 {
        let mut offset = self.raw_offset;
        if self.use_daylight {
            debug_assert!(
                date >= -12_219_292_800_000,
                "the Julian calendar is not reproduced"
            );
            // Get the year in local time: `cal.getCalendarDate(date + rawOffset,
            // cdate)`, whose sum may overflow as Java's does.
            let local = date.wrapping_add(i64::from(self.raw_offset));
            let year = gregorian_year_from_fixed_date(fixed_date_of_millis(local));
            if year >= self.start_year {
                // `cdate.setTimeOfDay(0, 0, 0, 0)`: the transition
                // calculations start from midnight.
                let mut cdate = TransitionDate { time_of_day: 0 };
                offset = self.get_offset_in_year(&mut cdate, year, date);
            }
        }
        offset
    }

    /// `SimpleTimeZone.getOffset(BaseCalendar, BaseCalendar.Date, int year,
    /// long time)`, without the cache.
    fn get_offset_in_year(&self, cdate: &mut TransitionDate, year: i32, time: i64) -> i32 {
        let mut start = self.get_start(cdate, year);
        let mut end = self.get_end(cdate, year);
        let mut offset = self.raw_offset;
        if start <= end {
            if time >= start && time < end {
                offset = offset.wrapping_add(self.dst_savings);
            }
        } else if time < end {
            start = self.get_start(cdate, year.wrapping_sub(1));
            if time >= start {
                offset = offset.wrapping_add(self.dst_savings);
            }
        } else if time >= start {
            end = self.get_end(cdate, year.wrapping_add(1));
            if time < end {
                offset = offset.wrapping_add(self.dst_savings);
            }
        }
        offset
    }

    /// `SimpleTimeZone.getStart`: the UTC instant daylight saving time starts
    /// in `year`.
    fn get_start(&self, cdate: &mut TransitionDate, year: i32) -> i64 {
        let mut time = self.start_time;
        if self.start_time_mode != UTC_TIME {
            time = time.wrapping_sub(self.raw_offset);
        }
        cdate.transition(
            self.start_mode,
            year,
            self.start_month,
            self.start_day,
            self.start_day_of_week,
            time,
        )
    }

    /// `SimpleTimeZone.getEnd`: the UTC instant daylight saving time ends in
    /// `year`.
    fn get_end(&self, cdate: &mut TransitionDate, year: i32) -> i64 {
        let mut time = self.end_time;
        if self.end_time_mode != UTC_TIME {
            time = time.wrapping_sub(self.raw_offset);
        }
        if self.end_time_mode == WALL_TIME {
            time = time.wrapping_sub(self.dst_savings);
        }
        cdate.transition(
            self.end_mode,
            year,
            self.end_month,
            self.end_day,
            self.end_day_of_week,
            time,
        )
    }
}

/// The part of the `BaseCalendar.Date` that `SimpleTimeZone.getOffsets`
/// threads through its transition calculations and that can change their
/// result: its time of day.
///
/// `getOffsets` clears it to midnight, and `AbstractCalendar.getTime(cdate)`
/// adds it to the date and then resets the date from the sum
/// (`getCalendarDate(ms, cdate)`). The sum stays at midnight unless
/// `(fixedDate - EPOCH_OFFSET) * DAY_IN_MILLIS` overflows, as it does for the
/// last months of year 292278994; the wrapped time of day then carries over
/// to the next calculation, as it does in Java.
struct TransitionDate {
    time_of_day: i64,
}

impl TransitionDate {
    /// `SimpleTimeZone.getTransition(cal, cdate, mode, year, month,
    /// dayOfMonth, dayOfWeek, timeOfDay)`.
    fn transition(
        &mut self,
        mode: i32,
        year: i32,
        month: i32,
        day_of_month: i32,
        day_of_week: i32,
        time_of_day: i32,
    ) -> i64 {
        let month = month + 1;
        let fixed_date = match mode {
            DOM_MODE => fixed_date(year, month, day_of_month),
            DOW_IN_MONTH_MODE => {
                let day = if day_of_month < 0 {
                    month_length(year, month)
                } else {
                    1
                };
                nth_day_of_week(day_of_month, day_of_week, fixed_date(year, month, day))
            }
            DOW_GE_DOM_MODE => {
                nth_day_of_week(1, day_of_week, fixed_date(year, month, day_of_month))
            }
            DOW_LE_DOM_MODE => {
                nth_day_of_week(-1, day_of_week, fixed_date(year, month, day_of_month))
            }
            // `decodeRules` gives a rule that uses daylight saving time one
            // of the four modes.
            _ => unreachable!("SimpleTimeZone mode {mode}"),
        };
        // `cal.getTime(cdate)`: in `DOM_MODE` on `cdate` itself, whose time of
        // day is then reset from the sum; in the other modes on the copy
        // `getNthDayOfWeek` returns, which inherits it and is then dropped.
        let ms = (fixed_date - EPOCH_OFFSET)
            .wrapping_mul(DAY_IN_MILLIS)
            .wrapping_add(self.time_of_day);
        if mode == DOM_MODE {
            self.time_of_day = ms.rem_euclid(DAY_IN_MILLIS);
        }
        ms.wrapping_add(i64::from(time_of_day))
    }
}

/// `AbstractCalendar.getNthDayOfWeek(nth, dayOfWeek, date)` on a fixed date:
/// the `nth` `dayOfWeek` on or after (`nth > 0`) or on or before (`nth <= 0`)
/// it.
fn nth_day_of_week(nth: i32, day_of_week: i32, fixed_date: i64) -> i64 {
    let nth = i64::from(nth);
    if nth > 0 {
        7 * nth + day_of_week_date_on_or_before(fixed_date - 1, day_of_week)
    } else {
        7 * nth + day_of_week_date_on_or_before(fixed_date + 7, day_of_week)
    }
}

/// `AbstractCalendar.getDayOfWeekDateOnOrBefore(fixedDate, dayOfWeek)`;
/// fixed date 1 (0001-01-01) is a Monday, and `dayOfWeek` counts from
/// Sunday (1).
fn day_of_week_date_on_or_before(fixed_date: i64, day_of_week: i32) -> i64 {
    let fd = fixed_date - i64::from(day_of_week - 1);
    fixed_date - fd.rem_euclid(7)
}

/// `CalendarUtils.isGregorianLeapYear(year)`.
fn is_leap_year(year: i32) -> bool {
    year % 4 == 0 && (year % 100 != 0 || year % 400 == 0)
}

/// `BaseCalendar.getMonthLength(year, month)`, `month` 1-based.
fn month_length(year: i32, month: i32) -> i32 {
    const DAYS_IN_MONTH: [i32; 13] = [0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
    let days = DAYS_IN_MONTH[month as usize];
    if month == 2 && is_leap_year(year) {
        days + 1
    } else {
        days
    }
}

/// `BaseCalendar.getFixedDate(year, month, dayOfMonth, null)`: the fixed date
/// (0001-01-01 is 1) of a Gregorian date, `month` 1-based; a day of month
/// beyond the month counts on into the next.
fn fixed_date(year: i32, month: i32, day_of_month: i32) -> i64 {
    let prevyear = i64::from(year) - 1;
    let month = i64::from(month);
    let mut days = i64::from(day_of_month) + 365 * prevyear + prevyear.div_euclid(4)
        - prevyear.div_euclid(100)
        + prevyear.div_euclid(400)
        + (367 * month - 362).div_euclid(12);
    if month > 2 {
        days -= if is_leap_year(year) { 1 } else { 2 };
    }
    days
}

/// The fixed date of the instant `millis`, as `AbstractCalendar.getCalendarDate`
/// computes it for a date without a time zone: floor division by a day.
fn fixed_date_of_millis(millis: i64) -> i64 {
    millis.div_euclid(DAY_IN_MILLIS) + EPOCH_OFFSET
}

/// `BaseCalendar.getGregorianYearFromFixedDate(fixedDate)`.
fn gregorian_year_from_fixed_date(fixed_date: i64) -> i32 {
    let d0 = fixed_date - 1;
    let n400 = d0.div_euclid(146_097) as i32;
    let d1 = d0.rem_euclid(146_097) as i32;
    let n100 = d1.div_euclid(36_524);
    let d2 = d1.rem_euclid(36_524);
    let n4 = d2.div_euclid(1_461);
    let d3 = d2.rem_euclid(1_461);
    let n1 = d3.div_euclid(365);
    let mut year = 400 * n400 + 100 * n100 + 4 * n4 + n1;
    if !(n100 == 4 || n1 == 4) {
        year += 1;
    }
    year
}

/// `ZoneInfo.DST_MASK` shift: the bits of a transition holding the index of
/// its saving in `offsets`.
const DST_NSHIFT: u32 = 4;
/// `ZoneInfo.UTC_TIME` (`getOffsets` type).
const OFFSETS_UTC_TIME: i32 = 0;
/// `ZoneInfo.STANDARD_TIME`.
const OFFSETS_STANDARD_TIME: i32 = 1;
/// `ZoneInfo.WALL_TIME`.
const OFFSETS_WALL_TIME: i32 = 2;

impl ZoneInfo {
    /// `ZoneInfo.getOffsets(date, offsets, type)`: the total offset, and the
    /// standard and daylight parts of it (`offsets[0]`, `offsets[1]`), at
    /// `date`, a UTC instant (`type == UTC_TIME`) or a local time.
    fn get_offsets_typed(&self, date: i64, kind: i32) -> (i32, [i32; 2]) {
        let Some(transitions) = self.transitions else {
            let offset = self.raw_offset;
            return (offset, [offset, 0]);
        };
        let index = Self::transition_index_typed(transitions, self.offsets, date, kind);
        // prior to the transition table, returns the raw offset.
        if index < 0 {
            let offset = self.raw_offset;
            return (offset, [offset, 0]);
        }
        let of_transition = |val: i64| -> (i32, [i32; 2]) {
            let offset = self.offsets[(val & OFFSET_MASK) as usize];
            let dst = ((val as u64 >> DST_NSHIFT) & 0xf) as usize;
            let save = if dst == 0 { 0 } else { self.offsets[dst] };
            (offset, [offset.wrapping_sub(save), save])
        };
        let index = index as usize;
        if index < transitions.len() {
            return of_transition(transitions[index]);
        }
        // beyond the transitions, delegate to SimpleTimeZone if there
        // is a rule; otherwise, return the offset of the last transition.
        match &self.last_rule {
            Some(tz) => {
                let rawoffset = tz.raw_offset;
                let mut msec = date;
                if kind != OFFSETS_UTC_TIME {
                    msec = msec.wrapping_sub(i64::from(self.raw_offset));
                }
                let mut dstoffset = tz.get_offset(msec).wrapping_sub(self.raw_offset);
                // Check if it's in a standard-to-daylight transition.
                if dstoffset > 0
                    && tz.get_offset(msec.wrapping_sub(i64::from(dstoffset))) == rawoffset
                    && kind == OFFSETS_WALL_TIME
                {
                    dstoffset = 0;
                }
                (rawoffset.wrapping_add(dstoffset), [rawoffset, dstoffset])
            }
            None => of_transition(transitions[transitions.len() - 1]),
        }
    }

    /// `ZoneInfo.getTransitionIndex(date, type)`.
    fn transition_index_typed(transitions: &[i64], offsets: &[i32], date: i64, kind: i32) -> i32 {
        let mut low: i32 = 0;
        let mut high: i32 = transitions.len() as i32 - 1;
        while low <= high {
            let mid = (low + high) / 2;
            let val = transitions[mid as usize];
            let mut mid_val = val >> TRANSITION_NSHIFT; // sign extended
            if kind != OFFSETS_UTC_TIME {
                mid_val = mid_val.wrapping_add(i64::from(offsets[(val & OFFSET_MASK) as usize]));
                // wall time
            }
            if kind == OFFSETS_STANDARD_TIME {
                let dst_index = ((val as u64 >> DST_NSHIFT) & 0xf) as usize;
                if dst_index != 0 {
                    mid_val = mid_val.wrapping_sub(i64::from(offsets[dst_index]));
                    // make it standard time
                }
            }
            match mid_val.cmp(&date) {
                std::cmp::Ordering::Less => low = mid + 1,
                std::cmp::Ordering::Greater => high = mid - 1,
                std::cmp::Ordering::Equal => return mid,
            }
        }
        // if beyond the transitions, returns that index.
        if low as usize >= transitions.len() {
            return low;
        }
        low - 1
    }
}

/// A `java.util.TimeZone`: the `sun.util.calendar.ZoneInfo`
/// `TimeZone.getTimeZone` returns, with the ID it was asked for.
///
/// Equivalent to `java.util.TimeZone` (its `ZoneInfo` subclass). Two values
/// are equal when their IDs and rules are, as `ZoneInfo.equals` compares them.
#[derive(Clone, Debug)]
pub struct TimeZone {
    id: String,
    zone: &'static ZoneInfo,
}

impl PartialEq for TimeZone {
    fn eq(&self, other: &Self) -> bool {
        self.id == other.id && std::ptr::eq(self.zone, other.zone)
    }
}

impl Eq for TimeZone {}

/// `TimeZone.setDefault`'s value; `None` until set.
static DEFAULT_ZONE: RwLock<Option<Arc<TimeZone>>> = RwLock::new(None);

impl TimeZone {
    /// `TimeZone.getTimeZone(String ID)`: the zone of a tzdb ID or alias, of
    /// a custom `GMT±hh:mm` ID (normalized), or `GMT` for any other ID. A
    /// three-letter ID of `ZoneId.SHORT_IDS` prints the JDK's deprecation
    /// warning on the standard error, as Java does.
    pub fn get_time_zone(id: &str) -> TimeZone {
        Self::get_time_zone_fallback(id, true).expect("INVARIANT: getTimeZone falls back to GMT")
    }

    /// `TimeZone.getTimeZone(String ID, boolean fallback)`.
    fn get_time_zone_fallback(id: &str, fallback: bool) -> Option<TimeZone> {
        let resolved = get_time_zone_id(id, fallback)?;
        let zone = zone_info(&resolved)
            .or_else(|| zone_info(id))
            .unwrap_or_else(|| custom_zone_info(custom_offset(&resolved)));
        Some(TimeZone { id: resolved, zone })
    }

    /// `getID()`.
    pub fn get_id(&self) -> &str {
        &self.id
    }

    /// `getRawOffset()`: the GMT offset of the last standard time, in
    /// milliseconds.
    pub fn get_raw_offset(&self) -> i32 {
        self.zone.raw_offset()
    }

    /// `getOffset(long date)`: the total offset from UTC at the UTC instant
    /// `date`, in milliseconds.
    pub fn get_offset(&self, date: i64) -> i32 {
        self.zone.get_offset(date)
    }

    /// `ZoneInfo.getOffsets(utc, offsets)`: the total offset at the UTC
    /// instant `utc`, with its standard and daylight parts.
    pub fn get_offsets(&self, utc: i64) -> (i32, [i32; 2]) {
        self.zone.get_offsets_typed(utc, OFFSETS_UTC_TIME)
    }

    /// `ZoneInfo.getOffsetsByWall(wall, offsets)`: the offsets of the local
    /// (wall) time `wall`.
    pub fn get_offsets_by_wall(&self, wall: i64) -> (i32, [i32; 2]) {
        self.zone.get_offsets_typed(wall, OFFSETS_WALL_TIME)
    }

    /// `ZoneInfo.getOffsetsByStandard(standard, offsets)`.
    pub fn get_offsets_by_standard(&self, standard: i64) -> (i32, [i32; 2]) {
        self.zone.get_offsets_typed(standard, OFFSETS_STANDARD_TIME)
    }

    /// `getDSTSavings()`, approximated by the saving of the zone's last rule
    /// (0 for a zone without one).
    ///
    /// **Divergence.** `ZoneInfo.getDSTSavings()` returns the `dstSavings`
    /// field `ZoneInfoFile` computes, which the rule data does not hold; the
    /// last rule's saving stands for it. Only the parsing of a daylight
    /// time-zone name reads it.
    pub fn get_dst_savings(&self) -> i32 {
        self.zone.last_rule.as_ref().map_or(0, |r| r.dst_savings)
    }

    /// `TimeZone.getDefault()`: the zone [`set_default`](Self::set_default)
    /// set, else the platform's (see the module documentation), computed
    /// once.
    pub fn get_default() -> TimeZone {
        if let Some(zone) = DEFAULT_ZONE
            .read()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
            .as_ref()
        {
            return (**zone).clone();
        }
        Self::get_time_zone(default_id())
    }

    /// `TimeZone.setDefault(zone)`; `None` restores the platform's.
    pub fn set_default(zone: Option<TimeZone>) {
        *DEFAULT_ZONE
            .write()
            .unwrap_or_else(std::sync::PoisonError::into_inner) = zone.map(Arc::new);
    }
}

/// The offset of a normalized custom ID (`GMT±hh:mm[:ss]`, or `GMT`), in
/// milliseconds.
fn custom_offset(id: &str) -> i32 {
    let Some(rest) = id.strip_prefix("GMT") else {
        return 0;
    };
    let (sign, rest) = match rest.as_bytes().first() {
        Some(b'+') => (1, &rest[1..]),
        Some(b'-') => (-1, &rest[1..]),
        _ => return 0,
    };
    let mut parts = rest.split(':').map(|p| p.parse::<i32>().unwrap_or(0));
    let hh = parts.next().unwrap_or(0);
    let mm = parts.next().unwrap_or(0);
    let ss = parts.next().unwrap_or(0);
    sign * (hh * 3_600 + mm * 60 + ss) * 1_000
}

/// `TimeZone.GMT_ID`.
const GMT_ID: &str = "GMT";

/// The zoneinfo directory of `TimeZone_md.c` on Linux.
const ZONEINFO_DIR: &str = "/usr/share/zoneinfo";

/// The default zoneinfo file of `TimeZone_md.c` on Linux.
const DEFAULT_ZONEINFO_FILE: &str = "/etc/localtime";

/// `TimeZone.getTimeZone(String ID, boolean fallback)` reduced to the ID of
/// the zone it returns: a tzdb ID or alias as given, a custom
/// `GMT±hh:mm` ID normalized, `GMT` for an unknown ID when `fallback`, and
/// `None` otherwise. A three-letter ID of `ZoneId.SHORT_IDS` prints the JDK's
/// deprecation warning on the standard error, as Java does.
pub fn get_time_zone_id(id: &str, fallback: bool) -> Option<String> {
    let data = data();
    if data.short_ids.contains(id) {
        eprintln!(
            "WARNING: Use of the three-letter time zone ID \"{id}\" is deprecated and it will be removed in a future release"
        );
    }
    if let Some(resolved) = data.zone_ids.get(id) {
        return Some(resolved.clone());
    }
    if let Some(custom) = parse_custom_time_zone(id) {
        return Some(custom);
    }
    if fallback {
        Some(GMT_ID.to_string())
    } else {
        None
    }
}

/// `TimeZone.parseCustomTimeZone(String)`, reduced to the normalized ID:
/// `GMT` followed by a sign and `h`, `hh`, `hmm`, `hhmm`, `h:mm`, `hh:mm` or
/// `hh:mm:ss`.
fn parse_custom_time_zone(id: &str) -> Option<String> {
    let id_units: Vec<u16> = id.encode_utf16().collect();
    let length = id_units.len();
    if length < GMT_ID.len() + 2 || !id.starts_with(GMT_ID) {
        return None;
    }
    let mut index = GMT_ID.len();
    let negative = match id_units[index] {
        0x2D => true,  // '-'
        0x2B => false, // '+'
        _ => return None,
    };
    index += 1;
    let mut hours = 0;
    let mut minutes = 0;
    let mut num = 0;
    let mut count_delim = 0;
    let mut len = 0;
    while index < length {
        let c = id_units[index];
        index += 1;
        if c == u16::from(b':') {
            if count_delim > 1 || len == 0 || len > 2 {
                return None;
            }
            if count_delim == 0 {
                hours = num;
            } else if count_delim == 1 {
                minutes = num;
            }
            count_delim += 1;
            num = 0;
            len = 0;
            continue;
        }
        if !(u16::from(b'0')..=u16::from(b'9')).contains(&c) {
            return None;
        }
        num = num * 10 + i32::from(c - u16::from(b'0'));
        len += 1;
    }
    if count_delim == 0 {
        if len <= 2 {
            hours = num;
            minutes = 0;
            num = 0;
        } else if len <= 4 {
            hours = num / 100;
            minutes = num % 100;
            num = 0;
        } else {
            return None;
        }
    } else if count_delim == 1 {
        if len == 2 {
            minutes = num;
            num = 0;
        } else {
            return None;
        }
    } else if len != 2 {
        return None;
    }
    if hours > 23 || minutes > 59 || num > 59 {
        return None;
    }
    let gmt_offset = (hours * 3_600 + minutes * 60 + num) * 1_000;
    if gmt_offset == 0 {
        return Some(if negative { "GMT-00:00" } else { "GMT+00:00" }.to_string());
    }
    Some(to_custom_id(if negative {
        -gmt_offset
    } else {
        gmt_offset
    }))
}

/// `ZoneInfoFile.toCustomID(int)`.
pub(crate) fn to_custom_id(gmt_offset: i32) -> String {
    let mut offset = gmt_offset / 1_000;
    let sign = if offset >= 0 {
        '+'
    } else {
        offset = -offset;
        '-'
    };
    let hh = offset / 3_600;
    let mm = (offset % 3_600) / 60;
    let ss = offset % 60;
    let mut id = format!("GMT{sign}{hh:02}:");
    if mm != 0 {
        id.push_str(&format!("{mm:02}"));
    } else {
        id.push_str("00");
    }
    if ss != 0 {
        id.push_str(&format!(":{ss:02}"));
    }
    id
}

/// `TimeZone.getDefault().getID()`, computed once, as the JVM computes it
/// once (`TimeZone.setDefaultZone`).
fn default_id() -> &'static str {
    static DEFAULT: LazyLock<String> = LazyLock::new(|| {
        // `user.timezone` is not set (see the module documentation)
        let zone_id = find_java_tz().unwrap_or_else(|| GMT_ID.to_string());
        match get_time_zone_id(&zone_id, false) {
            Some(id) => id,
            // `getSystemGMTOffsetID()` is not emulated (see the module
            // documentation)
            None => GMT_ID.to_string(),
        }
    });
    &DEFAULT
}

/// `findJavaTZ_md` of `TimeZone_md.c` on Linux: the `TZ` environment
/// variable, else the zone `/etc/localtime` names, without a leading `:` or
/// `posix/`.
fn find_java_tz() -> Option<String> {
    let tz = match std::env::var_os("TZ") {
        Some(tz) if !tz.is_empty() => Some(tz.to_string_lossy().into_owned()),
        _ => platform_time_zone_id(),
    }?;
    let tz = tz.strip_prefix(':').unwrap_or(&tz);
    let tz = tz.strip_prefix("posix/").unwrap_or(tz);
    Some(tz.to_string())
}

/// `getPlatformTimeZoneID()` of `TimeZone_md.c` on Linux.
fn platform_time_zone_id() -> Option<String> {
    let meta = std::fs::symlink_metadata(DEFAULT_ZONEINFO_FILE).ok()?;
    if meta.file_type().is_symlink() {
        let link = std::fs::read_link(DEFAULT_ZONEINFO_FILE).ok()?;
        let link = collapse(&remove_duplicate_slashes(&link.to_string_lossy()));
        if let Some(name) = zone_name(&link) {
            return Some(name.to_string());
        }
    }
    // a regular file: find the zoneinfo file of the same content
    let buf = std::fs::read(DEFAULT_ZONEINFO_FILE).ok()?;
    find_zoneinfo_file(&buf, Path::new(ZONEINFO_DIR))
}

/// `getZoneName(char*)`: the part after the first `zoneinfo/`.
fn zone_name(path: &str) -> Option<&str> {
    const ZIDIR: &str = "zoneinfo/";
    path.find(ZIDIR).map(|pos| &path[pos + ZIDIR.len()..])
}

/// `removeDuplicateSlashes(char*)`.
fn remove_duplicate_slashes(path: &str) -> String {
    let mut out = String::with_capacity(path.len());
    let mut previous_slash = false;
    for c in path.chars() {
        if c == '/' && previous_slash {
            continue;
        }
        previous_slash = c == '/';
        out.push(c);
    }
    out
}

/// `collapse(char*)` of `path_util.c`: the `.` names removed, and each `..`
/// removed with the name before it (or alone, at the start of an absolute
/// path).
fn collapse(path: &str) -> String {
    let absolute = path.starts_with('/');
    let names_part = if absolute { &path[1..] } else { path };
    let mut names: Vec<Option<&str>> = names_part.split('/').map(Some).collect();
    if names_part.is_empty() {
        names.clear();
    }
    let dots = names.iter().any(|n| matches!(n, Some(".") | Some("..")));
    if !dots || names.len() < 2 {
        return path.to_string();
    }
    let nc = names.len();
    let mut i = 0;
    while i < nc {
        let mut dots = 0;
        while i < nc {
            match names[i] {
                Some(".") => {
                    dots = 1;
                    break;
                }
                Some("..") => {
                    dots = 2;
                    break;
                }
                _ => i += 1,
            }
        }
        if i >= nc {
            break;
        }
        if dots == 1 {
            names[i] = None;
        } else {
            match (0..i).rev().find(|&j| names[j].is_some()) {
                Some(j) => {
                    names[j] = None;
                    names[i] = None;
                }
                None => {
                    if absolute {
                        names[i] = None;
                    }
                }
            }
        }
        i += 1;
    }
    let joined = names.into_iter().flatten().collect::<Vec<_>>().join("/");
    if absolute {
        format!("/{joined}")
    } else {
        joined
    }
}

/// `findZoneinfoFile(char*, size_t, const char*)`: the ID of the first file
/// under `dir` whose content is `buf`, `UTC` and `GMT` first, then in
/// directory order, skipping `.`-names, `ROC`, `posixrules` and `localtime`.
fn find_zoneinfo_file(buf: &[u8], dir: &Path) -> Option<String> {
    if dir == Path::new(ZONEINFO_DIR) {
        for popular in ["UTC", "GMT"] {
            if let Some(tz) = is_file_identical(buf, &dir.join(popular)) {
                return Some(tz);
            }
        }
    }
    for entry in std::fs::read_dir(dir).ok()?.flatten() {
        let name = entry.file_name();
        let name = name.to_string_lossy();
        if name.starts_with('.') || name == "ROC" || name == "posixrules" || name == "localtime" {
            continue;
        }
        if let Some(tz) = is_file_identical(buf, &dir.join(name.as_ref())) {
            return Some(tz);
        }
    }
    None
}

/// `isFileIdentical(char*, size_t, char*)`.
fn is_file_identical(buf: &[u8], path: &Path) -> Option<String> {
    let meta = std::fs::metadata(path).ok()?;
    if meta.is_dir() {
        return find_zoneinfo_file(buf, path);
    }
    if meta.is_file() && meta.len() == buf.len() as u64 {
        let content = std::fs::read(path).ok()?;
        if content == buf {
            let path = path.to_string_lossy();
            return zone_name(&path).map(str::to_string);
        }
    }
    None
}
