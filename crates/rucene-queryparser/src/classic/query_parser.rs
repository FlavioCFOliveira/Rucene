//! The port of `QueryParser.java`, of the Java package
//! `org.apache.lucene.queryparser.classic`: the parser JavaCC generates from
//! `QueryParser.jj`.
//!
//! The regions between `// @generated begin` and `// @generated end` are
//! written by `tools/translate/javacc_java_to_rust.py` from the generated
//! Java; the rest is the grammar's `PARSER_BEGIN` user code, translated by
//! hand (the translator pins its Java tokens).
//!
//! Java's class is rendered as the state [`QueryParser`] and the trait
//! [`QueryParserOps`], whose provided methods are the generated public
//! members; the subclasses (`MultiFieldQueryParser`,
//! `ComplexPhraseQueryParser`, `ExtendableQueryParser`) embed a
//! [`QueryParser`] and implement the traits, overriding what their Java
//! classes override.

