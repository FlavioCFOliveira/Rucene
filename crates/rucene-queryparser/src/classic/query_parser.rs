/// The default operator for parsing queries. Use
/// [`QueryParserBaseOps::set_default_operator`] to change it.
///
/// Equivalent to `org.apache.lucene.queryparser.classic.QueryParser.Operator`.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Operator {
    /// Java constant `OR`.
    Or,
    /// Java constant `AND`.
    And,
}

/// Default split on whitespace behavior.
///
/// Equivalent to `QueryParser.DEFAULT_SPLIT_ON_WHITESPACE`.
pub const DEFAULT_SPLIT_ON_WHITESPACE: bool = false;

/// This class is generated by JavaCC. The most important method is
/// [`parse`](QueryParserBaseOps::parse).
///
/// The syntax for query strings is as follows: a Query is a series of
/// clauses. A clause may be prefixed by a plus (`+`) or a minus (`-`) sign,
/// indicating that the clause is required or prohibited respectively; or a
/// term followed by a colon, indicating the field to be searched. A clause
/// may be either a term, indicating all the documents that contain this
/// term; or a nested query, enclosed in parentheses.
///
/// Note that QueryParser is *not* thread-safe.
///
/// Equivalent to `org.apache.lucene.queryparser.classic.QueryParser`.
#[derive(Debug)]
pub struct QueryParser {
    /// The `QueryParserBase` state Java's class extends.
    pub(crate) base: QueryParserBase,
    pub(crate) split_on_whitespace: bool,
    /// The fields JavaCC generates.
    pub(crate) jj: JjState,
}

impl QueryParser {
    /// Create a query parser.
    ///
    /// `f` is the default field for query terms, `a` is used to find terms
    /// in the query text.
    ///
    /// Equivalent to `new QueryParser(String, Analyzer)`.
    ///
    /// # Errors
    ///
    /// None in practice: `init` sets `autoGeneratePhraseQueries` to `false`,
    /// which the override accepts.
    pub fn new(f: Option<&str>, a: Option<Arc<dyn Analyzer>>) -> Result<Self> {
        let mut parser = Self::with_char_stream(Box::new(FastCharStream::new(Box::new(
            StringCharReader::new(""),
        ))));
        parser.init(f, a)?;
        Ok(parser)
    }

    /// Constructor with user supplied CharStream.
    ///
    /// Equivalent to the protected `QueryParser(CharStream)`.
    pub fn with_char_stream(stream: Box<dyn CharStream>) -> Self {
        Self {
            base: QueryParserBase::new(),
            split_on_whitespace: DEFAULT_SPLIT_ON_WHITESPACE,
            jj: JjState::with_char_stream(stream),
        }
    }

    /// Constructor with generated Token Manager.
    ///
    /// Equivalent to the protected `QueryParser(QueryParserTokenManager)`.
    pub fn with_token_manager(tm: QueryParserTokenManager) -> Self {
        Self {
            base: QueryParserBase::new(),
            split_on_whitespace: DEFAULT_SPLIT_ON_WHITESPACE,
            jj: JjState::with_token_manager(tm),
        }
    }
}

/// `QueryParser.setAutoGeneratePhraseQueries(boolean)`, the override of
/// [`QueryParserBaseOps::set_auto_generate_phrase_queries`] every
/// [`QueryParserOps`] implementation delegates to.
///
/// Set to true if phrase queries will be automatically generated when the
/// analyzer returns more than one term from whitespace delimited text. NOTE:
/// this behavior may not be suitable for all languages. Set to false if
/// phrase queries should only be generated when surrounded by double quotes.
/// The combination splitOnWhitespace=false and autoGeneratePhraseQueries=true
/// is disallowed (LUCENE-7533).
///
/// # Errors
///
/// `IllegalArgumentException` for `true` while `getSplitOnWhitespace()` is
/// `false`.
pub fn set_auto_generate_phrase_queries<P: QueryParserOps + ?Sized>(
    this: &mut P,
    value: bool,
) -> Result<()> {
    if !this.query_parser().split_on_whitespace && value {
        return Err(LuceneError::illegal_argument(
            "setAutoGeneratePhraseQueries(true) is disallowed when getSplitOnWhitespace() == false",
        ));
    }
    this.query_parser_base_mut().auto_generate_phrase_queries = value;
    Ok(())
}

/// The token kinds that may not follow a multi-term run: `COLON`, `STAR`,
/// `FUZZY_SLOP`, `CARAT`, `AND`, `OR`.
///
/// Equivalent to the private static `IntHashSet disallowedPostMultiTerm`.
static DISALLOWED_POST_MULTI_TERM: [i32; 6] = [
    qpc::COLON,
    qpc::STAR,
    qpc::FUZZY_SLOP,
    qpc::CARAT,
    qpc::AND,
    qpc::OR,
];

/// Equivalent to the private static `allowedPostMultiTerm(int)`.
fn allowed_post_multi_term(token_kind: i32) -> bool {
    !DISALLOWED_POST_MULTI_TERM.contains(&token_kind)
}

