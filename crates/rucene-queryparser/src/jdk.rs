//! The JDK behaviour `lucene/queryparser` calls that the `rucene` crate does
//! not emulate: `java.util.Locale` (with `Locale.getDefault()`),
//! `String.toLowerCase(Locale)`, `java.util.TimeZone`, `java.util.Calendar`
//! (Gregorian, Buddhist and Japanese), `java.util.Date`,
//! `java.text.DateFormat` / `SimpleDateFormat` (`getDateInstance`, parse and
//! format), `java.text.NumberFormat` / `DecimalFormat`
//! (`getInstance`, `getNumberInstance`, `getIntegerInstance`, parse and
//! format), `ParsePosition`, `FieldPosition` and `java.text.ParseException`;
//! for the flexible query parser, `java.lang.CharSequence`, the reflection
//! of `java.lang.Class`, `java.lang.Object` message arguments,
//! `java.util.ResourceBundle` and `java.text.MessageFormat`; and for the XML
//! query parser, the JAXP DOM (`DocumentBuilderFactory`, `org.w3c.dom`,
//! `org.xml.sax`).
//!
//! **Divergence.** These modules are emulations, not ports of a Lucene file:
//! the JDK is GPL with the Classpath Exception, so each one reproduces, from
//! the JDK's specification (OpenJDK 25 sources read as specification, no
//! code copied), the part of JDK 25 the query parsers and their tests call,
//! over JDK 25 data dumped by `tools/translate/JdkFormatData.java`,
//! `tools/translate/JdkCombiningClassData.java` and
//! `tools/gen/TimeZoneRules.java`. Several modules start from the copies
//! other crates of the workspace hold (`rucene-analysis-common`,
//! `rucene-test-framework`), which this crate cannot depend on. Each states
//! at its point what the JDK does and where the emulation differs.

