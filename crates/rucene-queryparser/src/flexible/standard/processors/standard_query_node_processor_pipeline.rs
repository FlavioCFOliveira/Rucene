/// This pipeline has all the processors needed to process a query node tree,
/// generated by `StandardSyntaxParser`, already assembled.
///
/// The order they are assembled affects the results.
///
/// This processor pipeline was designed to work with
/// `StandardQueryConfigHandler`.
///
/// The result query node tree can be used to build a `Query` object using
/// `StandardQueryTreeBuilder`.
///
/// Equivalent to `org.apache.lucene.queryparser.flexible.standard.processors.StandardQueryNodeProcessorPipeline`,
/// which extends `QueryNodeProcessorPipeline` (embedded, and reached by
/// dereference) and adds only a constructor.
#[derive(Debug)]
pub struct StandardQueryNodeProcessorPipeline {
    base: QueryNodeProcessorPipeline,
}

impl StandardQueryNodeProcessorPipeline {
    /// Equivalent to `new StandardQueryNodeProcessorPipeline(QueryConfigHandler
    /// queryConfig)`: the standard processors, in Lucene's order.
    pub fn new(query_config: Option<Arc<QueryConfigHandler>>) -> Self {
        let base = QueryNodeProcessorPipeline::with_query_config_handler(query_config);
        base.add(Arc::new(WildcardQueryNodeProcessor::new()));
        base.add(Arc::new(MultiFieldQueryNodeProcessor::new()));
        base.add(Arc::new(FuzzyQueryNodeProcessor::new()));
        base.add(Arc::new(RegexpQueryNodeProcessor::new()));
        base.add(Arc::new(MatchAllDocsQueryNodeProcessor::new()));
        base.add(Arc::new(OpenRangeQueryNodeProcessor::new()));
        base.add(Arc::new(PointQueryNodeProcessor::new()));
        base.add(Arc::new(PointRangeQueryNodeProcessor::new()));
        base.add(Arc::new(TermRangeQueryNodeProcessor::new()));
        base.add(Arc::new(AllowLeadingWildcardProcessor::new()));
        base.add(Arc::new(AnalyzerQueryNodeProcessor::new()));
        base.add(Arc::new(PhraseSlopQueryNodeProcessor::new()));
        // add(new GroupQueryNodeProcessor());
        base.add(Arc::new(BooleanQuery2ModifierNodeProcessor::new()));
        base.add(Arc::new(NoChildOptimizationQueryNodeProcessor::new()));
        base.add(Arc::new(RemoveDeletedQueryNodesProcessor::new()));
        base.add(Arc::new(RemoveEmptyNonLeafQueryNodeProcessor::new()));
        base.add(Arc::new(
            BooleanSingleChildOptimizationQueryNodeProcessor::new(),
        ));
        base.add(Arc::new(DefaultPhraseSlopQueryNodeProcessor::new()));
        base.add(Arc::new(BoostQueryNodeProcessor::new()));
        base.add(Arc::new(MultiTermRewriteMethodProcessor::new()));
        base.add(Arc::new(IntervalQueryNodeProcessor::new()));
        Self { base }
    }

    /// The `QueryNodeProcessorPipeline` this pipeline extends.
    pub fn query_node_processor_pipeline(&self) -> &QueryNodeProcessorPipeline {
        &self.base
    }
}

impl Deref for StandardQueryNodeProcessorPipeline {
    type Target = QueryNodeProcessorPipeline;

    fn deref(&self) -> &QueryNodeProcessorPipeline {
        &self.base
    }
}

impl QueryNodeProcessor for StandardQueryNodeProcessorPipeline {
    fn process(&self, query_tree: QueryNodeRef) -> Result<QueryNodeRef> {
        self.base.process(query_tree)
    }

    fn set_query_config_handler(&self, query_config_handler: Option<Arc<QueryConfigHandler>>) {
        self.base.set_query_config_handler(query_config_handler);
    }

    fn get_query_config_handler(&self) -> Option<Arc<QueryConfigHandler>> {
        self.base.get_query_config_handler()
    }

    fn as_any(&self) -> &dyn std::any::Any {
        self
    }
}
