//! The offsets `java.util.TimeZone` gives on JDK 25, and the hour of day
//! `java.util.GregorianCalendar` derives from them.
//!
//! **Divergence.** An emulation of JDK 25, not a port of a Lucene file (see
//! the [module documentation](super)). `TimeZone.getTimeZone(id)` returns a
//! `sun.util.calendar.ZoneInfo`: `ZoneInfoFile` derives it from the tzdb
//! rules as a transition table bounded to 1900..2037 and, for a zone that
//! still observes daylight saving time, a `SimpleTimeZone` "last rule" for
//! the instants beyond it. That is the form `GregorianCalendar` reads, and it
//! differs from `java.time.zone.ZoneRules` (measured on JDK 25: the hour of
//! `Africa/Casablanca`, `Africa/El_Aaiun`, `Africa/Windhoek`, `Asia/Gaza` and
//! `Asia/Hebron` disagrees for some instants). The rule data, generated by
//! `tools/gen/TimeZoneRules.java` on the JDK 25 oracle, is therefore each
//! zone's `ZoneInfo` fields and the fields of its last rule as the
//! `SimpleTimeZone` constructor decoded them; this module reproduces, from
//! the JDK's specification, the computations that read them:
//! `ZoneInfo.getOffsets(long, int[], UTC_TIME)`, `SimpleTimeZone.getOffsets`
//! and the time-of-day half of `GregorianCalendar.computeFields`.
//!
//! What is not reproduced:
//!
//! * `SimpleTimeZone`'s one-year cache, which a `TimeZone` instance keeps
//!   across calls. It changes no answer, except for an instant within
//!   `rawOffset` of `Long.MAX_VALUE`: there `date + rawOffset` overflows and
//!   a fresh computation finds no daylight saving time, while a cached period
//!   from an earlier call on the same instance may contain the instant. This
//!   module always computes afresh, as a new `TimeZone.getTimeZone(id)`
//!   does.
//! * The Julian calendar `SimpleTimeZone` uses before the Gregorian cutover
//!   (`-12219292800000`): a last rule is only reached beyond a transition
//!   table, which ends in 2037 or later.

use super::time_zone_data::{IDS, RULES};

/// `ZoneInfo.OFFSET_MASK`: the bits of a transition holding the index of
/// its total offset in `offsets`.
const OFFSET_MASK: i64 = 0x0f;
/// `ZoneInfo.TRANSITION_NSHIFT`: the shift of a transition's UTC instant, in
/// milliseconds.
const TRANSITION_NSHIFT: u32 = 12;

/// `AbstractCalendar.DAY_IN_MILLIS`.
const DAY_IN_MILLIS: i64 = 86_400_000;
/// `AbstractCalendar.EPOCH_OFFSET`: the fixed date of 1970-01-01.
const EPOCH_OFFSET: i64 = 719_163;
/// `GregorianCalendar.ONE_HOUR`.
const ONE_HOUR: i32 = 3_600_000;

/// `SimpleTimeZone.DOM_MODE`: "Mar 1".
const DOM_MODE: i32 = 1;
/// `SimpleTimeZone.DOW_IN_MONTH_MODE`: "lastSun".
const DOW_IN_MONTH_MODE: i32 = 2;
/// `SimpleTimeZone.DOW_GE_DOM_MODE`: "Sun>=15".
const DOW_GE_DOM_MODE: i32 = 3;
/// `SimpleTimeZone.DOW_LE_DOM_MODE`: "Sun<=21".
const DOW_LE_DOM_MODE: i32 = 4;
/// `SimpleTimeZone.WALL_TIME`.
const WALL_TIME: i32 = 0;
/// `SimpleTimeZone.UTC_TIME`.
const UTC_TIME: i32 = 2;

/// The fields of a `sun.util.calendar.ZoneInfo` that its offsets depend on.
///
/// `rawOffsetDiff`, which only `setRawOffset` changes, is 0 for every zone
/// `TimeZone.getTimeZone` returns (the generator checks it), so
/// `getLastRawOffset()` is `raw_offset`.
#[derive(Debug)]
pub struct ZoneInfo {
    /// `rawOffset`: the GMT offset of the last standard time, in
    /// milliseconds.
    pub(super) raw_offset: i32,
    /// `transitions`: each a UTC instant in milliseconds shifted left by
    /// [`TRANSITION_NSHIFT`], with the index of its total offset in the low
    /// four bits and of its saving in the next four. `None` for a zone that
    /// never changed its offset.
    pub(super) transitions: Option<&'static [i64]>,
    /// `offsets`: the offsets the transitions index.
    pub(super) offsets: &'static [i32],
    /// `getLastRuleInstance()`: the rule beyond the table, `None` for a zone
    /// that no longer observes daylight saving time.
    pub(super) last_rule: Option<SimpleTimeZone>,
}

/// The fields of a `java.util.SimpleTimeZone` its offsets depend on, as its
/// constructor decoded them (`decodeRules`).
#[derive(Debug)]
pub struct SimpleTimeZone {
    /// `useDaylight`.
    pub(super) use_daylight: bool,
    /// `rawOffset`.
    pub(super) raw_offset: i32,
    /// `dstSavings`.
    pub(super) dst_savings: i32,
    /// `startYear`.
    pub(super) start_year: i32,
    /// `startMode`.
    pub(super) start_mode: i32,
    /// `startMonth`, 0-based.
    pub(super) start_month: i32,
    /// `startDay`.
    pub(super) start_day: i32,
    /// `startDayOfWeek`, `Calendar.SUNDAY` (1) to `Calendar.SATURDAY` (7).
    pub(super) start_day_of_week: i32,
    /// `startTime`, in milliseconds.
    pub(super) start_time: i32,
    /// `startTimeMode`.
    pub(super) start_time_mode: i32,
    /// `endMode`.
    pub(super) end_mode: i32,
    /// `endMonth`, 0-based.
    pub(super) end_month: i32,
    /// `endDay`.
    pub(super) end_day: i32,
    /// `endDayOfWeek`.
    pub(super) end_day_of_week: i32,
    /// `endTime`, in milliseconds.
    pub(super) end_time: i32,
    /// `endTimeMode`.
    pub(super) end_time_mode: i32,
}

/// Returns the `ZoneInfo` `TimeZone.getTimeZone(id)` returns for an ID of
/// `TimeZone.getAvailableIDs()`, or `None` for any other ID.
pub fn zone_info(id: &str) -> Option<&'static ZoneInfo> {
    IDS.binary_search_by(|(key, _)| key.encode_utf16().cmp(id.encode_utf16()))
        .ok()
        .map(|i| &RULES[IDS[i].1])
}

impl ZoneInfo {
    /// Returns the total offset from UTC, in milliseconds, at the UTC instant
    /// `date`.
    ///
    /// Equivalent to `ZoneInfo.getOffset(long)`, `getOffsets(date, null,
    /// UTC_TIME)`: the raw offset before the table (Java's "FIXME: should
    /// support LMT"), the offset of the transition at or before `date` inside
    /// it, and beyond its last instant the last rule — or, without one, the
    /// last transition's offset. An instant equal to the last transition is
    /// inside the table; any later one is beyond it.
    pub fn get_offset(&self, date: i64) -> i32 {
        let Some(transitions) = self.transitions else {
            return self.raw_offset;
        };
        let index = Self::transition_index(transitions, date);
        if index < 0 {
            return self.raw_offset;
        }
        let index = index as usize;
        if index < transitions.len() {
            return self.offsets[(transitions[index] & OFFSET_MASK) as usize];
        }
        match &self.last_rule {
            Some(tz) => {
                let rawoffset = tz.raw_offset;
                // `tz.getOffset(msec) - rawOffset`: `ZoneInfo.rawOffset`, which
                // the last rule was built with.
                let dstoffset = tz.get_offset(date).wrapping_sub(self.raw_offset);
                rawoffset.wrapping_add(dstoffset)
            }
            None => {
                let val = transitions[transitions.len() - 1];
                self.offsets[(val & OFFSET_MASK) as usize]
            }
        }
    }

    /// `ZoneInfo.getTransitionIndex(date, UTC_TIME)`: the index of the
    /// transition equal to `date`, else of the last one before it (-1 when
    /// none), else `transitions.length` when `date` is beyond them all.
    fn transition_index(transitions: &[i64], date: i64) -> i32 {
        let mut low: i32 = 0;
        let mut high: i32 = transitions.len() as i32 - 1;
        while low <= high {
            let mid = (low + high) / 2;
            let mid_val = transitions[mid as usize] >> TRANSITION_NSHIFT; // sign extended
            match mid_val.cmp(&date) {
                std::cmp::Ordering::Less => low = mid + 1,
                std::cmp::Ordering::Greater => high = mid - 1,
                std::cmp::Ordering::Equal => return mid,
            }
        }
        // if beyond the transitions, returns that index.
        if low as usize >= transitions.len() {
            return low;
        }
        low - 1
    }

    /// The UTC instants of the transition table, in milliseconds
    /// (`transitions[i] >> TRANSITION_NSHIFT`); empty for a zone without one.
    pub fn transition_instants(&self) -> impl Iterator<Item = i64> + '_ {
        self.transitions
            .unwrap_or(&[])
            .iter()
            .map(|val| val >> TRANSITION_NSHIFT)
    }

    /// Returns whether the zone has a last rule, the `SimpleTimeZone` that
    /// applies beyond its transition table.
    pub fn has_last_rule(&self) -> bool {
        self.last_rule.is_some()
    }
}

impl SimpleTimeZone {
    /// `SimpleTimeZone.getOffset(long date)`, `getOffsets(date, null)`,
    /// computed without the instance's cache (see the module documentation).
    fn get_offset(&self, date: i64) -> i32 {
        let mut offset = self.raw_offset;
        if self.use_daylight {
            debug_assert!(
                date >= -12_219_292_800_000,
                "the Julian calendar is not reproduced"
            );
            // Get the year in local time: `cal.getCalendarDate(date + rawOffset,
            // cdate)`, whose sum may overflow as Java's does.
            let local = date.wrapping_add(i64::from(self.raw_offset));
            let year = gregorian_year_from_fixed_date(fixed_date_of_millis(local));
            if year >= self.start_year {
                // `cdate.setTimeOfDay(0, 0, 0, 0)`: the transition
                // calculations start from midnight.
                let mut cdate = TransitionDate { time_of_day: 0 };
                offset = self.get_offset_in_year(&mut cdate, year, date);
            }
        }
        offset
    }

    /// `SimpleTimeZone.getOffset(BaseCalendar, BaseCalendar.Date, int year,
    /// long time)`, without the cache.
    fn get_offset_in_year(&self, cdate: &mut TransitionDate, year: i32, time: i64) -> i32 {
        let mut start = self.get_start(cdate, year);
        let mut end = self.get_end(cdate, year);
        let mut offset = self.raw_offset;
        if start <= end {
            if time >= start && time < end {
                offset = offset.wrapping_add(self.dst_savings);
            }
        } else if time < end {
            start = self.get_start(cdate, year.wrapping_sub(1));
            if time >= start {
                offset = offset.wrapping_add(self.dst_savings);
            }
        } else if time >= start {
            end = self.get_end(cdate, year.wrapping_add(1));
            if time < end {
                offset = offset.wrapping_add(self.dst_savings);
            }
        }
        offset
    }

    /// `SimpleTimeZone.getStart`: the UTC instant daylight saving time starts
    /// in `year`.
    fn get_start(&self, cdate: &mut TransitionDate, year: i32) -> i64 {
        let mut time = self.start_time;
        if self.start_time_mode != UTC_TIME {
            time = time.wrapping_sub(self.raw_offset);
        }
        cdate.transition(
            self.start_mode,
            year,
            self.start_month,
            self.start_day,
            self.start_day_of_week,
            time,
        )
    }

    /// `SimpleTimeZone.getEnd`: the UTC instant daylight saving time ends in
    /// `year`.
    fn get_end(&self, cdate: &mut TransitionDate, year: i32) -> i64 {
        let mut time = self.end_time;
        if self.end_time_mode != UTC_TIME {
            time = time.wrapping_sub(self.raw_offset);
        }
        if self.end_time_mode == WALL_TIME {
            time = time.wrapping_sub(self.dst_savings);
        }
        cdate.transition(
            self.end_mode,
            year,
            self.end_month,
            self.end_day,
            self.end_day_of_week,
            time,
        )
    }
}

/// The part of the `BaseCalendar.Date` that `SimpleTimeZone.getOffsets`
/// threads through its transition calculations and that can change their
/// result: its time of day.
///
/// `getOffsets` clears it to midnight, and `AbstractCalendar.getTime(cdate)`
/// adds it to the date and then resets the date from the sum
/// (`getCalendarDate(ms, cdate)`). The sum stays at midnight unless
/// `(fixedDate - EPOCH_OFFSET) * DAY_IN_MILLIS` overflows, as it does for the
/// last months of year 292278994; the wrapped time of day then carries over
/// to the next calculation, as it does in Java.
struct TransitionDate {
    time_of_day: i64,
}

impl TransitionDate {
    /// `SimpleTimeZone.getTransition(cal, cdate, mode, year, month,
    /// dayOfMonth, dayOfWeek, timeOfDay)`.
    fn transition(
        &mut self,
        mode: i32,
        year: i32,
        month: i32,
        day_of_month: i32,
        day_of_week: i32,
        time_of_day: i32,
    ) -> i64 {
        let month = month + 1;
        let fixed_date = match mode {
            DOM_MODE => fixed_date(year, month, day_of_month),
            DOW_IN_MONTH_MODE => {
                let day = if day_of_month < 0 {
                    month_length(year, month)
                } else {
                    1
                };
                nth_day_of_week(day_of_month, day_of_week, fixed_date(year, month, day))
            }
            DOW_GE_DOM_MODE => {
                nth_day_of_week(1, day_of_week, fixed_date(year, month, day_of_month))
            }
            DOW_LE_DOM_MODE => {
                nth_day_of_week(-1, day_of_week, fixed_date(year, month, day_of_month))
            }
            // `decodeRules` gives a rule that uses daylight saving time one
            // of the four modes.
            _ => unreachable!("SimpleTimeZone mode {mode}"),
        };
        // `cal.getTime(cdate)`: in `DOM_MODE` on `cdate` itself, whose time of
        // day is then reset from the sum; in the other modes on the copy
        // `getNthDayOfWeek` returns, which inherits it and is then dropped.
        let ms = (fixed_date - EPOCH_OFFSET)
            .wrapping_mul(DAY_IN_MILLIS)
            .wrapping_add(self.time_of_day);
        if mode == DOM_MODE {
            self.time_of_day = ms.rem_euclid(DAY_IN_MILLIS);
        }
        ms.wrapping_add(i64::from(time_of_day))
    }
}

/// `AbstractCalendar.getNthDayOfWeek(nth, dayOfWeek, date)` on a fixed date:
/// the `nth` `dayOfWeek` on or after (`nth > 0`) or on or before (`nth <= 0`)
/// it.
fn nth_day_of_week(nth: i32, day_of_week: i32, fixed_date: i64) -> i64 {
    let nth = i64::from(nth);
    if nth > 0 {
        7 * nth + day_of_week_date_on_or_before(fixed_date - 1, day_of_week)
    } else {
        7 * nth + day_of_week_date_on_or_before(fixed_date + 7, day_of_week)
    }
}

/// `AbstractCalendar.getDayOfWeekDateOnOrBefore(fixedDate, dayOfWeek)`;
/// fixed date 1 (0001-01-01) is a Monday, and `dayOfWeek` counts from
/// Sunday (1).
fn day_of_week_date_on_or_before(fixed_date: i64, day_of_week: i32) -> i64 {
    let fd = fixed_date - i64::from(day_of_week - 1);
    fixed_date - fd.rem_euclid(7)
}

/// `CalendarUtils.isGregorianLeapYear(year)`.
fn is_leap_year(year: i32) -> bool {
    year % 4 == 0 && (year % 100 != 0 || year % 400 == 0)
}

/// `BaseCalendar.getMonthLength(year, month)`, `month` 1-based.
fn month_length(year: i32, month: i32) -> i32 {
    const DAYS_IN_MONTH: [i32; 13] = [0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
    let days = DAYS_IN_MONTH[month as usize];
    if month == 2 && is_leap_year(year) {
        days + 1
    } else {
        days
    }
}

/// `BaseCalendar.getFixedDate(year, month, dayOfMonth, null)`: the fixed date
/// (0001-01-01 is 1) of a Gregorian date, `month` 1-based; a day of month
/// beyond the month counts on into the next.
fn fixed_date(year: i32, month: i32, day_of_month: i32) -> i64 {
    let prevyear = i64::from(year) - 1;
    let month = i64::from(month);
    let mut days = i64::from(day_of_month) + 365 * prevyear + prevyear.div_euclid(4)
        - prevyear.div_euclid(100)
        + prevyear.div_euclid(400)
        + (367 * month - 362).div_euclid(12);
    if month > 2 {
        days -= if is_leap_year(year) { 1 } else { 2 };
    }
    days
}

/// The fixed date of the instant `millis`, as `AbstractCalendar.getCalendarDate`
/// computes it for a date without a time zone: floor division by a day.
fn fixed_date_of_millis(millis: i64) -> i64 {
    millis.div_euclid(DAY_IN_MILLIS) + EPOCH_OFFSET
}

/// `BaseCalendar.getGregorianYearFromFixedDate(fixedDate)`.
fn gregorian_year_from_fixed_date(fixed_date: i64) -> i32 {
    let d0 = fixed_date - 1;
    let n400 = d0.div_euclid(146_097) as i32;
    let d1 = d0.rem_euclid(146_097) as i32;
    let n100 = d1.div_euclid(36_524);
    let d2 = d1.rem_euclid(36_524);
    let n4 = d2.div_euclid(1_461);
    let d3 = d2.rem_euclid(1_461);
    let n1 = d3.div_euclid(365);
    let mut year = 400 * n400 + 100 * n100 + 4 * n4 + n1;
    if !(n100 == 4 || n1 == 4) {
        year += 1;
    }
    year
}

/// Returns `HOUR_OF_DAY` of a `GregorianCalendar` in `zone` whose time is
/// `time`.
///
/// Equivalent to the time-of-day half of `GregorianCalendar.computeFields`:
/// `zoneOffset = zone.getOffsets(time, zoneOffsets)`, then the time of day of
/// `time + zoneOffset`, computed from the two separately so that the sum
/// cannot overflow, divided by `ONE_HOUR`.
pub fn gregorian_calendar_hour_of_day(zone: &ZoneInfo, time: i64) -> i32 {
    let zone_offset = zone.get_offset(time);
    let one_day = DAY_IN_MILLIS as i32;
    let mut time_of_day = zone_offset % one_day;
    time_of_day += (time % DAY_IN_MILLIS) as i32;
    if time_of_day >= one_day {
        time_of_day -= one_day;
    } else {
        while time_of_day < 0 {
            time_of_day += one_day;
        }
    }
    time_of_day / ONE_HOUR
}

#[cfg(test)]
mod tests {
    use super::*;

    /// `simple_time_zone_offsets.tsv`, written by the oracle's
    /// `TimeZoneOracle`: synthetic `SimpleTimeZone`s whose rules no JDK 25
    /// zone has (`DOM_MODE`, `DOW_LE_DOM_MODE`, transitions overflowing
    /// `long` in year 292278994), each with the fields its constructor
    /// decoded and the digest of `getOffset` over the oracle's grid.
    #[test]
    fn synthetic_simple_time_zones_match_java() {
        const YEARS: [i32; 6] = [1970, 2026, 2038, 100_000, 292_278_993, 292_278_994];
        const MAX_MINUS: [i64; 10] = [
            0, 1, 999, 3_599_999, 3_600_000, 46_799_999, 46_800_000, 50_400_000, 86_399_999,
            86_400_000,
        ];
        let jan1 = |year: i32| (fixed_date(year, 1, 1) - EPOCH_OFFSET) * DAY_IN_MILLIS;
        let path = concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/tests/fixtures/simple_time_zone_offsets.tsv"
        );
        let text = std::fs::read_to_string(path).expect("read simple_time_zone_offsets.tsv");
        let mut rows = 0;
        for (row, line) in text
            .lines()
            .filter(|l| !l.starts_with('#') && !l.is_empty())
            .enumerate()
        {
            let r: Vec<&str> = line.split('\t').collect();
            let n = |i: usize| -> i32 { r[i].parse().expect("an int field") };
            let tz = SimpleTimeZone {
                use_daylight: r[1] == "true",
                raw_offset: n(2),
                dst_savings: n(3),
                start_year: n(4),
                start_mode: n(5),
                start_month: n(6),
                start_day: n(7),
                start_day_of_week: n(8),
                start_time: n(9),
                start_time_mode: n(10),
                end_mode: n(11),
                end_month: n(12),
                end_day: n(13),
                end_day_of_week: n(14),
                end_time: n(15),
                end_time_mode: n(16),
            };
            let mut g = vec![0, 1];
            g.extend(MAX_MINUS.iter().map(|k| i64::MAX - k));
            for year in YEARS {
                let lo = jan1(year);
                let hi = if year == 292_278_994 {
                    i64::MAX
                } else {
                    jan1(year + 1)
                };
                let mut x = lo;
                while x < hi {
                    let y = if hi - x > DAY_IN_MILLIS {
                        x + DAY_IN_MILLIS
                    } else {
                        hi
                    };
                    if tz.get_offset(y) != tz.get_offset(x) {
                        let (mut a, mut c) = (x, y);
                        let oa = tz.get_offset(a);
                        while c - a > 1 {
                            let m = a + (c - a) / 2;
                            if tz.get_offset(m) == oa {
                                a = m;
                            } else {
                                c = m;
                            }
                        }
                        g.extend([c - 1, c]);
                    }
                    x = y;
                }
            }
            let random = randomizedtesting::jdk::random::JdkRandom::new(row as i64);
            for _ in 0..64 {
                g.push(crate::util::TestUtil::next_long(&random, 0, i64::MAX));
            }
            let mut h: u64 = 0xcbf2_9ce4_8422_2325;
            for &instant in &g {
                let offset = tz.get_offset(instant);
                for b in instant
                    .to_le_bytes()
                    .into_iter()
                    .chain(offset.to_le_bytes())
                {
                    h ^= u64::from(b);
                    h = h.wrapping_mul(0x0100_0000_01b3);
                }
            }
            assert_eq!(
                format!("{}\t{h:016x}", g.len()),
                format!("{}\t{}", r[17], r[18]),
                "{}",
                r[0]
            );
            rows += 1;
        }
        assert_eq!(rows, 5);
    }

    #[test]
    fn fixed_dates_match_the_epoch_and_year_one() {
        assert_eq!(fixed_date(1, 1, 1), 1);
        assert_eq!(fixed_date(1970, 1, 1), EPOCH_OFFSET);
        assert_eq!(fixed_date_of_millis(-1), EPOCH_OFFSET - 1);
        for year in [-400, -1, 0, 1, 1900, 1970, 2000, 2100, 292_278_994] {
            let jan1 = fixed_date(year, 1, 1);
            assert_eq!(gregorian_year_from_fixed_date(jan1), year, "{year}");
            assert_eq!(gregorian_year_from_fixed_date(jan1 - 1), year - 1, "{year}");
        }
    }

    #[test]
    fn day_of_week_counts_from_sunday() {
        // 1970-01-04 was a Sunday.
        let sunday = fixed_date(1970, 1, 4);
        assert_eq!(day_of_week_date_on_or_before(sunday + 6, 1), sunday);
        assert_eq!(day_of_week_date_on_or_before(sunday, 1), sunday);
        assert_eq!(day_of_week_date_on_or_before(sunday - 1, 1), sunday - 7);
    }

    #[test]
    fn every_available_id_resolves() {
        for id in super::super::time_zone_available_ids() {
            assert!(zone_info(id).is_some(), "{id}");
        }
        assert!(zone_info("Mars/Olympus_Mons").is_none());
    }
}
