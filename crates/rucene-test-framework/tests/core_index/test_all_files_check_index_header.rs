/// `TestAllFilesCheckIndexHeader`.
pub fn class_def() -> Arc<Class> {
    class_annotated(
        "org.apache.lucene.index.TestAllFilesCheckIndexHeader",
        vec![test("test", test_)],
        |b| {
            b.annotate(SuppressFileSystems {
                value: vec!["ExtrasFS".to_string()],
            })
        },
    )
}

/// Port of `TestAllFilesCheckIndexHeader.test`.
fn test_() -> Result<()> {
    let dir = LuceneTestCase::new_directory();
    let mut conf = LuceneTestCase::new_index_writer_config_analyzer(Some(Arc::new(
        rucene_test_framework::analysis::MockAnalyzer::new(&*random()),
    )));
    conf.set_codec(TestUtil::get_default_codec())?;

    // Disable CFS 80% of the time so we can truncate individual files, but the other 20% of the
    // time we test truncation of .cfs/.cfe too:
    if random().next_int_bound(5) != 1 {
        disable_cfs(&mut conf)?;
    }

    let riw = RandomIndexWriter::new_with_config(&*random(), dir.as_directory(), conf)?;
    add_line_file_docs(&riw)?;

    if !*TEST_NIGHTLY {
        riw.force_merge(1)?;
    }
    riw.close()?;
    check_index_header(&dir.as_directory())?;
    dir.close()
}

/// `private void checkIndexHeader(Directory dir)`.
fn check_index_header(dir: &Arc<dyn Directory>) -> Result<()> {
    for name in dir.list_all()? {
        if name != WRITE_LOCK_NAME {
            check_one_file(dir, &name)?;
        }
    }
    Ok(())
}

/// `private void checkOneFile(Directory dir, String victim)`.
fn check_one_file(dir: &Arc<dyn Directory>, victim: &str) -> Result<()> {
    // use ramdir explicit, as we do evil things like try to generate broken files, deletes must
    // work.
    let dir_copy = TestDirectory::Mock(MockDirectoryWrapper::new(
        &*random(),
        Arc::new(ByteBuffersDirectory::new()),
    ));
    set_check_index_on_close(&dir_copy, false);
    let copy = dir_copy.as_directory();
    let victim_length = dir.file_length(victim)?;
    let wrong_bytes = TestUtil::next_int(&*random(), 1, victim_length.min(100) as i32);
    debug_assert!(victim_length > 0);

    if verbose() {
        println!(
            "TEST: now break file {victim} by randomizing first {wrong_bytes} of {victim_length}"
        );
    }

    for name in dir.list_all()? {
        if name != victim {
            copy.copy_from(&**dir, &name, &name, &*DEFAULT_IO_CONTEXT)?;
        } else {
            // Iterate until our randomly generated bytes are indeed different from the first bytes of
            // the file ... the vast majority of the
            // time this will only require one iteration!
            loop {
                let mut out = copy.create_output(&name, &*DEFAULT_IO_CONTEXT)?;
                let mut input = dir.open_input(&name, &*READONCE_IO_CONTEXT)?;
                // keeps same file length, but replaces the first wrongBytes with random bytes:
                let mut bytes = vec![0u8; wrong_bytes as usize];
                random().next_bytes(&mut bytes);
                out.write_bytes(&bytes, 0, bytes.len())?;
                let mut bytes2 = vec![0u8; wrong_bytes as usize];
                let len2 = bytes2.len();
                input.read_bytes(Some(&mut bytes2), 0, len2)?;
                if bytes != bytes2 {
                    // We successfully randomly generated bytes that differ from the bytes in the file:
                    out.copy_bytes(&mut *input, victim_length - wrong_bytes as i64)?;
                    input.close()?;
                    out.close()?;
                    break;
                }
                input.close()?;
                out.close()?;
                // we have to try again, delete the first attempt and retry the loop
                copy.delete_file(&name)?;
            }
        }
        sync_one(&copy, &name)?;
    }

    // NOTE: we .close so that if the test fails (truncation not detected) we don't also get all
    // these confusing errors about open files:
    let classes = [
        "org.apache.lucene.index.CorruptIndexException",
        "java.io.EOFException",
        "org.apache.lucene.index.IndexFormatTooOldException",
    ];
    expect_throws_any_of(&classes, || {
        directory_reader::open(Arc::clone(&copy))?.close()
    });

    // CheckIndex should also fail:
    expect_throws_any_of(&classes, || {
        directory_reader::open(Arc::clone(&copy))?.close()
    });
    dir_copy.close()
}
