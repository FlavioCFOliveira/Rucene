/// `TestFacetUtils` (extends `LuceneTestCase`).
pub fn class_def() -> Arc<Class> {
    class(
        "org.apache.lucene.facet.TestFacetUtils",
        vec![test("testBasic", test_basic)],
    )
}

/// `numericDV` used both as the iterator `liveDocsDISI` wraps and as the
/// value source (`numericDV.longValue()`), as the Java test does with one
/// object.
struct SharedDv(Rc<RefCell<Box<dyn NumericDocValues>>>);

impl DocIdSetIterator for SharedDv {
    fn doc_id(&self) -> i32 {
        self.0.borrow().doc_id()
    }
    fn next_doc(&mut self) -> Result<i32> {
        self.0.borrow_mut().next_doc()
    }
    fn advance(&mut self, target: i32) -> Result<i32> {
        self.0.borrow_mut().advance(target)
    }
    fn cost(&self) -> i64 {
        self.0.borrow().cost()
    }
}

fn test_basic() -> Result<()> {
    let random = LuceneTestCase::random();
    let dir = LuceneTestCase::new_directory();
    let writer = RandomIndexWriter::new_with_mock_analyzer(&*random, dir.as_directory())?;
    let max_docs = 256;
    // Create up to maxDocs number of documents with (id, val) fields having
    // string and numeric representation of the same value
    for i in 0..max_docs {
        let mut doc = Document::new();
        doc.add(StringField::new("id", i.to_string(), Store::NO)?);
        doc.add(NumericDocValuesField::new("val", i64::from(i)));
        writer.add_document(&doc)?;
    }
    // Pick a random number of docs to delete.
    // Actual deleted docs might be less than this because
    // of duplicates generated by random()
    let num_docs_to_delete = random.next_int_bound(max_docs);
    let mut deleted_docs = FixedBitSet::new(max_docs as usize);
    // Delete a random number of randomly picked documents
    // Record what we deleted to make sure we don't find them
    // during iteration
    let mut actual_docs_deleted = 0;
    for _ in 0..num_docs_to_delete {
        let deleted_doc_id = random.next_int_bound(max_docs);
        if deleted_docs.get(deleted_doc_id as usize) {
            // we already deleted and recorded this doc-id
            continue;
        }
        deleted_docs.set(deleted_doc_id as usize);
        writer.delete_documents(Term::from_text("id", &deleted_doc_id.to_string()))?;
        actual_docs_deleted += 1;
    }
    let reader = writer.get_reader()?;
    let searcher = LuceneTestCase::new_searcher(Arc::clone(&reader));
    let fc = searcher.search_with_manager(
        Arc::new(MatchAllDocsQuery::instance()),
        &FacetsCollectorManager::new(),
    )?;
    let mut visited_docs = 0;
    for m in fc.get_matching_docs()? {
        let leaf = m.context().leaf_reader();
        let numeric_dv = Rc::new(RefCell::new(DocValues::get_numeric(&*leaf, "val")?));
        let live_docs = leaf.get_live_docs();
        // Only use the liveDocsDISI if liveDocs is not null
        let mut disi: Box<dyn DocIdSetIterator> = match live_docs {
            None => Box::new(SharedDv(Rc::clone(&numeric_dv))),
            Some(live_docs) => {
                FacetUtils::live_docs_disi(Box::new(SharedDv(Rc::clone(&numeric_dv))), live_docs)
            }
        };
        // Iterating over disi should only give values for live docs
        while disi.next_doc()? != NO_MORE_DOCS {
            visited_docs += 1;
            let val = numeric_dv.borrow().long_value()? as i32;
            Assert::assert_true_msg(
                &format!("Deleted doc {val} found during iteration"),
                !deleted_docs.get(val as usize),
            );
        }
    }
    Assert::assert_true_msg(
        &format!(
            "Visited document [{visited_docs}] != Live documents [{}]",
            max_docs - actual_docs_deleted
        ),
        visited_docs == max_docs - actual_docs_deleted,
    );
    writer.close()?;
    searcher.get_index_reader().close()?;
    dir.close()
}
