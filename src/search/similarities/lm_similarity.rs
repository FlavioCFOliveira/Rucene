/// Language model based on the Jelinek-Mercer smoothing method.
///
/// Equivalent to
/// `org.apache.lucene.search.similarities.LMJelinekMercerSimilarity`. From
/// Chengxiang Zhai and John Lafferty, *A study of smoothing methods for
/// language models applied to Ad Hoc information retrieval*, SIGIR '01,
/// pp. 334-342.
///
/// The model has a single parameter, *λ*. According to the paper its optimal
/// value depends on both the collection and the query, and is around `0.1` for
/// title queries and `0.7` for long ones. Values near zero score more like a
/// conjunction (coordinate level matching); values near one behave more like a
/// pure disjunction.
#[derive(Debug)]
pub struct LMJelinekMercerSimilarity {
    lambda: f32,
    collection_model: Box<dyn CollectionModel>,
    discount_overlaps: bool,
}

impl LMJelinekMercerSimilarity {
    /// Rejects a `lambda` Java's constructors reject
    /// (`LMJelinekMercerSimilarity.java:47-49`).
    fn check_lambda(lambda: f32) -> Result<()> {
        if lambda.is_nan() || lambda <= 0.0 || lambda > 1.0 {
            return Err(LuceneError::IllegalArgument(
                "lambda must be in the range (0 .. 1]".to_string(),
            ));
        }
        Ok(())
    }

    /// Creates the similarity with the specified *λ* and the default collection
    /// model.
    ///
    /// Equivalent to `new LMJelinekMercerSimilarity(float)`
    /// (`LMJelinekMercerSimilarity.java:62-68`).
    ///
    /// # Errors
    ///
    /// Returns [`LuceneError::IllegalArgument`] when `lambda` is NaN or outside
    /// `(0 .. 1]`.
    pub fn with_lambda(lambda: f32) -> Result<Self> {
        Self::check_lambda(lambda)?;
        Ok(Self {
            lambda,
            collection_model: Box::new(DefaultCollectionModel::new()),
            discount_overlaps: true,
        })
    }

    /// Creates the similarity with the specified collection model and *λ*.
    ///
    /// Equivalent to `new LMJelinekMercerSimilarity(CollectionModel, float)`
    /// (`LMJelinekMercerSimilarity.java:47-49`).
    ///
    /// # Errors
    ///
    /// See [`Self::with_lambda`].
    pub fn with_collection_model_and_lambda(
        collection_model: Box<dyn CollectionModel>,
        lambda: f32,
    ) -> Result<Self> {
        Self::with_parameters(collection_model, true, lambda)
    }

    /// Creates the similarity with every parameter supplied.
    ///
    /// Equivalent to
    /// `new LMJelinekMercerSimilarity(CollectionModel, boolean, float)`
    /// (`LMJelinekMercerSimilarity.java:52-60`).
    ///
    /// # Errors
    ///
    /// See [`Self::with_lambda`].
    pub fn with_parameters(
        collection_model: Box<dyn CollectionModel>,
        discount_overlaps: bool,
        lambda: f32,
    ) -> Result<Self> {
        Self::check_lambda(lambda)?;
        Ok(Self {
            lambda,
            collection_model,
            discount_overlaps,
        })
    }

    /// Returns the *λ* parameter.
    ///
    /// Equivalent to `LMJelinekMercerSimilarity.getLambda()`.
    pub fn lambda(&self) -> f32 {
        self.lambda
    }
}

impl Similarity for LMJelinekMercerSimilarity {
    fn discount_overlaps(&self) -> bool {
        self.discount_overlaps
    }

    fn scorer<'a>(
        &'a self,
        boost: f32,
        collection_stats: &CollectionStatistics,
        term_stats: &[TermStatistics],
    ) -> Box<dyn SimScorer + 'a> {
        similarity_base_scorer(self, boost, collection_stats, term_stats)
    }
}

impl SimilarityBase for LMJelinekMercerSimilarity {
    type Stats = LMStats;

    fn simple_name(&self) -> &'static str {
        "LMJelinekMercerSimilarity"
    }

    fn new_stats(&self, field: &str, boost: f64) -> LMStats {
        lm_new_stats(field, boost)
    }

    fn fill_basic_stats(
        &self,
        stats: &mut LMStats,
        collection_stats: &CollectionStatistics,
        term_stats: &TermStatistics,
    ) {
        lm_fill_basic_stats(
            self.collection_model.as_ref(),
            stats,
            collection_stats,
            term_stats,
        );
    }

    fn score(&self, stats: &LMStats, freq: f64, doc_len: f64) -> f64 {
        // `1 - lambda` is an `int` minus a `float` in Java, so it is computed
        // in `float` and only then widened.
        let one_minus_lambda = f64::from(1.0f32 - self.lambda);
        stats.boost()
            * (1.0
                + (one_minus_lambda * freq / doc_len)
                    / (f64::from(self.lambda) * stats.collection_probability()))
            .ln()
    }

    fn explain_details(
        &self,
        subs: &mut Vec<Explanation>,
        stats: &LMStats,
        freq: f64,
        doc_len: f64,
    ) {
        if stats.boost() != 1.0 {
            subs.push(Explanation::matched(stats.boost() as f32, "boost", vec![]));
        }
        subs.push(Explanation::matched(self.lambda, "lambda", vec![]));
        subs.push(Explanation::matched(
            stats.collection_probability() as f32,
            "P, probability that the current term is generated by the collection",
            vec![],
        ));
        subs.push(Explanation::matched(
            freq as f32,
            "freq, number of occurrences of term in the document",
            vec![],
        ));
        subs.push(Explanation::matched(
            doc_len as f32,
            "dl, length of field",
            vec![],
        ));
        lm_explain_details(self.collection_model.as_ref(), subs, stats);
    }

    /// Overrides the base explanation, as
    /// `LMJelinekMercerSimilarity.explain(BasicStats, Explanation, double)`
    /// does (`LMJelinekMercerSimilarity.java:92-106`).
    fn explain(&self, stats: &LMStats, freq: &Explanation, doc_len: f64) -> Explanation {
        let mut subs = Vec::new();
        let freq_value = freq.value().double_value();
        self.explain_details(&mut subs, stats, freq_value, doc_len);

        Explanation::matched(
            self.score(stats, freq_value, doc_len) as f32,
            format!(
                "score({}, freq={}), computed as boost * log(1 + ((1 - lambda) * freq / dl) /(lambda * P)) from:",
                self.simple_name(),
                freq.value()
            ),
            subs,
        )
    }
}

impl LMSimilarity for LMJelinekMercerSimilarity {
    fn collection_model(&self) -> &dyn CollectionModel {
        self.collection_model.as_ref()
    }

    fn name(&self) -> String {
        format!(
            "Jelinek-Mercer({})",
            java_fmt::format_f(f64::from(self.lambda))
        )
    }
}

impl fmt::Display for LMJelinekMercerSimilarity {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&lm_to_string(self))
    }
}

// ---------------------------------------------------------------------------
// IndriDirichletSimilarity
// ---------------------------------------------------------------------------

/// Models `p(w|C)` as the number of occurrences of the term in the collection,
/// divided by the total number of tokens.
///
/// Equivalent to the nested
/// `IndriDirichletSimilarity.IndriCollectionModel`
/// (`IndriDirichletSimilarity.java:107-119`). Note that, despite the Javadoc it
/// inherits, this model does *not* add one to the denominator — unlike
/// [`DefaultCollectionModel`].
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct IndriCollectionModel;

impl IndriCollectionModel {
    /// Creates the parameter-free collection model.
    ///
    /// Equivalent to `new IndriDirichletSimilarity.IndriCollectionModel()`.
    pub fn new() -> Self {
        Self
    }
}

impl CollectionModel for IndriCollectionModel {
    fn compute_probability(&self, stats: &BasicStats) -> f64 {
        stats.total_term_freq() as f64 / stats.number_of_field_tokens() as f64
    }

    fn name(&self) -> Option<String> {
        None
    }
}

/// Bayesian smoothing using Dirichlet priors as implemented in the Indri search
/// engine.
///
/// Equivalent to
/// `org.apache.lucene.search.similarities.IndriDirichletSimilarity`:
///
/// ```text
/// tf_E + mu*P(t|D)   P(t|E) = documentLength + documentMu
/// mu*P(t|C) + tf_D   where   P(t|D) = doclen + mu
/// ```
///
/// A larger `mu` produces more smoothing. Smoothing matters most for short
/// documents, where the probabilities are more granular.
///
/// Note the asymmetry Lucene's constructors have and this port keeps: the
/// no-argument form uses [`IndriCollectionModel`], while the `mu`-only form
/// inherits [`DefaultCollectionModel`] from `LMSimilarity`'s default
/// constructor. Unlike [`LMDirichletSimilarity`], `mu` is not validated.
#[derive(Debug)]
pub struct IndriDirichletSimilarity {
    mu: f32,
    collection_model: Box<dyn CollectionModel>,
    discount_overlaps: bool,
}

impl IndriDirichletSimilarity {
    /// Creates the similarity with the default `mu` of `2000` and the Indri
    /// collection model.
    ///
    /// Equivalent to `new IndriDirichletSimilarity()`
    /// (`IndriDirichletSimilarity.java:63-65`).
    pub fn new() -> Self {
        Self {
            mu: 2000.0,
            collection_model: Box::new(IndriCollectionModel::new()),
            discount_overlaps: true,
        }
    }

    /// Creates the similarity with the provided `mu`.
    ///
    /// Equivalent to `new IndriDirichletSimilarity(float)`
    /// (`IndriDirichletSimilarity.java:53-55`), whose implicit `super()` call
    /// installs [`DefaultCollectionModel`] — not [`IndriCollectionModel`].
    pub fn with_mu(mu: f32) -> Self {
        Self {
            mu,
            collection_model: Box::new(DefaultCollectionModel::new()),
            discount_overlaps: true,
        }
    }

    /// Creates the similarity with the provided collection model and the
    /// default `mu` of `2000`.
    ///
    /// Equivalent to `new IndriDirichletSimilarity(CollectionModel)`
    /// (`IndriDirichletSimilarity.java:58-60`).
    pub fn with_collection_model(collection_model: Box<dyn CollectionModel>) -> Self {
        Self {
            mu: 2000.0,
            collection_model,
            discount_overlaps: true,
        }
    }

    /// Creates the similarity with the provided collection model and `mu`.
    ///
    /// Equivalent to `new IndriDirichletSimilarity(CollectionModel, float)`
    /// (`IndriDirichletSimilarity.java:47-50`).
    pub fn with_collection_model_and_mu(
        collection_model: Box<dyn CollectionModel>,
        mu: f32,
    ) -> Self {
        Self {
            mu,
            collection_model,
            discount_overlaps: true,
        }
    }

    /// Creates the similarity with every parameter supplied.
    ///
    /// Equivalent to
    /// `new IndriDirichletSimilarity(CollectionModel, boolean, float)`
    /// (`IndriDirichletSimilarity.java:41-45`).
    pub fn with_parameters(
        collection_model: Box<dyn CollectionModel>,
        discount_overlaps: bool,
        mu: f32,
    ) -> Self {
        Self {
            mu,
            collection_model,
            discount_overlaps,
        }
    }

    /// Returns the `mu` parameter.
    ///
    /// Equivalent to `IndriDirichletSimilarity.getMu()`.
    pub fn mu(&self) -> f32 {
        self.mu
    }
}

