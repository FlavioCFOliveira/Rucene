//! The language-modelling similarities, ported from
//! `org.apache.lucene.search.similarities.LMSimilarity` and its three
//! descendants.
//!
//! `LMSimilarity` introduces three types beyond the ranking models themselves:
//! [`LMStats`], which adds the probability that the collection language model
//! generates the current term; [`CollectionModel`], the strategy that computes
//! `p(w|C)`; and [`DefaultCollectionModel`], the implementation that divides
//! the term's collection frequency by the total token count.

#![deny(unsafe_code)]

use std::borrow::{Borrow, BorrowMut};
use std::fmt::{self, Debug};
use std::ops::Deref;

use crate::error::{LuceneError, Result};

use super::similarity_base::{fill_basic_stats, similarity_base_scorer};
use super::{java_fmt, BasicStats, CollectionStatistics, Explanation};
use super::{SimScorer, Similarity, SimilarityBase, TermStatistics};

// ---------------------------------------------------------------------------
// LMStats
// ---------------------------------------------------------------------------

/// Stores the collection distribution of the current term.
///
/// Equivalent to the nested `LMSimilarity.LMStats`
/// (`LMSimilarity.java:107-121`), which extends `BasicStats`. Rust has no
/// inheritance, so the base statistics are held as a field and reached through
/// [`Deref`]; that is what lets the formulas below read `stats.boost()` exactly
/// as their Java counterparts do, and what replaces the
/// `(LMStats) stats` downcasts Lucene performs.
#[derive(Debug, Clone, PartialEq)]
pub struct LMStats {
    base: BasicStats,
    collection_probability: f64,
}

impl LMStats {
    /// Creates `LMStats` for the provided field and query-time boost.
    ///
    /// Equivalent to `new LMSimilarity.LMStats(String, double)`
    /// (`LMSimilarity.java:112-114`).
    pub fn new(field: impl Into<String>, boost: f64) -> Self {
        Self {
            base: BasicStats::new(field, boost),
            collection_probability: 0.0,
        }
    }

    /// Returns the probability that the current term is generated by the
    /// collection.
    ///
    /// Equivalent to `LMStats.getCollectionProbability()`.
    pub fn collection_probability(&self) -> f64 {
        self.collection_probability
    }

    /// Sets the probability that the current term is generated by the
    /// collection.
    ///
    /// Equivalent to `LMStats.setCollectionProbability(double)`.
    pub fn set_collection_probability(&mut self, collection_probability: f64) {
        self.collection_probability = collection_probability;
    }
}

impl From<BasicStats> for LMStats {
    fn from(base: BasicStats) -> Self {
        Self {
            base,
            collection_probability: 0.0,
        }
    }
}

impl Deref for LMStats {
    type Target = BasicStats;

    fn deref(&self) -> &BasicStats {
        &self.base
    }
}

impl Borrow<BasicStats> for LMStats {
    fn borrow(&self) -> &BasicStats {
        &self.base
    }
}

impl BorrowMut<BasicStats> for LMStats {
    fn borrow_mut(&mut self) -> &mut BasicStats {
        &mut self.base
    }
}

// ---------------------------------------------------------------------------
// CollectionModel
// ---------------------------------------------------------------------------

/// A strategy for computing the collection language model.
///
/// Equivalent to the nested interface `LMSimilarity.CollectionModel`
/// (`LMSimilarity.java:124-133`).
pub trait CollectionModel: Debug + Send + Sync {
    /// Computes the probability `p(w|C)` for the current term.
    ///
    /// Equivalent to `CollectionModel.computeProbability(BasicStats)`.
    fn compute_probability(&self, stats: &BasicStats) -> f64;

    /// Returns the name of the collection-model strategy.
    ///
    /// Equivalent to `CollectionModel.getName()`, which returns `null` for the
    /// two models Lucene ships; `None` carries that here, and
    /// [`lm_to_string`] omits the suffix for it.
    fn name(&self) -> Option<String>;
}

/// Models `p(w|C)` as the number of occurrences of the term in the collection,
/// divided by the total number of tokens `+ 1`.
///
/// Equivalent to the nested `LMSimilarity.DefaultCollectionModel`
/// (`LMSimilarity.java:139-153`).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct DefaultCollectionModel;

impl DefaultCollectionModel {
    /// Creates the parameter-free collection model.
    ///
    /// Equivalent to `new LMSimilarity.DefaultCollectionModel()`.
    pub fn new() -> Self {
        Self
    }
}

impl CollectionModel for DefaultCollectionModel {
    fn compute_probability(&self, stats: &BasicStats) -> f64 {
        (stats.total_term_freq() as f64 + 1.0) / (stats.number_of_field_tokens() as f64 + 1.0)
    }

    fn name(&self) -> Option<String> {
        None
    }
}

// ---------------------------------------------------------------------------
// LMSimilarity
// ---------------------------------------------------------------------------

/// Superclass for language-modelling similarities.
///
/// Equivalent to `org.apache.lucene.search.similarities.LMSimilarity`. Java
/// overrides `newStats`, `fillBasicStats`, `explain(List, …)` and `toString()`
/// here and inherits them into the three concrete models; a Rust subtrait
/// cannot override a supertrait's methods, so the shared bodies are the free
/// functions [`lm_new_stats`], [`lm_fill_basic_stats`], [`lm_explain_details`]
/// and [`lm_to_string`], and each concrete model forwards to them in one line.
pub trait LMSimilarity: SimilarityBase<Stats = LMStats> {
    /// Returns the collection model this similarity smooths with.
    ///
    /// Java holds it in the `protected final collectionModel` field
    /// (`LMSimilarity.java:38`).
    fn collection_model(&self) -> &dyn CollectionModel;

    /// Returns the name of the LM method, parameter values included.
    ///
    /// Equivalent to the abstract `LMSimilarity.getName()`
    /// (`LMSimilarity.java:79`). Used by [`lm_to_string`].
    fn name(&self) -> String;
}

/// Creates the statistics object the language-modelling family scores from.
///
/// This is the body of `LMSimilarity.newStats` (`LMSimilarity.java:47-49`).
pub fn lm_new_stats(field: &str, boost: f64) -> LMStats {
    LMStats::new(field, boost)
}

/// Computes the collection probability of the current term in addition to the
/// usual statistics.
///
/// This is the body of `LMSimilarity.fillBasicStats`
/// (`LMSimilarity.java:55-61`), including its `super.fillBasicStats` call.
pub fn lm_fill_basic_stats(
    collection_model: &dyn CollectionModel,
    stats: &mut LMStats,
    collection_stats: &CollectionStatistics,
    term_stats: &TermStatistics,
) {
    fill_basic_stats(&mut stats.base, collection_stats, term_stats);
    let probability = collection_model.compute_probability(&stats.base);
    stats.set_collection_probability(probability);
}

/// Adds the collection-probability node every language model reports.
///
/// This is the body of `LMSimilarity.explain(List, BasicStats, double, double)`
/// (`LMSimilarity.java:64-69`), which the three concrete models reach through
/// `super.explain` at the *end* of their own `explain`.
pub fn lm_explain_details(
    collection_model: &dyn CollectionModel,
    sub_expls: &mut Vec<Explanation>,
    stats: &LMStats,
) {
    sub_expls.push(Explanation::matched(
        collection_model.compute_probability(&stats.base) as f32,
        "collection probability",
        vec![],
    ));
}

/// Renders a language-modelling similarity.
///
/// This is the body of `LMSimilarity.toString()`
/// (`LMSimilarity.java:88-95`): the LM method's name, plus the collection
/// model's name when it has one.
pub fn lm_to_string(similarity: &dyn LMSimilarity) -> String {
    match similarity.collection_model().name() {
        Some(collection) => format!("LM {} - {}", similarity.name(), collection),
        None => format!("LM {}", similarity.name()),
    }
}

