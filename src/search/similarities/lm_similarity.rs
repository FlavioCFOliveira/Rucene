/// Bayesian smoothing using Dirichlet priors.
///
/// Equivalent to `org.apache.lucene.search.similarities.LMDirichletSimilarity`.
/// From Chengxiang Zhai and John Lafferty, *A study of smoothing methods for
/// language models applied to Ad Hoc information retrieval*, SIGIR '01,
/// pp. 334-342.
///
/// The formula as defined in the paper assigns a negative score to documents
/// that contain the term but with fewer occurrences than the collection
/// language model predicts; Lucene returns `0` for such documents, and so does
/// this port.
#[derive(Debug)]
pub struct LMDirichletSimilarity {
    mu: f32,
    collection_model: Box<dyn CollectionModel>,
    discount_overlaps: bool,
}

impl LMDirichletSimilarity {
    /// Rejects a `mu` Java's constructors reject
    /// (`LMDirichletSimilarity.java:41-44`).
    fn check_mu(mu: f32) -> Result<()> {
        if !mu.is_finite() || mu < 0.0 {
            return Err(LuceneError::IllegalArgument(format!(
                "illegal mu value: {}, must be a non-negative finite value",
                java_fmt::float_to_string(mu)
            )));
        }
        Ok(())
    }

    /// Creates the similarity with the default `mu` of `2000` and the default
    /// collection model.
    ///
    /// Equivalent to `new LMDirichletSimilarity()`
    /// (`LMDirichletSimilarity.java:71-73`).
    pub fn new() -> Self {
        Self {
            mu: 2000.0,
            collection_model: Box::new(DefaultCollectionModel::new()),
            discount_overlaps: true,
        }
    }

    /// Creates the similarity with the provided `mu` and the default collection
    /// model.
    ///
    /// Equivalent to `new LMDirichletSimilarity(float)`
    /// (`LMDirichletSimilarity.java:60-65`).
    ///
    /// # Errors
    ///
    /// Returns [`LuceneError::IllegalArgument`] when `mu` is not finite or is
    /// negative.
    pub fn with_mu(mu: f32) -> Result<Self> {
        Self::check_mu(mu)?;
        Ok(Self {
            mu,
            collection_model: Box::new(DefaultCollectionModel::new()),
            discount_overlaps: true,
        })
    }

    /// Creates the similarity with the provided collection model and the
    /// default `mu` of `2000`.
    ///
    /// Equivalent to `new LMDirichletSimilarity(CollectionModel)`
    /// (`LMDirichletSimilarity.java:67-69`).
    pub fn with_collection_model(collection_model: Box<dyn CollectionModel>) -> Self {
        Self {
            mu: 2000.0,
            collection_model,
            discount_overlaps: true,
        }
    }

    /// Creates the similarity with the provided collection model and `mu`.
    ///
    /// Equivalent to `new LMDirichletSimilarity(CollectionModel, float)`
    /// (`LMDirichletSimilarity.java:35-37`).
    ///
    /// # Errors
    ///
    /// See [`Self::with_mu`].
    pub fn with_collection_model_and_mu(
        collection_model: Box<dyn CollectionModel>,
        mu: f32,
    ) -> Result<Self> {
        Self::with_parameters(collection_model, true, mu)
    }

    /// Creates the similarity with every parameter supplied.
    ///
    /// Equivalent to
    /// `new LMDirichletSimilarity(CollectionModel, boolean, float)`
    /// (`LMDirichletSimilarity.java:39-47`).
    ///
    /// # Errors
    ///
    /// See [`Self::with_mu`].
    pub fn with_parameters(
        collection_model: Box<dyn CollectionModel>,
        discount_overlaps: bool,
        mu: f32,
    ) -> Result<Self> {
        Self::check_mu(mu)?;
        Ok(Self {
            mu,
            collection_model,
            discount_overlaps,
        })
    }

    /// Returns the `mu` parameter.
    ///
    /// Equivalent to `LMDirichletSimilarity.getMu()`.
    pub fn mu(&self) -> f32 {
        self.mu
    }
}

impl Default for LMDirichletSimilarity {
    fn default() -> Self {
        Self::new()
    }
}

impl Similarity for LMDirichletSimilarity {
    fn discount_overlaps(&self) -> bool {
        self.discount_overlaps
    }

    fn scorer<'a>(
        &'a self,
        boost: f32,
        collection_stats: &CollectionStatistics,
        term_stats: &[TermStatistics],
    ) -> Box<dyn SimScorer + 'a> {
        similarity_base_scorer(self, boost, collection_stats, term_stats)
    }
}

impl SimilarityBase for LMDirichletSimilarity {
    type Stats = LMStats;

    fn simple_name(&self) -> &'static str {
        "LMDirichletSimilarity"
    }

    fn new_stats(&self, field: &str, boost: f64) -> LMStats {
        lm_new_stats(field, boost)
    }

    fn fill_basic_stats(
        &self,
        stats: &mut LMStats,
        collection_stats: &CollectionStatistics,
        term_stats: &TermStatistics,
    ) {
        lm_fill_basic_stats(
            self.collection_model.as_ref(),
            stats,
            collection_stats,
            term_stats,
        );
    }

    fn score(&self, stats: &LMStats, freq: f64, doc_len: f64) -> f64 {
        let mu = f64::from(self.mu);
        let score = stats.boost()
            * ((1.0 + freq / (mu * stats.collection_probability())).ln()
                + (mu / (doc_len + mu)).ln());
        if score > 0.0 {
            score
        } else {
            0.0
        }
    }

    fn explain_details(
        &self,
        subs: &mut Vec<Explanation>,
        stats: &LMStats,
        freq: f64,
        doc_len: f64,
    ) {
        if stats.boost() != 1.0 {
            subs.push(Explanation::matched(
                stats.boost() as f32,
                "query boost",
                vec![],
            ));
        }
        let mu = f64::from(self.mu);
        let p = stats.collection_probability();
        let expl_p = Explanation::matched(
            p as f32,
            "P, probability that the current term is generated by the collection",
            vec![],
        );
        let expl_freq = Explanation::matched(
            freq as f32,
            "freq, number of occurrences of term in the document",
            vec![],
        );

        subs.push(Explanation::matched(self.mu, "mu", vec![]));
        subs.push(Explanation::matched(
            (1.0 + freq / (mu * p)).ln() as f32,
            "term weight, computed as log(1 + freq /(mu * P)) from:",
            vec![expl_freq, expl_p],
        ));
        subs.push(Explanation::matched(
            (mu / (doc_len + mu)).ln() as f32,
            "document norm, computed as log(mu / (dl + mu))",
            vec![],
        ));
        subs.push(Explanation::matched(
            doc_len as f32,
            "dl, length of field",
            vec![],
        ));
        lm_explain_details(self.collection_model.as_ref(), subs, stats);
    }

    /// Overrides the base explanation, as
    /// `LMDirichletSimilarity.explain(BasicStats, Explanation, double)` does
    /// (`LMDirichletSimilarity.java:110-124`), taking the frequency as a
    /// `double`.
    fn explain(&self, stats: &LMStats, freq: &Explanation, doc_len: f64) -> Explanation {
        let mut subs = Vec::new();
        let freq_value = freq.value().double_value();
        self.explain_details(&mut subs, stats, freq_value, doc_len);

        Explanation::matched(
            self.score(stats, freq_value, doc_len) as f32,
            format!(
                "score({}, freq={}), computed as boost * (term weight + document norm) from:",
                self.simple_name(),
                freq.value()
            ),
            subs,
        )
    }
}

impl LMSimilarity for LMDirichletSimilarity {
    fn collection_model(&self) -> &dyn CollectionModel {
        self.collection_model.as_ref()
    }

    fn name(&self) -> String {
        format!("Dirichlet({})", java_fmt::format_f(f64::from(self.mu)))
    }
}

impl fmt::Display for LMDirichletSimilarity {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&lm_to_string(self))
    }
}

